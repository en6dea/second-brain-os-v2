import type { LucideIcon } from 'lucide-react'
import { cn } from '@/design-system/classNames'
import { ЗНАЧОК } from '@/design-system/iconSize'

/**
 * Значок сущности.
 *
 * Цвет определяется тем, что значок обозначает, а не тем, на какой странице
 * он оказался. Деньги всегда зелёные, долги коралловые, цели лиловые — и на
 * главной, и в меню, и внутри карточки. Так значок становится опознавательным
 * знаком, а не украшением.
 *
 * Толщина обводки и скругления концов заданы один раз в `index.css` для всех
 * значков сразу, поэтому здесь их нет.
 */

export type СмыслЗначка =
  /* Домены: свой цвет у каждого, как в референсе. */
  | 'сегодня'
  | 'планы'
  | 'жизнь'
  | 'деньги'
  | 'знания'
  | 'система'
  /* Сущности внутри разделов. */
  | 'дело'
  | 'время'
  | 'цель'
  | 'привычка'
  | 'человек'
  | 'близкий'
  | 'деньги'
  | 'долг'
  | 'знание'
  | 'запись'
  | 'внимание'
  | 'система'

const ЦВЕТА: Record<СмыслЗначка, string> = {
  сегодня: 'text-warn',
  планы: 'text-info',
  жизнь: 'text-know',
  знания: 'text-warn',
  система: 'text-ink-3',
  дело: 'text-accent',
  время: 'text-info',
  цель: 'text-know',
  привычка: 'text-info',
  человек: 'text-info',
  близкий: 'text-bad',
  деньги: 'text-accent',
  долг: 'text-warn',
  знание: 'text-info',
  запись: 'text-ink-2',
  внимание: 'text-warn',
}

export function Icon({
  значок: Значок,
  смысл,
  размер = ЗНАЧОК.крупный,
  монохромный = false,
  className,
}: {
  значок: LucideIcon
  смысл: СмыслЗначка
  размер?: number
  /** Навигация использует один цвет; семантика остаётся у значков в данных. */
  монохромный?: boolean
  className?: string
}) {
  return (
    <Значок
      size={размер}
      aria-hidden="true"
      className={cn(
        'shrink-0',
        монохромный ? 'text-current' : ЦВЕТА[смысл],
        className,
      )}
    />
  )
}
