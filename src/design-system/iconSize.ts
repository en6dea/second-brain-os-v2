/**
 * Шкала размеров значков.
 *
 * Размер значка у lucide задаётся числом в разметке, а не классом, поэтому
 * токеном CSS его не выразить. Раньше в коде встречалось одиннадцать разных
 * чисел от 11 до 22 — подобранных на глаз в момент написания экрана. Ступени
 * ниже соответствуют шкале текста из `index.css`: значок рядом с подписью,
 * рядом с текстом, рядом с показанием.
 *
 * Новый код берёт размер отсюда; `npm run check:scale` следит, чтобы список
 * произвольных чисел не рос.
 */
export const ЗНАЧОК = {
  /** Рядом с подписью и метаданными. */
  подпись: 12,
  /** Внутри строки списка, кнопки малого размера. */
  строка: 14,
  /** Основной размер: пункт меню, кнопка, заголовок карточки. */
  основной: 16,
  /** Заметный: действие в шапке, крупная кнопка. */
  крупный: 18,
  /** Рядом с показанием прибора, пустое состояние. */
  показание: 20,
} as const

export type РазмерЗначка = (typeof ЗНАЧОК)[keyof typeof ЗНАЧОК]
