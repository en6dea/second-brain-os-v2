import { useMemo } from 'react'
import { CircleDollarSign, Repeat, Target } from 'lucide-react'

/**
 * Приборное свечение: несколько знаков, медленно дрейфующих в глубине карточки.
 *
 * Это не украшение ради украшения. Знаки взяты из самой системы — цель,
 * повтор, деньги, — и живут в фоне на пределе видимости. Экран перестаёт быть
 * неподвижным, но ничто не отвлекает от цифр на переднем плане.
 *
 * Полное отключение при `prefers-reduced-motion` задано в таблице стилей.
 */

const ЗНАКИ = [
  { Иконка: Target, левее: 8, ниже: 18, размер: 52, длительность: 47, задержка: 0 },
  {
    Иконка: Repeat,
    левее: 74,
    ниже: 12,
    размер: 40,
    длительность: 61,
    задержка: -14,
  },
  {
    Иконка: CircleDollarSign,
    левее: 46,
    ниже: 62,
    размер: 34,
    длительность: 53,
    задержка: -29,
  },
  {
    Иконка: Target,
    левее: 88,
    ниже: 70,
    размер: 26,
    длительность: 67,
    задержка: -8,
  },
]

export function AmbientField() {
  // Точки рассчитываются один раз: их положение не должно меняться при
  // каждой перерисовке, иначе движение станет дёрганым.
  const знаки = useMemo(() => ЗНАКИ, [])

  return (
    <div
      aria-hidden="true"
      className="поле-свечения pointer-events-none absolute inset-0 overflow-hidden"
    >
      {знаки.map((знак, номер) => (
        <span
          key={номер}
          className="дрейф absolute text-accent"
          style={{
            left: `${знак.левее}%`,
            top: `${знак.ниже}%`,
            animationDuration: `${знак.длительность}s`,
            animationDelay: `${знак.задержка}s`,
          }}
        >
          <знак.Иконка size={знак.размер} strokeWidth={1} />
        </span>
      ))}
    </div>
  )
}
