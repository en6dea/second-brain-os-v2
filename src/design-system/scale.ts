/**
 * Пять делений оценки.
 *
 * Раньше оценка ставилась одиннадцатью кнопками 0…10 — тридцать три мишени
 * размером с ноготь в одном окне. Точность в одну единицу из десяти всё равно
 * недостижима: между «6» и «7» нет разницы, которую человек удержит от вечера
 * к вечеру.
 *
 * Хранится по-прежнему число 0…10, поэтому прежние записи читаются без
 * миграции: деление подсвечивается по диапазону, в который попало записанное
 * число, а при нажатии записывается опорное значение деления.
 *
 * Ноль — это ноль («совсем нет»). «Не отмечено» — это `null`.
 */

export interface Деление {
  подпись: string
  /** Что записывается при нажатии. */
  значение: number
  /** Диапазон, при попадании в который деление считается выбранным. */
  от: number
  до: number
}

export const ДЕЛЕНИЯ: Деление[] = [
  { подпись: 'совсем нет', значение: 0, от: 0, до: 1 },
  { подпись: 'мало', значение: 3, от: 2, до: 3 },
  { подпись: 'средне', значение: 5, от: 4, до: 6 },
  { подпись: 'много', значение: 8, от: 7, до: 8 },
  { подпись: 'очень', значение: 10, от: 9, до: 10 },
]

/** Деление, в диапазон которого попадает записанное число. */
export function делениеПоЗначению(значение: number | null): Деление | null {
  if (значение === null) return null
  return ДЕЛЕНИЯ.find((д) => значение >= д.от && значение <= д.до) ?? null
}

/** Оценка словами: «средне». Для списков, где число само по себе ничего не говорит. */
export function оценкаСловами(значение: number | null): string | null {
  return делениеПоЗначению(значение)?.подпись ?? null
}
