import { useEffect } from 'react'
import { база } from '@/core/db/db'
import { изменитьНастройки, читатьНастройки } from '@/core/db/repo'
import { сегодня } from '@/core/calendar/CalendarRu'
import { расписаниеДня, пораПоказать, type ДанныеРасписания } from '@/core/reminders/Schedule'
import { сводкаЦикла } from '@/features/relationship/model/Cycle'
import { показать } from '@/core/reminders/Notifications'
import { useИнтерфейс } from '@/app/providers/ui'

const ИНТЕРВАЛ_ПРОВЕРКИ = 60_000

/**
 * Доставка напоминаний.
 *
 * Расписание в `core/reminders/Schedule.ts` — чистая функция без побочных
 * эффектов, её нельзя проверить тестом, если она сама лезет в базу и в
 * браузер. Здесь — обвязка: раз в минуту читает записи, спрашивает
 * расписание, что наступило, и показывает то, что ещё не показывали.
 *
 * Работает, только пока вкладка открыта. Настоящего push с сервера нет —
 * это означает бы завести сервер, а его в этом приложении нет и не будет.
 * Честно говорится и в настройках.
 */
export function useНапоминания() {
  const сообщить = useИнтерфейс((с) => с.сообщить)

  useEffect(() => {
    let остановлено = false

    async function проверить() {
      const настройки = await читатьНастройки()
      if (!настройки.уведомленияВключены) return
      if (typeof Notification === 'undefined' || Notification.permission !== 'granted') {
        return
      }

      const день = сегодня()
      const [задачи, привычки, обязательства, замыслы, дниПартнёра, обзоры] =
        await Promise.all([
          база.tasks.toArray(),
          база.habits.toArray(),
          база.obligations.toArray(),
          база.intentions.toArray(),
          база.partnerDays.toArray(),
          база.reviews.toArray(),
        ])

      const дневникЗаСегодня = await база.journal
        .where('дата')
        .equals(день)
        .and((запись) => запись.вид === 'подсознание')
        .count()

      const данные: ДанныеРасписания = {
        задачи,
        привычки,
        обязательства,
        замыслы,
        люди: await база.people.toArray(),
        обзоры,
        ожидаемоеНачалоЦикла: сводкаЦикла(дниПартнёра, день).ожидаемоеНачало,
        дневникЗаполнен: дневникЗаСегодня > 0,
      }

      const расписание = расписаниеДня(данные, день)

      // Список показанного сбрасывается со сменой дня: вчерашние ключи
      // сегодняшнему расписанию не мешают.
      const показанные =
        настройки.показанныеНапоминания.день === день
          ? настройки.показанныеНапоминания.ключи
          : []

      const кПоказу = пораПоказать(расписание, new Date().toISOString(), показанные)
      if (кПоказу.length === 0 || остановлено) return

      for (const оповещение of кПоказу) {
        показать(оповещение)
        сообщить(оповещение.заголовок)
      }

      await изменитьНастройки({
        показанныеНапоминания: {
          день,
          ключи: [...показанные, ...кПоказу.map((о) => о.ключ)],
        },
      })
    }

    void проверить()
    const таймер = window.setInterval(() => void проверить(), ИНТЕРВАЛ_ПРОВЕРКИ)
    return () => {
      остановлено = true
      window.clearInterval(таймер)
    }
  }, [сообщить])
}
