import { useEffect, useState } from 'react'
import { useLiveQuery } from 'dexie-react-hooks'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import { использоватьИнтерфейс } from '@/app/providers/ui'
import { рублиВКопейки } from '@/core/money/Money'
import { сегодня } from '@/core/calendar/CalendarRu'
import {
  Input,
  MoneyInput,
  Select,
  Button,
  Dialog,
  Field,
  Segmented,
  Textarea,
} from '@/design-system/components'

type Вид =
  | 'задача'
  | 'расход'
  | 'доход'
  | 'заметка'
  | 'событие'
  | 'цель'
  | 'привычка'
  | 'идея'

const ВИДЫ: { ключ: Вид; подпись: string }[] = [
  { ключ: 'задача', подпись: 'Задача' },
  { ключ: 'расход', подпись: 'Расход' },
  { ключ: 'доход', подпись: 'Доход' },
  { ключ: 'заметка', подпись: 'Заметка' },
  { ключ: 'событие', подпись: 'Событие' },
  { ключ: 'цель', подпись: 'Цель' },
  { ключ: 'привычка', подпись: 'Привычка' },
  { ключ: 'идея', подпись: 'Идея' },
]

export function QuickAdd() {
  const открыто = использоватьИнтерфейс((с) => с.быстроеДобавление)
  const открыть = использоватьИнтерфейс((с) => с.открытьБыстроеДобавление)
  const сообщить = использоватьИнтерфейс((с) => с.сообщить)

  const [вид, установитьВид] = useState<Вид>('задача')
  const [название, установитьНазвание] = useState('')
  const [текст, установитьТекст] = useState('')
  const [сумма, установитьСумму] = useState('')
  const [дата, установитьДату] = useState(сегодня())
  const [счётId, установитьСчёт] = useState('')
  const [категорияId, установитьКатегорию] = useState('')
  const [сохраняем, установитьСохраняем] = useState(false)

  const счета = useLiveQuery(
    () => база.accounts.filter((с) => !с.архив).toArray(),
    [],
  )
  const категории = useLiveQuery(
    () => база.moneyCategories.filter((к) => !к.архив).toArray(),
    [],
  )

  useEffect(() => {
    if (открыто) {
      установитьВид('задача')
      установитьНазвание('')
      установитьТекст('')
      установитьСумму('')
      установитьДату(сегодня())
      установитьСчёт('')
      установитьКатегорию('')
    }
  }, [открыто])

  const деньги = вид === 'расход' || вид === 'доход'
  const категорииВида = (категории ?? []).filter((к) =>
    вид === 'доход' ? к.вид === 'доход' : к.вид === 'расход',
  )

  const можноСохранить = деньги
    ? (рублиВКопейки(сумма) ?? 0) > 0
    : название.trim().length > 0 || текст.trim().length > 0

  async function сохранить() {
    if (!можноСохранить || сохраняем) return
    установитьСохраняем(true)
    try {
      switch (вид) {
        case 'задача':
          await база.tasks.add(
            новаяЗапись({
              название: название.trim(),
              заметка: текст.trim(),
              дата,
              время: null,
              длительностьМинут: null,
              состояние: 'новая',
              важность: 'обычная',
              проектId: null,
              цельId: null,
              сфераId: null,
              выполненаВ: null,
              переносов: 0,
              повтор: null,
            }) as never,
          )
          сообщить('Задача добавлена')
          break

        case 'расход':
        case 'доход':
          await база.operations.add(
            новаяЗапись({
              дата,
              тип: вид,
              сумма: рублиВКопейки(сумма) ?? 0,
              счётId: счётId || null,
              счётПолучательId: null,
              категорияId: категорияId || null,
              классРасхода: null,
              заметка: название.trim(),
              планId: null,
              отпечатокИмпорта: null,
              разобрана: Boolean(категорияId),
            }) as never,
          )
          сообщить(вид === 'расход' ? 'Расход записан' : 'Доход записан')
          break

        case 'заметка':
          await база.knowledge.add(
            новаяЗапись({
              заголовок: название.trim() || 'Заметка',
              вид: 'заметка',
              текст: текст.trim(),
              ссылка: '',
              меткиId: [],
              папкаId: null,
              проектId: null,
              цельId: null,
              избранное: false,
            }) as never,
          )
          сообщить('Заметка сохранена')
          break

        case 'идея':
          await база.inbox.add(
            новаяЗапись({
              текст: `${название.trim()} ${текст.trim()}`.trim(),
              разобрано: false,
              источник: 'быстрая запись',
            }) as never,
          )
          сообщить('Идея отправлена в разбор')
          break

        case 'событие':
          await база.events.add(
            новаяЗапись({
              название: название.trim(),
              дата,
              время: null,
              длительностьМинут: null,
              место: '',
              заметка: текст.trim(),
              сфераId: null,
              весьДень: true,
            }) as never,
          )
          сообщить('Событие добавлено')
          break

        case 'цель':
          await база.goals.add(
            новаяЗапись({
              название: название.trim(),
              зачем: текст.trim(),
              сфераId: null,
              состояние: 'активна',
              срок: null,
              цель: null,
              текущее: null,
              единица: '',
              порядок: 0,
              вехи: [],
              последняяАктивность: new Date().toISOString(),
            }) as never,
          )
          сообщить('Цель создана')
          break

        case 'привычка':
          await база.habits.add(
            новаяЗапись({
              название: название.trim(),
              иконка: '',
              цвет: 'accent',
              частота: 'ежедневно',
              дниНедели: [],
              разВНеделю: null,
              норма: 1,
              единица: 'раз',
              цельId: null,
              сфераId: null,
              активна: true,
              отметки: {},
            }) as never,
          )
          сообщить('Привычка добавлена')
          break
      }
      открыть(false)
    } finally {
      установитьСохраняем(false)
    }
  }

  return (
    <Dialog
      открыто={открыто}
      наЗакрытие={() => открыть(false)}
      заголовок="Быстрое добавление"
      подпись="Одна запись — один шаг. Подробности можно дополнить позже."
      подвал={
        <>
          <Button вид="тихая" onClick={() => открыть(false)}>
            Отмена
          </Button>
          <Button
            вид="основная"
            onClick={сохранить}
            disabled={!можноСохранить || сохраняем}
          >
            Сохранить
          </Button>
        </>
      }
    >
      <div className="space-y-4">
        <div className="-mx-1 overflow-x-auto px-1 pb-1">
          <Segmented значения={ВИДЫ} выбрано={вид} наВыбор={установитьВид} />
        </div>

        {деньги ? (
          <>
            <Field подпись="Сумма" обязательное>
              <MoneyInput
                value={сумма}
                onChange={установитьСумму}
                placeholder="0"
                autoFocus
              />
            </Field>
            <div className="grid gap-4 sm:grid-cols-2">
              <Field
                подпись="Категория"
                подсказка="Без категории операция попадёт в разбор"
              >
                <Select
                  value={категорияId}
                  onChange={(событие) => установитьКатегорию(событие.target.value)}
                >
                  <option value="">Не выбрана</option>
                  {категорииВида.map((категория) => (
                    <option key={категория.id} value={категория.id}>
                      {категория.название}
                    </option>
                  ))}
                </Select>
              </Field>
              <Field подпись="Счёт">
                <Select
                  value={счётId}
                  onChange={(событие) => установитьСчёт(событие.target.value)}
                >
                  <option value="">Не выбран</option>
                  {(счета ?? []).map((счёт) => (
                    <option key={счёт.id} value={счёт.id}>
                      {счёт.название}
                    </option>
                  ))}
                </Select>
              </Field>
            </div>
            <Field подпись="Комментарий">
              <Input
                value={название}
                onChange={(событие) => установитьНазвание(событие.target.value)}
                placeholder="Например: продукты на неделю"
              />
            </Field>
            <Field подпись="Дата">
              <Input
                type="date"
                value={дата}
                onChange={(событие) => установитьДату(событие.target.value)}
              />
            </Field>
          </>
        ) : (
          <>
            <Field подпись={вид === 'идея' ? 'Мысль' : 'Название'} обязательное>
              <Input
                value={название}
                onChange={(событие) => установитьНазвание(событие.target.value)}
                placeholder={
                  вид === 'задача'
                    ? 'Что нужно сделать?'
                    : вид === 'цель'
                      ? 'Чего вы хотите достичь?'
                      : 'Коротко'
                }
                autoFocus
              />
            </Field>

            {вид === 'задача' || вид === 'событие' ? (
              <Field подпись="Дата">
                <Input
                  type="date"
                  value={дата}
                  onChange={(событие) => установитьДату(событие.target.value)}
                />
              </Field>
            ) : null}

            {вид !== 'привычка' ? (
              <Field
                подпись={вид === 'цель' ? 'Зачем это нужно' : 'Подробности'}
                подсказка={
                  вид === 'цель'
                    ? 'Цель без ответа «зачем» первой теряет смысл'
                    : undefined
                }
              >
                <Textarea
                  value={текст}
                  onChange={(событие) => установитьТекст(событие.target.value)}
                  rows={3}
                />
              </Field>
            ) : null}
          </>
        )}
      </div>
    </Dialog>
  )
}
