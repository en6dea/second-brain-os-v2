import { useEffect } from 'react'
import { изменитьНастройки, читатьНастройки } from '@/core/db/repo'
import {
  установитьПоставщика,
  поставщикСинхронизации,
  БезОблака,
} from '@/core/sync/provider'

const ИНТЕРВАЛ_СИНХРОНИЗАЦИИ = 60_000

/**
 * Фоновая синхронизация.
 *
 * Firebase — тяжёлый пакет (сам SDK, не считая приложения, весит больше
 * мегабайта). Пока конфигурация не сохранена, ни он, ни движок синхронизации
 * не подгружаются вовсе: `import()` внутри эффекта заставляет сборщик
 * вынести их в отдельный файл, который браузер скачивает только тому, кто
 * действительно включил синхронизацию. Раньше статический импорт наверху
 * файла утаскивал Firebase в главный пакет — его получал каждый, кто просто
 * открыл приложение, даже без единого слова о синхронизации в настройках.
 *
 * Раз в минуту, если подключено, вызывает один проход движка и запоминает
 * новую отметку. Ошибка сети не показывается назойливо — тихо пробуется
 * снова через минуту.
 */
export function useСинхронизацию() {
  useEffect(() => {
    let остановлено = false

    async function проход() {
      const настройки = await читатьНастройки()
      const конфигурация = настройки.синхронизация.конфигурация
      if (!конфигурация) {
        установитьПоставщика(БезОблака)
        return
      }

      const [{ синхронизировать }, { создатьFirebaseПоставщика }] = await Promise.all([
        import('@/core/sync/engine'),
        import('@/core/sync/FirebaseProvider'),
      ])
      if (остановлено) return

      if (поставщикСинхронизации().название !== 'Firebase') {
        установитьПоставщика(создатьFirebaseПоставщика(конфигурация))
      }

      const итог = await синхронизировать(настройки.синхронизация.отметка)
      await изменитьНастройки({
        синхронизация: { конфигурация, отметка: итог.новаяОтметка },
      })
    }

    void проход()
    const таймер = window.setInterval(() => void проход(), ИНТЕРВАЛ_СИНХРОНИЗАЦИИ)
    return () => {
      остановлено = true
      window.clearInterval(таймер)
    }
  }, [])
}
