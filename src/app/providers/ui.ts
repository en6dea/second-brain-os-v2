import { create } from 'zustand'

export type ВидБыстрогоДобавления =
  | 'задача'
  | 'расход'
  | 'доход'
  | 'заметка'
  | 'событие'
  | 'цель'
  | 'привычка'
  | 'идея'

interface СостояниеИнтерфейса {
  командноеОкно: boolean
  быстроеДобавление: boolean
  видБыстрогоДобавления: ВидБыстрогоДобавления | null
  менюНаТелефоне: boolean
  уведомление: string | null
  открытьКомандноеОкно: (значение: boolean) => void
  открытьБыстроеДобавление: (значение: boolean, вид?: ВидБыстрогоДобавления) => void
  открытьМеню: (значение: boolean) => void
  сообщить: (текст: string) => void
}

export const useИнтерфейс = create<СостояниеИнтерфейса>((set) => ({
  командноеОкно: false,
  быстроеДобавление: false,
  видБыстрогоДобавления: null,
  менюНаТелефоне: false,
  уведомление: null,
  открытьКомандноеОкно: (значение) => set({ командноеОкно: значение }),
  открытьБыстроеДобавление: (значение, вид) =>
    set({
      быстроеДобавление: значение,
      видБыстрогоДобавления: значение ? (вид ?? null) : null,
    }),
  открытьМеню: (значение) => set({ менюНаТелефоне: значение }),
  сообщить: (текст) => {
    set({ уведомление: текст })
    setTimeout(() => set({ уведомление: null }), 3200)
  },
}))
