/**
 * Домен, которому принадлежит адрес.
 *
 * Совпадение ищется по самому длинному подходящему пути: иначе «/» подошло бы
 * ко всему подряд и любой экран считался бы разделом «Сегодня».
 */
export function доменПоАдресу(адрес: string): Домен | null {
  let найден: Домен | null = null
  let длина = -1

  for (const домен of ДОМЕНЫ) {
    for (const раздел of домен.разделы) {
      const подходит =
        раздел.путь === '/' ? адрес === '/' : адрес.startsWith(раздел.путь)
      if (подходит && раздел.путь.length > длина) {
        длина = раздел.путь.length
        найден = домен
      }
    }
  }

  return найден
}
