/**
 * Честный GameLife.
 *
 * Прежний ГеймЛайф не перенесён из первой версии осознанно: его очки,
 * уровни и монеты не выводились из данных — отдельная игровая надстройка,
 * которую можно было «накрутить», не сделав ничего. Здесь очки — это
 * подписанный счётчик реальных действий: сколько задач закрыто, сколько
 * отметок привычек поставлено, сколько целей достигнуто, сколько обзоров
 * закрыто. Веса между источниками — открытая константа, показанная в
 * интерфейсе, а не спрятанная магия: единственный честный способ признать,
 * что веса — это выбор, а не объективный факт.
 */

export interface ИсточникиОчков {
  задачСделано: number
  привычекОтмечено: number
  целейДостигнуто: number
  обзоровЗакрыто: number
}

export interface ПоказателиGameLife {
  очков: number
  уровень: number
  вЭтомУровне: number
  доСледующегоУровня: number
  источники: ИсточникиОчков
}

export const ОЧКОВ_НА_УРОВЕНЬ = 50

export const ВЕС = {
  задача: 1,
  привычка: 1,
  цель: 10,
  обзор: 5,
} as const

export function посчитатьGameLife(источники: ИсточникиОчков): ПоказателиGameLife {
  const очков =
    источники.задачСделано * ВЕС.задача +
    источники.привычекОтмечено * ВЕС.привычка +
    источники.целейДостигнуто * ВЕС.цель +
    источники.обзоровЗакрыто * ВЕС.обзор

  const уровень = Math.floor(очков / ОЧКОВ_НА_УРОВЕНЬ) + 1
  const вЭтомУровне = очков % ОЧКОВ_НА_УРОВЕНЬ

  return {
    очков,
    уровень,
    вЭтомУровне,
    доСледующегоУровня: ОЧКОВ_НА_УРОВЕНЬ - вЭтомУровне,
    источники,
  }
}
