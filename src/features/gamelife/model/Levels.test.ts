import { describe, expect, it } from 'vitest'
import { посчитатьGameLife, ВЕС, ОЧКОВ_НА_УРОВЕНЬ } from './Levels'

const пусто = {
  задачСделано: 0,
  привычекОтмечено: 0,
  целейДостигнуто: 0,
  обзоровЗакрыто: 0,
}

describe('посчитатьGameLife', () => {
  it('нулевые данные — нулевые очки, первый уровень', () => {
    const итог = посчитатьGameLife(пусто)
    expect(итог.очков).toBe(0)
    expect(итог.уровень).toBe(1)
    expect(итог.доСледующегоУровня).toBe(ОЧКОВ_НА_УРОВЕНЬ)
  })

  it('очки считаются по весам источников', () => {
    const итог = посчитатьGameLife({
      задачСделано: 3,
      привычекОтмечено: 2,
      целейДостигнуто: 1,
      обзоровЗакрыто: 1,
    })
    expect(итог.очков).toBe(3 * ВЕС.задача + 2 * ВЕС.привычка + ВЕС.цель + ВЕС.обзор)
  })

  it('переход на следующий уровень при накоплении очков за порог', () => {
    const итог = посчитатьGameLife({ ...пусто, задачСделано: ОЧКОВ_НА_УРОВЕНЬ + 5 })
    expect(итог.уровень).toBe(2)
    expect(итог.вЭтомУровне).toBe(5)
    expect(итог.доСледующегоУровня).toBe(ОЧКОВ_НА_УРОВЕНЬ - 5)
  })

  it('ровно на границе уровня — новый уровень, ноль очков в нём', () => {
    const итог = посчитатьGameLife({ ...пусто, задачСделано: ОЧКОВ_НА_УРОВЕНЬ })
    expect(итог.уровень).toBe(2)
    expect(итог.вЭтомУровне).toBe(0)
    expect(итог.доСледующегоУровня).toBe(ОЧКОВ_НА_УРОВЕНЬ)
  })

  it('источники передаются насквозь для показа «как считается»', () => {
    const источники = { задачСделано: 1, привычекОтмечено: 2, целейДостигнуто: 0, обзоровЗакрыто: 3 }
    expect(посчитатьGameLife(источники).источники).toEqual(источники)
  })
})
