import { useMemo, useState } from 'react'
import { useLiveQuery } from 'dexie-react-hooks'
import { Check, ChevronLeft, ChevronRight } from 'lucide-react'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import type { План, ТипПлана } from '@/core/db/types'
import {
  границыМесяца,
  границыНедели,
  деньСловами,
  месяцСловами,
  сдвинутьДень,
  сегодня,
} from '@/core/calendar/CalendarRu'
import { склонение } from '@/core/language/Plural'
import { деньги } from '@/core/money/Money'
import { итогПериода } from '@/features/finance/model/calc'
import { сейчас } from '@/core/db/RecordId'
import { useИнтерфейс } from '@/app/providers/ui'
import {
  Badge,
  Button,
  Card,
  CardBody,
  CardHeader,
  Field,
  Metric,
  Segmented,
  Skeleton,
  Textarea,
} from '@/design-system/components'

const ГОРИЗОНТЫ: { ключ: ТипПлана; подпись: string; смысл: string }[] = [
  { ключ: 'день', подпись: 'День', смысл: 'что сегодня главное' },
  { ключ: 'неделя', подпись: 'Неделя', смысл: 'куда идёт неделя' },
  { ключ: 'месяц', подпись: 'Месяц', смысл: 'чем закончится месяц' },
  { ключ: 'квартал', подпись: 'Квартал', смысл: 'что должно сдвинуться' },
  { ключ: 'год', подпись: 'Год', смысл: 'каким станет год' },
]

/** Ключ периода и его границы для выбранного горизонта и сдвига. */
function период(тип: ТипПлана, сдвиг: number) {
  const день = сегодня()

  if (тип === 'день') {
    const дата = сдвинутьДень(день, сдвиг)
    return { ключ: дата, от: дата, до: дата, название: деньСловами(дата) }
  }

  if (тип === 'неделя') {
    const границы = границыНедели(сдвинутьДень(день, сдвиг * 7))
    return {
      ключ: `${границы.от}—${границы.до}`,
      от: границы.от,
      до: границы.до,
      название: `${деньСловами(границы.от)} — ${деньСловами(границы.до)}`,
    }
  }

  const [год, месяц] = день.slice(0, 7).split('-').map(Number)

  if (тип === 'месяц') {
    const дата = new Date(год ?? 2026, (месяц ?? 1) - 1 + сдвиг, 1)
    const ключ = `${дата.getFullYear()}-${String(дата.getMonth() + 1).padStart(2, '0')}`
    const границы = границыМесяца(ключ)
    return { ключ, от: границы.от, до: границы.до, название: месяцСловами(ключ) }
  }

  if (тип === 'квартал') {
    const дата = new Date(год ?? 2026, (месяц ?? 1) - 1 + сдвиг * 3, 1)
    const номер = Math.floor(дата.getMonth() / 3) + 1
    const первый = (номер - 1) * 3
    const от = `${дата.getFullYear()}-${String(первый + 1).padStart(2, '0')}-01`
    const границыПоследнего = границыМесяца(
      `${дата.getFullYear()}-${String(первый + 3).padStart(2, '0')}`,
    )
    return {
      ключ: `${дата.getFullYear()}-К${номер}`,
      от,
      до: границыПоследнего.до,
      название: `${номер}-й квартал ${дата.getFullYear()}`,
    }
  }

  const нужныйГод = (год ?? 2026) + сдвиг
  return {
    ключ: String(нужныйГод),
    от: `${нужныйГод}-01-01`,
    до: `${нужныйГод}-12-31`,
    название: `${нужныйГод} год`,
  }
}

export function PlanningPage() {
  const сообщить = useИнтерфейс((с) => с.сообщить)
  const [тип, установитьТип] = useState<ТипПлана>('месяц')
  const [сдвиг, установитьСдвиг] = useState(0)
  const [черновики, установитьЧерновики] = useState<Record<string, string>>({})

  const текущий = период(тип, сдвиг)

  const данные = useLiveQuery(async () => {
    const [планы, цели, задачи, операции, опыт, вызовы] = await Promise.all([
      база.plans.toArray(),
      база.goals.toArray(),
      база.tasks.toArray(),
      база.operations.toArray(),
      база.experiences.toArray(),
      база.challenges.toArray(),
    ])
    return { планы, цели, задачи, операции, опыт, вызовы }
  }, [])

  const посчитано = useMemo(() => {
    if (!данные) return null
    const задачиПериода = данные.задачи.filter(
      (з) =>
        з.дата !== null &&
        з.дата >= текущий.от &&
        з.дата <= текущий.до &&
        з.состояние !== 'отменена',
    )
    return {
      задачВсего: задачиПериода.length,
      задачСделано: задачиПериода.filter((з) => з.состояние === 'сделана').length,
      деньги: итогПериода(данные.операции, текущий.от, текущий.до),
    }
  }, [данные, текущий.от, текущий.до])

  if (!данные || !посчитано) {
    return (
      <Card>
        <Skeleton строк={5} />
      </Card>
    )
  }

  const план =
    данные.планы.find((п) => п.тип === тип && п.период === текущий.ключ) ?? null

  const значение = (поле: keyof План) =>
    черновики[поле] ?? ((план?.[поле] as string) || '')

  const изменить = (поле: keyof План, текст: string) =>
    установитьЧерновики((текущие) => ({ ...текущие, [поле]: текст }))

  const целиПериода = данные.цели.filter(
    (цель) =>
      цель.состояние === 'активна' &&
      (план?.целиId.includes(цель.id) ||
        (цель.срок !== null && цель.срок >= текущий.от && цель.срок <= текущий.до)),
  )

  const опытМесяца =
    тип === 'месяц' ? данные.опыт.filter((о) => о.месяц === текущий.ключ) : []
  const вызовМесяца =
    тип === 'месяц' ? данные.вызовы.filter((в) => в.месяц === текущий.ключ) : []

  async function сохранить(закрыть = false) {
    const поля = {
      тип,
      период: текущий.ключ,
      намерение: значение('намерение'),
      главныеСобытия: значение('главныеСобытия'),
      целиId: план?.целиId ?? [],
      обучение: значение('обучение'),
      опыт: значение('опыт'),
      вызовId: план?.вызовId ?? null,
      итог: значение('итог'),
      закрыт: закрыть || Boolean(план?.закрыт),
    }

    if (план) {
      await база.plans.put({ ...план, ...поля, updatedAt: сейчас() })
    } else {
      await база.plans.add(новаяЗапись(поля) as never)
    }
    установитьЧерновики({})
    сообщить(закрыть ? 'План закрыт итогом' : 'План сохранён')
  }

  const месячный = тип === 'месяц' || тип === 'квартал' || тип === 'год'

  return (
    <div className="anim-rise space-y-5">
      <div>
        <h1 className="text-h2 font-semibold text-ink">Планирование</h1>
        <p className="mt-0.5 text-meta text-ink-3">
          Пять горизонтов. План — это решение, куда уходит период, а не список дел.
        </p>
      </div>

      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="-mx-1 overflow-x-auto px-1 pb-1">
          <Segmented
            значения={ГОРИЗОНТЫ.map((г) => ({ ключ: г.ключ, подпись: г.подпись }))}
            выбрано={тип}
            наВыбор={(ключ) => {
              установитьТип(ключ)
              установитьСдвиг(0)
              установитьЧерновики({})
            }}
          />
        </div>
        <div className="flex items-center gap-2">
          <Button
            размер="малый"
            иконка={<ChevronLeft size={15} />}
            onClick={() => {
              установитьСдвиг(сдвиг - 1)
              установитьЧерновики({})
            }}
          >
            Назад
          </Button>
          {сдвиг !== 0 ? (
            <Button
              размер="малый"
              onClick={() => {
                установитьСдвиг(0)
                установитьЧерновики({})
              }}
            >
              Сейчас
            </Button>
          ) : null}
          <Button
            размер="малый"
            onClick={() => {
              установитьСдвиг(сдвиг + 1)
              установитьЧерновики({})
            }}
          >
            Вперёд
            <ChevronRight size={15} />
          </Button>
        </div>
      </div>

      <Card>
        <CardHeader
          заголовок={текущий.название}
          подпись={ГОРИЗОНТЫ.find((г) => г.ключ === тип)?.смысл}
          действие={
            план ? (
              <Badge тон={план.закрыт ? 'успех' : 'сведения'}>
                {план.закрыт ? 'закрыт итогом' : 'план есть'}
              </Badge>
            ) : (
              <Badge>плана нет</Badge>
            )
          }
        />
        <div className="grid grid-cols-2 gap-5 px-5 pb-5 lg:grid-cols-4">
          <Metric
            единица="шт · задачи"
            подпись="Закрыто за период"
            значение={`${посчитано.задачСделано}/${посчитано.задачВсего}`}
            источник={
              посчитано.задачВсего === 0 ? 'задач с датой нет' : 'по датам задач'
            }
          />
          <Metric
            единица="шт · цели"
            подпись="Целей на период"
            значение={String(целиПериода.length)}
            источник="со сроком внутри периода"
          />
          <Metric
            единица="₽ · получено"
            подпись="Доходы"
            значение={деньги(посчитано.деньги.доходы)}
            тон={посчитано.деньги.доходы > 0 ? 'успех' : 'нейтральный'}
          />
          <Metric
            единица="₽ · поток"
            подпись="Доходы минус расходы"
            значение={деньги(посчитано.деньги.поток, { знак: true })}
            тон={посчитано.деньги.поток < 0 ? 'опасность' : 'успех'}
            источник={`${посчитано.деньги.операций} ${склонение(посчитано.деньги.операций, 'операция', 'операции', 'операций')}`}
          />
        </div>

        {целиПериода.length > 0 ? (
          <div className="border-t border-line px-5 py-3">
            <p className="mb-1.5 text-micro font-semibold tracking-[0.14em] text-ink-3 uppercase">
              Цели с сроком в этом периоде
            </p>
            <div className="flex flex-wrap gap-1.5">
              {целиПериода.map((цель) => (
                <Badge key={цель.id} тон="знание">
                  {цель.название}
                </Badge>
              ))}
            </div>
          </div>
        ) : null}
      </Card>

      <Card>
        <CardHeader
          заголовок="План"
          подпись="Заполняется в начале периода, итог — в конце"
        />
        <CardBody className="space-y-4">
          <Field
            подпись="Намерение"
            подсказка="Одной фразой: чем этот период должен отличаться"
          >
            <Textarea
              rows={2}
              value={значение('намерение')}
              onChange={(событие) => изменить('намерение', событие.target.value)}
            />
          </Field>

          <Field подпись="Главные события">
            <Textarea
              rows={3}
              value={значение('главныеСобытия')}
              onChange={(событие) =>
                изменить('главныеСобытия', событие.target.value)
              }
            />
          </Field>

          {месячный ? (
            <div className="grid gap-4 sm:grid-cols-2">
              <Field подпись="Что изучить">
                <Textarea
                  rows={3}
                  value={значение('обучение')}
                  onChange={(событие) => изменить('обучение', событие.target.value)}
                />
              </Field>
              <Field подпись="Новый опыт" подсказка="Что попробовать впервые">
                <Textarea
                  rows={3}
                  value={значение('опыт')}
                  onChange={(событие) => изменить('опыт', событие.target.value)}
                />
              </Field>
            </div>
          ) : null}

          <Field
            подпись="Итог периода"
            подсказка="Заполняется в конце. Пока пусто — период не закрыт"
          >
            <Textarea
              rows={3}
              value={значение('итог')}
              onChange={(событие) => изменить('итог', событие.target.value)}
            />
          </Field>

          <div className="flex flex-wrap gap-2">
            <Button вид="основная" onClick={() => сохранить(false)}>
              Сохранить план
            </Button>
            <Button
              иконка={<Check size={15} />}
              onClick={() => сохранить(true)}
              disabled={!значение('итог').trim()}
            >
              Закрыть итогом
            </Button>
          </div>
        </CardBody>
      </Card>

      {тип === 'месяц' ? (
        <Card>
          <CardHeader
            заголовок="Опыт и вызов месяца"
            подпись="Ведутся в разделе «Опыт и вызовы», здесь видно, что выбрано"
          />
          <CardBody>
            {опытМесяца.length === 0 && вызовМесяца.length === 0 ? (
              <p className="text-meta text-ink-3">
                На этот месяц ничего не выбрано.
              </p>
            ) : (
              <div className="flex flex-wrap gap-1.5">
                {опытМесяца.map((о) => (
                  <Badge key={о.id} тон="знание">
                    опыт: {о.название} · {о.состояние}
                  </Badge>
                ))}
                {вызовМесяца.map((в) => (
                  <Badge key={в.id} тон={в.завершён ? 'успех' : 'внимание'}>
                    вызов: {в.название}
                  </Badge>
                ))}
              </div>
            )}
          </CardBody>
        </Card>
      ) : null}

      <Card>
        <CardHeader заголовок="Закрытые периоды" подпись={`горизонт: ${тип}`} />
        <CardBody>
          {данные.планы.filter((п) => п.тип === тип && п.закрыт).length === 0 ? (
            <p className="text-meta text-ink-3">
              Закрытых периодов нет. Период считается закрытым, когда у него есть
              итог.
            </p>
          ) : (
            <div className="space-y-2">
              {данные.планы
                .filter((п) => п.тип === тип && п.закрыт)
                .sort((а, б) => б.период.localeCompare(а.период))
                .slice(0, 8)
                .map((п) => (
                  <div
                    key={п.id}
                    className="border-b border-line pb-2 last:border-0"
                  >
                    <p className="text-meta font-medium text-ink">{п.период}</p>
                    <p className="text-caption whitespace-pre-wrap text-ink-3">
                      {п.итог}
                    </p>
                  </div>
                ))}
            </div>
          )}
        </CardBody>
      </Card>
    </div>
  )
}
