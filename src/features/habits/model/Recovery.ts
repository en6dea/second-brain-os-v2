import type { ПричинаСрываПривычки, Привычка, РольПомощника } from '@/core/db/types'
import { сдвинутьДень } from '@/core/calendar/CalendarRu'

export interface СоветВосстановления {
  роль: РольПомощника
  поддержка: string
  вопрос: string
  микрошаг: string
  минут: 2 | 5 | 10
}

function безТочки(название: string): string {
  return название.trim().replace(/[.!?]+$/u, '') || 'привычку'
}

/**
 * Помощник отвечает только на препятствие, выбранное человеком. Он не ставит
 * диагнозов, не меняет отметки и предлагает редактируемое минимальное действие.
 */
export function советВосстановления(
  причина: ПричинаСрываПривычки,
  название: string,
): СоветВосстановления {
  const действие = безТочки(название)

  if (причина === 'слишком сложно') {
    return {
      роль: 'тайм-менеджер',
      поддержка:
        'Планка оказалась выше доступного ресурса. Уменьшение шага сохраняет ритм лучше, чем попытка наверстать всё сразу.',
      вопрос: 'Какая версия будет настолько маленькой, что её трудно отложить?',
      микрошаг: `Сделать минимальную версию «${действие}»`,
      минут: 5,
    }
  }

  if (причина === 'нет опоры') {
    return {
      роль: 'тайм-менеджер',
      поддержка:
        'Привычке проще начаться после уже устойчивого события, чем по абстрактному напоминанию.',
      вопрос: 'После какого ежедневного действия её легче всего запустить?',
      микрошаг: `Выбрать одно событие-триггер для «${действие}»`,
      минут: 2,
    }
  }

  if (причина === 'нет сил') {
    return {
      роль: 'психолог',
      поддержка:
        'Низкий ресурс — ограничение сегодняшнего плана, а не характеристика вас. Возвращение может быть бережным и коротким.',
      вопрос: 'Как сохранить контакт с привычкой, не требуя от себя продолжения?',
      микрошаг: `Начать «${действие}» и остановиться через две минуты`,
      минут: 2,
    }
  }

  if (причина === 'изменился день') {
    return {
      роль: 'тайм-менеджер',
      поддержка:
        'Старое место в расписании больше не работает. Перенастроим контекст вместо того, чтобы рассчитывать на силу воли.',
      вопрос:
        'В каком реальном окне ближайшего дня есть место для маленькой версии?',
      микрошаг: `Назначить новое короткое окно для «${действие}»`,
      минут: 5,
    }
  }

  return {
    роль: 'бизнес-коуч',
    поддержка:
      'Привычка без связи с важным результатом превращается в обязанность. Сначала вернём ей смысл, затем решим, продолжать ли.',
    вопрос:
      'Какой результат в вашей жизни должна поддерживать эта привычка сейчас?',
    микрошаг: `Записать один актуальный смысл для «${действие}»`,
    минут: 5,
  }
}

/** Только видимый факт: число отметок за семь календарных дней. */
export function отметокЗаСемьДней(привычка: Привычка, день: string): number {
  let всего = 0
  for (let шаг = 0; шаг < 7; шаг += 1) {
    const дата = сдвинутьДень(день, -шаг)
    if ((привычка.отметки[дата] ?? 0) > 0) всего += 1
  }
  return всего
}
