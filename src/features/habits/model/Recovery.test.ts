import { describe, expect, it } from 'vitest'
import type { Привычка } from '@/core/db/types'
import { отметокЗаСемьДней, советВосстановления } from './Recovery'

describe('восстановление привычки', () => {
  it('не угадывает препятствие и отвечает на выбранную причину', () => {
    const совет = советВосстановления('нет сил', 'Чтение')

    expect(совет.роль).toBe('психолог')
    expect(совет.минут).toBe(2)
    expect(совет.микрошаг).toContain('Чтение')
  })

  it('считает только фактические отметки в окне из семи дней', () => {
    const привычка = {
      отметки: {
        '2026-08-26': 1,
        '2026-08-24': 1,
        '2026-08-19': 1,
      },
    } as unknown as Привычка

    expect(отметокЗаСемьДней(привычка, '2026-08-26')).toBe(2)
  })
})
