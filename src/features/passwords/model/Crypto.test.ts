import { describe, expect, it } from 'vitest'
import { вывестиКлюч, зашифровать, новаяСоль, расшифровать } from './Crypto'

describe('шифрование мастер-паролем', () => {
  it('расшифровывает то, что зашифровал тот же ключ', async () => {
    const соль = новаяСоль()
    const ключ = await вывестиКлюч('пароль-123', соль)
    const шифр = await зашифровать(ключ, 'секретный текст')
    expect(await расшифровать(ключ, шифр)).toBe('секретный текст')
  })

  it('разные вызовы дают разный вектор инициализации', async () => {
    const соль = новаяСоль()
    const ключ = await вывестиКлюч('пароль-123', соль)
    const первый = await зашифровать(ключ, 'текст')
    const второй = await зашифровать(ключ, 'текст')
    expect(первый.vector).not.toBe(второй.vector)
    expect(первый.данные).not.toBe(второй.данные)
  })

  it('тот же мастер-пароль и та же соль дают ключ, которым можно расшифровать', async () => {
    const соль = новаяСоль()
    const ключ1 = await вывестиКлюч('мастер', соль)
    const шифр = await зашифровать(ключ1, 'данные')
    const ключ2 = await вывестиКлюч('мастер', соль)
    expect(await расшифровать(ключ2, шифр)).toBe('данные')
  })

  it('неверный мастер-пароль не расшифровывает', async () => {
    const соль = новаяСоль()
    const ключВерный = await вывестиКлюч('верный', соль)
    const шифр = await зашифровать(ключВерный, 'данные')
    const ключНеверный = await вывестиКлюч('неверный', соль)
    await expect(расшифровать(ключНеверный, шифр)).rejects.toThrow()
  })

  it('разная соль при том же пароле даёт непригодный для расшифровки ключ', async () => {
    const ключ1 = await вывестиКлюч('мастер', новаяСоль())
    const шифр = await зашифровать(ключ1, 'данные')
    const ключ2 = await вывестиКлюч('мастер', новаяСоль())
    await expect(расшифровать(ключ2, шифр)).rejects.toThrow()
  })

  it('новаяСоль даёт разные значения каждый раз', () => {
    expect(новаяСоль()).not.toBe(новаяСоль())
  })
})
