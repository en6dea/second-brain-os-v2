import { create } from 'zustand'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import { вывестиКлюч, зашифровать, новаяСоль, расшифровать } from './model/Crypto'

/**
 * Ключ шифрования живёт только в памяти, только на время сессии.
 *
 * `localStorage` здесь не используется нигде — как и во всём приложении.
 * Закрытие вкладки или перезагрузка страницы сами стирают состояние: это
 * обычный модуль zustand без персистентности, а не что-то, что нужно
 * специально очищать.
 */

const ПРОВЕРОЧНЫЙ_ТЕКСТ = 'второй-мозг-пароли'

interface СессияПаролей {
  ключ: CryptoKey | null
  разблокировано: boolean
  /** Хранилище ещё не создано — первый заход в раздел. */
  создатьХранилище: (мастерПароль: string) => Promise<void>
  /** `false` — неверный мастер-пароль или хранилища ещё нет. */
  разблокировать: (мастерПароль: string) => Promise<boolean>
  заблокировать: () => void
}

export const useСессияПаролей = create<СессияПаролей>((set) => ({
  ключ: null,
  разблокировано: false,

  async создатьХранилище(мастерПароль) {
    const соль = новаяСоль()
    const ключ = await вывестиКлюч(мастерПароль, соль)
    const проверка = await зашифровать(ключ, ПРОВЕРОЧНЫЙ_ТЕКСТ)
    await база.passwordsVault.add(новаяЗапись({ соль, проверка }) as never)
    set({ ключ, разблокировано: true })
  },

  async разблокировать(мастерПароль) {
    const [конфигурация] = await база.passwordsVault.toArray()
    if (!конфигурация) return false
    try {
      const ключ = await вывестиКлюч(мастерПароль, конфигурация.соль)
      const расшифровано = await расшифровать(ключ, конфигурация.проверка)
      if (расшифровано !== ПРОВЕРОЧНЫЙ_ТЕКСТ) return false
      set({ ключ, разблокировано: true })
      return true
    } catch {
      // Неверный ключ на AES-GCM бросает исключение — это и есть честная
      // проверка мастер-пароля, отдельного хеша заводить не нужно.
      return false
    }
  },

  заблокировать() {
    set({ ключ: null, разблокировано: false })
  },
}))
