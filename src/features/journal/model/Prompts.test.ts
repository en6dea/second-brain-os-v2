import { describe, expect, it } from 'vitest'
import { другоеУтверждение, утверждениеДня, УТВЕРЖДЕНИЯ } from './Prompts'

/** Насколько сегодняшний день сдвинут от начала круга. */
function номерСмещения(дата: string): number {
  return утверждениеДня(дата, ['x']).номер - 1
}

describe('утверждениеДня', () => {
  it('одна дата всегда даёт одно утверждение', () => {
    expect(утверждениеДня('2026-08-12').текст).toBe(утверждениеДня('2026-08-12').текст)
  })

  it('соседние дни дают разные утверждения', () => {
    const дни = ['2026-08-10', '2026-08-11', '2026-08-12', '2026-08-13']
    const тексты = new Set(дни.map((день) => утверждениеДня(день).текст))
    expect(тексты.size).toBeGreaterThan(1)
  })

  it('круг проходится без повторов', () => {
    const первое = утверждениеДня('2026-08-12')
    const дни: string[] = []
    for (let шаг = 0; шаг < первое.всего; шаг += 1) {
      дни.push(другоеУтверждение('2026-08-12', [], шаг).текст)
    }
    expect(new Set(дни).size).toBe(первое.всего)
  })

  it('свои формулировки стоят в начале круга', () => {
    const своё = 'Я сегодня не сказал того, что думал.'
    const первый = другоеУтверждение('2026-08-12', [своё], -номерСмещения('2026-08-12'))
    expect(первый.текст).toBe(своё)
    expect(первый.источник).toBe('своё')
  })

  it('пустые свои строки не попадают в набор', () => {
    const итог = утверждениеДня('2026-08-12', ['', '   '])
    expect(итог.текст.trim().length).toBeGreaterThan(0)
    expect(итог.источник).toBe('набор')
    expect(итог.всего).toBe(УТВЕРЖДЕНИЯ.length)
  })

  it('сдвиг даёт другое утверждение', () => {
    const первое = утверждениеДня('2026-08-12')
    const второе = другоеУтверждение('2026-08-12', [], 1)
    expect(второе.текст).not.toBe(первое.текст)
  })

  it('в наборе нет повторов', () => {
    expect(new Set(УТВЕРЖДЕНИЯ).size).toBe(УТВЕРЖДЕНИЯ.length)
  })
})
