export interface УтверждениеДня {
  текст: string
  /** Откуда взято: своё или из набора приложения. */
  источник: 'своё' | 'набор'
  /** Номер в круге — чтобы было видно, что выбор не случаен. */
  номер: number
  всего: number
}

/** Номер дня от начала отсчёта. Одна дата — один номер, всегда. */
function номерДня(дата: string): number {
  const время = Date.parse(`${дата}T12:00:00Z`)
  return Number.isNaN(время) ? 0 : Math.floor(время / 86_400_000)
}

function собратьНабор(свои: string[]): { набор: string[]; своих: number } {
  const очищенные = свои.map((строка) => строка.trim()).filter(Boolean)
  return { набор: [...очищенные, ...УТВЕРЖДЕНИЯ], своих: очищенные.length }
}

function выбрать(набор: string[], своих: number, позиция: number): УтверждениеДня {
  const всего = набор.length
  const номер = ((позиция % всего) + всего) % всего
  return {
    текст: набор[номер] ?? '',
    источник: номер < своих ? 'своё' : 'набор',
    номер: номер + 1,
    всего,
  }
}

/**
 * Утверждение на конкретный день.
 *
 * Круг проходится подряд, а не наугад: пока набор не кончится, повторов не
 * будет. Выбор зависит только от даты — вернувшись к вчерашней записи, человек
 * увидит то же утверждение, а не новое.
 *
 * Свои формулировки стоят в начале круга: они всегда точнее общих.
 */
export function утверждениеДня(дата: string, свои: string[] = []): УтверждениеДня {
  const { набор, своих } = собратьНабор(свои)
  return выбрать(набор, своих, номерДня(дата))
}

/** Следующее утверждение, если сегодняшнее не отзывается. */
export function другоеУтверждение(
  дата: string,
  свои: string[],
  сдвиг: number,
): УтверждениеДня {
  const { набор, своих } = собратьНабор(свои)
  return выбрать(набор, своих, номерДня(дата) + сдвиг)
}
