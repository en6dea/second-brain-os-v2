import { describe, expect, it } from 'vitest'
import { наблюденияПоНастроению } from './MoodTrend'
import { сдвинутьДень } from '@/core/calendar/CalendarRu'
import type { ЗаписьДневника } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'
const день = '2026-08-17'

function запись(изменения: Partial<ЗаписьДневника> = {}): ЗаписьДневника {
  return {
    id: 'з' + Math.random(),
    createdAt: момент,
    updatedAt: момент,
    дата: день,
    вид: 'день',
    заголовок: '',
    текст: 'текст',
    настроение: null,
    сон: null,
    личное: false,
    утверждение: '',
    чтоЧувствую: '',
    чтоДумаю: '',
    согласие: null,
    ...изменения,
  }
}

/** N записей с одним значением настроения, начиная со сдвига `от` дней назад. */
function сериюЗаписей(
  количество: number,
  сдвигОт: number,
  настроение: number,
): ЗаписьДневника[] {
  return Array.from({ length: количество }, (_, шаг) =>
    запись({ дата: сдвинутьДень(день, -(сдвигОт + шаг)), настроение }),
  )
}

describe('наблюденияПоНастроению', () => {
  it('мало записей в недавнем окне — молчит', () => {
    const записи = [
      ...сериюЗаписей(2, 0, 3),
      ...сериюЗаписей(10, 10, 8),
    ]
    expect(наблюденияПоНастроению(записи, день)).toHaveLength(0)
  })

  it('мало записей в базовом окне — молчит', () => {
    const записи = [
      ...сериюЗаписей(6, 0, 3),
      ...сериюЗаписей(2, 10, 8),
    ]
    expect(наблюденияПоНастроению(записи, день)).toHaveLength(0)
  })

  it('разница меньше порога — молчит', () => {
    const записи = [
      ...сериюЗаписей(6, 0, 7),
      ...сериюЗаписей(10, 10, 7.5),
    ]
    expect(наблюденияПоНастроению(записи, день)).toHaveLength(0)
  })

  it('настроение выросло — молчит: это не про рапорт об успехах', () => {
    const записи = [
      ...сериюЗаписей(6, 0, 8),
      ...сериюЗаписей(10, 10, 4),
    ]
    expect(наблюденияПоНастроению(записи, день)).toHaveLength(0)
  })

  it('заметное снижение — сообщает с точными числами', () => {
    const записи = [
      ...сериюЗаписей(6, 0, 3),
      ...сериюЗаписей(10, 10, 7),
    ]
    const итог = наблюденияПоНастроению(записи, день)
    expect(итог).toHaveLength(1)
    expect(итог[0]).toContain('3.0')
    expect(итог[0]).toContain('7.0')
    expect(итог[0]).toContain('не диагноз')
  })

  it('записи без настроения не считаются', () => {
    const записи = [
      ...сериюЗаписей(6, 0, 3),
      ...сериюЗаписей(10, 10, 7),
      ...Array.from({ length: 5 }, () => запись({ настроение: null })),
    ]
    expect(наблюденияПоНастроению(записи, день)).toHaveLength(1)
  })
})
