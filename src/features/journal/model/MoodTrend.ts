import type { ДатаДень, ЗаписьДневника } from '@/core/db/types'
import { склонение } from '@/core/language/Plural'

/**
 * Честное наблюдение по настроению.
 *
 * Тот же принцип, что и в `наблюдения()` для цикла в разделе «Отношения»:
 * сравнение двух средних по числовой шкале, порог минимума записей, и
 * только про то, что видно из чисел — не диагноз и не причина. Настроение
 * записывается по шкале 1–10 (`ЗаписьДневника.настроение`), не свободным
 * текстом, поэтому тренд по нему честен.
 *
 * Срабатывает только на ухудшение: это забота, а не рапорт об успехах —
 * рост настроения не обязан ничего «объяснять».
 */

const ОКНО_НЕДАВНИХ_ДНЕЙ = 7
const ОКНО_БАЗОВЫХ_ДНЕЙ = 30
const МИНИМУМ_ЗАПИСЕЙ = 5
const ПОРОГ_РАЗНИЦЫ = 1.5

function разностьДней(от: ДатаДень, до: ДатаДень): number {
  const начало = new Date(`${от}T00:00:00`)
  const конец = new Date(`${до}T00:00:00`)
  return Math.round((конец.getTime() - начало.getTime()) / 86_400_000)
}

function среднее(записи: ЗаписьДневника[]): number {
  return записи.reduce((сумма, з) => сумма + (з.настроение ?? 0), 0) / записи.length
}

export function наблюденияПоНастроению(
  записи: ЗаписьДневника[],
  сегодня: ДатаДень,
): string[] {
  const сОценкой = записи.filter((з) => з.настроение !== null)

  const недавние = сОценкой.filter((з) => {
    const сдвиг = разностьДней(з.дата, сегодня)
    return сдвиг >= 0 && сдвиг < ОКНО_НЕДАВНИХ_ДНЕЙ
  })
  const базовые = сОценкой.filter((з) => {
    const сдвиг = разностьДней(з.дата, сегодня)
    return сдвиг >= ОКНО_НЕДАВНИХ_ДНЕЙ && сдвиг < ОКНО_НЕДАВНИХ_ДНЕЙ + ОКНО_БАЗОВЫХ_ДНЕЙ
  })

  if (недавние.length < МИНИМУМ_ЗАПИСЕЙ || базовые.length < МИНИМУМ_ЗАПИСЕЙ) return []

  const среднееНедавних = среднее(недавние)
  const среднееБазовых = среднее(базовые)
  const разница = среднееБазовых - среднееНедавних

  if (разница < ПОРОГ_РАЗНИЦЫ) return []

  return [
    `Настроение за последние ${недавние.length} ${склонение(недавние.length, 'запись', 'записи', 'записей')} в среднем ${среднееНедавних.toFixed(1)} из 10 — ` +
      `ниже, чем ${среднееБазовых.toFixed(1)} за предыдущие ${базовые.length} ${склонение(базовые.length, 'запись', 'записи', 'записей')}. ` +
      `Это числа по вашим отметкам, не диагноз и не причина сама по себе.`,
  ]
}
