import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import { сейчас } from '@/core/db/RecordId'
import type { Замысел, ПунктЗамысла } from '@/core/db/types'

/**
 * Задача из пункта замысла — мост «замысел → реальное действие».
 *
 * Пункт остаётся в замысле, но получает `задачаId`: кнопка в диалоге
 * переключается на «в задачах» и не создаёт дубль при повторном нажатии.
 * Вызывается из двух мест (Планер и совместные планы в «Отношениях») —
 * оба замысла живут в одной таблице, мост один и тот же.
 */
export async function создатьЗадачуИзПункта(
  замысел: Замысел,
  пункт: ПунктЗамысла,
): Promise<string> {
  const задача = новаяЗапись({
    название: пункт.название,
    заметка: '',
    дата: пункт.срок,
    время: null,
    длительностьМинут: null,
    состояние: 'новая',
    важность: 'обычная',
    проектId: null,
    цельId: замысел.цельId,
    сфераId: null,
    выполненаВ: null,
    переносов: 0,
    повтор: null,
  })
  await база.tasks.add(задача as never)

  const текущий = await база.intentions.get(замысел.id)
  if (текущий) {
    await база.intentions.put({
      ...текущий,
      пункты: текущий.пункты.map((п) =>
        п.id === пункт.id ? { ...п, задачаId: задача.id } : п,
      ),
      updatedAt: сейчас(),
    })
  }

  return задача.id
}
