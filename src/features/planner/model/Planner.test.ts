import { describe, expect, it } from 'vitest'
import {
  замыслыПериода,
  откладыватьВНеделю,
  подсказкиПунктов,
  свестиЗамысел,
  следующийПункт,
} from './Planner'
import type { Замысел, ПунктЗамысла } from '@/core/db/types'
import { сдвинутьДень, сегодня } from '@/core/calendar/CalendarRu'

const момент = '2026-08-01T10:00:00.000Z'

function пункт(изменения: Partial<ПунктЗамысла> = {}): ПунктЗамысла {
  return {
    id: Math.random().toString(36),
    название: 'Пункт',
    выполнен: false,
    срок: null,
    стоимость: null,
    заметка: '',
    ...изменения,
  }
}

function замысел(изменения: Partial<Замысел> = {}): Замысел {
  return {
    id: 'з',
    createdAt: момент,
    updatedAt: момент,
    название: 'Поездка в Карелию',
    вид: 'поездка',
    зачем: 'Давно обещали себе вырваться на неделю',
    состояние: 'готовлюсь',
    датаЦели: сдвинутьДень(сегодня(), 70),
    датаОкончания: null,
    бюджет: 12000000,
    отложено: 4000000,
    пункты: [],
    вдвоём: false,
    сфераId: null,
    цельId: null,
    заметка: '',
    итог: '',
    ...изменения,
  }
}

describe('подсказкиПунктов', () => {
  it('для поездки предлагает то, о чём забывают', () => {
    const подсказки = подсказкиПунктов('поездка', [])
    expect(подсказки.some((текст) => текст.includes('страховк'))).toBe(true)
  })

  it('уже добавленное второй раз не предлагается', () => {
    const первый = подсказкиПунктов('поездка', [])[0] ?? ''
    const второй = подсказкиПунктов('поездка', [первый])
    expect(второй).not.toContain(первый)
  })

  it('разные виды дают разные списки', () => {
    expect(подсказкиПунктов('покупка', [])).not.toEqual(подсказкиПунктов('поездка', []))
  })
})

describe('свестиЗамысел', () => {
  it('без пунктов готовность не считается, а не равна нулю', () => {
    const сводка = свестиЗамысел(замысел())
    expect(сводка.готовность).toBeNull()
    expect(сводка.замечания[0]).toContain('Ни одного пункта')
  })

  it('готовность считается по выполненным пунктам', () => {
    const сводка = свестиЗамысел(
      замысел({
        пункты: [пункт({ выполнен: true }), пункт(), пункт(), пункт()],
      }),
    )
    expect(сводка.готовность).toBe(25)
  })

  it('пункты без цены не считаются нулём и видны отдельно', () => {
    const сводка = свестиЗамысел(
      замысел({
        пункты: [пункт({ стоимость: 500000 }), пункт(), пункт()],
      }),
    )
    expect(сводка.посчитаноПоПунктам).toBe(500000)
    expect(сводка.пунктовБезЦены).toBe(2)
  })

  it('когда цены нет ни у одного пункта, суммы нет', () => {
    const сводка = свестиЗамысел(замысел({ пункты: [пункт(), пункт()] }))
    expect(сводка.посчитаноПоПунктам).toBeNull()
    expect(сводка.остатокБюджета).toBeNull()
  })

  it('превышение бюджета замечается', () => {
    const сводка = свестиЗамысел(
      замысел({ бюджет: 100000, пункты: [пункт({ стоимость: 300000 })] }),
    )
    expect(сводка.остатокБюджета).toBe(-200000)
    expect(сводка.замечания.some((текст) => текст.includes('больше бюджета'))).toBe(true)
  })

  it('пункт со сроком позже даты замысла попадает в замечания', () => {
    const сводка = свестиЗамысел(
      замысел({
        датаЦели: сдвинутьДень(сегодня(), 10),
        пункты: [пункт({ срок: сдвинутьДень(сегодня(), 30) })],
      }),
    )
    expect(сводка.просроченныеПункты).toBe(1)
  })

  it('прошедшая дата у незакрытого замысла — замечание', () => {
    const сводка = свестиЗамысел(
      замысел({ датаЦели: сдвинутьДень(сегодня(), -5), пункты: [пункт()] }),
    )
    expect(сводка.замечания.some((текст) => текст.includes('прошла'))).toBe(true)
  })

  it('у закрытого замысла прошедшая дата замечанием не является', () => {
    const сводка = свестиЗамысел(
      замысел({
        состояние: 'сделано',
        датаЦели: сдвинутьДень(сегодня(), -5),
        пункты: [пункт({ выполнен: true })],
      }),
    )
    expect(сводка.замечания.some((текст) => текст.includes('прошла'))).toBe(false)
  })
})

describe('откладыватьВНеделю', () => {
  it('без бюджета ответа нет', () => {
    expect(откладыватьВНеделю(замысел({ бюджет: null }))).toBeNull()
  })

  it('без даты ответа нет', () => {
    expect(откладыватьВНеделю(замысел({ датаЦели: null }))).toBeNull()
  })

  it('считает по остатку и числу недель', () => {
    const итог = откладыватьВНеделю(
      замысел({ бюджет: 1000000, отложено: 0, датаЦели: сдвинутьДень(сегодня(), 70) }),
    )
    // 70 дней — десять недель, значит по 1000 ₽ в неделю.
    expect(итог).toBe(100000)
  })

  it('когда отложено достаточно, откладывать больше нечего', () => {
    expect(
      откладыватьВНеделю(замысел({ бюджет: 100000, отложено: 200000 })),
    ).toBe(0)
  })
})

describe('следующийПункт', () => {
  it('берёт первый невыполненный', () => {
    const итог = следующийПункт(
      замысел({
        пункты: [
          пункт({ название: 'Купить билеты', выполнен: true }),
          пункт({ название: 'Оформить страховку' }),
        ],
      }),
    )
    expect(итог).toBe('Оформить страховку')
  })

  it('когда всё сделано, шага нет', () => {
    expect(следующийПункт(замысел({ пункты: [пункт({ выполнен: true })] }))).toBeNull()
  })
})

describe('замыслыПериода', () => {
  it('замысел без даты ни в один период не попадает', () => {
    const без = замысел({ датаЦели: null })
    expect(замыслыПериода([без], '2026-01-01', '2026-12-31')).toEqual([])
  })

  it('границы периода включаются', () => {
    const наГранице = замысел({ датаЦели: '2026-08-10' })
    expect(замыслыПериода([наГранице], '2026-08-10', '2026-08-16')).toHaveLength(1)
    expect(замыслыПериода([наГранице], '2026-08-11', '2026-08-16')).toHaveLength(0)
  })
})
