export function подсказкиПунктов(вид: ВидЗамысла, уже: string[]): string[] {
  const имеющиеся = new Set(
    уже.map((строка) => строка.toLowerCase().replace(/ё/g, 'е').trim()),
  )
  return (ПОДСКАЗКИ[вид] ?? []).filter(
    (пункт) => !имеющиеся.has(пункт.toLowerCase().replace(/ё/g, 'е')),
  )
}

export interface СводкаЗамысла {
  всегоПунктов: number
  выполнено: number
  /** Доля выполненного от 0 до 100. `null` — пунктов нет, считать нечего. */
  готовность: number | null

  /** Сумма стоимостей пунктов. `null` — ни у одного пункта цены нет. */
  посчитаноПоПунктам: Копейки | null
  /** У скольких пунктов цена не указана. */
  пунктовБезЦены: number
  /** Бюджет минус посчитанное. `null` — бюджета или расчёта нет. */
  остатокБюджета: Копейки | null
  /** Сколько ещё отложить до бюджета. `null` — бюджет неизвестен. */
  осталосьОтложить: Копейки | null

  днейДоЦели: number | null
  /** Пункты со сроком позже даты замысла. */
  просроченныеПункты: number
  /** Что мешает считать замысел готовым. Пусто — всё в порядке. */
  замечания: string[]
}

export function свестиЗамысел(замысел: Замысел): СводкаЗамысла {
  const всегоПунктов = замысел.пункты.length
  const выполнено = замысел.пункты.filter((пункт) => пункт.выполнен).length

  const сЦеной = замысел.пункты.filter((пункт) => пункт.стоимость !== null)
  const посчитаноПоПунктам =
    сЦеной.length === 0
      ? null
      : сЦеной.reduce((сумма, пункт) => сумма + (пункт.стоимость ?? 0), 0)

  const остатокБюджета =
    замысел.бюджет === null || посчитаноПоПунктам === null
      ? null
      : замысел.бюджет - посчитаноПоПунктам

  const осталосьОтложить =
    замысел.бюджет === null ? null : замысел.бюджет - (замысел.отложено ?? 0)

  const дней = замысел.датаЦели === null ? null : днейДо(замысел.датаЦели)

  const просроченныеПункты = замысел.пункты.filter(
    (пункт) =>
      !пункт.выполнен &&
      пункт.срок !== null &&
      замысел.датаЦели !== null &&
      пункт.срок > замысел.датаЦели,
  ).length

  const замечания: string[] = []

  if (всегоПунктов === 0) {
    замечания.push('Ни одного пункта. Замысел без списка остаётся намерением.')
  }
  if (замысел.зачем.trim().length < 5) {
    замечания.push('Не записано, зачем это нужно.')
  }
  if (замысел.датаЦели === null) {
    замечания.push('Нет даты. Без неё замысел не начинается.')
  } else if (дней !== null && дней < 0 && замысел.состояние !== 'сделано') {
    замечания.push(
      `Дата прошла ${Math.abs(дней)} дней назад, а замысел не закрыт. Перенесите или закройте.`,
    )
  }
  if (остатокБюджета !== null && остатокБюджета < 0) {
    замечания.push('Сумма пунктов больше бюджета.')
  }
  if (просроченныеПункты > 0) {
    замечания.push(
      `${просроченныеПункты} ${просроченныеПункты === 1 ? 'пункт' : 'пунктов'} со сроком позже самой даты замысла.`,
    )
  }

  return {
    всегоПунктов,
    выполнено,
    готовность:
      всегоПунктов === 0 ? null : Math.round((выполнено / всегоПунктов) * 100),
    посчитаноПоПунктам,
    пунктовБезЦены: всегоПунктов - сЦеной.length,
    остатокБюджета,
    осталосьОтложить,
    днейДоЦели: дней,
    просроченныеПункты,
    замечания,
  }
}

/**
 * Сколько откладывать в неделю, чтобы успеть к дате.
 *
 * Считается только когда известны все три величины. Ни одной из них
 * приложение не придумывает: без бюджета или без даты ответа нет.
 */
export function откладыватьВНеделю(замысел: Замысел): Копейки | null {
  if (замысел.бюджет === null) return null
  const дней = замысел.датаЦели === null ? null : днейДо(замысел.датаЦели)
  if (дней === null || дней <= 0) return null
  const осталось = замысел.бюджет - (замысел.отложено ?? 0)
  if (осталось <= 0) return 0
  const недель = Math.max(1, Math.ceil(дней / 7))
  return Math.ceil(осталось / недель)
}

/** Следующий невыполненный пункт — то, за что браться прямо сейчас. */
export function следующийПункт(замысел: Замысел): string | null {
  const пункт = замысел.пункты.find((элемент) => !элемент.выполнен)
  return пункт?.название ?? null
}
