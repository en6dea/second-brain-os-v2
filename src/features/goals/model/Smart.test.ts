import { describe, expect, it } from 'vitest'
import { разобратьПоSMART, самаяНеготовая } from './Smart'
import type { Цель } from '@/core/db/types'
import { сдвинутьДень, сегодня } from '@/core/calendar/CalendarRu'

const момент = '2026-08-01T10:00:00.000Z'

function цель(изменения: Partial<Цель> = {}): Цель {
  return {
    id: 'ц',
    createdAt: момент,
    updatedAt: момент,
    название: 'Пробежать полумарафон за два часа',
    зачем: 'Хочу вернуть форму и доказать себе, что довожу до конца',
    сфераId: null,
    состояние: 'активна',
    срок: сдвинутьДень(сегодня(), 90),
    цель: 21,
    текущее: 5,
    единица: 'км',
    порядок: 0,
    вехи: [{ id: 'в', название: 'Пробежать 10 км', срок: null, выполнена: false }],
    последняяАктивность: null,
    постер: '',
    ...изменения,
  }
}

describe('разобратьПоSMART', () => {
  it('полная цель проходит все пять критериев', () => {
    const разбор = разобратьПоSMART(цель())
    expect(разбор.выполнено).toBe(5)
    expect(разбор.готова).toBe(true)
  })

  it('расплывчатое название не считается конкретным', () => {
    const разбор = разобратьПоSMART(цель({ название: 'Улучшить здоровье' }))
    const критерий = разбор.критерии.find((к) => к.ключ === 'конкретность')
    expect(критерий?.выполнен).toBe(false)
    expect(критерий?.замечание).toContain('улучшить')
  })

  it('цель без числа не измерима', () => {
    const разбор = разобратьПоSMART(цель({ цель: null }))
    expect(разбор.критерии.find((к) => к.ключ === 'измеримость')?.выполнен).toBe(false)
  })

  it('ноль как целевое значение — это число, а не пропуск', () => {
    const разбор = разобратьПоSMART(цель({ цель: 0 }))
    expect(разбор.критерии.find((к) => к.ключ === 'измеримость')?.выполнен).toBe(true)
  })

  it('цель без вех не считается разбитой на части', () => {
    const разбор = разобратьПоSMART(цель({ вехи: [] }))
    expect(разбор.критерии.find((к) => к.ключ === 'достижимость')?.выполнен).toBe(false)
  })

  it('короткое «зачем» не засчитывается', () => {
    const разбор = разобратьПоSMART(цель({ зачем: 'надо' }))
    expect(разбор.критерии.find((к) => к.ключ === 'значимость')?.выполнен).toBe(false)
  })

  it('просроченный срок отмечается прямо', () => {
    const разбор = разобратьПоSMART(цель({ срок: сдвинутьДень(сегодня(), -10) }))
    const критерий = разбор.критерии.find((к) => к.ключ === 'срок')
    expect(критерий?.замечание).toContain('прошёл')
  })
})

describe('следующий шаг', () => {
  it('чинит первый проваленный критерий, а не последний', () => {
    const разбор = разобратьПоSMART(
      цель({ название: 'Улучшить сон', цель: null, вехи: [] }),
    )
    expect(разбор.следующийШаг).toContain('название')
  })

  it('у готовой цели ведёт к ближайшей невыполненной вехе', () => {
    const разбор = разобратьПоSMART(цель())
    expect(разбор.следующийШаг).toContain('Пробежать 10 км')
  })
})

describe('самаяНеготовая', () => {
  it('без целей возвращает ничего', () => {
    expect(самаяНеготовая([])).toBeNull()
  })

  it('когда все цели готовы, придираться не к чему', () => {
    expect(самаяНеготовая([цель()])).toBeNull()
  })

  it('находит цель с наименьшим числом выполненных критериев', () => {
    const слабая = цель({
      id: 'слабая',
      название: 'Начать',
      зачем: '',
      цель: null,
      срок: null,
      вехи: [],
    })
    const итог = самаяНеготовая([цель(), слабая])
    expect(итог?.цель.id).toBe('слабая')
    expect(итог?.разбор.выполнено).toBe(0)
  })

  it('отложенные цели не разбираются', () => {
    const отложена = цель({ id: 'о', состояние: 'отложена', зачем: '', цель: null })
    expect(самаяНеготовая([отложена])).toBeNull()
  })
})
