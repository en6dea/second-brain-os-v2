import { describe, expect, it } from 'vitest'
import type { Задача, Цель } from '@/core/db/types'
import { прогрессМиссии, следующийХодМиссии } from './Campaign'

function цель(изменения: Partial<Цель> = {}): Цель {
  return {
    id: 'цель',
    createdAt: '2026-08-24T08:00:00.000Z',
    updatedAt: '2026-08-24T08:00:00.000Z',
    название: 'Создать капитал',
    зачем: '',
    сфераId: null,
    состояние: 'активна',
    срок: null,
    цель: null,
    текущее: null,
    единица: '',
    порядок: 0,
    вехи: [],
    последняяАктивность: null,
    постер: '',
    ...изменения,
  }
}

function задача(изменения: Partial<Задача> = {}): Задача {
  return {
    id: 'задача',
    createdAt: '2026-08-24T08:00:00.000Z',
    updatedAt: '2026-08-24T08:00:00.000Z',
    название: 'Следующий ход',
    заметка: '',
    дата: null,
    время: null,
    длительностьМинут: null,
    состояние: 'новая',
    важность: 'обычная',
    проектId: null,
    цельId: 'цель',
    сфераId: null,
    выполненаВ: null,
    переносов: 0,
    повтор: null,
    ...изменения,
  }
}

describe('прогрессМиссии', () => {
  it('считает результат по показателю', () => {
    expect(прогрессМиссии(цель({ текущее: 25, цель: 100 }))).toEqual(
      expect.objectContaining({ источник: 'показатель', значение: 25 }),
    )
  })

  it('использует вехи, если числового результата нет', () => {
    const итог = прогрессМиссии(
      цель({
        вехи: [
          { id: '1', название: 'Первая', срок: null, выполнена: true },
          { id: '2', название: 'Вторая', срок: null, выполнена: false },
        ],
      }),
    )
    expect(итог).toEqual({ источник: 'вехи', значение: 50, выполнено: 1, всего: 2 })
  })

  it('не выдаёт выполненные задачи за процент результата', () => {
    expect(прогрессМиссии(цель()).значение).toBeNull()
  })
})

describe('следующийХодМиссии', () => {
  it('выбирает ближайшую открытую задачу и честно считает время', () => {
    const итог = следующийХодМиссии('цель', [
      задача({ id: 'позже', дата: '2026-08-30', длительностьМинут: 40 }),
      задача({ id: 'раньше', дата: '2026-08-25', длительностьМинут: null }),
      задача({ id: 'сделано', состояние: 'сделана', длительностьМинут: 999 }),
    ])

    expect(итог.задача?.id).toBe('раньше')
    expect(итог.минутИзвестно).toBe(40)
    expect(итог.задачБезВремени).toBe(1)
    expect(итог.открытыхЗадач).toBe(2)
  })

  it('при одинаковой дате выбирает более важную задачу', () => {
    const итог = следующийХодМиссии('цель', [
      задача({ id: 'обычная', дата: '2026-08-25', важность: 'обычная' }),
      задача({ id: 'важная', дата: '2026-08-25', важность: 'высокая' }),
    ])

    expect(итог.задача?.id).toBe('важная')
  })
})
