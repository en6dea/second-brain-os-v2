import type { Задача, ПульсЦели, РефлексияЦели, Цель } from '@/core/db/types'
import { границыНедели } from '@/core/calendar/CalendarRu'

export interface ЧерновикРефлексииЦели {
  период: string
  пульс: ПульсЦели
  победа: string
  препятствие: string
  вывод: string
  следующийШаг: string
  значение: number | null
}

export interface СоветЦели {
  основание: string
  психолог: string
  бизнесКоуч: string
  таймМенеджер: string
}

export interface ДинамикаЦели {
  последнее: number
  предыдущее: number | null
  изменение: number | null
}

/** Последняя обновлённая рефлексия, независимо от порядка массива. */
export function последняяРефлексияЦели(цель: Цель): РефлексияЦели | null {
  return (
    [...(цель.рефлексии ?? [])].sort((а, б) =>
      б.updatedAt.localeCompare(а.updatedAt),
    )[0] ?? null
  )
}

export function рефлексияЦелиЗаПериод(
  цель: Цель,
  период: string,
): РефлексияЦели | null {
  return (цель.рефлексии ?? []).find((запись) => запись.период === период) ?? null
}

/** Динамика строится только из известных чисел; `null` не считается нулём. */
export function динамикаЦели(цель: Цель): ДинамикаЦели | null {
  const известные = (цель.историяПрогресса ?? [])
    .filter(
      (запись): запись is typeof запись & { значение: number } =>
        запись.значение !== null && Number.isFinite(запись.значение),
    )
    .sort((а, б) => а.createdAt.localeCompare(б.createdAt))
  const последнее = известные.at(-1)
  if (!последнее) return null
  const предыдущее = известные.at(-2)?.значение ?? null
  return {
    последнее: последнее.значение,
    предыдущее,
    изменение: предыдущее === null ? null : последнее.значение - предыдущее,
  }
}

/**
 * Сохраняет один недельный разбор и при необходимости новый замер прогресса.
 * Повторное сохранение той же недели обновляет запись, а не создаёт дубль.
 */
export function применитьРефлексиюЦели({
  цель,
  черновик,
  момент,
  рефлексияId,
  прогрессId,
}: {
  цель: Цель
  черновик: ЧерновикРефлексииЦели
  момент: string
  рефлексияId: string
  прогрессId: string
}): { цель: Цель; рефлексия: РефлексияЦели } {
  const существующая = рефлексияЦелиЗаПериод(цель, черновик.период)
  const рефлексия: РефлексияЦели = {
    id: существующая?.id ?? рефлексияId,
    createdAt: существующая?.createdAt ?? момент,
    updatedAt: момент,
    период: черновик.период,
    пульс: черновик.пульс,
    победа: черновик.победа.trim(),
    препятствие: черновик.препятствие.trim(),
    вывод: черновик.вывод.trim(),
    следующийШаг: черновик.следующийШаг.trim(),
    задачаId:
      существующая?.следующийШаг.trim() === черновик.следующийШаг.trim()
        ? (существующая.задачаId ?? null)
        : null,
  }

  const рефлексии = (цель.рефлексии ?? []).filter(
    (запись) => запись.период !== черновик.период,
  )
  рефлексии.push(рефлексия)

  const историяПрогресса = [...(цель.историяПрогресса ?? [])]
  const последнее = [...историяПрогресса]
    .sort((а, б) => а.createdAt.localeCompare(б.createdAt))
    .at(-1)
  const показательОпределён = цель.цель !== null && цель.цель > 0
  const новоеЗначение = показательОпределён ? черновик.значение : null
  if (
    новоеЗначение !== null &&
    Number.isFinite(новоеЗначение) &&
    (последнее === undefined || последнее.значение !== новоеЗначение)
  ) {
    историяПрогресса.push({
      id: прогрессId,
      createdAt: момент,
      значение: новоеЗначение,
      заметка: черновик.победа.trim() || черновик.вывод.trim(),
    })
  }

  return {
    цель: {
      ...цель,
      текущее: новоеЗначение ?? цель.текущее,
      историяПрогресса,
      рефлексии,
      последняяАктивность: момент,
      updatedAt: момент,
    },
    рефлексия,
  }
}

/**
 * Три прозрачные точки зрения. Основание — выбранный человеком пульс и
 * связанные задачи; приложение не выводит психологический диагноз.
 */
export function советПоЦели({
  цель,
  задачи,
  пульс,
  день,
}: {
  цель: Цель
  задачи: Задача[]
  пульс: ПульсЦели
  день: string
}): СоветЦели {
  const границы = границыНедели(день)
  const связанные = задачи.filter((задача) => задача.цельId === цель.id)
  const открытые = связанные.filter(
    (задача) => задача.состояние !== 'сделана' && задача.состояние !== 'отменена',
  )
  const сделаноЗаНеделю = связанные.filter((задача) => {
    const дата = задача.выполненаВ?.slice(0, 10)
    return дата !== undefined && дата >= границы.от && дата <= границы.до
  }).length
  const повторноПеренесено = открытые.filter(
    (задача) => задача.переносов >= 2,
  ).length
  const основание = `${сделаноЗаНеделю} завершено за неделю · ${открытые.length} открыто · ${повторноПеренесено} переносилось 2+ раза`

  if (пульс === 'движется') {
    return {
      основание,
      психолог:
        'Заметьте, что именно поддержало движение. Это поможет опираться на рабочие условия, а не только на силу воли.',
      бизнесКоуч:
        'Зафиксируйте один видимый результат следующей недели — не список активности, а проверяемое изменение.',
      таймМенеджер:
        'Защитите следующий шаг отдельным блоком времени, пока неделя ещё не заполнилась случайными делами.',
    }
  }

  if (пульс === 'пересмотреть') {
    return {
      основание,
      психолог:
        'Разрешите себе проверить актуальность цели без самообвинения: отказ от чужой или устаревшей цели тоже освобождает ресурс.',
      бизнесКоуч:
        'Сравните ожидаемый результат с ценой времени. Решение недели — продолжить, изменить критерий или осознанно отложить.',
      таймМенеджер:
        'Не добавляйте новые задачи, пока не выбрано решение по самой цели. Иначе календарь будет обслуживать неопределённость.',
    }
  }

  const нетХода = открытые.length === 0
  const естьПереносы = повторноПеренесено > 0
  return {
    основание,
    психолог: естьПереносы
      ? 'Повторный перенос может означать, что шаг слишком тяжёлый или эмоционально неприятный. Назовите препятствие своими словами — это не диагноз.'
      : 'Отделите факт от самооценки: цель застряла, но это ничего не говорит о вас как о человеке. Что именно сейчас неясно или тяжело?',
    бизнесКоуч: нетХода
      ? 'У цели нет открытого хода. Сформулируйте минимальный результат, после которого станет понятно, что движение началось.'
      : 'Выберите одно ограничение, которое сильнее всего тормозит результат, и решение только для него.',
    таймМенеджер: естьПереносы
      ? 'Уменьшите следующий шаг до 15–25 минут и назначьте конкретный день. Большой переносимый пункт не становится реальнее от новой даты.'
      : 'Подготовьте один физический шаг на 25 минут. Задача появится только после отдельного подтверждения.',
  }
}
