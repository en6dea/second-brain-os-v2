import type { Цель } from '@/core/db/types'
import { днейДо } from '@/core/calendar/CalendarRu'

/**
 * Разбор цели по SMART.
 *
 * Здесь нет искусственного интеллекта, и это осознанно: настоящий означал бы
 * отправку ваших целей на чужой сервер. Разбор построен на самих полях цели,
 * и каждый вывод показывает, из какого поля он получен.
 *
 * Смысл разбора не в оценке, а в одном вопросе: что именно мешает начать.
 * Прокрастинация чаще всего означает не лень, а нерешённость — цель звучит
 * как намерение, а не как действие, и мозгу не за что взяться.
 */

export type КритерийКлюч = 'конкретность' | 'измеримость' | 'достижимость' | 'значимость' | 'срок'

export interface Критерий {
  ключ: КритерийКлюч
  название: string
  /** Выполнен ли критерий. */
  выполнен: boolean
  /** Что именно не так и что с этим делать. */
  замечание: string
  /** Из какого поля цели сделан вывод. */
  поле: string
}

export interface РазборSMART {
  критерии: Критерий[]
  выполнено: number
  всего: number
  /**
   * Первый шаг, который стоит сделать. Это не совет вообще, а действие,
   * выведенное из первого невыполненного критерия.
   */
  следующийШаг: string
  /** Готова ли цель к работе: провалов нет. */
  готова: boolean
}

/** Слова, за которыми обычно прячется намерение вместо действия. */
const РАСПЛЫВЧАТЫЕ = [
  'улучшить',
  'наладить',
  'подтянуть',
  'разобраться',
  'начать',
  'больше',
  'меньше',
  'лучше',
  'регулярно',
  'постараться',
  'попробовать',
]

function расплывчато(название: string): boolean {
  const текст = название.toLowerCase().replace(/ё/g, 'е')
  return РАСПЛЫВЧАТЫЕ.some((слово) => текст.includes(слово))
}

export function разобратьПоSMART(цель: Цель): РазборSMART {
  const название = цель.название.trim()
  const слов = название.split(/\s+/).filter(Boolean).length

  const критерии: Критерий[] = [
    {
      ключ: 'конкретность',
      название: 'Конкретная',
      выполнен: слов >= 3 && !расплывчато(название),
      замечание: расплывчато(название)
        ? 'В названии есть слово вроде «улучшить» или «начать». По нему не видно, что именно вы сделаете. Замените на действие: не «наладить сон», а «ложиться до 23:30».'
        : слов < 3
          ? 'Название из одного-двух слов. Допишите, что именно должно произойти.'
          : 'Название называет действие, а не намерение.',
      поле: 'название',
    },
    {
      ключ: 'измеримость',
      название: 'Измеримая',
      выполнен: цель.цель !== null,
      замечание:
        цель.цель !== null
          ? `Есть число: ${цель.цель} ${цель.единица || 'единиц'}. Прогресс будет видно.`
          : 'Нет числа, по которому видно движение. Поставьте целевое значение — иначе «сделано» и «не сделано» решается настроением.',
      поле: 'цель',
    },
    {
      ключ: 'достижимость',
      название: 'Достижимая',
      выполнен: цель.вехи.length > 0,
      замечание:
        цель.вехи.length > 0
          ? `Разбита на ${цель.вехи.length} ${цель.вехи.length === 1 ? 'веху' : 'вех'} — есть с чего начать.`
          : 'Нет ни одной вехи. Большая цель без первого куска откладывается лучше всего — разбейте её хотя бы на две части.',
      поле: 'вехи',
    },
    {
      ключ: 'значимость',
      название: 'Значимая',
      выполнен: цель.зачем.trim().length >= 10,
      замечание:
        цель.зачем.trim().length >= 10
          ? 'Записано, зачем она вам. В трудный день это единственное, что работает.'
          : 'Не записано, зачем эта цель. Без ответа на «зачем» первая же занятая неделя её вытеснит.',
      поле: 'зачем',
    },
    {
      ключ: 'срок',
      название: 'Со сроком',
      выполнен: цель.срок !== null,
      замечание: срокЗамечание(цель),
      поле: 'срок',
    },
  ]

  const выполнено = критерии.filter((критерий) => критерий.выполнен).length

  return {
    критерии,
    выполнено,
    всего: критерии.length,
    следующийШаг: следующийШаг(цель, критерии),
    готова: выполнено === критерии.length,
  }
}

function срокЗамечание(цель: Цель): string {
  if (цель.срок === null) {
    return 'Нет срока. Цель без даты не начинается никогда — поставьте день, к которому хотите её закрыть.'
  }
  const дней = днейДо(цель.срок)
  if (дней === null) return 'Срок поставлен.'
  if (дней < 0) return `Срок прошёл ${Math.abs(дней)} дней назад. Перенесите его или закройте цель — просроченная цель давит и ничего не двигает.`
  if (дней > 365) return `До срока ${дней} дней. Это далеко: поставьте промежуточную веху на ближайший месяц.`
  return `До срока ${дней} дней.`
}

/**
 * Первое физическое действие.
 *
 * Против прокрастинации работает не «начать цель», а конкретный шаг, который
 * делается за один присест. Шаг выводится из первого невыполненного
 * критерия — чинить нужно то, что мешает раньше всего.
 */
function следующийШаг(цель: Цель, критерии: Критерий[]): string {
  const слабый = критерии.find((критерий) => !критерий.выполнен)

  if (!слабый) {
    const веха = цель.вехи.find((элемент) => !элемент.выполнена)
    return веха
      ? `Взяться за веху «${веха.название}» — она следующая по списку.`
      : 'Цель описана полностью. Ближайшее действие — отметить сегодняшнее продвижение числом.'
  }

  const шаги: Record<КритерийКлюч, string> = {
    конкретность:
      'Переписать название так, чтобы оно называло действие. Пять минут, прямо сейчас.',
    измеримость:
      'Поставить число: сколько именно и в чём измеряется. Если число неизвестно — взять любое разумное, его можно поправить.',
    достижимость:
      'Написать первую веху — кусок, который делается за неделю. Не всю цель, только первый кусок.',
    значимость:
      'Ответить в поле «зачем» одним предложением: что изменится в жизни, когда цель будет достигнута.',
    срок: 'Поставить дату окончания. Любую реальную — без неё цель не начнётся.',
  }

  return шаги[слабый.ключ]
}

/** Разбор всех целей: где прокрастинация вероятнее всего. */
export function самаяНеготовая(цели: Цель[]): { цель: Цель; разбор: РазборSMART } | null {
  const активные = цели.filter((цель) => цель.состояние === 'активна')
  if (активные.length === 0) return null

  let худшая: { цель: Цель; разбор: РазборSMART } | null = null
  for (const цель of активные) {
    const разбор = разобратьПоSMART(цель)
    if (!худшая || разбор.выполнено < худшая.разбор.выполнено) {
      худшая = { цель, разбор }
    }
  }
  return худшая && худшая.разбор.готова ? null : худшая
}
