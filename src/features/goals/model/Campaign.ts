import type { Задача, Цель } from '@/core/db/types'

export interface ПрогрессМиссии {
  источник: 'показатель' | 'вехи' | 'не определён'
  значение: number | null
  выполнено: number
  всего: number
}

export interface СледующийХодМиссии {
  задача: Задача | null
  минутИзвестно: number
  задачБезВремени: number
  открытыхЗадач: number
}

/**
 * Прогресс миссии измеряется результатом, а не количеством кликов.
 * Связанные задачи показывают работу, но не подменяют достижение цели.
 */
export function прогрессМиссии(цель: Цель): ПрогрессМиссии {
  if (цель.цель !== null && цель.цель > 0 && цель.текущее !== null) {
    return {
      источник: 'показатель',
      значение: Math.min(100, Math.max(0, (цель.текущее / цель.цель) * 100)),
      выполнено: цель.текущее,
      всего: цель.цель,
    }
  }

  if (цель.вехи.length > 0) {
    const выполнено = цель.вехи.filter((веха) => веха.выполнена).length
    return {
      источник: 'вехи',
      значение: (выполнено / цель.вехи.length) * 100,
      выполнено,
      всего: цель.вехи.length,
    }
  }

  return {
    источник: 'не определён',
    значение: null,
    выполнено: 0,
    всего: 0,
  }
}

const ВЕС_ВАЖНОСТИ: Record<Задача['важность'], number> = {
  срочная: 4,
  высокая: 3,
  обычная: 2,
  низкая: 1,
}

/**
 * Следующий ход берётся только из реально созданных открытых задач цели.
 * Сначала ближайшая дата, затем важность. Отсутствующая дата не превращается
 * в сегодняшнюю, а неизвестная длительность остаётся отдельным пробелом.
 */
export function следующийХодМиссии(
  цельId: string,
  задачи: Задача[],
): СледующийХодМиссии {
  const открытые = задачи.filter(
    (задача) =>
      задача.цельId === цельId &&
      задача.состояние !== 'сделана' &&
      задача.состояние !== 'отменена',
  )
  const отсортированные = [...открытые].sort((а, б) => {
    if (а.дата !== б.дата) {
      if (а.дата === null) return 1
      if (б.дата === null) return -1
      return а.дата.localeCompare(б.дата)
    }
    return ВЕС_ВАЖНОСТИ[б.важность] - ВЕС_ВАЖНОСТИ[а.важность]
  })

  return {
    задача: отсортированные[0] ?? null,
    минутИзвестно: открытые.reduce(
      (сумма, задача) => сумма + (задача.длительностьМинут ?? 0),
      0,
    ),
    задачБезВремени: открытые.filter((задача) => задача.длительностьМинут === null)
      .length,
    открытыхЗадач: открытые.length,
  }
}
