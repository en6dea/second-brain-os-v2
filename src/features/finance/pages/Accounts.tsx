import { useState } from 'react'
import { useLiveQuery } from 'dexie-react-hooks'
import { Pencil, Plus, Trash2 } from 'lucide-react'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import { СОБСТВЕННЫЕ_ТИПЫ, type Счёт, type ТипСчёта } from '@/core/db/types'
import { расчётныйОстаток, итогПоСчетам } from '@/features/finance/model/calc'
import { деньги, копейкиВРубли, рублиВКопейки } from '@/core/money/Money'
import { сейчас } from '@/core/db/RecordId'
import { useИнтерфейс } from '@/app/providers/ui'
import {
  Input,
  MoneyInput,
  Select,
  Skeleton,
  Badge,
  Card,
  Button,
  IconButton,
  Metric,
  Dialog,
  Switch,
  Field,
  EmptyState,
  CardHeader,
} from '@/design-system/components'

const ТИПЫ: { ключ: ТипСчёта; подпись: string }[] = [
  { ключ: 'карта', подпись: 'Банковская карта' },
  { ключ: 'наличные', подпись: 'Наличные' },
  { ключ: 'вклад', подпись: 'Вклад' },
  { ключ: 'накопительный', подпись: 'Накопительный счёт' },
  { ключ: 'кредитная карта', подпись: 'Кредитная карта' },
  { ключ: 'иное', подпись: 'Другое' },
]

interface Черновик {
  id: string | null
  название: string
  тип: ТипСчёта
  остаток: string
  кредитныйЛимит: string
  учитыватьВДоступных: boolean
}

const пустойЧерновик: Черновик = {
  id: null,
  название: '',
  тип: 'карта',
  остаток: '',
  кредитныйЛимит: '',
  учитыватьВДоступных: true,
}

export function AccountsPage() {
  const сообщить = useИнтерфейс((с) => с.сообщить)
  const [черновик, установитьЧерновик] = useState<Черновик | null>(null)
  const [кУдалению, установитьКУдалению] = useState<Счёт | null>(null)

  const данные = useLiveQuery(async () => {
    const [счета, операции] = await Promise.all([
      база.accounts.orderBy('порядок').toArray(),
      база.operations.toArray(),
    ])
    return { счета, операции }
  }, [])

  if (!данные) {
    return (
      <Card>
        <Skeleton строк={3} />
      </Card>
    )
  }

  const итог = итогПоСчетам(данные.счета)

  async function сохранить() {
    if (!черновик || !черновик.название.trim()) return
    const остаток = рублиВКопейки(черновик.остаток)
    const лимит = рублиВКопейки(черновик.кредитныйЛимит)

    if (черновик.id) {
      const текущий = await база.accounts.get(черновик.id)
      if (!текущий) return
      const остатокИзменился = текущий.фактическийОстаток !== остаток
      await база.accounts.put({
        ...текущий,
        название: черновик.название.trim(),
        тип: черновик.тип,
        фактическийОстаток: остаток,
        подтверждён:
          остаток === null
            ? null
            : остатокИзменился
              ? сейчас()
              : текущий.подтверждён,
        кредитныйЛимит: лимит,
        учитыватьВДоступных: черновик.учитыватьВДоступных,
        updatedAt: сейчас(),
      })
      сообщить('Счёт обновлён')
    } else {
      await база.accounts.add(
        новаяЗапись({
          название: черновик.название.trim(),
          тип: черновик.тип,
          валюта: 'RUB',
          фактическийОстаток: остаток,
          подтверждён: остаток === null ? null : сейчас(),
          кредитныйЛимит: лимит,
          учитыватьВДоступных: черновик.учитыватьВДоступных,
          архив: false,
          порядок: данные?.счета.length ?? 0,
        }) as never,
      )
      сообщить('Счёт добавлен')
    }
    установитьЧерновик(null)
  }

  async function удалить() {
    if (!кУдалению) return
    await база.accounts.delete(кУдалению.id)
    сообщить('Счёт удалён. Операции по нему остались и потеряли привязку к счёту.')
    установитьКУдалению(null)
  }

  return (
    <div className="anim-rise space-y-5">
      <Card>
        <div className="grid grid-cols-2 gap-5 p-5 sm:grid-cols-3">
          <Metric
            подпись="Собственные деньги"
            значение={деньги(итог.собственные)}
            источник={`учтено счетов: ${итог.счетовУчтено}`}
          />
          <Metric
            подпись="Без остатка"
            значение={String(итог.счетовБезОстатка)}
            источник="не участвуют в сумме"
            тон={итог.счетовБезОстатка > 0 ? 'внимание' : 'нейтральный'}
          />
          <Metric
            подпись="Кредитный лимит"
            значение={деньги(итог.кредитныйЛимитДоступен)}
            источник="доступно, но не ваше"
          />
        </div>
      </Card>

      <Card>
        <CardHeader
          заголовок="Счета"
          подпись="Остаток «не заполнен» и «ноль» — разные состояния"
          действие={
            <Button
              вид="основная"
              размер="малый"
              иконка={<Plus size={15} />}
              onClick={() => установитьЧерновик(пустойЧерновик)}
            >
              Счёт
            </Button>
          }
        />

        {данные.счета.length === 0 ? (
          <EmptyState
            заголовок="Счетов пока нет"
            подпись="Добавьте счета, которыми пользуетесь. Пока их нет, сумма доступных денег неизвестна."
            действие={
              <Button
                вид="контур"
                onClick={() => установитьЧерновик(пустойЧерновик)}
              >
                Добавить первый счёт
              </Button>
            }
          />
        ) : (
          <div className="divide-y divide-line border-t border-line">
            {данные.счета.map((счёт) => {
              const расчёт = расчётныйОстаток(счёт, данные.операции)
              const расходится =
                расчёт !== null &&
                счёт.фактическийОстаток !== null &&
                расчёт !== счёт.фактическийОстаток
              return (
                <div
                  key={счёт.id}
                  className="flex flex-wrap items-center gap-3 px-5 py-3.5"
                >
                  <div className="min-w-0 flex-1">
                    <p className="truncate text-meta font-medium text-ink">
                      {счёт.название}
                    </p>
                    <p className="mt-0.5 flex flex-wrap items-center gap-2 text-caption text-ink-3">
                      <span>
                        {ТИПЫ.find((т) => т.ключ === счёт.тип)?.подпись ?? счёт.тип}
                      </span>
                      {!СОБСТВЕННЫЕ_ТИПЫ.includes(счёт.тип) ? (
                        <Badge тон="внимание">кредитные деньги</Badge>
                      ) : null}
                      {!счёт.учитыватьВДоступных ? (
                        <Badge>не в доступных</Badge>
                      ) : null}
                    </p>
                  </div>

                  <div className="text-right">
                    <p className="tnum text-body font-semibold text-ink">
                      {счёт.фактическийОстаток === null
                        ? 'не заполнен'
                        : деньги(счёт.фактическийОстаток)}
                    </p>
                    <p className="tnum mt-0.5 text-micro text-ink-3">
                      {расчёт === null
                        ? 'расчёт невозможен'
                        : расходится
                          ? `расчётный: ${деньги(расчёт)}`
                          : 'совпадает с расчётом'}
                    </p>
                  </div>

                  <div className="flex gap-1">
                    <IconButton
                      подпись={`Изменить счёт ${счёт.название}`}
                      onClick={() =>
                        установитьЧерновик({
                          id: счёт.id,
                          название: счёт.название,
                          тип: счёт.тип,
                          остаток:
                            счёт.фактическийОстаток === null
                              ? ''
                              : String(копейкиВРубли(счёт.фактическийОстаток)),
                          кредитныйЛимит:
                            счёт.кредитныйЛимит === null
                              ? ''
                              : String(копейкиВРубли(счёт.кредитныйЛимит)),
                          учитыватьВДоступных: счёт.учитыватьВДоступных,
                        })
                      }
                    >
                      <Pencil size={16} />
                    </IconButton>
                    <IconButton
                      подпись={`Удалить счёт ${счёт.название}`}
                      onClick={() => установитьКУдалению(счёт)}
                    >
                      <Trash2 size={16} />
                    </IconButton>
                  </div>
                </div>
              )
            })}
          </div>
        )}
      </Card>

      <Dialog
        открыто={черновик !== null}
        наЗакрытие={() => установитьЧерновик(null)}
        заголовок={черновик?.id ? 'Изменить счёт' : 'Новый счёт'}
        подпись="Оставьте остаток пустым, если он сейчас неизвестен"
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьЧерновик(null)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={сохранить}
              disabled={!черновик?.название.trim()}
            >
              Сохранить
            </Button>
          </>
        }
      >
        {черновик ? (
          <div className="space-y-4">
            <Field подпись="Название" обязательное>
              <Input
                value={черновик.название}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    название: событие.target.value,
                  })
                }
                placeholder="Например: Основная карта"
                autoFocus
              />
            </Field>

            <Field подпись="Тип счёта">
              <Select
                value={черновик.тип}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    тип: событие.target.value as ТипСчёта,
                  })
                }
              >
                {ТИПЫ.map((тип) => (
                  <option key={тип.ключ} value={тип.ключ}>
                    {тип.подпись}
                  </option>
                ))}
              </Select>
            </Field>

            <Field
              подпись="Текущий остаток"
              подсказка="Пустое поле означает «неизвестно» — счёт не войдёт в сумму денег"
            >
              <MoneyInput
                value={черновик.остаток}
                onChange={(значение) =>
                  установитьЧерновик({ ...черновик, остаток: значение })
                }
                placeholder="не заполнено"
              />
            </Field>

            {черновик.тип === 'кредитная карта' ? (
              <Field
                подпись="Кредитный лимит"
                подсказка="Лимит не увеличивает количество собственных денег"
              >
                <MoneyInput
                  value={черновик.кредитныйЛимит}
                  onChange={(значение) =>
                    установитьЧерновик({ ...черновик, кредитныйЛимит: значение })
                  }
                />
              </Field>
            ) : null}

            <Switch
              включён={черновик.учитыватьВДоступных}
              наИзменение={(значение) =>
                установитьЧерновик({ ...черновик, учитыватьВДоступных: значение })
              }
              подпись="Учитывать в доступных деньгах"
              описание="Выключите для счетов, деньги с которых нельзя тратить прямо сейчас"
            />
          </div>
        ) : null}
      </Dialog>

      <Dialog
        открыто={кУдалению !== null}
        наЗакрытие={() => установитьКУдалению(null)}
        заголовок="Удалить счёт?"
        ширина="узкая"
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьКУдалению(null)}>
              Отмена
            </Button>
            <Button вид="опасная" onClick={удалить}>
              Удалить
            </Button>
          </>
        }
      >
        <p className="text-meta text-ink-2">
          Счёт «{кУдалению?.название}» будет удалён. Операции по нему{' '}
          <b className="text-ink">не удаляются</b> — они останутся в списке, но
          потеряют привязку к счёту. Отменить это действие нельзя.
        </p>
      </Dialog>
    </div>
  )
}
