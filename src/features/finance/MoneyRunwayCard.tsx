import { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'
import { Banknote, CalendarClock, Plus, ShieldCheck } from 'lucide-react'
import { база } from '@/core/db/db'
import { изменитьНастройки, новаяЗапись } from '@/core/db/repo'
import type {
  КатегорияДенег,
  Настройки,
  Обязательство,
  ПлановыйПлатёж,
  Счёт,
} from '@/core/db/types'
import { сейчас } from '@/core/db/RecordId'
import { деньСловами, сегодня } from '@/core/calendar/CalendarRu'
import { деньги, копейкиВРубли, рублиВКопейки } from '@/core/money/Money'
import type { РасчётДоДохода } from './model/SafeToSpend'
import type { ПереносВыходного, СобытиеДохода } from './model/IncomeSchedule'
import { useИнтерфейс } from '@/app/providers/ui'
import { ЗНАЧОК } from '@/design-system/iconSize'
import {
  Badge,
  Button,
  Card,
  CardBody,
  CardHeader,
  Dialog,
  EmptyState,
  Field,
  Input,
  Metric,
  MoneyInput,
  Select,
  Switch,
} from '@/design-system/components'

interface ЧерновикПлатежа {
  название: string
  сумма: string
  дата: string
  обязательствоId: string
  счётId: string
  категорияId: string
}

interface ЧерновикПолученияДохода {
  сумма: string
  дата: string
  счётId: string
  категорияId: string
}

const ID_ЗАРПЛАТЫ = 'salary'
const ID_АВАНСА = 'advance'

function допустимыйДень(значение: string) {
  const день = Number(значение)
  return Number.isInteger(день) && день >= 1 && день <= 31
}

function причинаТекст(расчёт: РасчётДоДохода) {
  switch (расчёт.причина) {
    case 'нет подтверждённого остатка':
      return 'Подтвердите остатки всех учитываемых собственных счетов.'
    case 'не указана дата следующего дохода':
      return 'Укажите дату ближайшего достаточно надёжного дохода.'
    case 'дата дохода уже прошла':
      return 'Дата дохода прошла или заполнена неверно — обновите горизонт.'
    case 'неизвестна сумма обязательного платежа':
      return 'У ближайшего долгового платежа не указана минимальная сумма.'
    default:
      return 'Заполните исходные данные, чтобы получить безопасный лимит.'
  }
}

export function MoneyRunwayCard({
  расчёт,
  настройки,
  платежи,
  обязательства,
  датаДохода: расчётнаяДатаДохода,
  следующийДоход,
  счета,
  категории,
}: {
  расчёт: РасчётДоДохода
  настройки: Настройки
  платежи: ПлановыйПлатёж[]
  обязательства: Обязательство[]
  датаДохода: string | null
  следующийДоход: СобытиеДохода | null
  счета: Счёт[]
  категории: КатегорияДенег[]
}) {
  const сообщить = useИнтерфейс((состояние) => состояние.сообщить)
  const [настройкаОткрыта, показатьНастройку] = useState(false)
  const [платёжОткрыт, показатьПлатёж] = useState(false)
  const [деньЗарплаты, установитьДеньЗарплаты] = useState('10')
  const [суммаЗарплаты, установитьСуммуЗарплаты] = useState('')
  const [деньАванса, установитьДеньАванса] = useState('25')
  const [суммаАванса, установитьСуммуАванса] = useState('')
  const [перенос, установитьПеренос] = useState<ПереносВыходного>('раньше')
  const [резервОтдельно, установитьРезервОтдельно] = useState(false)
  const [черновик, установитьЧерновик] = useState<ЧерновикПлатежа>({
    название: '',
    сумма: '',
    дата: сегодня(),
    обязательствоId: '',
    счётId: '',
    категорияId: '',
  })
  const [кПроведению, установитьКПроведению] = useState<ПлановыйПлатёж | null>(null)
  const [счётПроведения, установитьСчётПроведения] = useState('')
  const [категорияПроведения, установитьКатегориюПроведения] = useState('')
  const [кПолучению, установитьКПолучению] = useState<СобытиеДохода | null>(null)
  const [получение, установитьПолучение] = useState<ЧерновикПолученияДохода>({
    сумма: '',
    дата: сегодня(),
    счётId: '',
    категорияId: '',
  })

  useEffect(() => {
    if (!настройкаОткрыта) return
    const горизонт = настройки.денежныйГоризонт
    const регулярные = горизонт?.регулярныеДоходы ?? []
    const прежниеДни = горизонт?.дниДохода ?? []
    const зарплата = регулярные.find((доход) => доход.id === ID_ЗАРПЛАТЫ)
    const аванс = регулярные.find((доход) => доход.id === ID_АВАНСА)
    установитьДеньЗарплаты(String(зарплата?.деньМесяца ?? прежниеДни[0] ?? 10))
    установитьСуммуЗарплаты(
      зарплата?.ожидаемаяСумма === null || зарплата?.ожидаемаяСумма === undefined
        ? ''
        : String(копейкиВРубли(зарплата.ожидаемаяСумма)),
    )
    установитьДеньАванса(String(аванс?.деньМесяца ?? прежниеДни[1] ?? 25))
    установитьСуммуАванса(
      аванс?.ожидаемаяСумма === null || аванс?.ожидаемаяСумма === undefined
        ? ''
        : String(копейкиВРубли(аванс.ожидаемаяСумма)),
    )
    установитьПеренос(горизонт?.переносВыходного ?? 'раньше')
    установитьРезервОтдельно(настройки.резервУжеИсключён ?? false)
  }, [настройкаОткрыта, настройки.денежныйГоризонт, настройки.резервУжеИсключён])

  const прежнийОжидаемыйДоход = настройки.денежныйГоризонт?.ожидаемыйДоход ?? null
  const естьНовыйГрафик =
    (настройки.денежныйГоризонт?.регулярныеДоходы?.length ?? 0) > 0
  const графикВалиден = допустимыйДень(деньЗарплаты) && допустимыйДень(деньАванса)
  const доходЖдётПодтверждения =
    следующийДоход !== null && следующийДоход.дата < сегодня()
  const ближайшиеПлатежи = платежи
    .filter((платёж) => платёж.обязательный && !платёж.оплачен)
    .sort((а, б) => а.дата.localeCompare(б.дата))
    .slice(0, 5)

  async function сохранитьГоризонт() {
    if (!графикВалиден) return
    const зарплата = рублиВКопейки(суммаЗарплаты)
    const аванс = рублиВКопейки(суммаАванса)
    const деньЗарплатыЧислом = Number(деньЗарплаты)
    const деньАвансаЧислом = Number(деньАванса)
    const дниДохода = [деньЗарплатыЧислом, деньАвансаЧислом]
    await изменитьНастройки({
      резервУжеИсключён: резервОтдельно,
      денежныйГоризонт: {
        датаСледующегоДохода:
          настройки.денежныйГоризонт?.датаСледующегоДохода ?? null,
        // Старое общее значение не удаляется: оно остаётся в резервной копии
        // прежней версии, но новый интерфейс использует две отдельные суммы.
        ожидаемыйДоход: прежнийОжидаемыйДоход,
        дниДохода,
        переносВыходного: перенос,
        регулярныеДоходы: [
          {
            id: ID_ЗАРПЛАТЫ,
            название: 'Зарплата',
            деньМесяца: деньЗарплатыЧислом,
            ожидаемаяСумма: зарплата,
          },
          {
            id: ID_АВАНСА,
            название: 'Аванс',
            деньМесяца: деньАвансаЧислом,
            ожидаемаяСумма: аванс,
          },
        ],
      },
    })
    показатьНастройку(false)
    сообщить('Денежный горизонт сохранён')
  }

  function открытьПолучениеДохода(событие: СобытиеДохода) {
    const доходныеКатегории = категории.filter(
      (категория) => !категория.архив && категория.вид === 'доход',
    )
    const подходящаяКатегория =
      доходныеКатегории.find((категория) =>
        категория.название.toLocaleLowerCase('ru-RU').includes('зарплат'),
      ) ?? доходныеКатегории[0]
    const счёт = счета.find(
      (элемент) => !элемент.архив && элемент.тип !== 'кредитная карта',
    )
    установитьКПолучению(событие)
    установитьПолучение({
      сумма:
        событие.источник.ожидаемаяСумма === null
          ? ''
          : String(копейкиВРубли(событие.источник.ожидаемаяСумма)),
      дата: сегодня(),
      счётId: счёт?.id ?? '',
      категорияId: подходящаяКатегория?.id ?? '',
    })
  }

  async function подтвердитьПолучениеДохода() {
    if (!кПолучению || !получение.счётId || !получение.дата) return
    const сумма = рублиВКопейки(получение.сумма)
    if (сумма === null || сумма <= 0) return

    const событие = кПолучению
    let создано = false
    await база.transaction('rw', база.operations, async () => {
      const ужеЕсть = (await база.operations.toArray()).some(
        (операция) =>
          операция.тип === 'доход' &&
          операция.регулярныйДоходId === событие.источник.id &&
          операция.плановаяДатаДохода === событие.дата,
      )
      if (ужеЕсть) return
      await база.operations.add(
        новаяЗапись({
          дата: получение.дата,
          тип: 'доход' as const,
          сумма,
          счётId: получение.счётId,
          счётПолучательId: null,
          категорияId: получение.категорияId || null,
          классРасхода: null,
          заметка: событие.источник.название,
          планId: null,
          регулярныйДоходId: событие.источник.id,
          плановаяДатаДохода: событие.дата,
          отпечатокИмпорта: null,
          разобрана: Boolean(получение.категорияId),
        }) as never,
      )
      создано = true
    })

    установитьКПолучению(null)
    сообщить(
      создано
        ? `${событие.источник.название}: поступление записано`
        : 'Эта выплата уже была подтверждена',
    )
  }

  async function сохранитьПлатёж() {
    const сумма = рублиВКопейки(черновик.сумма)
    if (
      !черновик.название.trim() ||
      сумма === null ||
      сумма <= 0 ||
      !черновик.дата
    ) {
      return
    }
    await база.plannedPayments.add(
      новаяЗапись({
        название: черновик.название.trim(),
        сумма,
        дата: черновик.дата,
        счётId: черновик.счётId || null,
        категорияId: черновик.категорияId || null,
        обязательствоId: черновик.обязательствоId || null,
        обязательный: true,
        оплачен: false,
        операцияId: null,
      }) as never,
    )
    показатьПлатёж(false)
    установитьЧерновик({
      название: '',
      сумма: '',
      дата: сегодня(),
      обязательствоId: '',
      счётId: '',
      категорияId: '',
    })
    сообщить('Обязательный платёж добавлен')
  }

  function открытьПроведение(платёж: ПлановыйПлатёж) {
    установитьКПроведению(платёж)
    установитьСчётПроведения(платёж.счётId ?? '')
    установитьКатегориюПроведения(платёж.категорияId ?? '')
  }

  async function провестиПлатёж() {
    if (!кПроведению || !счётПроведения) return
    const платёж = кПроведению
    const категория = категории.find(
      (элемент) => элемент.id === категорияПроведения,
    )
    await база.transaction(
      'rw',
      база.operations,
      база.plannedPayments,
      async () => {
        const свежий = await база.plannedPayments.get(платёж.id)
        if (!свежий || свежий.оплачен) return
        const операция = новаяЗапись({
          дата: сегодня(),
          тип: 'расход' as const,
          сумма: свежий.сумма,
          счётId: счётПроведения,
          счётПолучательId: null,
          категорияId: категорияПроведения || null,
          классРасхода: категория?.классПоУмолчанию ?? 'обязательный',
          заметка: свежий.название,
          планId: свежий.id,
          отпечатокИмпорта: null,
          разобрана: Boolean(категорияПроведения),
        })
        await база.operations.add(операция as never)
        await база.plannedPayments.put({
          ...свежий,
          счётId: счётПроведения,
          категорияId: категорияПроведения || null,
          оплачен: true,
          операцияId: операция.id,
          updatedAt: сейчас(),
        })
      },
    )
    установитьКПроведению(null)
    сообщить('Платёж проведён и записан в операции')
  }

  return (
    <>
      <Card>
        <CardHeader
          заголовок={
            <span className="flex items-center gap-2.5">
              <ShieldCheck size={ЗНАЧОК.основной} className="text-accent" />
              Капитал до следующего дохода
            </span>
          }
          подпись="Главный денежный ресурс: только уже имеющиеся собственные деньги"
          действие={
            <Button
              вид="контур"
              размер="малый"
              onClick={() => показатьНастройку(true)}
            >
              Настроить
            </Button>
          }
        />

        {расчёт.готов ? (
          <>
            <div className="grid grid-cols-2 gap-5 px-5 pb-5 lg:grid-cols-4">
              <Metric
                подпись="Собственные деньги"
                значение={деньги(расчёт.собственные)}
                источник="расчётные остатки счетов"
              />
              <Metric
                подпись="Защищено"
                значение={деньги(расчёт.защищено)}
                источник="резерв + ближайшие платежи"
              />
              <Metric
                подпись="Можно потратить"
                значение={деньги(расчёт.можноПотратить)}
                источник={`до ${расчётнаяДатаДохода ? деньСловами(расчётнаяДатаДохода) : 'дохода'}`}
                тон={(расчёт.можноПотратить ?? 0) < 0 ? 'опасность' : 'успех'}
              />
              <Metric
                подпись="Лимит в день"
                значение={деньги(расчёт.лимитВДень)}
                источник={`на ${расчёт.дней ?? 0} дн., без будущего дохода`}
                тон={(расчёт.можноПотратить ?? 0) < 0 ? 'опасность' : 'нейтральный'}
              />
            </div>
            <div className="grid gap-2 border-t border-line px-5 py-4 text-caption text-ink-2 sm:grid-cols-3">
              <p>
                Резерв:{' '}
                <span className="tnum text-ink">{деньги(расчёт.резерв)}</span>
              </p>
              <p>
                Плановые платежи:{' '}
                <span className="tnum text-ink">
                  {деньги(расчёт.плановыеПлатежи)}
                </span>
              </p>
              <p>
                Минимумы по долгам:{' '}
                <span className="tnum text-ink">
                  {деньги(расчёт.платежиПоДолгам)}
                </span>
              </p>
            </div>
          </>
        ) : (
          <EmptyState
            иконка={<CalendarClock size={ЗНАЧОК.основной} />}
            заголовок="Безопасный лимит пока неизвестен"
            подпись={причинаТекст(расчёт)}
            действие={
              расчёт.причина === 'нет подтверждённого остатка' ? (
                <Link
                  to="/finance/accounts"
                  className="inline-flex h-11 items-center rounded-2 border border-accent-line px-4 text-meta font-medium text-accent hover:bg-accent-soft"
                >
                  Проверить счета
                </Link>
              ) : расчёт.причина === 'неизвестна сумма обязательного платежа' ? (
                <Link
                  to="/obligations"
                  className="inline-flex h-11 items-center rounded-2 border border-accent-line px-4 text-meta font-medium text-accent hover:bg-accent-soft"
                >
                  Проверить обязательства
                </Link>
              ) : (
                <Button вид="контур" onClick={() => показатьНастройку(true)}>
                  Указать доход
                </Button>
              )
            }
          />
        )}

        <div className="border-t border-line">
          <div className="flex flex-wrap items-center gap-4 px-5 py-4">
            <div className="flex size-10 shrink-0 items-center justify-center rounded-2 bg-good-soft text-good">
              <Banknote size={ЗНАЧОК.основной} />
            </div>
            {следующийДоход ? (
              <>
                <div className="min-w-48 flex-1">
                  <p className="text-meta font-medium text-ink">
                    {доходЖдётПодтверждения
                      ? 'Требует подтверждения: '
                      : 'Следом — '}
                    {следующийДоход.источник.название.toLocaleLowerCase('ru-RU')}
                  </p>
                  <p className="text-caption text-ink-3">
                    {деньСловами(следующийДоход.дата)}
                    {следующийДоход.источник.ожидаемаяСумма !== null
                      ? ` · ожидается ${деньги(следующийДоход.источник.ожидаемаяСумма)}`
                      : ' · сумма не указана'}
                  </p>
                </div>
                <Badge тон="сведения">Не входит в доступные до получения</Badge>
                <Button
                  вид="контур"
                  размер="малый"
                  onClick={() => открытьПолучениеДохода(следующийДоход)}
                >
                  Получено
                </Button>
              </>
            ) : (
              <>
                <div className="min-w-48 flex-1">
                  <p className="text-meta font-medium text-ink">Цикл доходов</p>
                  <p className="text-caption text-ink-3">
                    Укажите отдельно зарплату и аванс, чтобы горизонт переключался
                    после подтверждения.
                  </p>
                </div>
                <Button
                  вид="контур"
                  размер="малый"
                  onClick={() => показатьНастройку(true)}
                >
                  Настроить
                </Button>
              </>
            )}
          </div>
        </div>

        <div className="border-t border-line">
          <div className="flex flex-wrap items-center justify-between gap-3 px-5 py-4">
            <div>
              <p className="text-meta font-medium text-ink">Ближайшие платежи</p>
              <p className="text-caption text-ink-3">
                Проведение создаёт расход и закрывает напоминание одной транзакцией
              </p>
            </div>
            <Button
              вид="обычная"
              размер="малый"
              иконка={<Plus size={ЗНАЧОК.строка} />}
              onClick={() => показатьПлатёж(true)}
            >
              Платёж
            </Button>
          </div>
          {ближайшиеПлатежи.length > 0 ? (
            <div className="divide-y divide-line border-t border-line">
              {ближайшиеПлатежи.map((платёж) => (
                <div key={платёж.id} className="flex items-center gap-3 px-5 py-3">
                  <div className="min-w-0 flex-1">
                    <p className="truncate text-meta text-ink">{платёж.название}</p>
                    <p className="text-caption text-ink-3">
                      {деньСловами(платёж.дата)}
                      {платёж.обязательствоId ? ' · связано с долгом' : ''}
                    </p>
                  </div>
                  <span className="tnum shrink-0 text-meta text-ink">
                    {деньги(платёж.сумма)}
                  </span>
                  <Button
                    вид="контур"
                    размер="малый"
                    onClick={() => открытьПроведение(платёж)}
                  >
                    Провести
                  </Button>
                </div>
              ))}
            </div>
          ) : (
            <CardBody className="border-t border-line py-4">
              <p className="text-meta text-ink-3">
                Обязательных платежей не добавлено. Это означает «нет данных», а не
                «платежей точно нет».
              </p>
            </CardBody>
          )}
        </div>

        {!следующийДоход &&
        прежнийОжидаемыйДоход !== null &&
        расчётнаяДатаДохода ? (
          <div className="border-t border-line px-5 py-3">
            <Badge тон="сведения">
              Прежний общий ориентир {деньги(прежнийОжидаемыйДоход)} · не прибавлен
              к доступным
            </Badge>
          </div>
        ) : null}
      </Card>

      <Dialog
        открыто={настройкаОткрыта}
        наЗакрытие={() => показатьНастройку(false)}
        заголовок="Денежный горизонт"
        подпись="До какой даты защитить обязательные деньги"
        подвал={
          <>
            <Button вид="тихая" onClick={() => показатьНастройку(false)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={сохранитьГоризонт}
              disabled={!графикВалиден}
            >
              Сохранить
            </Button>
          </>
        }
      >
        <div className="space-y-4">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div>
              <p className="text-meta font-medium text-ink">Зарплата и аванс</p>
              <p className="text-caption text-ink-3">
                Суммы — ориентиры, пока вы не подтвердили реальное поступление.
              </p>
            </div>
            <Button
              вид="контур"
              размер="малый"
              onClick={() => {
                установитьДеньЗарплаты('10')
                установитьДеньАванса('25')
                установитьПеренос('раньше')
              }}
            >
              Вернуть график 10/25
            </Button>
          </div>

          <div className="grid gap-3 sm:grid-cols-2">
            <div className="rounded-3 border border-line bg-sunken p-4">
              <p className="mb-3 text-meta font-medium text-ink">Зарплата</p>
              <div className="grid gap-3">
                <Field подпись="День месяца" обязательное>
                  <Input
                    type="number"
                    min="1"
                    max="31"
                    inputMode="numeric"
                    value={деньЗарплаты}
                    onChange={(событие) =>
                      установитьДеньЗарплаты(событие.target.value)
                    }
                  />
                </Field>
                <Field подпись="Ожидаемая сумма">
                  <MoneyInput
                    value={суммаЗарплаты}
                    onChange={установитьСуммуЗарплаты}
                    placeholder="не задана"
                  />
                </Field>
              </div>
            </div>

            <div className="rounded-3 border border-line bg-sunken p-4">
              <p className="mb-3 text-meta font-medium text-ink">Аванс</p>
              <div className="grid gap-3">
                <Field подпись="День месяца" обязательное>
                  <Input
                    type="number"
                    min="1"
                    max="31"
                    inputMode="numeric"
                    value={деньАванса}
                    onChange={(событие) =>
                      установитьДеньАванса(событие.target.value)
                    }
                  />
                </Field>
                <Field подпись="Ожидаемая сумма">
                  <MoneyInput
                    value={суммаАванса}
                    onChange={установитьСуммуАванса}
                    placeholder="не задана"
                  />
                </Field>
              </div>
            </div>
          </div>

          {!графикВалиден ? (
            <p className="text-caption text-bad">
              День каждой выплаты должен быть целым числом от 1 до 31.
            </p>
          ) : null}

          <Field подпись="Если выплата в выходной">
            <Select
              value={перенос}
              onChange={(событие) =>
                установитьПеренос(событие.target.value as ПереносВыходного)
              }
            >
              <option value="раньше">Предыдущий рабочий день</option>
              <option value="позже">Следующий рабочий день</option>
              <option value="без переноса">Не переносить</option>
            </Select>
          </Field>
          <p className="text-caption text-ink-3">
            Учитываются суббота и воскресенье. Официальные праздники без
            производственного календаря приложение не угадывает.
          </p>

          {!естьНовыйГрафик && прежнийОжидаемыйДоход !== null ? (
            <p className="rounded-3 border border-line bg-sunken px-4 py-3 text-meta text-ink-2">
              Раньше был указан общий ориентир {деньги(прежнийОжидаемыйДоход)}. Он
              сохранён без изменений; распределите сумму между зарплатой и авансом
              вручную.
            </p>
          ) : null}
          <Switch
            включён={резервОтдельно}
            наИзменение={установитьРезервОтдельно}
            подпись="Резерв уже вынесен из доступных денег"
            описание="Включайте только если резерв лежит на счёте с выключенным учётом в доступных — тогда он не вычтется второй раз"
          />
        </div>
      </Dialog>

      <Dialog
        открыто={кПолучению !== null}
        наЗакрытие={() => установитьКПолучению(null)}
        заголовок="Подтвердить поступление"
        подпись={
          кПолучению
            ? `${кПолучению.источник.название} · по графику ${деньСловами(кПолучению.дата)}`
            : undefined
        }
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьКПолучению(null)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={подтвердитьПолучениеДохода}
              disabled={!получение.сумма || !получение.дата || !получение.счётId}
            >
              Записать доход
            </Button>
          </>
        }
      >
        <div className="space-y-4">
          <p className="rounded-3 border border-good/30 bg-good-soft px-4 py-3 text-meta text-ink-2">
            Подтверждайте только после фактического поступления. Будет создана
            операция дохода, а денежный горизонт переключится на следующую выплату.
          </p>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Получено" обязательное>
              <MoneyInput
                value={получение.сумма}
                onChange={(сумма) => установитьПолучение({ ...получение, сумма })}
              />
            </Field>
            <Field подпись="Дата поступления" обязательное>
              <Input
                type="date"
                value={получение.дата}
                onChange={(событие) =>
                  установитьПолучение({ ...получение, дата: событие.target.value })
                }
              />
            </Field>
          </div>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Зачислить на счёт" обязательное>
              <Select
                value={получение.счётId}
                onChange={(событие) =>
                  установитьПолучение({
                    ...получение,
                    счётId: событие.target.value,
                  })
                }
              >
                <option value="">Не выбран</option>
                {счета
                  .filter((счёт) => !счёт.архив && счёт.тип !== 'кредитная карта')
                  .map((счёт) => (
                    <option key={счёт.id} value={счёт.id}>
                      {счёт.название}
                    </option>
                  ))}
              </Select>
            </Field>
            <Field подпись="Категория дохода">
              <Select
                value={получение.категорияId}
                onChange={(событие) =>
                  установитьПолучение({
                    ...получение,
                    категорияId: событие.target.value,
                  })
                }
              >
                <option value="">Без категории</option>
                {категории
                  .filter(
                    (категория) => !категория.архив && категория.вид === 'доход',
                  )
                  .map((категория) => (
                    <option key={категория.id} value={категория.id}>
                      {категория.название}
                    </option>
                  ))}
              </Select>
            </Field>
          </div>
        </div>
      </Dialog>

      <Dialog
        открыто={платёжОткрыт}
        наЗакрытие={() => показатьПлатёж(false)}
        заголовок="Обязательный платёж"
        подпись="Будет защищён в расчёте до дохода"
        подвал={
          <>
            <Button вид="тихая" onClick={() => показатьПлатёж(false)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={сохранитьПлатёж}
              disabled={
                !черновик.название.trim() || !черновик.сумма || !черновик.дата
              }
            >
              Добавить
            </Button>
          </>
        }
      >
        <div className="space-y-4">
          <Field подпись="Название" обязательное>
            <Input
              value={черновик.название}
              onChange={(событие) =>
                установитьЧерновик({ ...черновик, название: событие.target.value })
              }
              autoFocus
            />
          </Field>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Сумма" обязательное>
              <MoneyInput
                value={черновик.сумма}
                onChange={(сумма) => установитьЧерновик({ ...черновик, сумма })}
              />
            </Field>
            <Field подпись="Дата" обязательное>
              <Input
                type="date"
                value={черновик.дата}
                onChange={(событие) =>
                  установитьЧерновик({ ...черновик, дата: событие.target.value })
                }
              />
            </Field>
          </div>
          <Field
            подпись="Связать с обязательством"
            подсказка="Связанный платёж не будет вычтен второй раз"
          >
            <Select
              value={черновик.обязательствоId}
              onChange={(событие) =>
                установитьЧерновик({
                  ...черновик,
                  обязательствоId: событие.target.value,
                })
              }
            >
              <option value="">Без связи</option>
              {обязательства
                .filter(
                  (обязательство) =>
                    !обязательство.закрыто &&
                    обязательство.направление === 'я должен',
                )
                .map((обязательство) => (
                  <option key={обязательство.id} value={обязательство.id}>
                    {обязательство.название}
                  </option>
                ))}
            </Select>
          </Field>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Счёт для оплаты">
              <Select
                value={черновик.счётId}
                onChange={(событие) =>
                  установитьЧерновик({ ...черновик, счётId: событие.target.value })
                }
              >
                <option value="">Выбрать при оплате</option>
                {счета
                  .filter((счёт) => !счёт.архив && счёт.тип !== 'кредитная карта')
                  .map((счёт) => (
                    <option key={счёт.id} value={счёт.id}>
                      {счёт.название}
                    </option>
                  ))}
              </Select>
            </Field>
            <Field подпись="Категория расхода">
              <Select
                value={черновик.категорияId}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    категорияId: событие.target.value,
                  })
                }
              >
                <option value="">Без категории</option>
                {категории
                  .filter(
                    (категория) => !категория.архив && категория.вид === 'расход',
                  )
                  .map((категория) => (
                    <option key={категория.id} value={категория.id}>
                      {категория.название}
                    </option>
                  ))}
              </Select>
            </Field>
          </div>
        </div>
      </Dialog>

      <Dialog
        открыто={кПроведению !== null}
        наЗакрытие={() => установитьКПроведению(null)}
        заголовок="Провести платёж"
        подпись={кПроведению?.название}
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьКПроведению(null)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={провестиПлатёж}
              disabled={!счётПроведения}
            >
              Провести {деньги(кПроведению?.сумма ?? null)}
            </Button>
          </>
        }
      >
        <div className="space-y-4">
          <p className="rounded-3 border border-warn/30 bg-warn-soft px-4 py-3 text-meta text-ink-2">
            После подтверждения будет создан расход сегодняшним днём, а платёж
            перестанет удерживаться в защищённой сумме.
          </p>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Списать со счёта" обязательное>
              <Select
                value={счётПроведения}
                onChange={(событие) =>
                  установитьСчётПроведения(событие.target.value)
                }
              >
                <option value="">Не выбран</option>
                {счета
                  .filter((счёт) => !счёт.архив && счёт.тип !== 'кредитная карта')
                  .map((счёт) => (
                    <option key={счёт.id} value={счёт.id}>
                      {счёт.название}
                    </option>
                  ))}
              </Select>
            </Field>
            <Field подпись="Категория">
              <Select
                value={категорияПроведения}
                onChange={(событие) =>
                  установитьКатегориюПроведения(событие.target.value)
                }
              >
                <option value="">Без категории</option>
                {категории
                  .filter(
                    (категория) => !категория.архив && категория.вид === 'расход',
                  )
                  .map((категория) => (
                    <option key={категория.id} value={категория.id}>
                      {категория.название}
                    </option>
                  ))}
              </Select>
            </Field>
          </div>
          {кПроведению?.обязательствоId ? (
            <p className="text-caption text-ink-3">
              Платёж связан с обязательством. Разбивка на тело, проценты и штрафы
              остаётся в разделе «Обязательства» и не угадывается автоматически.
            </p>
          ) : null}
        </div>
      </Dialog>
    </>
  )
}
