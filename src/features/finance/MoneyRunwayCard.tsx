import { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'
import { CalendarClock, Plus, ShieldCheck } from 'lucide-react'
import { база } from '@/core/db/db'
import { изменитьНастройки, новаяЗапись } from '@/core/db/repo'
import type {
  КатегорияДенег,
  Настройки,
  Обязательство,
  ПлановыйПлатёж,
  Счёт,
} from '@/core/db/types'
import { сейчас } from '@/core/db/RecordId'
import { деньСловами, сегодня } from '@/core/calendar/CalendarRu'
import { деньги, копейкиВРубли, рублиВКопейки } from '@/core/money/Money'
import type { РасчётДоДохода } from './model/SafeToSpend'
import { разобратьДниДохода, type ПереносВыходного } from './model/IncomeSchedule'
import { useИнтерфейс } from '@/app/providers/ui'
import { ЗНАЧОК } from '@/design-system/iconSize'
import {
  Badge,
  Button,
  Card,
  CardBody,
  CardHeader,
  Dialog,
  EmptyState,
  Field,
  Input,
  Metric,
  MoneyInput,
  Select,
  Switch,
} from '@/design-system/components'

interface ЧерновикПлатежа {
  название: string
  сумма: string
  дата: string
  обязательствоId: string
  счётId: string
  категорияId: string
}

function причинаТекст(расчёт: РасчётДоДохода) {
  switch (расчёт.причина) {
    case 'нет подтверждённого остатка':
      return 'Подтвердите остатки всех учитываемых собственных счетов.'
    case 'не указана дата следующего дохода':
      return 'Укажите дату ближайшего достаточно надёжного дохода.'
    case 'дата дохода уже прошла':
      return 'Дата дохода прошла или заполнена неверно — обновите горизонт.'
    case 'неизвестна сумма обязательного платежа':
      return 'У ближайшего долгового платежа не указана минимальная сумма.'
    default:
      return 'Заполните исходные данные, чтобы получить безопасный лимит.'
  }
}

export function MoneyRunwayCard({
  расчёт,
  настройки,
  платежи,
  обязательства,
  датаДохода: расчётнаяДатаДохода,
  счета,
  категории,
}: {
  расчёт: РасчётДоДохода
  настройки: Настройки
  платежи: ПлановыйПлатёж[]
  обязательства: Обязательство[]
  датаДохода: string | null
  счета: Счёт[]
  категории: КатегорияДенег[]
}) {
  const сообщить = useИнтерфейс((состояние) => состояние.сообщить)
  const [настройкаОткрыта, показатьНастройку] = useState(false)
  const [платёжОткрыт, показатьПлатёж] = useState(false)
  const [датаДохода, установитьДатуДохода] = useState('')
  const [доход, установитьДоход] = useState('')
  const [дниДохода, установитьДниДохода] = useState('')
  const [перенос, установитьПеренос] = useState<ПереносВыходного>('без переноса')
  const [резервОтдельно, установитьРезервОтдельно] = useState(false)
  const [черновик, установитьЧерновик] = useState<ЧерновикПлатежа>({
    название: '',
    сумма: '',
    дата: сегодня(),
    обязательствоId: '',
    счётId: '',
    категорияId: '',
  })
  const [кПроведению, установитьКПроведению] = useState<ПлановыйПлатёж | null>(null)
  const [счётПроведения, установитьСчётПроведения] = useState('')
  const [категорияПроведения, установитьКатегориюПроведения] = useState('')

  useEffect(() => {
    if (!настройкаОткрыта) return
    установитьДатуДохода(настройки.денежныйГоризонт?.датаСледующегоДохода ?? '')
    const ожидаемый = настройки.денежныйГоризонт?.ожидаемыйДоход
    установитьДоход(
      ожидаемый === null || ожидаемый === undefined
        ? ''
        : String(копейкиВРубли(ожидаемый)),
    )
    установитьДниДохода((настройки.денежныйГоризонт?.дниДохода ?? []).join(', '))
    установитьПеренос(
      настройки.денежныйГоризонт?.переносВыходного ?? 'без переноса',
    )
    установитьРезервОтдельно(настройки.резервУжеИсключён ?? false)
  }, [настройкаОткрыта, настройки.денежныйГоризонт, настройки.резервУжеИсключён])

  const ожидаемыйДоход = настройки.денежныйГоризонт?.ожидаемыйДоход ?? null
  const ближайшиеПлатежи = платежи
    .filter((платёж) => платёж.обязательный && !платёж.оплачен)
    .sort((а, б) => а.дата.localeCompare(б.дата))
    .slice(0, 5)

  async function сохранитьГоризонт() {
    await изменитьНастройки({
      резервУжеИсключён: резервОтдельно,
      денежныйГоризонт: {
        датаСледующегоДохода: датаДохода || null,
        ожидаемыйДоход: рублиВКопейки(доход),
        дниДохода: разобратьДниДохода(дниДохода),
        переносВыходного: перенос,
      },
    })
    показатьНастройку(false)
    сообщить('Денежный горизонт сохранён')
  }

  async function сохранитьПлатёж() {
    const сумма = рублиВКопейки(черновик.сумма)
    if (
      !черновик.название.trim() ||
      сумма === null ||
      сумма <= 0 ||
      !черновик.дата
    ) {
      return
    }
    await база.plannedPayments.add(
      новаяЗапись({
        название: черновик.название.trim(),
        сумма,
        дата: черновик.дата,
        счётId: черновик.счётId || null,
        категорияId: черновик.категорияId || null,
        обязательствоId: черновик.обязательствоId || null,
        обязательный: true,
        оплачен: false,
        операцияId: null,
      }) as never,
    )
    показатьПлатёж(false)
    установитьЧерновик({
      название: '',
      сумма: '',
      дата: сегодня(),
      обязательствоId: '',
      счётId: '',
      категорияId: '',
    })
    сообщить('Обязательный платёж добавлен')
  }

  function открытьПроведение(платёж: ПлановыйПлатёж) {
    установитьКПроведению(платёж)
    установитьСчётПроведения(платёж.счётId ?? '')
    установитьКатегориюПроведения(платёж.категорияId ?? '')
  }

  async function провестиПлатёж() {
    if (!кПроведению || !счётПроведения) return
    const платёж = кПроведению
    const категория = категории.find(
      (элемент) => элемент.id === категорияПроведения,
    )
    await база.transaction(
      'rw',
      база.operations,
      база.plannedPayments,
      async () => {
        const свежий = await база.plannedPayments.get(платёж.id)
        if (!свежий || свежий.оплачен) return
        const операция = новаяЗапись({
          дата: сегодня(),
          тип: 'расход' as const,
          сумма: свежий.сумма,
          счётId: счётПроведения,
          счётПолучательId: null,
          категорияId: категорияПроведения || null,
          классРасхода: категория?.классПоУмолчанию ?? 'обязательный',
          заметка: свежий.название,
          планId: свежий.id,
          отпечатокИмпорта: null,
          разобрана: Boolean(категорияПроведения),
        })
        await база.operations.add(операция as never)
        await база.plannedPayments.put({
          ...свежий,
          счётId: счётПроведения,
          категорияId: категорияПроведения || null,
          оплачен: true,
          операцияId: операция.id,
          updatedAt: сейчас(),
        })
      },
    )
    установитьКПроведению(null)
    сообщить('Платёж проведён и записан в операции')
  }

  return (
    <>
      <Card>
        <CardHeader
          заголовок={
            <span className="flex items-center gap-2.5">
              <ShieldCheck size={ЗНАЧОК.основной} className="text-accent" />
              Капитал до следующего дохода
            </span>
          }
          подпись="Главный денежный ресурс: только уже имеющиеся собственные деньги"
          действие={
            <Button
              вид="контур"
              размер="малый"
              onClick={() => показатьНастройку(true)}
            >
              Настроить
            </Button>
          }
        />

        {расчёт.готов ? (
          <>
            <div className="grid grid-cols-2 gap-5 px-5 pb-5 lg:grid-cols-4">
              <Metric
                подпись="Собственные деньги"
                значение={деньги(расчёт.собственные)}
                источник="расчётные остатки счетов"
              />
              <Metric
                подпись="Защищено"
                значение={деньги(расчёт.защищено)}
                источник="резерв + ближайшие платежи"
              />
              <Metric
                подпись="Можно потратить"
                значение={деньги(расчёт.можноПотратить)}
                источник={`до ${расчётнаяДатаДохода ? деньСловами(расчётнаяДатаДохода) : 'дохода'}`}
                тон={(расчёт.можноПотратить ?? 0) < 0 ? 'опасность' : 'успех'}
              />
              <Metric
                подпись="Лимит в день"
                значение={деньги(расчёт.лимитВДень)}
                источник={`на ${расчёт.дней ?? 0} дн., без будущего дохода`}
                тон={(расчёт.можноПотратить ?? 0) < 0 ? 'опасность' : 'нейтральный'}
              />
            </div>
            <div className="grid gap-2 border-t border-line px-5 py-4 text-caption text-ink-2 sm:grid-cols-3">
              <p>
                Резерв:{' '}
                <span className="tnum text-ink">{деньги(расчёт.резерв)}</span>
              </p>
              <p>
                Плановые платежи:{' '}
                <span className="tnum text-ink">
                  {деньги(расчёт.плановыеПлатежи)}
                </span>
              </p>
              <p>
                Минимумы по долгам:{' '}
                <span className="tnum text-ink">
                  {деньги(расчёт.платежиПоДолгам)}
                </span>
              </p>
            </div>
          </>
        ) : (
          <EmptyState
            иконка={<CalendarClock size={ЗНАЧОК.основной} />}
            заголовок="Безопасный лимит пока неизвестен"
            подпись={причинаТекст(расчёт)}
            действие={
              расчёт.причина === 'нет подтверждённого остатка' ? (
                <Link
                  to="/finance/accounts"
                  className="inline-flex h-11 items-center rounded-2 border border-accent-line px-4 text-meta font-medium text-accent hover:bg-accent-soft"
                >
                  Проверить счета
                </Link>
              ) : расчёт.причина === 'неизвестна сумма обязательного платежа' ? (
                <Link
                  to="/obligations"
                  className="inline-flex h-11 items-center rounded-2 border border-accent-line px-4 text-meta font-medium text-accent hover:bg-accent-soft"
                >
                  Проверить обязательства
                </Link>
              ) : (
                <Button вид="контур" onClick={() => показатьНастройку(true)}>
                  Указать доход
                </Button>
              )
            }
          />
        )}

        <div className="border-t border-line">
          <div className="flex flex-wrap items-center justify-between gap-3 px-5 py-4">
            <div>
              <p className="text-meta font-medium text-ink">Ближайшие платежи</p>
              <p className="text-caption text-ink-3">
                Проведение создаёт расход и закрывает напоминание одной транзакцией
              </p>
            </div>
            <Button
              вид="обычная"
              размер="малый"
              иконка={<Plus size={ЗНАЧОК.строка} />}
              onClick={() => показатьПлатёж(true)}
            >
              Платёж
            </Button>
          </div>
          {ближайшиеПлатежи.length > 0 ? (
            <div className="divide-y divide-line border-t border-line">
              {ближайшиеПлатежи.map((платёж) => (
                <div key={платёж.id} className="flex items-center gap-3 px-5 py-3">
                  <div className="min-w-0 flex-1">
                    <p className="truncate text-meta text-ink">{платёж.название}</p>
                    <p className="text-caption text-ink-3">
                      {деньСловами(платёж.дата)}
                      {платёж.обязательствоId ? ' · связано с долгом' : ''}
                    </p>
                  </div>
                  <span className="tnum shrink-0 text-meta text-ink">
                    {деньги(платёж.сумма)}
                  </span>
                  <Button
                    вид="контур"
                    размер="малый"
                    onClick={() => открытьПроведение(платёж)}
                  >
                    Провести
                  </Button>
                </div>
              ))}
            </div>
          ) : (
            <CardBody className="border-t border-line py-4">
              <p className="text-meta text-ink-3">
                Обязательных платежей не добавлено. Это означает «нет данных», а не
                «платежей точно нет».
              </p>
            </CardBody>
          )}
        </div>

        {ожидаемыйДоход !== null && расчётнаяДатаДохода ? (
          <div className="border-t border-line px-5 py-3">
            <Badge тон="сведения">
              Ожидается {деньги(ожидаемыйДоход)} · не прибавлено к доступным
            </Badge>
          </div>
        ) : null}
      </Card>

      <Dialog
        открыто={настройкаОткрыта}
        наЗакрытие={() => показатьНастройку(false)}
        заголовок="Денежный горизонт"
        подпись="До какой даты защитить обязательные деньги"
        подвал={
          <>
            <Button вид="тихая" onClick={() => показатьНастройку(false)}>
              Отмена
            </Button>
            <Button вид="основная" onClick={сохранитьГоризонт}>
              Сохранить
            </Button>
          </>
        }
      >
        <div className="space-y-4">
          <Field подпись="Дата следующего надёжного дохода">
            <Input
              type="date"
              value={датаДохода}
              onChange={(событие) => установитьДатуДохода(событие.target.value)}
            />
          </Field>
          <div className="rounded-3 border border-line bg-sunken p-4">
            <div className="flex flex-wrap items-end gap-3">
              <Field
                подпись="Повторяющиеся дни месяца"
                подсказка="Например: 10, 25"
                className="min-w-48 flex-1"
              >
                <Input
                  value={дниДохода}
                  onChange={(событие) => установитьДниДохода(событие.target.value)}
                  placeholder="10, 25"
                />
              </Field>
              <Button
                вид="контур"
                размер="малый"
                onClick={() => {
                  установитьДниДохода('10, 25')
                  установитьПеренос('раньше')
                }}
              >
                Пресет: 10 и 25
              </Button>
            </div>
            <Field подпись="Если выплата в выходной" className="mt-3">
              <Select
                value={перенос}
                onChange={(событие) =>
                  установитьПеренос(событие.target.value as ПереносВыходного)
                }
              >
                <option value="раньше">Предыдущий рабочий день</option>
                <option value="позже">Следующий рабочий день</option>
                <option value="без переноса">Не переносить</option>
              </Select>
            </Field>
            <p className="mt-2 text-caption text-ink-3">
              По графику дата пересчитается сама. Учитываются суббота и воскресенье;
              официальные праздники приложение не угадывает.
            </p>
          </div>
          <Field
            подпись="Ожидаемая сумма"
            подсказка="Только ориентир: до фактического получения не считается деньгами"
          >
            <MoneyInput
              value={доход}
              onChange={установитьДоход}
              placeholder="не задана"
            />
          </Field>
          <Switch
            включён={резервОтдельно}
            наИзменение={установитьРезервОтдельно}
            подпись="Резерв уже вынесен из доступных денег"
            описание="Включайте только если резерв лежит на счёте с выключенным учётом в доступных — тогда он не вычтется второй раз"
          />
        </div>
      </Dialog>

      <Dialog
        открыто={платёжОткрыт}
        наЗакрытие={() => показатьПлатёж(false)}
        заголовок="Обязательный платёж"
        подпись="Будет защищён в расчёте до дохода"
        подвал={
          <>
            <Button вид="тихая" onClick={() => показатьПлатёж(false)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={сохранитьПлатёж}
              disabled={
                !черновик.название.trim() || !черновик.сумма || !черновик.дата
              }
            >
              Добавить
            </Button>
          </>
        }
      >
        <div className="space-y-4">
          <Field подпись="Название" обязательное>
            <Input
              value={черновик.название}
              onChange={(событие) =>
                установитьЧерновик({ ...черновик, название: событие.target.value })
              }
              autoFocus
            />
          </Field>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Сумма" обязательное>
              <MoneyInput
                value={черновик.сумма}
                onChange={(сумма) => установитьЧерновик({ ...черновик, сумма })}
              />
            </Field>
            <Field подпись="Дата" обязательное>
              <Input
                type="date"
                value={черновик.дата}
                onChange={(событие) =>
                  установитьЧерновик({ ...черновик, дата: событие.target.value })
                }
              />
            </Field>
          </div>
          <Field
            подпись="Связать с обязательством"
            подсказка="Связанный платёж не будет вычтен второй раз"
          >
            <Select
              value={черновик.обязательствоId}
              onChange={(событие) =>
                установитьЧерновик({
                  ...черновик,
                  обязательствоId: событие.target.value,
                })
              }
            >
              <option value="">Без связи</option>
              {обязательства
                .filter(
                  (обязательство) =>
                    !обязательство.закрыто &&
                    обязательство.направление === 'я должен',
                )
                .map((обязательство) => (
                  <option key={обязательство.id} value={обязательство.id}>
                    {обязательство.название}
                  </option>
                ))}
            </Select>
          </Field>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Счёт для оплаты">
              <Select
                value={черновик.счётId}
                onChange={(событие) =>
                  установитьЧерновик({ ...черновик, счётId: событие.target.value })
                }
              >
                <option value="">Выбрать при оплате</option>
                {счета
                  .filter((счёт) => !счёт.архив && счёт.тип !== 'кредитная карта')
                  .map((счёт) => (
                    <option key={счёт.id} value={счёт.id}>
                      {счёт.название}
                    </option>
                  ))}
              </Select>
            </Field>
            <Field подпись="Категория расхода">
              <Select
                value={черновик.категорияId}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    категорияId: событие.target.value,
                  })
                }
              >
                <option value="">Без категории</option>
                {категории
                  .filter(
                    (категория) => !категория.архив && категория.вид === 'расход',
                  )
                  .map((категория) => (
                    <option key={категория.id} value={категория.id}>
                      {категория.название}
                    </option>
                  ))}
              </Select>
            </Field>
          </div>
        </div>
      </Dialog>

      <Dialog
        открыто={кПроведению !== null}
        наЗакрытие={() => установитьКПроведению(null)}
        заголовок="Провести платёж"
        подпись={кПроведению?.название}
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьКПроведению(null)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={провестиПлатёж}
              disabled={!счётПроведения}
            >
              Провести {деньги(кПроведению?.сумма ?? null)}
            </Button>
          </>
        }
      >
        <div className="space-y-4">
          <p className="rounded-3 border border-warn/30 bg-warn-soft px-4 py-3 text-meta text-ink-2">
            После подтверждения будет создан расход сегодняшним днём, а платёж
            перестанет удерживаться в защищённой сумме.
          </p>
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Списать со счёта" обязательное>
              <Select
                value={счётПроведения}
                onChange={(событие) =>
                  установитьСчётПроведения(событие.target.value)
                }
              >
                <option value="">Не выбран</option>
                {счета
                  .filter((счёт) => !счёт.архив && счёт.тип !== 'кредитная карта')
                  .map((счёт) => (
                    <option key={счёт.id} value={счёт.id}>
                      {счёт.название}
                    </option>
                  ))}
              </Select>
            </Field>
            <Field подпись="Категория">
              <Select
                value={категорияПроведения}
                onChange={(событие) =>
                  установитьКатегориюПроведения(событие.target.value)
                }
              >
                <option value="">Без категории</option>
                {категории
                  .filter(
                    (категория) => !категория.архив && категория.вид === 'расход',
                  )
                  .map((категория) => (
                    <option key={категория.id} value={категория.id}>
                      {категория.название}
                    </option>
                  ))}
              </Select>
            </Field>
          </div>
          {кПроведению?.обязательствоId ? (
            <p className="text-caption text-ink-3">
              Платёж связан с обязательством. Разбивка на тело, проценты и штрафы
              остаётся в разделе «Обязательства» и не угадывается автоматически.
            </p>
          ) : null}
        </div>
      </Dialog>
    </>
  )
}
