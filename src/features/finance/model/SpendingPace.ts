import type { Копейки, ДатаДень } from '@/core/db/types'
import { разностьДней } from '@/core/calendar/CalendarRu'

/**
 * Темп трат — прогноз, а не просто остаток.
 *
 * Считается только из того, что уже потрачено к сегодняшнему дню: сколько
 * дней прошло, сколько тратится в среднем за день, сколько это даст на
 * оставшиеся дни периода. Ничего не додумывается сверх арифметики — прогноз
 * линейный, без попытки угадать будущие траты умнее, чем позволяют цифры.
 */
export interface ТемпТрат {
  расходыДоСегодня: Копейки
  прошедшихДней: number
  всегоДнейПериода: number
  оставшихсяДней: number
  темпВДень: Копейки
  прогнозНаОстаток: Копейки
  прогнозИтогПериода: Копейки
}

/** `null` — сегодня вне периода: закрытый или будущий период не прогнозируется. */
export function темпТрат(параметры: {
  расходыДоСегодня: Копейки
  от: ДатаДень
  до: ДатаДень
  сегодня: ДатаДень
}): ТемпТрат | null {
  const { расходыДоСегодня, от, до, сегодня } = параметры
  if (сегодня < от || сегодня > до) return null

  const всегоДнейПериода = разностьДней(от, до) + 1
  const прошедшихДней = разностьДней(от, сегодня) + 1
  const оставшихсяДней = всегоДнейПериода - прошедшихДней
  const темпВДень = Math.round(расходыДоСегодня / прошедшихДней)
  const прогнозНаОстаток = темпВДень * оставшихсяДней

  return {
    расходыДоСегодня,
    прошедшихДней,
    всегоДнейПериода,
    оставшихсяДней,
    темпВДень,
    прогнозНаОстаток,
    прогнозИтогПериода: расходыДоСегодня + прогнозНаОстаток,
  }
}
