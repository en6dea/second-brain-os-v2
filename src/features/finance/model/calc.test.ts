describe('объяснитьРасхождение', () => {
  it('при совпадении не выдумывает причин', () => {
    const итог = объяснитьРасхождение({
      фактический: 100000,
      расчётный: 100000,
      неразобранныхОпераций: 0,
      переводовЗаПериод: 0,
      остатокНеПодтверждён: false,
      возможныхДублей: 0,
    })
    expect(итог.совпало).toBe(true)
    expect(итог.причины).toHaveLength(0)
  })

  it('называет конкретные причины расхождения', () => {
    const итог = объяснитьРасхождение({
      фактический: 120000,
      расчётный: 100000,
      неразобранныхОпераций: 3,
      переводовЗаПериод: 1,
      остатокНеПодтверждён: true,
      возможныхДублей: 2,
    })
    expect(итог.расхождение).toBe(20000)
    expect(итог.причины.length).toBeGreaterThanOrEqual(4)
    expect(итог.причины.at(-1)).toContain('поступления')
  })

  it('без начального остатка честно сообщает, что сравнивать не с чем', () => {
    const итог = объяснитьРасхождение({
      фактический: 100000,
      расчётный: null,
      неразобранныхОпераций: 0,
      переводовЗаПериод: 0,
      остатокНеПодтверждён: true,
      возможныхДублей: 0,
    })
    expect(итог.совпало).toBe(false)
    expect(итог.причины[0]).toContain('не заполнен')
  })
})
