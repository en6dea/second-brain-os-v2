import { describe, expect, it } from 'vitest'
import {
  влияниеНаСчёт,
  итогОбязательств,
  итогПериода,
  итогПоСчетам,
  объяснитьРасхождение,
  расчётныйОстаток,
  свободныеДеньги,
} from './calc'
import type { Обязательство, Операция, Счёт } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'

function счёт(изменения: Partial<Счёт> = {}): Счёт {
  return {
    id: 'с1',
    createdAt: момент,
    updatedAt: момент,
    название: 'Карта',
    тип: 'карта',
    валюта: 'RUB',
    фактическийОстаток: 0,
    подтверждён: null,
    кредитныйЛимит: null,
    учитыватьВДоступных: true,
    архив: false,
    порядок: 0,
    ...изменения,
  }
}

function операция(изменения: Partial<Операция> = {}): Операция {
  return {
    id: 'о1',
    createdAt: момент,
    updatedAt: момент,
    дата: '2026-08-05',
    тип: 'расход',
    сумма: 10000,
    счётId: 'с1',
    счётПолучательId: null,
    категорияId: null,
    классРасхода: null,
    заметка: '',
    планId: null,
    отпечатокИмпорта: null,
    разобрана: true,
    ...изменения,
  }
}

describe('итогПоСчетам', () => {
  it('не считает незаполненный остаток нулём', () => {
    const итог = итогПоСчетам([
      счёт({ id: 'а', фактическийОстаток: 500000 }),
      счёт({ id: 'б', фактическийОстаток: null, название: 'Вклад' }),
    ])
    expect(итог.собственные).toBe(500000)
    expect(итог.счетовБезОстатка).toBe(1)
    expect(итог.названияБезОстатка).toEqual(['Вклад'])
  })

  it('не считает кредитный лимит собственными деньгами', () => {
    const итог = итогПоСчетам([
      счёт({
        id: 'к',
        тип: 'кредитная карта',
        фактическийОстаток: -20000,
        кредитныйЛимит: 10000000,
      }),
    ])
    expect(итог.собственные).toBe(0)
    expect(итог.кредитныйЛимитДоступен).toBe(9980000)
  })

  it('пропускает счета, исключённые из доступных', () => {
    const итог = итогПоСчетам([
      счёт({ id: 'а', фактическийОстаток: 100000 }),
      счёт({ id: 'б', фактическийОстаток: 900000, учитыватьВДоступных: false }),
    ])
    expect(итог.собственные).toBe(100000)
  })
})

describe('влияниеНаСчёт и расчётныйОстаток', () => {
  it('перевод уменьшает счёт-источник и увеличивает получателя', () => {
    const перевод = операция({
      тип: 'перевод',
      сумма: 50000,
      счётId: 'с1',
      счётПолучательId: 'с2',
    })
    expect(влияниеНаСчёт(перевод, 'с1')).toBe(-50000)
    expect(влияниеНаСчёт(перевод, 'с2')).toBe(50000)
    expect(влияниеНаСчёт(перевод, 'с3')).toBe(0)
  })

  it('учитывает только операции после подтверждения остатка', () => {
    const текущий = счёт({
      фактическийОстаток: 100000,
      подтверждён: '2026-08-10T00:00:00.000Z',
    })
    const до = операция({ createdAt: '2026-08-09T00:00:00.000Z', сумма: 30000 })
    const после = операция({
      id: 'о2',
      createdAt: '2026-08-11T00:00:00.000Z',
      сумма: 25000,
    })
    expect(расчётныйОстаток(текущий, [до, после])).toBe(75000)
  })

  it('без подтверждённого остатка возвращает «неизвестно»', () => {
    expect(расчётныйОстаток(счёт({ фактическийОстаток: null }), [])).toBeNull()
  })
})

describe('итогПериода', () => {
  it('перевод не является ни доходом, ни расходом', () => {
    const итог = итогПериода(
      [
        операция({ id: '1', тип: 'доход', сумма: 100000, дата: '2026-08-03' }),
        операция({ id: '2', тип: 'расход', сумма: 40000, дата: '2026-08-04' }),
        операция({
          id: '3',
          тип: 'перевод',
          сумма: 70000,
          дата: '2026-08-05',
          счётПолучательId: 'с2',
        }),
      ],
      '2026-08-01',
      '2026-08-31',
    )
    expect(итог.доходы).toBe(100000)
    expect(итог.расходы).toBe(40000)
    expect(итог.переводы).toBe(70000)
    expect(итог.поток).toBe(60000)
  })

  it('возврат уменьшает расходы', () => {
    const итог = итогПериода(
      [
        операция({ id: '1', тип: 'расход', сумма: 50000, дата: '2026-08-02' }),
        операция({ id: '2', тип: 'возврат', сумма: 20000, дата: '2026-08-06' }),
      ],
      '2026-08-01',
      '2026-08-31',
    )
    expect(итог.расходы).toBe(30000)
  })
})

