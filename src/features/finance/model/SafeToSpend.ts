import type {
  ДатаДень,
  Копейки,
  Обязательство,
  ПлановыйПлатёж,
} from '@/core/db/types'

export type ПричинаНеполногоГоризонта =
  | 'нет подтверждённого остатка'
  | 'не указана дата следующего дохода'
  | 'дата дохода уже прошла'
  | 'неизвестна сумма обязательного платежа'

export interface РасчётДоДохода {
  готов: boolean
  причина: ПричинаНеполногоГоризонта | null
  дней: number | null
  собственные: Копейки | null
  резерв: Копейки
  плановыеПлатежи: Копейки
  платежиПоДолгам: Копейки
  защищено: Копейки
  можноПотратить: Копейки | null
  лимитВДень: Копейки | null
  платежейУчтено: number
  долговУчтено: number
  долговБезСуммы: number
}

function деньUTC(дата: ДатаДень): number | null {
  const совпадение = /^(\d{4})-(\d{2})-(\d{2})$/.exec(дата)
  if (!совпадение) return null
  const год = Number(совпадение[1])
  const месяц = Number(совпадение[2])
  const день = Number(совпадение[3])
  const значение = Date.UTC(год, месяц - 1, день)
  const проверка = new Date(значение)
  if (
    проверка.getUTCFullYear() !== год ||
    проверка.getUTCMonth() !== месяц - 1 ||
    проверка.getUTCDate() !== день
  ) {
    return null
  }
  return значение
}

function попадаетВГоризонт(дата: ДатаДень | null, от: ДатаДень, до: ДатаДень) {
  return дата !== null && дата >= от && дата <= до
}

/**
 * Сколько действительно можно потратить до следующего подтверждённого дохода.
 *
 * В расчёт входят только уже имеющиеся собственные деньги. Будущий доход,
 * кредитные лимиты и суммы «мне должны» сюда не прибавляются. Из остатка
 * защищаются резерв, обязательные запланированные платежи и минимальные
 * платежи по долгам, срок которых наступает внутри горизонта.
 */
export function рассчитатьДоДохода(параметры: {
  сегодня: ДатаДень
  датаСледующегоДохода: ДатаДень | null
  собственные: Копейки | null
  минимальныйРезерв: Копейки
  плановыеПлатежи: ПлановыйПлатёж[]
  обязательства: Обязательство[]
}): РасчётДоДохода {
  const основа = {
    собственные: параметры.собственные,
    резерв: Math.max(0, параметры.минимальныйРезерв),
    плановыеПлатежи: 0,
    платежиПоДолгам: 0,
    защищено: Math.max(0, параметры.минимальныйРезерв),
    можноПотратить: null,
    лимитВДень: null,
    платежейУчтено: 0,
    долговУчтено: 0,
    долговБезСуммы: 0,
  } satisfies Omit<РасчётДоДохода, 'готов' | 'причина' | 'дней'>

  if (параметры.собственные === null) {
    return {
      готов: false,
      причина: 'нет подтверждённого остатка',
      дней: null,
      ...основа,
    }
  }

  if (параметры.датаСледующегоДохода === null) {
    return {
      готов: false,
      причина: 'не указана дата следующего дохода',
      дней: null,
      ...основа,
    }
  }

  const сегодняUTC = деньUTC(параметры.сегодня)
  const доходUTC = деньUTC(параметры.датаСледующегоДохода)
  if (сегодняUTC === null || доходUTC === null || доходUTC < сегодняUTC) {
    return {
      готов: false,
      причина: 'дата дохода уже прошла',
      дней: null,
      ...основа,
    }
  }

  const платежи = параметры.плановыеПлатежи.filter(
    (платёж) =>
      платёж.обязательный &&
      !платёж.оплачен &&
      попадаетВГоризонт(
        платёж.дата,
        параметры.сегодня,
        параметры.датаСледующегоДохода as ДатаДень,
      ),
  )
  const плановыеПлатежи = платежи.reduce((сумма, платёж) => сумма + платёж.сумма, 0)

  // Если плановый платёж явно связан с обязательством, он точнее общего
  // минимального платежа и учитывается один раз, а не двумя вычетами.
  const связанныеОбязательства = new Set(
    параметры.плановыеПлатежи
      .filter(
        (платёж) =>
          платёж.обязательный &&
          попадаетВГоризонт(
            платёж.дата,
            параметры.сегодня,
            параметры.датаСледующегоДохода as ДатаДень,
          ) &&
          (!платёж.оплачен || платёж.операцияId !== null),
      )
      .map((платёж) => платёж.обязательствоId)
      .filter((id): id is string => typeof id === 'string' && id.length > 0),
  )

  const долги = параметры.обязательства.filter(
    (обязательство) =>
      обязательство.направление === 'я должен' &&
      !обязательство.закрыто &&
      !связанныеОбязательства.has(обязательство.id) &&
      попадаетВГоризонт(
        обязательство.датаСледующегоПлатежа,
        параметры.сегодня,
        параметры.датаСледующегоДохода as ДатаДень,
      ),
  )
  const известныеДолги = долги.filter(
    (обязательство) => обязательство.минимальныйПлатёж !== null,
  )
  const платежиПоДолгам = известныеДолги.reduce(
    (сумма, обязательство) => сумма + (обязательство.минимальныйПлатёж ?? 0),
    0,
  )

  const резерв = Math.max(0, параметры.минимальныйРезерв)
  const защищено = резерв + плановыеПлатежи + платежиПоДолгам
  const можноПотратить = параметры.собственные - защищено
  const дней = Math.floor((доходUTC - сегодняUTC) / 86_400_000) + 1
  const долговБезСуммы = долги.length - известныеДолги.length

  if (долговБезСуммы > 0) {
    return {
      готов: false,
      причина: 'неизвестна сумма обязательного платежа',
      дней,
      собственные: параметры.собственные,
      резерв,
      плановыеПлатежи,
      платежиПоДолгам,
      защищено,
      можноПотратить: null,
      лимитВДень: null,
      платежейУчтено: платежи.length,
      долговУчтено: известныеДолги.length,
      долговБезСуммы,
    }
  }

  return {
    готов: true,
    причина: null,
    дней,
    собственные: параметры.собственные,
    резерв,
    плановыеПлатежи,
    платежиПоДолгам,
    защищено,
    можноПотратить,
    лимитВДень: Math.floor(Math.max(0, можноПотратить) / дней),
    платежейУчтено: платежи.length,
    долговУчтено: известныеДолги.length,
    долговБезСуммы,
  }
}
