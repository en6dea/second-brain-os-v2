import { describe, expect, it } from 'vitest'
import type { Обязательство, ПлановыйПлатёж } from '@/core/db/types'
import { рассчитатьДоДохода } from './SafeToSpend'

function платёж(изменения: Partial<ПлановыйПлатёж> = {}): ПлановыйПлатёж {
  return {
    id: 'платёж',
    createdAt: '2026-08-24T08:00:00.000Z',
    updatedAt: '2026-08-24T08:00:00.000Z',
    название: 'Аренда',
    сумма: 30_000_00,
    дата: '2026-08-28',
    категорияId: null,
    счётId: null,
    обязательный: true,
    оплачен: false,
    операцияId: null,
    ...изменения,
  }
}

function долг(изменения: Partial<Обязательство> = {}): Обязательство {
  return {
    id: 'долг',
    createdAt: '2026-08-24T08:00:00.000Z',
    updatedAt: '2026-08-24T08:00:00.000Z',
    название: 'Кредит',
    направление: 'я должен',
    вид: 'кредит',
    телоОстаток: 200_000_00,
    начисленныеПроценты: null,
    штрафы: null,
    ставкаГодовых: null,
    минимальныйПлатёж: 10_000_00,
    датаСледующегоПлатежа: '2026-08-29',
    повторПлатежа: 'ежемесячно',
    датаОкончания: null,
    контрагент: '',
    закрыто: false,
    заметка: '',
    ...изменения,
  }
}

describe('рассчитатьДоДохода', () => {
  it('защищает резерв и только платежи внутри горизонта', () => {
    const итог = рассчитатьДоДохода({
      сегодня: '2026-08-24',
      датаСледующегоДохода: '2026-08-31',
      собственные: 100_000_00,
      минимальныйРезерв: 20_000_00,
      плановыеПлатежи: [
        платёж(),
        платёж({ id: 'позже', дата: '2026-09-02', сумма: 99_000_00 }),
        платёж({ id: 'оплачен', оплачен: true, сумма: 7_000_00 }),
      ],
      обязательства: [долг()],
    })

    expect(итог).toEqual(
      expect.objectContaining({
        готов: true,
        дней: 8,
        плановыеПлатежи: 30_000_00,
        платежиПоДолгам: 10_000_00,
        защищено: 60_000_00,
        можноПотратить: 40_000_00,
        лимитВДень: 5_000_00,
      }),
    )
  })

  it('не считает всё тело долга расходом до дохода', () => {
    const итог = рассчитатьДоДохода({
      сегодня: '2026-08-24',
      датаСледующегоДохода: '2026-08-31',
      собственные: 50_000_00,
      минимальныйРезерв: 0,
      плановыеПлатежи: [],
      обязательства: [
        долг({ телоОстаток: 900_000_00, минимальныйПлатёж: 5_000_00 }),
      ],
    })

    expect(итог.можноПотратить).toBe(45_000_00)
    expect(итог.платежиПоДолгам).toBe(5_000_00)
  })

  it('не выдаёт ноль за расчёт, если остаток неизвестен', () => {
    const итог = рассчитатьДоДохода({
      сегодня: '2026-08-24',
      датаСледующегоДохода: '2026-08-31',
      собственные: null,
      минимальныйРезерв: 10_000_00,
      плановыеПлатежи: [],
      обязательства: [],
    })

    expect(итог.готов).toBe(false)
    expect(итог.причина).toBe('нет подтверждённого остатка')
    expect(итог.можноПотратить).toBeNull()
  })

  it('показывает неизвестный минимальный платёж, не подставляя ноль', () => {
    const итог = рассчитатьДоДохода({
      сегодня: '2026-08-24',
      датаСледующегоДохода: '2026-08-31',
      собственные: 50_000_00,
      минимальныйРезерв: 0,
      плановыеПлатежи: [],
      обязательства: [долг({ минимальныйПлатёж: null })],
    })

    expect(итог.долговБезСуммы).toBe(1)
    expect(итог.платежиПоДолгам).toBe(0)
    expect(итог.готов).toBe(false)
    expect(итог.можноПотратить).toBeNull()
    expect(итог.причина).toBe('неизвестна сумма обязательного платежа')
  })

  it('не вычитает долг второй раз, если с ним связан плановый платёж', () => {
    const итог = рассчитатьДоДохода({
      сегодня: '2026-08-24',
      датаСледующегоДохода: '2026-08-31',
      собственные: 50_000_00,
      минимальныйРезерв: 0,
      плановыеПлатежи: [платёж({ обязательствоId: 'долг', сумма: 12_000_00 })],
      обязательства: [долг({ минимальныйПлатёж: 10_000_00 })],
    })

    expect(итог.готов).toBe(true)
    expect(итог.плановыеПлатежи).toBe(12_000_00)
    expect(итог.платежиПоДолгам).toBe(0)
    expect(итог.можноПотратить).toBe(38_000_00)
  })

  it('не возвращает минимум долга после проведения связанного платежа', () => {
    const итог = рассчитатьДоДохода({
      сегодня: '2026-08-24',
      датаСледующегоДохода: '2026-08-31',
      собственные: 38_000_00,
      минимальныйРезерв: 0,
      плановыеПлатежи: [
        платёж({
          обязательствоId: 'долг',
          сумма: 12_000_00,
          оплачен: true,
          операцияId: 'операция',
        }),
      ],
      обязательства: [долг({ минимальныйПлатёж: 10_000_00 })],
    })

    expect(итог.готов).toBe(true)
    expect(итог.плановыеПлатежи).toBe(0)
    expect(итог.платежиПоДолгам).toBe(0)
    expect(итог.можноПотратить).toBe(38_000_00)
  })

  it('не использует прошедшую дату дохода', () => {
    const итог = рассчитатьДоДохода({
      сегодня: '2026-08-24',
      датаСледующегоДохода: '2026-08-23',
      собственные: 50_000_00,
      минимальныйРезерв: 0,
      плановыеПлатежи: [],
      обязательства: [],
    })

    expect(итог.готов).toBe(false)
    expect(итог.причина).toBe('дата дохода уже прошла')
  })
})
