import { рублиВКопейки } from '@/core/money/Money'
import type { Копейки } from '@/core/db/types'

/**
 * Разбор банковской выписки.
 *
 * Форматы у банков разные, поэтому разделитель, кодировка чисел и порядок
 * столбцов определяются по содержимому, а результат обязательно показывается
 * человеку до записи в базу.
 */

export type Направление = 'доход' | 'расход'

export interface СтрокаВыписки {
  номер: number
  дата: string | null
  /** Сумма со знаком: расход отрицателен. */
  сумма: Копейки | null
  направление: Направление
  /** Почему выбрано это направление. Показывается человеку в предпросмотре. */
  основаниеЗнака: string
  описание: string
  исходная: string[]
  отпечаток: string
}

export interface Столбцы {
  дата: number | null
  сумма: number | null
  приход: number | null
  расход: number | null
  направление: number | null
  описание: number | null
}

export interface РазборВыписки {
  разделитель: string
  заголовки: string[]
  столбцы: Столбцы
  строки: СтрокаВыписки[]
  пропущено: number
  доходов: number
  расходов: number
  /**
   * Знак определён по содержимому файла, а не предположен.
   * Ложь означает: в файле нет ни знака, ни столбца направления,
   * и направление принято по умолчанию — это нужно показать человеку.
   */
  знакНадёжен: boolean
  предупреждения: string[]
}

/** Разбор строки CSV с учётом кавычек. */
export function разобратьСтроку(строка: string, разделитель: string): string[] {
  const ячейки: string[] = []
  let текущая = ''
  let вКавычках = false

  for (let индекс = 0; индекс < строка.length; индекс += 1) {
    const символ = строка[индекс]
    if (символ === '"') {
      if (вКавычках && строка[индекс + 1] === '"') {
        текущая += '"'
        индекс += 1
      } else вКавычках = !вКавычках
    } else if (символ === разделитель && !вКавычках) {
      ячейки.push(текущая.trim())
      текущая = ''
    } else {
      текущая += символ
    }
  }
  ячейки.push(текущая.trim())
  return ячейки
}

export function определитьРазделитель(текст: string): string {
  const первые = текст.split(/\r?\n/).slice(0, 5).join('\n')
  const кандидаты = [';', ',', '\t', '|']
  let лучший = ';'
  let максимум = 0
  for (const кандидат of кандидаты) {
    const количество = первые.split(кандидат).length - 1
    if (количество > максимум) {
      максимум = количество
      лучший = кандидат
    }
  }
  return лучший
}

/** Дата из выписки: ДД.ММ.ГГГГ, ГГГГ-ММ-ДД, ДД/ММ/ГГГГ. */
export function разобратьДату(значение: string): string | null {
  const текст = значение.trim()
  if (!текст) return null

  const исо = текст.match(/^(\d{4})-(\d{2})-(\d{2})/)
  if (исо) return `${исо[1]}-${исо[2]}-${исо[3]}`

  const точки = текст.match(/^(\d{2})[./](\d{2})[./](\d{4})/)
  if (точки) return `${точки[3]}-${точки[2]}-${точки[1]}`

  const короткий = текст.match(/^(\d{2})[./](\d{2})[./](\d{2})\b/)
  if (короткий) return `20${короткий[3]}-${короткий[2]}-${короткий[1]}`

  return null
}

/** Сумма из выписки: «1 234,56», «-1234.56», «1 234,56 ₽». */
export function разобратьСумму(значение: string): Копейки | null {
  const исходное = значение.trim()

  // Отрицательное число банки записывают тремя способами: минусом впереди,
  // минусом в конце («1 234,56-») и скобками («(1 234,56)»). Все три
  // означают списание, и потерять этот знак нельзя.
  const вСкобках = /^\(.*\)$/.test(исходное)
  const минусВКонце = /[-−]\s*$/.test(исходное)

  let очищено = исходное
    .replace(/[^\d,.\-−]/g, '')
    .replace(/−/g, '-')
    .trim()
  if (!очищено || очищено === '-') return null

  if (вСкобках || минусВКонце) {
    очищено = `-${очищено.replace(/-/g, '')}`
  }

  // Если есть и точка, и запятая — последняя из них дробный разделитель.
  const последняяЗапятая = очищено.lastIndexOf(',')
  const последняяТочка = очищено.lastIndexOf('.')
  let нормализовано = очищено

  if (последняяЗапятая >= 0 && последняяТочка >= 0) {
    нормализовано =
      последняяЗапятая > последняяТочка
        ? очищено.replace(/\./g, '').replace(',', '.')
        : очищено.replace(/,/g, '')
  } else if (последняяЗапятая >= 0) {
    нормализовано = очищено.replace(',', '.')
  }

  return рублиВКопейки(нормализовано)
}

const ИМЕНА_ОПИСАНИЯ = [
  'описание',
  'назначение',
  'детали',
  'контрагент',
  'получатель',
  'комментарий',
  'description',
]

/** Слова, по которым в ячейке узнаётся списание. */
const СЛОВА_РАСХОДА = [
  'расход',
  'списан',
  'снятие',
  'покупка',
  'оплата',
  'платеж',
  'платёж',
  'дебет',
  'debit',
  'withdrawal',
  'outgoing',
]

/** Слова, по которым в ячейке узнаётся поступление. */
const СЛОВА_ПРИХОДА = [
  'приход',
  'поступлен',
  'зачислен',
  'пополнен',
  'возврат',
  'кредит',
  'credit',
  'deposit',
  'incoming',
]

function содержит(строка: string, слова: string[]): boolean {
  return слова.some((слово) => строка.includes(слово))
}

/**
 * Роль столбца по его заголовку.
 *
 * Порядок правил важен. Заголовок «Сумма списания» содержит и «сумма», и
 * «списан»; если сначала проверять «сумма», такой столбец станет обычной
 * суммой, знак потеряется и все расходы превратятся в доходы. Поэтому
 * приход и расход проверяются раньше суммы.
 */
export function рольСтолбца(заголовокСырой: string): keyof Столбцы | null {
  const заголовок = заголовокСырой.toLowerCase().replace(/ё/g, 'е').trim()
  if (!заголовок) return null

  const кПриходу = содержит(заголовок, ['приход', 'поступлен', 'зачислен', 'пополнен'])
  const кРасходу = содержит(заголовок, ['расход', 'списан', 'снятие'])

  // «Приход/Расход» — это не сумма, а направление одной колонкой.
  if (кПриходу && кРасходу) return 'направление'
  if (кПриходу) return 'приход'
  if (кРасходу) return 'расход'

  if (заголовок === 'дебет' || заголовок === 'debit') return 'расход'
  if (заголовок === 'кредит' || заголовок === 'credit') return 'приход'

  if (
    заголовок.includes('тип') ||
    заголовок === 'направление' ||
    заголовок === 'вид'
  ) {
    return 'направление'
  }

  if (заголовок.includes('сумма') || заголовок === 'amount') return 'сумма'
  if (заголовок.includes('дата') || заголовок.includes('date')) return 'дата'
  if (содержит(заголовок, ИМЕНА_ОПИСАНИЯ) || заголовок === 'операция') {
    return 'описание'
  }
  return null
}

export function определитьСтолбцы(заголовки: string[]): Столбцы {
  const столбцы: Столбцы = {
    дата: null,
    сумма: null,
    приход: null,
    расход: null,
    направление: null,
    описание: null,
  }
  заголовки.forEach((заголовок, индекс) => {
    const роль = рольСтолбца(заголовок)
    // Первый подходящий столбец выигрывает: в выписках повторные столбцы
    // обычно уточняющие («Сумма в валюте операции» после «Сумма платежа»).
    if (роль && столбцы[роль] === null) столбцы[роль] = индекс
  })
  return столбцы
}

/** Направление по значению столбца направления. `null` — слово незнакомое. */
export function направлениеИзЯчейки(значение: string): Направление | null {
  const текст = значение.toLowerCase().replace(/ё/g, 'е').trim()
  if (!текст) return null
  if (содержит(текст, СЛОВА_ПРИХОДА)) return 'доход'
  if (содержит(текст, СЛОВА_РАСХОДА)) return 'расход'
  return null
}

export function отпечатокСтроки(
  дата: string | null,
  сумма: Копейки | null,
  описание: string,
): string {
  const текст = описание.toLowerCase().replace(/\s+/g, ' ').trim()
  return `${дата ?? 'нет-даты'}|${сумма ?? 'нет-суммы'}|${текст}`
}

export function разобратьВыписку(содержимое: string): РазборВыписки {
  const разделитель = определитьРазделитель(содержимое)
  const строкиФайла = содержимое
    .split(/\r?\n/)
    .filter((строка) => строка.trim().length > 0)

  const пустыеСтолбцы: Столбцы = {
    дата: null,
    сумма: null,
    приход: null,
    расход: null,
    направление: null,
    описание: null,
  }

  if (строкиФайла.length === 0) {
    return {
      разделитель,
      заголовки: [],
      столбцы: пустыеСтолбцы,
      строки: [],
      пропущено: 0,
      доходов: 0,
      расходов: 0,
      знакНадёжен: true,
      предупреждения: [],
    }
  }

  const заголовки = разобратьСтроку(строкиФайла[0] ?? '', разделитель)
  const столбцы = определитьСтолбцы(заголовки)

  const строки: СтрокаВыписки[] = []
  const предупреждения: string[] = []
  let пропущено = 0
  let безОснования = 0

  // Несёт ли столбец суммы знак — решается по всему файлу сразу. По одной
  // строке этого не понять: «1500» без минуса может быть и доходом, и
  // расходом, а вот наличие минусов где-то ниже отвечает на вопрос.
  const столбецСоЗнаком =
    столбцы.сумма !== null &&
    строкиФайла.slice(1).some((строка) => {
      const значение =
        разобратьСтроку(строка, разделитель)[столбцы.сумма as number] ?? ''
      const сумма = разобратьСумму(значение)
      return сумма !== null && сумма < 0
    })

  for (let индекс = 1; индекс < строкиФайла.length; индекс += 1) {
    const ячейки = разобратьСтроку(строкиФайла[индекс] ?? '', разделитель)
    const дата =
      столбцы.дата !== null ? разобратьДату(ячейки[столбцы.дата] ?? '') : null

    const разобранное = разобратьЗнак(ячейки, столбцы, столбецСоЗнаком)
    const описание =
      столбцы.описание !== null
        ? (ячейки[столбцы.описание] ?? '')
        : ячейки.join(' ')

    if (дата === null || разобранное === null) {
      пропущено += 1
      continue
    }

    if (разобранное.основание === ПО_УМОЛЧАНИЮ) безОснования += 1

    строки.push({
      номер: индекс,
      дата,
      сумма: разобранное.сумма,
      направление: разобранное.сумма < 0 ? 'расход' : 'доход',
      основаниеЗнака: разобранное.основание,
      описание,
      исходная: ячейки,
      отпечаток: отпечатокСтроки(дата, разобранное.сумма, описание),
    })
  }

  const доходов = строки.filter((строка) => строка.направление === 'доход').length
  const расходов = строки.length - доходов
  const знакНадёжен = безОснования === 0

  if (!знакНадёжен) {
    предупреждения.push(
      `В файле нет ни знака у суммы, ни столбца с направлением. ` +
        `${безОснования} из ${строки.length} строк принято за расходы — ` +
        `так чаще всего и бывает в выписке. Проверьте и при необходимости ` +
        `поменяйте направление кнопкой ниже.`,
    )
  }

  if (столбцы.дата === null) {
    предупреждения.push('Столбец с датой не найден — строки без даты пропущены.')
  }

  return {
    разделитель,
    заголовки,
    столбцы,
    строки,
    пропущено,
    доходов,
    расходов,
    знакНадёжен,
    предупреждения,
  }
}

/** Пометка строки, знак которой пришлось принять по умолчанию. */
export const ПО_УМОЛЧАНИЮ = 'знак не указан в файле'

/**
 * Знак суммы одной строки.
 *
 * Порядок доверия:
 *  1. Отдельные столбцы прихода и расхода — самое однозначное.
 *  2. Столбец направления рядом с суммой.
 *  3. Знак у самой суммы.
 *  4. Ничего из этого — считаем расходом и честно помечаем строку.
 *
 * Четвёртый случай — единственный, где приложение принимает решение за
 * человека, и именно поэтому он отмечается отдельно и виден в предпросмотре.
 */
export function разобратьЗнак(
  ячейки: string[],
  столбцы: Столбцы,
  столбецСоЗнаком: boolean,
): { сумма: Копейки; основание: string } | null {
  if (столбцы.приход !== null || столбцы.расход !== null) {
    const приход =
      столбцы.приход !== null ? разобратьСумму(ячейки[столбцы.приход] ?? '') : null
    const расход =
      столбцы.расход !== null ? разобратьСумму(ячейки[столбцы.расход] ?? '') : null

    if (расход !== null && расход !== 0) {
      return { сумма: -Math.abs(расход), основание: 'столбец расхода' }
    }
    if (приход !== null && приход !== 0) {
      return { сумма: Math.abs(приход), основание: 'столбец прихода' }
    }
    // Оба столбца пусты — возможно, сумма лежит в отдельном столбце.
  }

  if (столбцы.сумма === null) return null
  const сумма = разобратьСумму(ячейки[столбцы.сумма] ?? '')
  if (сумма === null || сумма === 0) return null

  if (столбцы.направление !== null) {
    const направление = направлениеИзЯчейки(ячейки[столбцы.направление] ?? '')
    if (направление === 'расход') {
      return { сумма: -Math.abs(сумма), основание: 'столбец направления' }
    }
    if (направление === 'доход') {
      return { сумма: Math.abs(сумма), основание: 'столбец направления' }
    }
  }

  if (сумма < 0) return { сумма, основание: 'минус у суммы' }

  // Положительная сумма. Если где-то в этом же столбце минусы встречаются,
  // значит столбец знак несёт, и плюс здесь означает настоящий доход.
  if (столбецСоЗнаком) return { сумма, основание: 'сумма без минуса' }

  // Минусов нет нигде: знака в файле просто нет. Решение принимается за
  // человека, и строка помечается, чтобы это было видно.
  return { сумма: -сумма, основание: ПО_УМОЛЧАНИЮ }
}

/** Подсказка категории по словам из назначения платежа. */
export function подсказатьКатегорию(
  описание: string,
  категории: { id: string; название: string; правила: string[]; вид: string }[],
): string | null {
  const текст = описание.toLowerCase()
  for (const категория of категории) {
    if (категория.вид !== 'расход') continue
    for (const правило of категория.правила) {
      if (правило && текст.includes(правило.toLowerCase())) return категория.id
    }
  }
  return null
}
