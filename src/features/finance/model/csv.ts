import { рублиВКопейки } from '@/core/money/Money'
import type { Копейки } from '@/core/db/types'

/**
 * Разбор банковской выписки.
 *
 * Форматы у банков разные, поэтому разделитель, кодировка чисел и порядок
 * столбцов определяются по содержимому, а результат обязательно показывается
 * человеку до записи в базу.
 */

export interface СтрокаВыписки {
  номер: number
  дата: string | null
  сумма: Копейки | null
  описание: string
  исходная: string[]
  отпечаток: string
}

export interface РазборВыписки {
  разделитель: string
  заголовки: string[]
  столбцы: {
    дата: number | null
    сумма: number | null
    приход: number | null
    расход: number | null
    описание: number | null
  }
  строки: СтрокаВыписки[]
  пропущено: number
}

/** Разбор строки CSV с учётом кавычек. */
export function разобратьСтроку(строка: string, разделитель: string): string[] {
  const ячейки: string[] = []
  let текущая = ''
  let вКавычках = false

  for (let индекс = 0; индекс < строка.length; индекс += 1) {
    const символ = строка[индекс]
    if (символ === '"') {
      if (вКавычках && строка[индекс + 1] === '"') {
        текущая += '"'
        индекс += 1
      } else вКавычках = !вКавычках
    } else if (символ === разделитель && !вКавычках) {
      ячейки.push(текущая.trim())
      текущая = ''
    } else {
      текущая += символ
    }
  }
  ячейки.push(текущая.trim())
  return ячейки
}

export function определитьРазделитель(текст: string): string {
  const первые = текст.split(/\r?\n/).slice(0, 5).join('\n')
  const кандидаты = [';', ',', '\t', '|']
  let лучший = ';'
  let максимум = 0
  for (const кандидат of кандидаты) {
    const количество = первые.split(кандидат).length - 1
    if (количество > максимум) {
      максимум = количество
      лучший = кандидат
    }
  }
  return лучший
}

/** Дата из выписки: ДД.ММ.ГГГГ, ГГГГ-ММ-ДД, ДД/ММ/ГГГГ. */
export function разобратьДату(значение: string): string | null {
  const текст = значение.trim()
  if (!текст) return null

  const исо = текст.match(/^(\d{4})-(\d{2})-(\d{2})/)
  if (исо) return `${исо[1]}-${исо[2]}-${исо[3]}`

  const точки = текст.match(/^(\d{2})[./](\d{2})[./](\d{4})/)
  if (точки) return `${точки[3]}-${точки[2]}-${точки[1]}`

  const короткий = текст.match(/^(\d{2})[./](\d{2})[./](\d{2})\b/)
  if (короткий) return `20${короткий[3]}-${короткий[2]}-${короткий[1]}`

  return null
}

/** Сумма из выписки: «1 234,56», «-1234.56», «1 234,56 ₽». */
export function разобратьСумму(значение: string): Копейки | null {
  const очищено = значение
    .replace(/[^\d,.\-−]/g, '')
    .replace(/−/g, '-')
    .trim()
  if (!очищено || очищено === '-') return null

  // Если есть и точка, и запятая — последняя из них дробный разделитель.
  const последняяЗапятая = очищено.lastIndexOf(',')
  const последняяТочка = очищено.lastIndexOf('.')
  let нормализовано = очищено

  if (последняяЗапятая >= 0 && последняяТочка >= 0) {
    нормализовано =
      последняяЗапятая > последняяТочка
        ? очищено.replace(/\./g, '').replace(',', '.')
        : очищено.replace(/,/g, '')
  } else if (последняяЗапятая >= 0) {
    нормализовано = очищено.replace(',', '.')
  }

  return рублиВКопейки(нормализовано)
}

const ИМЕНА_ДАТЫ = ['дата', 'date', 'дата операции', 'дата проводки']
const ИМЕНА_СУММЫ = ['сумма', 'amount', 'сумма операции', 'сумма в валюте счёта']
const ИМЕНА_ПРИХОДА = ['приход', 'поступление', 'кредит', 'зачисление', 'credit']
const ИМЕНА_РАСХОДА = ['расход', 'списание', 'дебет', 'debit']
const ИМЕНА_ОПИСАНИЯ = [
  'описание',
  'назначение',
  'назначение платежа',
  'операция',
  'детали',
  'контрагент',
  'description',
]

function найтиСтолбец(заголовки: string[], имена: string[]): number | null {
  for (let индекс = 0; индекс < заголовки.length; индекс += 1) {
    const заголовок = (заголовки[индекс] ?? '').toLowerCase().trim()
    if (имена.some((имя) => заголовок === имя)) return индекс
  }
  for (let индекс = 0; индекс < заголовки.length; индекс += 1) {
    const заголовок = (заголовки[индекс] ?? '').toLowerCase().trim()
    if (имена.some((имя) => заголовок.includes(имя))) return индекс
  }
  return null
}

export function отпечатокСтроки(
  дата: string | null,
  сумма: Копейки | null,
  описание: string,
): string {
  const текст = описание.toLowerCase().replace(/\s+/g, ' ').trim()
  return `${дата ?? 'нет-даты'}|${сумма ?? 'нет-суммы'}|${текст}`
}

export function разобратьВыписку(содержимое: string): РазборВыписки {
  const разделитель = определитьРазделитель(содержимое)
  const строкиФайла = содержимое
    .split(/\r?\n/)
    .filter((строка) => строка.trim().length > 0)

  if (строкиФайла.length === 0) {
    return {
      разделитель,
      заголовки: [],
      столбцы: {
        дата: null,
        сумма: null,
        приход: null,
        расход: null,
        описание: null,
      },
      строки: [],
      пропущено: 0,
    }
  }

  const заголовки = разобратьСтроку(строкиФайла[0] ?? '', разделитель)
  const столбцы = {
    дата: найтиСтолбец(заголовки, ИМЕНА_ДАТЫ),
    сумма: найтиСтолбец(заголовки, ИМЕНА_СУММЫ),
    приход: найтиСтолбец(заголовки, ИМЕНА_ПРИХОДА),
    расход: найтиСтолбец(заголовки, ИМЕНА_РАСХОДА),
    описание: найтиСтолбец(заголовки, ИМЕНА_ОПИСАНИЯ),
  }

  const строки: СтрокаВыписки[] = []
  let пропущено = 0

  for (let индекс = 1; индекс < строкиФайла.length; индекс += 1) {
    const ячейки = разобратьСтроку(строкиФайла[индекс] ?? '', разделитель)
    const дата =
      столбцы.дата !== null ? разобратьДату(ячейки[столбцы.дата] ?? '') : null

    let сумма: Копейки | null = null
    if (столбцы.сумма !== null) {
      сумма = разобратьСумму(ячейки[столбцы.сумма] ?? '')
    } else {
      const приход =
        столбцы.приход !== null
          ? разобратьСумму(ячейки[столбцы.приход] ?? '')
          : null
      const расход =
        столбцы.расход !== null
          ? разобратьСумму(ячейки[столбцы.расход] ?? '')
          : null
      if (приход !== null && приход !== 0) сумма = Math.abs(приход)
      else if (расход !== null && расход !== 0) сумма = -Math.abs(расход)
    }

    const описание =
      столбцы.описание !== null
        ? (ячейки[столбцы.описание] ?? '')
        : ячейки.join(' ')

    if (дата === null || сумма === null || сумма === 0) {
      пропущено += 1
      continue
    }

    строки.push({
      номер: индекс,
      дата,
      сумма,
      описание,
      исходная: ячейки,
      отпечаток: отпечатокСтроки(дата, сумма, описание),
    })
  }

  return { разделитель, заголовки, столбцы, строки, пропущено }
}

/** Подсказка категории по словам из назначения платежа. */
export function подсказатьКатегорию(
  описание: string,
  категории: { id: string; название: string; правила: string[]; вид: string }[],
): string | null {
  const текст = описание.toLowerCase()
  for (const категория of категории) {
    if (категория.вид !== 'расход') continue
    for (const правило of категория.правила) {
      if (правило && текст.includes(правило.toLowerCase())) return категория.id
    }
  }
  return null
}
