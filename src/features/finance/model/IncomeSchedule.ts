import type { ДатаДень, РегулярныйДоход } from '@/core/db/types'

export type ПереносВыходного = 'раньше' | 'позже' | 'без переноса'

export interface СобытиеДохода {
  ключ: string
  источник: РегулярныйДоход
  дата: ДатаДень
}

const ДНЕЙ_ДЛЯ_ПОЗДНЕГО_ПОДТВЕРЖДЕНИЯ = 7

function строкаДня(дата: Date): ДатаДень {
  return `${дата.getUTCFullYear()}-${String(дата.getUTCMonth() + 1).padStart(2, '0')}-${String(
    дата.getUTCDate(),
  ).padStart(2, '0')}`
}

function разобратьДень(дата: ДатаДень): Date | null {
  const совпадение = /^(\d{4})-(\d{2})-(\d{2})$/.exec(дата)
  if (!совпадение) return null
  const значение = new Date(
    Date.UTC(
      Number(совпадение[1]),
      Number(совпадение[2]) - 1,
      Number(совпадение[3]),
    ),
  )
  return Number.isNaN(значение.getTime()) ? null : значение
}

function скорректироватьВыходной(дата: Date, перенос: ПереносВыходного) {
  const результат = new Date(дата)
  if (перенос === 'без переноса') return результат
  const шаг = перенос === 'раньше' ? -1 : 1
  while (результат.getUTCDay() === 0 || результат.getUTCDay() === 6) {
    результат.setUTCDate(результат.getUTCDate() + шаг)
  }
  return результат
}

function календарнаяДата(
  год: number,
  месяц: number,
  день: number,
  перенос: ПереносВыходного,
) {
  const последнийДень = new Date(Date.UTC(год, месяц + 1, 0)).getUTCDate()
  return скорректироватьВыходной(
    new Date(Date.UTC(год, месяц, Math.min(день, последнийДень))),
    перенос,
  )
}

function ключСобытия(источникId: string, дата: ДатаДень) {
  return `${источникId}:${дата}`
}

/**
 * Ближайшая ещё не подтверждённая выплата из персонального графика.
 * Подтверждение передаётся ключом «источник:плановая-дата» и хранится в
 * фактической операции дохода, поэтому повторное открытие приложения не
 * возвращает уже полученную выплату.
 */
export function следующееСобытиеДохода(параметры: {
  сегодня: ДатаДень
  доходы: РегулярныйДоход[]
  переносВыходного: ПереносВыходного
  подтверждённые?: ReadonlySet<string>
}): СобытиеДохода | null {
  const сегодня = разобратьДень(параметры.сегодня)
  if (!сегодня) return null
  const доходы = параметры.доходы.filter(
    (доход) =>
      доход.id.trim() &&
      доход.название.trim() &&
      Number.isInteger(доход.деньМесяца) &&
      доход.деньМесяца >= 1 &&
      доход.деньМесяца <= 31,
  )
  if (доходы.length === 0) return null

  const кандидаты: СобытиеДохода[] = []
  for (let сдвиг = -1; сдвиг <= 3; сдвиг += 1) {
    const месяц = new Date(
      Date.UTC(сегодня.getUTCFullYear(), сегодня.getUTCMonth() + сдвиг, 1),
    )
    for (const источник of доходы) {
      const дата = строкаДня(
        календарнаяДата(
          месяц.getUTCFullYear(),
          месяц.getUTCMonth(),
          источник.деньМесяца,
          параметры.переносВыходного,
        ),
      )
      кандидаты.push({
        ключ: ключСобытия(источник.id, дата),
        источник,
        дата,
      })
    }
  }

  const сегодняВремя = сегодня.getTime()
  const началоПозднегоПодтверждения =
    сегодняВремя - ДНЕЙ_ДЛЯ_ПОЗДНЕГО_ПОДТВЕРЖДЕНИЯ * 86_400_000
  const неподтверждённые = кандидаты.filter(
    (событие) => !параметры.подтверждённые?.has(событие.ключ),
  )
  const просроченная = неподтверждённые
    .filter((событие) => {
      const дата = разобратьДень(событие.дата)?.getTime() ?? 0
      return дата < сегодняВремя && дата >= началоПозднегоПодтверждения
    })
    .sort((а, б) => б.дата.localeCompare(а.дата))[0]
  if (просроченная) return просроченная

  return (
    неподтверждённые
      .filter((событие) => {
        const дата = разобратьДень(событие.дата)
        return дата !== null && дата.getTime() >= сегодняВремя
      })
      .sort((а, б) => а.дата.localeCompare(б.дата))[0] ?? null
  )
}

export function ключПодтверждённогоДохода(параметры: {
  регулярныйДоходId?: string | null
  плановаяДатаДохода?: ДатаДень | null
}): string | null {
  if (!параметры.регулярныйДоходId || !параметры.плановаяДатаДохода) return null
  return ключСобытия(параметры.регулярныйДоходId, параметры.плановаяДатаДохода)
}

/**
 * Ближайшая дата повторяющегося дохода. Праздники не угадываются: без
 * производственного календаря достоверно известны только суббота и воскресенье.
 */
export function следующаяДатаДохода(параметры: {
  сегодня: ДатаДень
  дниМесяца: number[]
  переносВыходного: ПереносВыходного
}): ДатаДень | null {
  const сегодня = разобратьДень(параметры.сегодня)
  if (!сегодня) return null
  const дни = [...new Set(параметры.дниМесяца)]
    .filter((день) => Number.isInteger(день) && день >= 1 && день <= 31)
    .sort((а, б) => а - б)
  if (дни.length === 0) return null

  const кандидаты: Date[] = []
  for (let сдвиг = 0; сдвиг <= 2; сдвиг += 1) {
    const начало = new Date(
      Date.UTC(сегодня.getUTCFullYear(), сегодня.getUTCMonth() + сдвиг, 1),
    )
    for (const день of дни) {
      кандидаты.push(
        календарнаяДата(
          начало.getUTCFullYear(),
          начало.getUTCMonth(),
          день,
          параметры.переносВыходного,
        ),
      )
    }
  }

  const сегодняВремя = сегодня.getTime()
  const ближайшая = кандидаты
    .filter((кандидат) => кандидат.getTime() >= сегодняВремя)
    .sort((а, б) => а.getTime() - б.getTime())[0]
  return ближайшая ? строкаДня(ближайшая) : null
}

export function разобратьДниДохода(строка: string): number[] {
  return [...new Set(строка.split(/[,;\s]+/).map(Number))]
    .filter((день) => Number.isInteger(день) && день >= 1 && день <= 31)
    .sort((а, б) => а - б)
}
