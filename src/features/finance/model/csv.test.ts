import { describe, expect, it } from 'vitest'
import {
  определитьРазделитель,
  отпечатокСтроки,
  подсказатьКатегорию,
  разобратьВыписку,
  разобратьДату,
  разобратьСтроку,
  разобратьСумму,
  рольСтолбца,
  этоПеревод,
} from './csv'

describe('разбор значений выписки', () => {
  it('понимает русский и международный формат даты', () => {
    expect(разобратьДату('11.08.2026')).toBe('2026-08-11')
    expect(разобратьДату('2026-08-11')).toBe('2026-08-11')
    expect(разобратьДату('11/08/2026')).toBe('2026-08-11')
    expect(разобратьДату('что-то')).toBeNull()
  })

  it('понимает суммы с пробелами, запятой и знаком валюты', () => {
    expect(разобратьСумму('1 234,56 ₽')).toBe(123456)
    expect(разобратьСумму('-1234.56')).toBe(-123456)
    expect(разобратьСумму('1.234,56')).toBe(123456)
    expect(разобратьСумму('1,234.56')).toBe(123456)
    expect(разобратьСумму('')).toBeNull()
  })

  it('уважает кавычки при разборе строки', () => {
    expect(разобратьСтроку('a;"b;c";d', ';')).toEqual(['a', 'b;c', 'd'])
    expect(разобратьСтроку('"он сказал ""да""";2', ';')).toEqual([
      'он сказал "да"',
      '2',
    ])
  })

  it('определяет разделитель по содержимому', () => {
    expect(определитьРазделитель('a;b;c\n1;2;3')).toBe(';')
    expect(определитьРазделитель('a,b,c\n1,2,3')).toBe(',')
  })
})

describe('разобратьВыписку', () => {
  const выписка = [
    'Дата операции;Сумма операции;Назначение платежа',
    '11.08.2026;-1 250,00;Оплата в ПЯТЁРОЧКА',
    '10.08.2026;148 000,00;Зачисление зарплаты',
    'мусор;;',
  ].join('\n')

  it('находит столбцы и разбирает строки', () => {
    const разбор = разобратьВыписку(выписка)
    expect(разбор.столбцы.дата).toBe(0)
    expect(разбор.столбцы.сумма).toBe(1)
    expect(разбор.столбцы.описание).toBe(2)
    expect(разбор.строки).toHaveLength(2)
    expect(разбор.строки[0]?.сумма).toBe(-125000)
    expect(разбор.строки[1]?.сумма).toBe(14800000)
  })

  it('честно сообщает о пропущенных строках, а не молча их теряет', () => {
    expect(разобратьВыписку(выписка).пропущено).toBe(1)
  })

  it('работает с раздельными столбцами прихода и расхода', () => {
    const разбор = разобратьВыписку(
      ['Дата;Приход;Расход;Описание', '11.08.2026;;500,00;Кофе'].join('\n'),
    )
    expect(разбор.строки[0]?.сумма).toBe(-50000)
  })

  it('отпечаток одинаков у одинаковых строк и различается у разных', () => {
    const первый = отпечатокСтроки('2026-08-11', -125000, 'Оплата в ПЯТЁРОЧКА')
    const второй = отпечатокСтроки('2026-08-11', -125000, 'оплата в пятёрочка')
    const третий = отпечатокСтроки('2026-08-11', -125001, 'Оплата в ПЯТЁРОЧКА')
    expect(первый).toBe(второй)
    expect(первый).not.toBe(третий)
  })
})

describe('подсказатьКатегорию', () => {
  const категории = [
    {
      id: 'к1',
      название: 'Продукты',
      правила: ['пятёроч', 'магнит'],
      вид: 'расход',
    },
    { id: 'к2', название: 'Кафе', правила: ['кофе'], вид: 'расход' },
    { id: 'к3', название: 'Зарплата', правила: ['зарплат'], вид: 'доход' },
  ]

  it('находит категорию по слову из назначения', () => {
    expect(подсказатьКатегорию('Оплата в ПЯТЁРОЧКА 1234', категории)).toBe('к1')
    expect(подсказатьКатегорию('Кофе на вынос', категории)).toBe('к2')
  })

  it('не подставляет категорию дохода в расходную подсказку', () => {
    expect(подсказатьКатегорию('Зачисление зарплаты', категории)).toBeNull()
  })

  it('возвращает null, когда совпадений нет', () => {
    expect(подсказатьКатегорию('Неизвестный платёж', категории)).toBeNull()
  })
})

/**
 * Проверки на возврат ошибки: расход, разобранный как доход.
 *
 * Каждый случай ниже встречается в настоящих выписках, и каждый однажды
 * приводил к тому, что списание попадало в приложение как поступление.
 */
describe('направление операции', () => {
  it('столбцы «Сумма прихода» и «Сумма расхода» не путаются с обычной суммой', () => {
    const файл = [
      'Дата;Сумма прихода;Сумма расхода;Описание',
      '01.08.2026;;1500,00;ПЯТЕРОЧКА',
      '02.08.2026;90000,00;;Зарплата',
    ].join('\n')

    const разбор = разобратьВыписку(файл)
    expect(разбор.строки[0]?.направление).toBe('расход')
    expect(разбор.строки[0]?.сумма).toBe(-150000)
    expect(разбор.строки[1]?.направление).toBe('доход')
    expect(разбор.строки[1]?.сумма).toBe(9000000)
    expect(разбор.знакНадёжен).toBe(true)
  })

  it('направление берётся из отдельного столбца типа операции', () => {
    const файл = [
      'Дата операции;Сумма операции;Тип операции;Описание',
      '01.08.2026;1500,00;Списание;ПЯТЕРОЧКА',
      '02.08.2026;90000,00;Пополнение;Зарплата',
    ].join('\n')

    const разбор = разобратьВыписку(файл)
    expect(разбор.строки[0]?.сумма).toBe(-150000)
    expect(разбор.строки[0]?.основаниеЗнака).toBe('столбец направления')
    expect(разбор.строки[1]?.сумма).toBe(9000000)
  })

  it('минус в конце суммы означает списание', () => {
    expect(разобратьСумму('1 234,56-')).toBe(-123456)
  })

  it('скобки вокруг суммы означают списание', () => {
    expect(разобратьСумму('(1 234,56)')).toBe(-123456)
  })

  it('в файле со знаками плюс остаётся доходом', () => {
    const файл = [
      'Дата;Сумма;Описание',
      '01.08.2026;-1500,00;ПЯТЕРОЧКА',
      '02.08.2026;90000,00;Зарплата',
    ].join('\n')

    const разбор = разобратьВыписку(файл)
    expect(разбор.строки[0]?.направление).toBe('расход')
    expect(разбор.строки[1]?.направление).toBe('доход')
    expect(разбор.знакНадёжен).toBe(true)
  })

  it('без единого признака направления считает расходом и говорит об этом', () => {
    const файл = [
      'Дата;Сумма;Описание',
      '01.08.2026;1500,00;ПЯТЕРОЧКА',
      '02.08.2026;780,00;ВКУСВИЛЛ',
    ].join('\n')

    const разбор = разобратьВыписку(файл)
    expect(разбор.расходов).toBe(2)
    expect(разбор.доходов).toBe(0)
    expect(разбор.знакНадёжен).toBe(false)
    expect(разбор.предупреждения[0]).toContain('нет ни знака')
  })

  it('столбец «Дебет» — расход, «Кредит» — приход', () => {
    const файл = [
      'Дата;Дебет;Кредит;Назначение',
      '01.08.2026;1500,00;;Оплата',
      '02.08.2026;;90000,00;Зачисление',
    ].join('\n')

    const разбор = разобратьВыписку(файл)
    expect(разбор.строки[0]?.сумма).toBe(-150000)
    expect(разбор.строки[1]?.сумма).toBe(9000000)
  })

  it('роль столбца определяется по самому точному совпадению', () => {
    expect(рольСтолбца('Сумма списания')).toBe('расход')
    expect(рольСтолбца('Сумма зачисления')).toBe('приход')
    expect(рольСтолбца('Сумма операции')).toBe('сумма')
    expect(рольСтолбца('Приход/Расход')).toBe('направление')
    expect(рольСтолбца('Дата операции')).toBe('дата')
  })
})

/**
 * Выписка Альфа-Банка.
 *
 * Столбцы названы латиницей, суммы идут без знака, а направление лежит в
 * `type` со значениями «Списание» и «Пополнение». Пока `type` не узнавался,
 * знака в файле не находилось вовсе — и вся выписка, включая зарплату,
 * записывалась расходом.
 *
 * Данные здесь выдуманные: настоящая выписка содержит номер счёта и карты.
 */
describe('выписка Альфа-Банка', () => {
  const шапка =
    'operationDate,transactionDate,accountName,accountNumber,cardName,' +
    'cardNumber,merchant,amount,currency,status,category,mcc,type,comment,' +
    'bonusValue,bonusTitle'

  const файл = [
    '﻿' + шапка,
    '12.08.2026,,Основной,40817,"Карта",2200****1111,"Kirov/PYATEROCHKA",244.96,RUR,"В обработке",Продукты,5411,Списание,,,',
    '11.08.2026,11.08.2026,Основной,40817,,,"Работодатель",90000,RUR,,Зарплата,,Пополнение,,,',
    '10.08.2026,10.08.2026,Основной,40817,,,"Между своими счетами",1000,RUR,,Между своими счетами,,Пополнение,,,',
    '09.08.2026,09.08.2026,Основной,40817,,,"Между своими счетами",1000,RUR,,Между своими счетами,,Списание,,,',
  ].join('\n')

  const разбор = разобратьВыписку(файл)

  it('находит столбцы, названные латиницей', () => {
    expect(разбор.разделитель).toBe(',')
    expect(разбор.столбцы.дата).toBe(0)
    expect(разбор.столбцы.сумма).toBe(7)
    expect(разбор.столбцы.направление).toBe(12)
    expect(разбор.столбцы.описание).toBe(6)
    expect(разбор.столбцы.категория).toBe(10)
  })

  it('берёт направление из столбца type, а не считает всё расходом', () => {
    expect(разбор.знакНадёжен).toBe(true)
    expect(разбор.строки[0]?.сумма).toBe(-24496)
    expect(разбор.строки[1]?.сумма).toBe(9000000)
    expect(разбор.строки[0]?.основаниеЗнака).toBe('столбец направления')
    expect(разбор.доходов).toBe(1)
    expect(разбор.расходов).toBe(1)
  })

  it('метка порядка байтов не мешает узнать первый столбец', () => {
    expect(разбор.заголовки[0]).toBe('operationDate')
    expect(разбор.пропущено).toBe(0)
  })

  it('описание берётся из merchant, а не из всей строки', () => {
    expect(разбор.строки[0]?.описание).toBe('Kirov/PYATEROCHKA')
    expect(разбор.строки[0]?.описание).not.toContain('40817')
  })

  it('перевод между своими счетами не доход и не расход', () => {
    expect(разбор.переводов).toBe(2)
    expect(разбор.строки[2]?.перевод).toBe(true)
    expect(разбор.строки[3]?.перевод).toBe(true)
    // Знак у перевода сохраняется: он говорит, в какую сторону ушли деньги.
    expect(разбор.строки[2]?.сумма).toBe(100000)
    expect(разбор.строки[3]?.сумма).toBe(-100000)
  })

  it('покупка в магазине переводом не считается', () => {
    expect(этоПеревод('Продукты', 'Kirov/PYATEROCHKA')).toBe(false)
    expect(этоПеревод('Между своими счетами', '')).toBe(true)
  })
})
