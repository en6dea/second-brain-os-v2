import { describe, expect, it } from 'vitest'
import { темпТрат } from './SpendingPace'

describe('темпТрат', () => {
  it('прогнозирует итог месяца по текущему темпу', () => {
    const итог = темпТрат({
      расходыДоСегодня: 300000,
      от: '2026-08-01',
      до: '2026-08-30',
      сегодня: '2026-08-10',
    })
    expect(итог).not.toBeNull()
    expect(итог?.прошедшихДней).toBe(10)
    expect(итог?.всегоДнейПериода).toBe(30)
    expect(итог?.оставшихсяДней).toBe(20)
    expect(итог?.темпВДень).toBe(30000)
    expect(итог?.прогнозНаОстаток).toBe(600000)
    expect(итог?.прогнозИтогПериода).toBe(900000)
  })

  it('однодневный период: прогноз равен уже потраченному', () => {
    const итог = темпТрат({
      расходыДоСегодня: 50000,
      от: '2026-08-05',
      до: '2026-08-05',
      сегодня: '2026-08-05',
    })
    expect(итог?.всегоДнейПериода).toBe(1)
    expect(итог?.оставшихсяДней).toBe(0)
    expect(итог?.прогнозИтогПериода).toBe(50000)
  })

  it('первый день периода: темп равен расходам за один день', () => {
    const итог = темпТрат({
      расходыДоСегодня: 15000,
      от: '2026-08-01',
      до: '2026-08-31',
      сегодня: '2026-08-01',
    })
    expect(итог?.прошедшихДней).toBe(1)
    expect(итог?.темпВДень).toBe(15000)
  })

  it('сегодня раньше периода — null, ничего не прогнозируется', () => {
    expect(
      темпТрат({
        расходыДоСегодня: 0,
        от: '2026-09-01',
        до: '2026-09-30',
        сегодня: '2026-08-15',
      }),
    ).toBeNull()
  })

  it('сегодня позже периода (период уже закрыт) — null', () => {
    expect(
      темпТрат({
        расходыДоСегодня: 100000,
        от: '2026-07-01',
        до: '2026-07-31',
        сегодня: '2026-08-15',
      }),
    ).toBeNull()
  })

  it('нулевые расходы — темп ноль, прогноз ноль', () => {
    const итог = темпТрат({
      расходыДоСегодня: 0,
      от: '2026-08-01',
      до: '2026-08-30',
      сегодня: '2026-08-10',
    })
    expect(итог?.темпВДень).toBe(0)
    expect(итог?.прогнозИтогПериода).toBe(0)
  })
})
