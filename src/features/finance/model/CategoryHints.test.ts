import { describe, expect, it } from 'vitest'
import { запомнить, опора, подсказать, слова, чемуНаучиться } from './CategoryHints'
import type { КатегорияДенег, Операция } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'

function категория(
  id: string,
  название: string,
  вид: 'доход' | 'расход' = 'расход',
  правила: string[] = [],
): КатегорияДенег {
  return {
    id,
    createdAt: момент,
    updatedAt: момент,
    название,
    вид,
    иконка: '',
    цвет: 'ink-2',
    месячныйЛимит: null,
    классПоУмолчанию: null,
    архив: false,
    порядок: 0,
    правила,
  }
}

function операция(заметка: string, категорияId: string): Операция {
  return {
    id: Math.random().toString(36),
    createdAt: момент,
    updatedAt: момент,
    дата: '2026-08-01',
    тип: 'расход',
    сумма: 10000,
    счётId: null,
    счётПолучательId: null,
    категорияId,
    классРасхода: null,
    заметка,
    планId: null,
    отпечатокИмпорта: null,
    разобрана: true,
  }
}

const продукты = категория('прод', 'Продукты', 'расход', ['лента'])
const кафе = категория('кафе', 'Кафе', 'расход')
const зарплата = категория('зп', 'Зарплата', 'доход')
const категории = [продукты, кафе, зарплата]

describe('разбор описания', () => {
  it('отбрасывает служебные слова и числа', () => {
    expect(слова('Оплата в ПЯТЁРОЧКА 1234 МСК')).toEqual(['пятерочка'])
  })

  it('приводит ё к е, чтобы написание не мешало', () => {
    expect(слова('ПЯТЁРОЧКА')).toEqual(слова('ПЯТЕРОЧКА'))
  })

  it('опора берёт первые значимые слова', () => {
    expect(опора('Оплата в ПЯТЕРОЧКА 1234 МСК')).toBe(опора('ПЯТЕРОЧКА 5678'))
  })
})

describe('подсказать', () => {
  it('без прошлого опыта и без правил молчит, а не угадывает', () => {
    const память = запомнить([])
    expect(подсказать('НЕИЗВЕСТНЫЙ ПЛАТЁЖ', память, [кафе], 'расход')).toBeNull()
  })

  it('учится на прошлых операциях человека', () => {
    const память = запомнить([
      операция('Оплата в ПЯТЕРОЧКА 1234', 'прод'),
      операция('ПЯТЕРОЧКА 9999 МСК', 'прод'),
    ])
    const подсказка = подсказать('Оплата ПЯТЕРОЧКА 7777', память, категории, 'расход')
    expect(подсказка?.категорияId).toBe('прод')
    expect(подсказка?.основание).toContain('похожих операций')
  })

  it('прошлый опыт весомее правила категории', () => {
    // «лента» стоит в правилах категории «Продукты», но человек всегда
    // относил эти платежи в «Кафе» — верим человеку.
    const память = запомнить([
      операция('ЛЕНТА КОФЕЙНЯ', 'кафе'),
      операция('ЛЕНТА КОФЕЙНЯ', 'кафе'),
    ])
    const подсказка = подсказать('ЛЕНТА КОФЕЙНЯ', память, категории, 'расход')
    expect(подсказка?.категорияId).toBe('кафе')
  })

  it('падает на правило категории, когда опыта нет', () => {
    const подсказка = подсказать('ЛЕНТА 44', запомнить([]), категории, 'расход')
    expect(подсказка?.категорияId).toBe('прод')
    expect(подсказка?.основание).toContain('правилах категории')
  })

  it('не предлагает доходную категорию для расхода', () => {
    const память = запомнить([операция('ЗАРПЛАТА', 'зп')])
    expect(подсказать('ЗАРПЛАТА', память, категории, 'расход')).toBeNull()
  })

  it('уверенность растёт с числом совпадений', () => {
    const мало = подсказать(
      'ПЯТЕРОЧКА',
      запомнить([операция('ПЯТЕРОЧКА', 'прод')]),
      категории,
      'расход',
    )
    const много = подсказать(
      'ПЯТЕРОЧКА',
      запомнить(
        Array.from({ length: 20 }, () => операция('ПЯТЕРОЧКА', 'прод')),
      ),
      категории,
      'расход',
    )
    expect(много!.уверенность).toBeGreaterThanOrEqual(мало!.уверенность)
  })
})

describe('чемуНаучиться', () => {
  it('предлагает слово, которого ещё нет в правилах', () => {
    expect(чемуНаучиться('ВКУСВИЛЛ 12', продукты)).toBe('вкусвилл')
  })

  it('молчит, если слово уже покрыто правилом', () => {
    expect(чемуНаучиться('ЛЕНТА 44', продукты)).toBeNull()
  })
})
