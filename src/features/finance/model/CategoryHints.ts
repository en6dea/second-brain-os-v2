import type { КатегорияДенег, Операция } from '@/core/db/types'

/**
 * Подсказчик категорий.
 *
 * Здесь нет искусственного интеллекта, и это осознанно: настоящий означал бы
 * отправку ваших операций на чужой сервер. Вместо этого подсказчик учится на
 * ваших же записях — на том, как вы сами раскладывали похожие платежи раньше.
 *
 * Для банковской выписки такое обучение работает лучше общей модели: названия
 * магазинов у каждого свои, и «ИП ПЕТРОВ» у вас может значить кофе, а у
 * другого — автосервис.
 *
 * Каждая подсказка обязана объяснять себя: сколько раз и на каком основании.
 */

export interface Подсказка {
  категорияId: string
  /** Насколько подсказчик уверен: от 0 до 1. */
  уверенность: number
  /** Почему предложена именно эта категория. Показывается человеку. */
  основание: string
}

/** Слова, которые есть в любой выписке и ничего не различают. */
const ШУМ = new Set([
  'оплата',
  'платеж',
  'платёж',
  'покупка',
  'товары',
  'услуги',
  'руб',
  'rub',
  'card',
  'карта',
  'перевод',
  'ооо',
  'оао',
  'зао',
  'ип',
  'пао',
  'ао',
  'мск',
  'moscow',
  'russia',
  'ru',
])

/** Разбор описания на значимые слова. */
export function слова(описание: string): string[] {
  return описание
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9\s]/g, ' ')
    .split(/\s+/)
    .filter((слово) => слово.length >= 3 && !ШУМ.has(слово) && !/^\d+$/.test(слово))
}

/**
 * Опорная часть описания: первые значимые слова.
 * «Оплата в ПЯТЕРОЧКА 1234 МОСКВА» и «ПЯТЕРОЧКА 5678» дают одну опору.
 */
export function опора(описание: string): string {
  return слова(описание).slice(0, 2).join(' ')
}

interface Счётчик {
  всего: number
  поКатегориям: Map<string, number>
}

export interface ПамятьПодсказчика {
  поОпоре: Map<string, Счётчик>
  поСловам: Map<string, Счётчик>
  операцийУчтено: number
}

/** Память строится один раз на список операций и переиспользуется. */
export function запомнить(операции: Операция[]): ПамятьПодсказчика {
  const поОпоре = new Map<string, Счётчик>()
  const поСловам = new Map<string, Счётчик>()
  let операцийУчтено = 0

  const учесть = (карта: Map<string, Счётчик>, ключ: string, категория: string) => {
    if (!ключ) return
    const счётчик = карта.get(ключ) ?? { всего: 0, поКатегориям: new Map() }
    счётчик.всего += 1
    счётчик.поКатегориям.set(категория, (счётчик.поКатегориям.get(категория) ?? 0) + 1)
    карта.set(ключ, счётчик)
  }

  for (const операция of операции) {
    if (!операция.категорияId || !операция.заметка) continue
    операцийУчтено += 1
    учесть(поОпоре, опора(операция.заметка), операция.категорияId)
    for (const слово of слова(операция.заметка)) {
      учесть(поСловам, слово, операция.категорияId)
    }
  }

  return { поОпоре, поСловам, операцийУчтено }
}

function лучшая(счётчик: Счётчик | undefined): { id: string; раз: number } | null {
  if (!счётчик) return null
  let лучшийId = ''
  let лучшееЧисло = 0
  for (const [id, число] of счётчик.поКатегориям) {
    if (число > лучшееЧисло) {
      лучшееЧисло = число
      лучшийId = id
    }
  }
  return лучшийId ? { id: лучшийId, раз: лучшееЧисло } : null
}

/**
 * Подсказка для одной строки выписки.
 *
 * Порядок доверия:
 *  1. Опора описания встречалась раньше — самое надёжное.
 *  2. Отдельные слова описания сходятся на одной категории.
 *  3. Слово из правил категории.
 *
 * Если ни одно основание не сработало, подсказки нет. Угадывать наугад хуже,
 * чем оставить поле пустым: пустое видно, а неверная категория тихо портит
 * отчёт.
 */
export function подсказать(
  описание: string,
  память: ПамятьПодсказчика,
  категории: КатегорияДенег[],
  вид: 'доход' | 'расход',
): Подсказка | null {
  const подходящие = new Set(
    категории.filter((к) => к.вид === вид && !к.архив).map((к) => к.id),
  )
  if (подходящие.size === 0) return null

  /* 1. Опора описания */
  const поОпоре = лучшая(память.поОпоре.get(опора(описание)))
  if (поОпоре && подходящие.has(поОпоре.id) && поОпоре.раз >= 1) {
    const счётчик = память.поОпоре.get(опора(описание))!
    const доля = поОпоре.раз / счётчик.всего
    return {
      категорияId: поОпоре.id,
      уверенность: Math.min(0.98, 0.6 + доля * 0.38),
      основание: `так же вы относили ${поОпоре.раз} ${поОпоре.раз === 1 ? 'похожую операцию' : 'похожих операций'}`,
    }
  }

  /* 2. Согласие отдельных слов */
  const голоса = new Map<string, number>()
  let словУчтено = 0
  for (const слово of слова(описание)) {
    const лучший = лучшая(память.поСловам.get(слово))
    if (!лучший || !подходящие.has(лучший.id)) continue
    словУчтено += 1
    голоса.set(лучший.id, (голоса.get(лучший.id) ?? 0) + лучший.раз)
  }
  if (голоса.size > 0) {
    let победитель = ''
    let максимум = 0
    for (const [id, вес] of голоса) {
      if (вес > максимум) {
        максимум = вес
        победитель = id
      }
    }
    if (победитель) {
      return {
        категорияId: победитель,
        уверенность: Math.min(0.75, 0.35 + словУчтено * 0.1),
        основание: `по словам из назначения; в прошлом они ${максимум} ${максимум === 1 ? 'раз вели' : 'раза вели'} в эту категорию`,
      }
    }
  }

  /* 3. Правила категории */
  const текст = описание.toLowerCase().replace(/ё/g, 'е')
  for (const категория of категории) {
    if (категория.вид !== вид || категория.архив) continue
    for (const правило of категория.правила) {
      const образец = правило.toLowerCase().replace(/ё/g, 'е')
      if (образец && текст.includes(образец)) {
        return {
          категорияId: категория.id,
          уверенность: 0.5,
          основание: `по слову «${правило}» в правилах категории`,
        }
      }
    }
  }

  return null
}

/**
 * Пополнение правил категории новыми словами.
 *
 * Когда человек поправил подсказку, стоит запомнить его выбор — но не молча:
 * функция возвращает слово, которое имеет смысл добавить, а решение принимает
 * человек.
 */
export function чемуНаучиться(
  описание: string,
  категория: КатегорияДенег,
): string | null {
  const кандидаты = слова(описание)
  if (кандидаты.length === 0) return null
  const первое = кандидаты[0]
  if (!первое) return null
  const уже = категория.правила.some((правило) =>
    первое.includes(правило.toLowerCase()),
  )
  return уже ? null : первое
}
