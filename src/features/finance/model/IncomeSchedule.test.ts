import { describe, expect, it } from 'vitest'
import { разобратьДниДохода, следующаяДатаДохода } from './IncomeSchedule'

describe('следующаяДатаДохода', () => {
  it('выбирает ближайший день из графика 10 и 25', () => {
    expect(
      следующаяДатаДохода({
        сегодня: '2026-08-24',
        дниМесяца: [10, 25],
        переносВыходного: 'раньше',
      }),
    ).toBe('2026-08-25')
  })

  it('переносит воскресенье на предыдущую пятницу', () => {
    expect(
      следующаяДатаДохода({
        сегодня: '2026-10-20',
        дниМесяца: [25],
        переносВыходного: 'раньше',
      }),
    ).toBe('2026-10-23')
  })

  it('не возвращает перенесённую дату, если она уже прошла', () => {
    expect(
      следующаяДатаДохода({
        сегодня: '2026-10-24',
        дниМесяца: [10, 25],
        переносВыходного: 'раньше',
      }),
    ).toBe('2026-11-10')
  })

  it('не угадывает график из пустого списка', () => {
    expect(
      следующаяДатаДохода({
        сегодня: '2026-08-24',
        дниМесяца: [],
        переносВыходного: 'раньше',
      }),
    ).toBeNull()
  })
})

describe('разобратьДниДохода', () => {
  it('принимает запятые, пробелы и убирает повторы', () => {
    expect(разобратьДниДохода('25, 10 25; 0; 40')).toEqual([10, 25])
  })
})
