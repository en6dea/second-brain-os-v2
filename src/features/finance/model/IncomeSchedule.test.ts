import { describe, expect, it } from 'vitest'
import {
  ключПодтверждённогоДохода,
  разобратьДниДохода,
  следующаяДатаДохода,
  следующееСобытиеДохода,
} from './IncomeSchedule'

const доходы = [
  { id: 'salary', название: 'Зарплата', деньМесяца: 10, ожидаемаяСумма: 12000000 },
  { id: 'advance', название: 'Аванс', деньМесяца: 25, ожидаемаяСумма: 4000000 },
]

describe('следующаяДатаДохода', () => {
  it('выбирает ближайший день из графика 10 и 25', () => {
    expect(
      следующаяДатаДохода({
        сегодня: '2026-08-24',
        дниМесяца: [10, 25],
        переносВыходного: 'раньше',
      }),
    ).toBe('2026-08-25')
  })

  it('переносит воскресенье на предыдущую пятницу', () => {
    expect(
      следующаяДатаДохода({
        сегодня: '2026-10-20',
        дниМесяца: [25],
        переносВыходного: 'раньше',
      }),
    ).toBe('2026-10-23')
  })

  it('не возвращает перенесённую дату, если она уже прошла', () => {
    expect(
      следующаяДатаДохода({
        сегодня: '2026-10-24',
        дниМесяца: [10, 25],
        переносВыходного: 'раньше',
      }),
    ).toBe('2026-11-10')
  })

  it('не угадывает график из пустого списка', () => {
    expect(
      следующаяДатаДохода({
        сегодня: '2026-08-24',
        дниМесяца: [],
        переносВыходного: 'раньше',
      }),
    ).toBeNull()
  })
})

describe('разобратьДниДохода', () => {
  it('принимает запятые, пробелы и убирает повторы', () => {
    expect(разобратьДниДохода('25, 10 25; 0; 40')).toEqual([10, 25])
  })
})

describe('следующееСобытиеДохода', () => {
  it('различает аванс и зарплату вместе с их суммами', () => {
    expect(
      следующееСобытиеДохода({
        сегодня: '2026-08-24',
        доходы,
        переносВыходного: 'раньше',
      }),
    ).toMatchObject({
      ключ: 'advance:2026-08-25',
      дата: '2026-08-25',
      источник: { название: 'Аванс', ожидаемаяСумма: 4000000 },
    })
  })

  it('после подтверждения сегодняшней выплаты переходит к следующей', () => {
    expect(
      следующееСобытиеДохода({
        сегодня: '2026-08-25',
        доходы,
        переносВыходного: 'раньше',
        подтверждённые: new Set(['advance:2026-08-25']),
      }),
    ).toMatchObject({
      ключ: 'salary:2026-09-10',
      дата: '2026-09-10',
      источник: { название: 'Зарплата' },
    })
  })

  it('не теряет вчерашнюю выплату, если её подтверждают с опозданием', () => {
    expect(
      следующееСобытиеДохода({
        сегодня: '2026-08-26',
        доходы,
        переносВыходного: 'раньше',
      }),
    ).toMatchObject({
      ключ: 'advance:2026-08-25',
      дата: '2026-08-25',
      источник: { название: 'Аванс' },
    })
  })

  it('не поднимает старые выплаты после первого включения графика', () => {
    expect(
      следующееСобытиеДохода({
        сегодня: '2026-09-05',
        доходы,
        переносВыходного: 'раньше',
      }),
    ).toMatchObject({
      ключ: 'salary:2026-09-10',
      дата: '2026-09-10',
    })
  })

  it('сохраняет плановую дату в устойчивом ключе подтверждения', () => {
    expect(
      ключПодтверждённогоДохода({
        регулярныйДоходId: 'salary',
        плановаяДатаДохода: '2026-09-10',
      }),
    ).toBe('salary:2026-09-10')
    expect(ключПодтверждённогоДохода({})).toBeNull()
  })
})
