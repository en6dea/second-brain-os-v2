import { describe, expect, it } from 'vitest'
import { месяцевЗапаса, среднийРасходВМесяц } from './Runway'
import { сдвинутьМесяц, текущийМесяц } from '@/core/calendar/CalendarRu'
import type { Операция } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'

function операция(изменения: Partial<Операция> = {}): Операция {
  return {
    id: 'о' + Math.random(),
    createdAt: момент,
    updatedAt: момент,
    дата: '2026-01-15',
    тип: 'расход',
    сумма: 1000,
    счётId: null,
    счётПолучательId: null,
    категорияId: null,
    классРасхода: null,
    заметка: '',
    планId: null,
    отпечатокИмпорта: null,
    разобрана: true,
    ...изменения,
  }
}

function месяцНазад(шагов: number): string {
  return сдвинутьМесяц(`${текущийМесяц()}-01`, -шагов).slice(0, 7)
}

describe('среднийРасходВМесяц', () => {
  it('без операций — null', () => {
    expect(среднийРасходВМесяц([], 3)).toBeNull()
  })

  it('усредняет расходы по прошедшим месяцам, текущий не считает', () => {
    const операции = [
      операция({ дата: `${месяцНазад(1)}-10`, сумма: 300000 }),
      операция({ дата: `${месяцНазад(2)}-10`, сумма: 100000 }),
      операция({ дата: `${месяцНазад(3)}-10`, сумма: 200000 }),
      // Текущий месяц не должен попасть в среднее.
      операция({ дата: `${текущийМесяц()}-01`, сумма: 900000 }),
    ]
    expect(среднийРасходВМесяц(операции, 3)).toBe(200000)
  })

  it('доход не считается расходом', () => {
    const операции = [операция({ дата: `${месяцНазад(1)}-10`, тип: 'доход', сумма: 500000 })]
    expect(среднийРасходВМесяц(операции, 3)).toBeNull()
  })
})

describe('месяцевЗапаса', () => {
  it('делит резерв на средний расход', () => {
    expect(месяцевЗапаса(600000, 200000)).toBe(3)
  })

  it('средний расход не известен — null', () => {
    expect(месяцевЗапаса(600000, null)).toBeNull()
  })

  it('средний расход нулевой — null, не бесконечность', () => {
    expect(месяцевЗапаса(600000, 0)).toBeNull()
  })

  it('округляет до одного знака', () => {
    expect(месяцевЗапаса(250000, 100000)).toBe(2.5)
  })
})
