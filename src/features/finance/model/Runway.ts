import type { Копейки, Операция } from '@/core/db/types'
import { границыМесяца, сдвинутьМесяц, текущийМесяц } from '@/core/calendar/CalendarRu'
import { итогПериода } from './calc'

/**
 * Резерв как «месяцев расходов», а не голое число в копейках.
 *
 * Средний расход считается по полностью прошедшим месяцам — текущий не
 * входит, он ещё не закончился, и его расход всегда занижен относительно
 * настоящего месячного темпа.
 */

/** `null` — расходов в этих месяцах не было вовсе, усреднять нечего. */
export function среднийРасходВМесяц(
  операции: Операция[],
  месяцев: number,
): Копейки | null {
  const текущий = текущийМесяц()
  let сумма = 0

  for (let шаг = 1; шаг <= месяцев; шаг += 1) {
    const месяц = сдвинутьМесяц(`${текущий}-01`, -шаг).slice(0, 7)
    const границы = границыМесяца(месяц)
    сумма += итогПериода(операции, границы.от, границы.до).расходы
  }

  return сумма === 0 ? null : Math.round(сумма / месяцев)
}

/** `null` — средний расход неизвестен или равен нулю, делить не на что. */
export function месяцевЗапаса(
  резерв: Копейки,
  среднийРасход: Копейки | null,
): number | null {
  if (среднийРасход === null || среднийРасход <= 0) return null
  return Math.round((резерв / среднийРасход) * 10) / 10
}
