import type { Копейки, Обязательство, Операция, Счёт } from '@/core/db/types'
import { СОБСТВЕННЫЕ_ТИПЫ } from '@/core/db/types'

/**
 * Финансовые расчёты — чистые функции без обращения к базе.
 * Каждое число, которое видит человек, приходит отсюда, и его можно проверить.
 *
 * Правила, унаследованные от прежней версии и сохранённые дословно:
 *  · Собственные деньги считаются отдельно от кредитных.
 *  · Незаполненный остаток (`null`) не превращается в ноль.
 *  · Перевод между своими счетами — не доход и не расход.
 *  · Платёж по обязательству уменьшает долг только частью «тело».
 */

export interface ИтогПоСчетам {
  собственные: Копейки
  кредитныйЛимитДоступен: Копейки
  счетовУчтено: number
  счетовБезОстатка: number
  названияБезОстатка: string[]
}

export function итогПоСчетам(счета: Счёт[]): ИтогПоСчетам {
  let собственные = 0
  let кредитныйЛимитДоступен = 0
  let счетовУчтено = 0
  const названияБезОстатка: string[] = []

  for (const счёт of счета) {
    if (счёт.архив) continue

    const своё = СОБСТВЕННЫЕ_ТИПЫ.includes(счёт.тип)
    if (счёт.фактическийОстаток === null) {
      if (своё) названияБезОстатка.push(счёт.название)
      continue
    }

    if (своё) {
      if (счёт.учитыватьВДоступных) собственные += счёт.фактическийОстаток
      счетовУчтено += 1
    } else if (счёт.кредитныйЛимит !== null) {
      // Остаток кредитной карты — это долг. Доступный лимит не собственные деньги.
      кредитныйЛимитДоступен += Math.max(
        0,
        счёт.кредитныйЛимит + счёт.фактическийОстаток,
      )
    }
  }

  return {
    собственные,
    кредитныйЛимитДоступен,
    счетовУчтено,
    счетовБезОстатка: названияБезОстатка.length,
    названияБезОстатка,
  }
}

/** Сумма долгов «я должен»: тело + проценты + штрафы. */
export function итогОбязательств(обязательства: Обязательство[]): {
  яДолжен: Копейки
  мнеДолжны: Копейки
  безДанных: number
} {
  let яДолжен = 0
  let мнеДолжны = 0
  let безДанных = 0

  for (const запись of обязательства) {
    if (запись.закрыто) continue
    const части = [запись.телоОстаток, запись.начисленныеПроценты, запись.штрафы]
    if (части.every((часть) => часть === null)) {
      безДанных += 1
      continue
    }
    const сумма = части.reduce<number>((итог, часть) => итог + (часть ?? 0), 0)
    if (запись.направление === 'я должен') яДолжен += сумма
    else мнеДолжны += сумма
  }

  return { яДолжен, мнеДолжны, безДанных }
}

/**
 * Свободные деньги = собственные − обязательства к погашению − минимальный резерв.
 * Отрицательный результат показывается как есть: это важная правда.
 */
export function свободныеДеньги(параметры: {
  собственные: Копейки
  яДолжен: Копейки
  минимальныйРезерв: Копейки
}): Копейки {
  return параметры.собственные - параметры.яДолжен - параметры.минимальныйРезерв
}

/** Влияние операции на конкретный счёт в копейках. */
export function влияниеНаСчёт(операция: Операция, счётId: string): Копейки {
  switch (операция.тип) {
    case 'доход':
    case 'возврат':
      return операция.счётId === счётId ? операция.сумма : 0
    case 'расход':
      return операция.счётId === счётId ? -операция.сумма : 0
    case 'перевод':
      if (операция.счётId === счётId) return -операция.сумма
      if (операция.счётПолучательId === счётId) return операция.сумма
      return 0
    case 'корректировка':
      // Корректировка задаёт разницу со знаком: сумма хранится положительной,
      // а знак берётся из счёта-получателя (есть — плюс, нет — минус).
      if (операция.счётПолучательId === счётId) return операция.сумма
      if (операция.счётId === счётId) return -операция.сумма
      return 0
  }
}

/**
 * Расчётный остаток счёта: подтверждённый остаток плюс всё, что записано
 * после подтверждения. Если остаток никогда не подтверждали — «неизвестно».
 */
export function расчётныйОстаток(счёт: Счёт, операции: Операция[]): Копейки | null {
  if (счёт.фактическийОстаток === null) return null
  const граница = счёт.подтверждён
  let итог = счёт.фактическийОстаток
  for (const операция of операции) {
    if (граница && операция.createdAt <= граница) continue
    итог += влияниеНаСчёт(операция, счёт.id)
  }
  return итог
}

export interface ИтогПериода {
  доходы: Копейки
  расходы: Копейки
  переводы: Копейки
  поток: Копейки
  операций: number
}

/** Итоги за период. Переводы не входят ни в доходы, ни в расходы. */
export function итогПериода(
  операции: Операция[],
  от: string,
  до: string,
): ИтогПериода {
  let доходы = 0
  let расходы = 0
  let переводы = 0
  let операций = 0

  for (const операция of операции) {
    if (операция.дата < от || операция.дата > до) continue
    операций += 1
    switch (операция.тип) {
      case 'доход':
        доходы += операция.сумма
        break
      case 'расход':
        расходы += операция.сумма
        break
      case 'возврат':
        расходы -= операция.сумма
        break
      case 'перевод':
        переводы += операция.сумма
        break
      case 'корректировка':
        break
    }
  }

  return { доходы, расходы, переводы, поток: доходы - расходы, операций }
}

/** Расходы по категориям за период — для честной картины, без выдуманных долей. */
export function расходыПоКатегориям(
  операции: Операция[],
  от: string,
  до: string,
): Map<string, Копейки> {
  const итог = new Map<string, Копейки>()
  for (const операция of операции) {
    if (операция.тип !== 'расход') continue
    if (операция.дата < от || операция.дата > до) continue
    const ключ = операция.категорияId ?? 'без категории'
    итог.set(ключ, (итог.get(ключ) ?? 0) + операция.сумма)
  }
  return итог
}

export interface РасхождениеСверки {
  расхождение: Копейки
  совпало: boolean
  причины: string[]
}

/**
 * Сверка: сравниваем то, что говорит банк, с тем, что насчитала система,
 * и называем вероятные причины расхождения вместо общей фразы «не сошлось».
 */
export function объяснитьРасхождение(параметры: {
  фактический: Копейки
  расчётный: Копейки | null
  неразобранныхОпераций: number
  переводовЗаПериод: number
  остатокНеПодтверждён: boolean
  возможныхДублей: number
}): РасхождениеСверки {
  if (параметры.расчётный === null) {
    return {
      расхождение: 0,
      совпало: false,
      причины: [
        'Начальный остаток счёта не заполнен — сравнивать не с чем. Укажите остаток и подтвердите его.',
      ],
    }
  }

  const расхождение = параметры.фактический - параметры.расчётный
  if (расхождение === 0) {
    return { расхождение: 0, совпало: true, причины: [] }
  }

  const причины: string[] = []
  if (параметры.неразобранныхОпераций > 0) {
    причины.push(
      `Не разобрано операций: ${параметры.неразобранныхОпераций}. Пока у них нет категории, картина неполная.`,
    )
  }
  if (параметры.возможныхДублей > 0) {
    причины.push(
      `Похожих операций, которые могут быть дублями: ${параметры.возможныхДублей}.`,
    )
  }
  if (параметры.переводовЗаПериод > 0) {
    причины.push(
      `Переводов между счетами за период: ${параметры.переводовЗаПериод}. Проверьте, что у каждого указан счёт-получатель.`,
    )
  }
  if (параметры.остатокНеПодтверждён) {
    причины.push(
      'Остаток счёта давно не подтверждали — расчёт мог накопить ошибку.',
    )
  }
  причины.push(
    расхождение > 0
      ? 'В системе не хватает поступления на эту сумму.'
      : 'В системе не хватает списания на эту сумму.',
  )

  return { расхождение, совпало: false, причины }
}
