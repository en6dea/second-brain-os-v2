import { describe, expect, it } from 'vitest'
import { следующийПлатёж } from './PaymentSchedule'

describe('следующийПлатёж', () => {
  it('ежемесячно — сдвигает на месяц', () => {
    expect(следующийПлатёж('2026-01-15', 'ежемесячно')).toBe('2026-02-15')
  })

  it('еженедельно — сдвигает на семь дней', () => {
    expect(следующийПлатёж('2026-01-15', 'еженедельно')).toBe('2026-01-22')
  })

  it('ежегодно — сдвигает на двенадцать месяцев', () => {
    expect(следующийПлатёж('2026-01-15', 'ежегодно')).toBe('2027-01-15')
  })

  it('без периодичности — null, дата не трогается', () => {
    expect(следующийПлатёж('2026-01-15', null)).toBeNull()
  })

  it('ежемесячно с 31 числа клэмпит на конец месяца', () => {
    expect(следующийПлатёж('2026-01-31', 'ежемесячно')).toBe('2026-02-28')
  })
})
