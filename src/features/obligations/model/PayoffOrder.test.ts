import { describe, expect, it } from 'vitest'
import { порядокПогашения } from './PayoffOrder'
import type { Обязательство } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'

function обязательство(изменения: Partial<Обязательство> = {}): Обязательство {
  return {
    id: 'о' + Math.random(),
    createdAt: момент,
    updatedAt: момент,
    название: 'Долг',
    направление: 'я должен',
    вид: 'кредит',
    телоОстаток: 100000,
    начисленныеПроценты: null,
    штрафы: null,
    ставкаГодовых: null,
    минимальныйПлатёж: null,
    датаСледующегоПлатежа: null,
    повторПлатежа: null,
    датаОкончания: null,
    контрагент: '',
    закрыто: false,
    заметка: '',
    ...изменения,
  }
}

describe('порядокПогашения', () => {
  it('сортирует по убыванию ставки', () => {
    const низкая = обязательство({ id: 'низкая', ставкаГодовых: 8 })
    const высокая = обязательство({ id: 'высокая', ставкаГодовых: 24 })
    const средняя = обязательство({ id: 'средняя', ставкаГодовых: 15 })
    const итог = порядокПогашения([низкая, высокая, средняя])
    expect(итог.map((о) => о.id)).toEqual(['высокая', 'средняя', 'низкая'])
  })

  it('обязательства без ставки уходят в конец', () => {
    const безСтавки = обязательство({ id: 'без-ставки', ставкаГодовых: null })
    const соСтавкой = обязательство({ id: 'со-ставкой', ставкаГодовых: 10 })
    const итог = порядокПогашения([безСтавки, соСтавкой])
    expect(итог.map((о) => о.id)).toEqual(['со-ставкой', 'без-ставки'])
  })

  it('при равной ставке — по убыванию остатка тела', () => {
    const меньше = обязательство({ id: 'меньше', ставкаГодовых: 10, телоОстаток: 50000 })
    const больше = обязательство({ id: 'больше', ставкаГодовых: 10, телоОстаток: 200000 })
    const итог = порядокПогашения([меньше, больше])
    expect(итог.map((о) => о.id)).toEqual(['больше', 'меньше'])
  })

  it('исходный массив не изменяется', () => {
    const список = [обязательство({ id: 'а', ставкаГодовых: 5 }), обязательство({ id: 'б', ставкаГодовых: 20 })]
    const копия = [...список]
    порядокПогашения(список)
    expect(список).toEqual(копия)
  })
})
