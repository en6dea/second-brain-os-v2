import type { Обязательство } from '@/core/db/types'

/**
 * Порядок погашения — метод «лавина».
 *
 * Сортировка по убыванию ставки: сначала гасится самый дорогой долг, это
 * математически быстрее «снежного кома» (по остатку) при равной сумме
 * платежей. Обязательства без указанной ставки уходят в конец — раз
 * ставка неизвестна, приравнивать её к нулю значило бы выдумать цифру.
 */
export function порядокПогашения(обязательства: Обязательство[]): Обязательство[] {
  return [...обязательства].sort((а, б) => {
    if (а.ставкаГодовых === null && б.ставкаГодовых === null) {
      return (б.телоОстаток ?? 0) - (а.телоОстаток ?? 0)
    }
    if (а.ставкаГодовых === null) return 1
    if (б.ставкаГодовых === null) return -1
    if (а.ставкаГодовых !== б.ставкаГодовых) return б.ставкаГодовых - а.ставкаГодовых
    return (б.телоОстаток ?? 0) - (а.телоОстаток ?? 0)
  })
}
