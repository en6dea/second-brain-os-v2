import type { Обязательство, ДатаДень } from '@/core/db/types'
import { сдвинутьДень, сдвинутьМесяц } from '@/core/calendar/CalendarRu'

/**
 * Дата следующего платежа после того, как один уже записан.
 *
 * `null` — периодичность не задана, дата остаётся на человеке, как и было
 * до появления этого поля. Ничего не угадывается: без выбранной
 * периодичности эта функция вообще не участвует в подсчёте.
 */
export function следующийПлатёж(
  текущая: ДатаДень,
  повтор: Обязательство['повторПлатежа'],
): ДатаДень | null {
  if (повтор === 'ежемесячно') return сдвинутьМесяц(текущая, 1)
  if (повтор === 'еженедельно') return сдвинутьДень(текущая, 7)
  if (повтор === 'ежегодно') return сдвинутьМесяц(текущая, 12)
  return null
}
