import { useState } from 'react'
import { useLiveQuery } from 'dexie-react-hooks'
import { Plus, Trash2 } from 'lucide-react'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import type { Обязательство } from '@/core/db/types'
import { итогОбязательств } from '@/features/finance/model/calc'
import { деньги, копейкиВРубли, рублиВКопейки } from '@/core/money/Money'
import { деньСловами, днейДо, сегодня } from '@/core/calendar/CalendarRu'
import { склонение } from '@/core/language/Plural'
import { сейчас } from '@/core/db/RecordId'
import { useИнтерфейс } from '@/app/providers/ui'
import {
  Input,
  MoneyInput,
  Select,
  Skeleton,
  Badge,
  Card,
  Button,
  IconButton,
  Metric,
  Dialog,
  Field,
  EmptyState,
  CardHeader,
} from '@/design-system/components'

interface Черновик {
  id: string | null
  название: string
  направление: Обязательство['направление']
  вид: Обязательство['вид']
  тело: string
  проценты: string
  штрафы: string
  минимальныйПлатёж: string
  датаПлатежа: string
  контрагент: string
}

interface ЧерновикПлатежа {
  обязательствоId: string
  всего: string
  тело: string
  проценты: string
  штрафы: string
}

export function ObligationsPage() {
  const сообщить = useИнтерфейс((с) => с.сообщить)
  const [черновик, установитьЧерновик] = useState<Черновик | null>(null)
  const [платёж, установитьПлатёж] = useState<ЧерновикПлатежа | null>(null)

  const данные = useLiveQuery(async () => {
    const [обязательства, платежи] = await Promise.all([
      база.obligations.toArray(),
      база.obligationPayments.toArray(),
    ])
    return { обязательства, платежи }
  }, [])

  if (!данные) {
    return (
      <Card>
        <Skeleton строк={4} />
      </Card>
    )
  }

  const итог = итогОбязательств(данные.обязательства)
  const открытые = данные.обязательства.filter((о) => !о.закрыто)
  const закрытые = данные.обязательства.filter((о) => о.закрыто)

  const суммаПлатежа = рублиВКопейки(платёж?.всего ?? '') ?? 0
  const суммаЧастей =
    (рублиВКопейки(платёж?.тело ?? '') ?? 0) +
    (рублиВКопейки(платёж?.проценты ?? '') ?? 0) +
    (рублиВКопейки(платёж?.штрафы ?? '') ?? 0)
  const частиСходятся = суммаПлатежа === суммаЧастей && суммаПлатежа > 0

  async function сохранить() {
    if (!черновик?.название.trim()) return
    const поля = {
      название: черновик.название.trim(),
      направление: черновик.направление,
      вид: черновик.вид,
      телоОстаток: рублиВКопейки(черновик.тело),
      начисленныеПроценты: рублиВКопейки(черновик.проценты),
      штрафы: рублиВКопейки(черновик.штрафы),
      минимальныйПлатёж: рублиВКопейки(черновик.минимальныйПлатёж),
      датаСледующегоПлатежа: черновик.датаПлатежа || null,
      контрагент: черновик.контрагент.trim(),
    }
    if (черновик.id) {
      const текущее = await база.obligations.get(черновик.id)
      if (текущее) {
        await база.obligations.put({ ...текущее, ...поля, updatedAt: сейчас() })
        сообщить('Обязательство обновлено')
      }
    } else {
      await база.obligations.add(
        новаяЗапись({
          ...поля,
          ставкаГодовых: null,
          датаОкончания: null,
          закрыто: false,
          заметка: '',
        }) as never,
      )
      сообщить('Обязательство добавлено')
    }
    установитьЧерновик(null)
  }

  async function записатьПлатёж() {
    if (!платёж || !частиСходятся) return
    const обязательство = await база.obligations.get(платёж.обязательствоId)
    if (!обязательство) return

    const тело = рублиВКопейки(платёж.тело) ?? 0
    const проценты = рублиВКопейки(платёж.проценты) ?? 0
    const штрафы = рублиВКопейки(платёж.штрафы) ?? 0

    await база.obligationPayments.add(
      новаяЗапись({
        обязательствоId: обязательство.id,
        дата: сегодня(),
        всего: суммаПлатежа,
        тело,
        проценты,
        штрафы,
        операцияId: null,
      }) as never,
    )

    // Основной долг уменьшает только часть «тело» — это правило системы.
    await база.obligations.put({
      ...обязательство,
      телоОстаток:
        обязательство.телоОстаток === null
          ? null
          : Math.max(0, обязательство.телоОстаток - тело),
      начисленныеПроценты:
        обязательство.начисленныеПроценты === null
          ? null
          : Math.max(0, обязательство.начисленныеПроценты - проценты),
      штрафы:
        обязательство.штрафы === null
          ? null
          : Math.max(0, обязательство.штрафы - штрафы),
      updatedAt: сейчас(),
    })

    сообщить('Платёж записан. Долг уменьшен только на сумму тела.')
    установитьПлатёж(null)
  }

  return (
    <div className="anim-rise space-y-5">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="text-[20px] font-semibold text-ink">Обязательства</h1>
          <p className="mt-0.5 text-[13px] text-ink-3">
            Платёж делится на тело, проценты и штрафы. Долг уменьшает только тело.
          </p>
        </div>
        <Button
          вид="основная"
          иконка={<Plus size={16} />}
          onClick={() =>
            установитьЧерновик({
              id: null,
              название: '',
              направление: 'я должен',
              вид: 'кредит',
              тело: '',
              проценты: '',
              штрафы: '',
              минимальныйПлатёж: '',
              датаПлатежа: '',
              контрагент: '',
            })
          }
        >
          Обязательство
        </Button>
      </div>

      <Card>
        <div className="grid grid-cols-2 gap-5 p-5 sm:grid-cols-3">
          <Metric
            подпись="Я должен"
            значение={деньги(итог.яДолжен)}
            тон={итог.яДолжен > 0 ? 'опасность' : 'нейтральный'}
            источник="тело + проценты + штрафы"
          />
          <Metric
            подпись="Мне должны"
            значение={деньги(итог.мнеДолжны)}
            тон={итог.мнеДолжны > 0 ? 'успех' : 'нейтральный'}
          />
          <Metric
            подпись="Без сумм"
            значение={String(итог.безДанных)}
            источник="не участвуют в расчёте"
            тон={итог.безДанных > 0 ? 'внимание' : 'нейтральный'}
          />
        </div>
      </Card>

      <Card>
        <CardHeader
          заголовок="Открытые обязательства"
          подпись={`${открытые.length} ${склонение(открытые.length, 'запись', 'записи', 'записей')}`}
        />
        {открытые.length === 0 ? (
          <EmptyState
            заголовок="Открытых обязательств нет"
            подпись="Если долгов нет — это лучшее состояние раздела."
          />
        ) : (
          <div className="divide-y divide-line border-t border-line">
            {открытые.map((обязательство) => {
              const дней = днейДо(обязательство.датаСледующегоПлатежа)
              const всего =
                (обязательство.телоОстаток ?? 0) +
                (обязательство.начисленныеПроценты ?? 0) +
                (обязательство.штрафы ?? 0)
              return (
                <div key={обязательство.id} className="px-5 py-4">
                  <div className="flex flex-wrap items-start justify-between gap-3">
                    <div className="min-w-0">
                      <p className="truncate text-[14px] font-medium text-ink">
                        {обязательство.название}
                      </p>
                      <p className="mt-1 flex flex-wrap items-center gap-1.5 text-[11.5px] text-ink-3">
                        <Badge
                          тон={
                            обязательство.направление === 'я должен'
                              ? 'опасность'
                              : 'успех'
                          }
                        >
                          {обязательство.направление}
                        </Badge>
                        <span>{обязательство.вид}</span>
                        {обязательство.контрагент ? (
                          <span>· {обязательство.контрагент}</span>
                        ) : null}
                        {обязательство.датаСледующегоПлатежа ? (
                          <Badge
                            тон={
                              дней !== null && дней < 0
                                ? 'опасность'
                                : дней !== null && дней <= 5
                                  ? 'внимание'
                                  : 'нейтральный'
                            }
                          >
                            {дней !== null && дней < 0
                              ? `просрочен на ${Math.abs(дней)} ${склонение(Math.abs(дней), 'день', 'дня', 'дней')}`
                              : `платёж ${деньСловами(обязательство.датаСледующегоПлатежа)}`}
                          </Badge>
                        ) : null}
                      </p>
                    </div>

                    <div className="text-right">
                      <p className="tnum text-[15px] font-semibold text-ink">
                        {деньги(всего)}
                      </p>
                      <p className="tnum text-[11px] text-ink-3">
                        тело {деньги(обязательство.телоОстаток)} · проценты{' '}
                        {деньги(обязательство.начисленныеПроценты)} · штрафы{' '}
                        {деньги(обязательство.штрафы)}
                      </p>
                    </div>
                  </div>

                  <div className="mt-3 flex flex-wrap gap-1.5">
                    <Button
                      размер="малый"
                      onClick={() =>
                        установитьПлатёж({
                          обязательствоId: обязательство.id,
                          всего: обязательство.минимальныйПлатёж
                            ? String(копейкиВРубли(обязательство.минимальныйПлатёж))
                            : '',
                          тело: '',
                          проценты: '',
                          штрафы: '',
                        })
                      }
                    >
                      Записать платёж
                    </Button>
                    <Button
                      размер="малый"
                      onClick={() =>
                        установитьЧерновик({
                          id: обязательство.id,
                          название: обязательство.название,
                          направление: обязательство.направление,
                          вид: обязательство.вид,
                          тело:
                            обязательство.телоОстаток === null
                              ? ''
                              : String(копейкиВРубли(обязательство.телоОстаток)),
                          проценты:
                            обязательство.начисленныеПроценты === null
                              ? ''
                              : String(
                                  копейкиВРубли(обязательство.начисленныеПроценты),
                                ),
                          штрафы:
                            обязательство.штрафы === null
                              ? ''
                              : String(копейкиВРубли(обязательство.штрафы)),
                          минимальныйПлатёж:
                            обязательство.минимальныйПлатёж === null
                              ? ''
                              : String(
                                  копейкиВРубли(обязательство.минимальныйПлатёж),
                                ),
                          датаПлатежа: обязательство.датаСледующегоПлатежа ?? '',
                          контрагент: обязательство.контрагент,
                        })
                      }
                    >
                      Изменить
                    </Button>
                    <Button
                      размер="малый"
                      onClick={async () => {
                        await база.obligations.put({
                          ...обязательство,
                          закрыто: true,
                          updatedAt: сейчас(),
                        })
                        сообщить('Обязательство закрыто')
                      }}
                    >
                      Закрыть
                    </Button>
                    <IconButton
                      подпись="Удалить обязательство"
                      onClick={async () => {
                        await база.obligations.delete(обязательство.id)
                        сообщить('Обязательство удалено')
                      }}
                    >
                      <Trash2 size={15} />
                    </IconButton>
                  </div>
                </div>
              )
            })}
          </div>
        )}
      </Card>

      {закрытые.length > 0 ? (
        <Card>
          <CardHeader заголовок="Закрытые" />
          <div className="flex flex-wrap gap-2 px-5 pb-5">
            {закрытые.map((обязательство) => (
              <span
                key={обязательство.id}
                className="rounded-full border border-line px-3 py-1.5 text-[12.5px] text-ink-3"
              >
                {обязательство.название}
              </span>
            ))}
          </div>
        </Card>
      ) : null}

      {/* --- Окно обязательства --- */}
      <Dialog
        открыто={черновик !== null}
        наЗакрытие={() => установитьЧерновик(null)}
        заголовок={черновик?.id ? 'Изменить обязательство' : 'Новое обязательство'}
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьЧерновик(null)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={сохранить}
              disabled={!черновик?.название.trim()}
            >
              Сохранить
            </Button>
          </>
        }
      >
        {черновик ? (
          <div className="space-y-4">
            <Field подпись="Название" обязательное>
              <Input
                value={черновик.название}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    название: событие.target.value,
                  })
                }
                autoFocus
              />
            </Field>
            <div className="grid gap-4 sm:grid-cols-2">
              <Field подпись="Направление">
                <Select
                  value={черновик.направление}
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      направление: событие.target
                        .value as Обязательство['направление'],
                    })
                  }
                >
                  <option value="я должен">Я должен</option>
                  <option value="мне должны">Мне должны</option>
                </Select>
              </Field>
              <Field подпись="Вид">
                <Select
                  value={черновик.вид}
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      вид: событие.target.value as Обязательство['вид'],
                    })
                  }
                >
                  <option value="кредит">Кредит</option>
                  <option value="заём">Заём</option>
                  <option value="рассрочка">Рассрочка</option>
                  <option value="подписка">Подписка</option>
                  <option value="иное">Иное</option>
                </Select>
              </Field>
            </div>
            <div className="grid gap-4 sm:grid-cols-3">
              <Field подпись="Тело долга">
                <MoneyInput
                  value={черновик.тело}
                  onChange={(значение) =>
                    установитьЧерновик({ ...черновик, тело: значение })
                  }
                  placeholder="не заполнено"
                />
              </Field>
              <Field подпись="Проценты">
                <MoneyInput
                  value={черновик.проценты}
                  onChange={(значение) =>
                    установитьЧерновик({ ...черновик, проценты: значение })
                  }
                  placeholder="не заполнено"
                />
              </Field>
              <Field подпись="Штрафы">
                <MoneyInput
                  value={черновик.штрафы}
                  onChange={(значение) =>
                    установитьЧерновик({ ...черновик, штрафы: значение })
                  }
                  placeholder="не заполнено"
                />
              </Field>
            </div>
            <div className="grid gap-4 sm:grid-cols-2">
              <Field подпись="Минимальный платёж">
                <MoneyInput
                  value={черновик.минимальныйПлатёж}
                  onChange={(значение) =>
                    установитьЧерновик({ ...черновик, минимальныйПлатёж: значение })
                  }
                />
              </Field>
              <Field подпись="Дата следующего платежа">
                <Input
                  type="date"
                  value={черновик.датаПлатежа}
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      датаПлатежа: событие.target.value,
                    })
                  }
                />
              </Field>
            </div>
            <Field подпись="Кому или от кого">
              <Input
                value={черновик.контрагент}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    контрагент: событие.target.value,
                  })
                }
              />
            </Field>
          </div>
        ) : null}
      </Dialog>

      {/* --- Окно платежа --- */}
      <Dialog
        открыто={платёж !== null}
        наЗакрытие={() => установитьПлатёж(null)}
        заголовок="Платёж по обязательству"
        подпись="Сумма платежа должна равняться сумме частей"
        ширина="узкая"
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьПлатёж(null)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={записатьПлатёж}
              disabled={!частиСходятся}
            >
              Записать
            </Button>
          </>
        }
      >
        {платёж ? (
          <div className="space-y-4">
            <Field подпись="Сумма платежа" обязательное>
              <MoneyInput
                value={платёж.всего}
                onChange={(значение) =>
                  установитьПлатёж({ ...платёж, всего: значение })
                }
                autoFocus
              />
            </Field>
            <div className="grid gap-4 sm:grid-cols-3">
              <Field подпись="Тело">
                <MoneyInput
                  value={платёж.тело}
                  onChange={(значение) =>
                    установитьПлатёж({ ...платёж, тело: значение })
                  }
                />
              </Field>
              <Field подпись="Проценты">
                <MoneyInput
                  value={платёж.проценты}
                  onChange={(значение) =>
                    установитьПлатёж({ ...платёж, проценты: значение })
                  }
                />
              </Field>
              <Field подпись="Штрафы">
                <MoneyInput
                  value={платёж.штрафы}
                  onChange={(значение) =>
                    установитьПлатёж({ ...платёж, штрафы: значение })
                  }
                />
              </Field>
            </div>

            <div
              className={
                частиСходятся
                  ? 'rounded-3 bg-good-soft px-4 py-2.5 text-[13px] text-good'
                  : 'rounded-3 bg-warn-soft px-4 py-2.5 text-[13px] text-warn'
              }
            >
              {частиСходятся
                ? 'Части сходятся с суммой платежа.'
                : `Тело + проценты + штрафы = ${деньги(суммаЧастей)}, а платёж — ${деньги(суммаПлатежа)}. Пока цифры не сойдутся, запись не сохранится: иначе долг посчитается неверно.`}
            </div>
          </div>
        ) : null}
      </Dialog>
    </div>
  )
}
