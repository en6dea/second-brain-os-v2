import { useMemo, useState } from 'react'
import { useLiveQuery } from 'dexie-react-hooks'
import { Check } from 'lucide-react'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import type { ВидОбзора, Обзор } from '@/core/db/types'
import {
  границыМесяца,
  границыНедели,
  деньСловами,
  месяцСловами,
  сегодня,
  текущийМесяц,
} from '@/core/calendar/CalendarRu'
import { склонение } from '@/core/language/Plural'
import { деньги, процент } from '@/core/money/Money'
import { сейчас } from '@/core/db/RecordId'
import { useИнтерфейс } from '@/app/providers/ui'
import { собратьПоказатели, вСлепок } from './model/ReviewMetrics'
import { выявитьПаттерны } from './model/Patterns'
import {
  Badge,
  Button,
  Card,
  CardBody,
  CardHeader,
  EmptyState,
  Field,
  Metric,
  Segmented,
  Skeleton,
  Textarea,
} from '@/design-system/components'

const ВИДЫ: { ключ: ВидОбзора; подпись: string; время: string }[] = [
  { ключ: 'день', подпись: 'День', время: '2–3 минуты' },
  { ключ: 'неделя', подпись: 'Неделя', время: '10–15 минут' },
  { ключ: 'месяц', подпись: 'Месяц', время: 'полный итог' },
]

function периодОбзора(вид: ВидОбзора): {
  ключ: string
  от: string
  до: string
  название: string
} {
  const день = сегодня()
  if (вид === 'день') {
    return { ключ: день, от: день, до: день, название: деньСловами(день) }
  }
  if (вид === 'неделя') {
    const границы = границыНедели(день)
    return {
      ключ: `${границы.от}—${границы.до}`,
      от: границы.от,
      до: границы.до,
      название: `${деньСловами(границы.от)} — ${деньСловами(границы.до)}`,
    }
  }
  const месяц = текущийМесяц()
  const границы = границыМесяца(месяц)
  return {
    ключ: месяц,
    от: границы.от,
    до: границы.до,
    название: месяцСловами(месяц),
  }
}

export function ReviewsPage() {
  const сообщить = useИнтерфейс((с) => с.сообщить)
  const [вид, установитьВид] = useState<ВидОбзора>('день')
  const [чтоПолучилось, установитьЧтоПолучилось] = useState<string | null>(null)
  const [чтоНет, установитьЧтоНет] = useState<string | null>(null)
  const [выводы, установитьВыводы] = useState<string | null>(null)
  const [следующийШаг, установитьСледующийШаг] = useState<string | null>(null)

  const период = периодОбзора(вид)

  const данные = useLiveQuery(async () => {
    const [задачи, привычки, цели, операции, обзоры, категории] = await Promise.all([
      база.tasks.toArray(),
      база.habits.toArray(),
      база.goals.toArray(),
      база.operations.toArray(),
      база.reviews.toArray(),
      база.moneyCategories.toArray(),
    ])
    return { задачи, привычки, цели, операции, обзоры, категории }
  }, [])

  const показатели = useMemo(
    () =>
      данные
        ? собратьПоказатели(
            {
              задачи: данные.задачи,
              привычки: данные.привычки,
              цели: данные.цели,
              операции: данные.операции,
            },
            период.от,
            период.до,
          )
        : null,
    [данные, период.от, период.до],
  )

  const паттерны = useMemo(
    () =>
      данные
        ? выявитьПаттерны(
            {
              задачи: данные.задачи,
              операции: данные.операции,
              цели: данные.цели,
              категории: данные.категории,
            },
            сегодня(),
          )
        : null,
    [данные],
  )

  if (!данные || !показатели) {
    return (
      <Card>
        <Skeleton строк={5} />
      </Card>
    )
  }

  const текущий =
    данные.обзоры.find((о) => о.вид === вид && о.период === период.ключ) ?? null

  const значение = (поле: keyof Обзор, черновик: string | null) =>
    черновик ?? ((текущий?.[поле] as string) || '')

  const выполнение = процент(показатели.задачСделано, показатели.задачВсего)
  const привычки = процент(показатели.отметокСделано, показатели.отметокВозможно)

  async function сохранить() {
    const поля = {
      вид,
      период: период.ключ,
      чтоПолучилось: значение('чтоПолучилось', чтоПолучилось),
      чтоНет: значение('чтоНет', чтоНет),
      выводы: значение('выводы', выводы),
      следующийШаг: значение('следующийШаг', следующийШаг),
      показатели: вСлепок(показатели!),
      закрыт: true,
    }

    if (текущий) {
      await база.reviews.put({ ...текущий, ...поля, updatedAt: сейчас() })
    } else {
      await база.reviews.add(новаяЗапись(поля) as never)
    }

    установитьЧтоПолучилось(null)
    установитьЧтоНет(null)
    установитьВыводы(null)
    установитьСледующийШаг(null)
    сообщить('Обзор сохранён вместе со снимком показателей')
  }

  const прошлые = данные.обзоры
    .filter((о) => о.вид === вид && о.период !== период.ключ)
    .sort((а, б) => б.период.localeCompare(а.период))
    .slice(0, 6)

  return (
    <div className="anim-rise space-y-5">
      <div>
        <h1 className="text-h2 font-semibold text-ink">Обзоры</h1>
        <p className="mt-0.5 text-meta text-ink-3">
          Место, где данные превращаются в решение. Показатели подставлены из
          записей — вводить их заново не нужно.
        </p>
      </div>

      <Segmented
        значения={ВИДЫ.map((в) => ({ ключ: в.ключ, подпись: в.подпись }))}
        выбрано={вид}
        наВыбор={установитьВид}
      />

      <Card>
        <CardHeader
          заголовок={период.название}
          подпись={`${ВИДЫ.find((в) => в.ключ === вид)?.время}${текущий ? ' · обзор уже сохранён' : ''}`}
          действие={текущий ? <Badge тон="успех">закрыт</Badge> : null}
        />

        <div className="grid grid-cols-2 gap-5 px-5 pb-5 lg:grid-cols-4">
          <Metric
            единица="шт · задачи"
            подпись="Закрыто за период"
            значение={`${показатели.задачСделано}/${показатели.задачВсего}`}
            источник={
              показатели.задачВсего === 0
                ? 'задач с датой в этом периоде не было'
                : `${выполнение ?? 0}% выполнено`
            }
            тон={
              выполнение === null
                ? 'нейтральный'
                : выполнение >= 70
                  ? 'успех'
                  : выполнение >= 40
                    ? 'внимание'
                    : 'опасность'
            }
          />
          <Metric
            единица="% · привычки"
            подпись="Выполнение"
            значение={привычки === null ? '—' : `${привычки}%`}
            источник={
              показатели.привычекАктивных === 0
                ? 'активных привычек нет'
                : `${показатели.отметокСделано} из ${показатели.отметокВозможно} отметок`
            }
            тон={
              привычки === null
                ? 'нейтральный'
                : привычки >= 70
                  ? 'успех'
                  : 'внимание'
            }
          />
          <Metric
            единица="₽ · поток"
            подпись="Доходы минус расходы"
            счётчик={{
              число: показатели.поток,
              запись: (з) => деньги(з, { знак: true }),
            }}
            источник={`${показатели.операций} ${склонение(показатели.операций, 'операция', 'операции', 'операций')}`}
            тон={показатели.поток < 0 ? 'опасность' : 'успех'}
          />
          <Metric
            единица="шт · цели"
            подпись="Без движения"
            значение={`${показатели.целейБезДвижения}/${показатели.целейАктивных}`}
            источник="не менялись за период"
            тон={показатели.целейБезДвижения > 0 ? 'внимание' : 'успех'}
          />
        </div>

        <div className="grid gap-5 border-t border-line px-5 py-4 sm:grid-cols-3">
          <Metric
            единица="₽ · получено"
            подпись="Доходы"
            значение={деньги(показатели.доходы)}
            тон="успех"
          />
          <Metric
            единица="₽ · израсходовано"
            подпись="Расходы"
            значение={деньги(показатели.расходы)}
          />
          <Metric
            единица="дн · серия"
            подпись="Лучшая серия привычки"
            значение={String(показатели.лучшаяСерия)}
            источник="дней подряд без пропуска"
          />
        </div>

        {показатели.задачПросрочено > 0 ? (
          <div className="border-t border-line px-5 py-3">
            <p className="text-caption text-warn">
              Кроме этого, {показатели.задачПросрочено}{' '}
              {склонение(
                показатели.задачПросрочено,
                'задача просрочена',
                'задачи просрочены',
                'задач просрочено',
              )}{' '}
              с прежних периодов. Они не попадают в выполнение за этот период, но
              никуда не делись.
            </p>
          </div>
        ) : null}
      </Card>

      <Card>
        <CardHeader
          заголовок="Разбор"
          подпись="Коротко и честно. Пустой обзор не сохраняется зря — он всё равно фиксирует показатели."
        />
        <CardBody className="space-y-4">
          <div className="grid gap-4 sm:grid-cols-2">
            <Field подпись="Что получилось">
              <Textarea
                rows={4}
                value={значение('чтоПолучилось', чтоПолучилось)}
                onChange={(событие) =>
                  установитьЧтоПолучилось(событие.target.value)
                }
              />
            </Field>
            <Field подпись="Что не получилось">
              <Textarea
                rows={4}
                value={значение('чтоНет', чтоНет)}
                onChange={(событие) => установитьЧтоНет(событие.target.value)}
              />
            </Field>
          </div>
          <Field
            подпись="Вывод"
            подсказка="Не пересказ событий, а то, что вы поняли"
          >
            <Textarea
              rows={3}
              value={значение('выводы', выводы)}
              onChange={(событие) => установитьВыводы(событие.target.value)}
            />
          </Field>
          <Field
            подпись="Следующий шаг"
            подсказка="Одно конкретное действие. Обзор без решения — это дневник"
          >
            <Textarea
              rows={2}
              value={значение('следующийШаг', следующийШаг)}
              onChange={(событие) => установитьСледующийШаг(событие.target.value)}
            />
          </Field>

          <Button вид="основная" иконка={<Check size={15} />} onClick={сохранить}>
            {текущий ? 'Обновить обзор' : 'Закрыть обзор'}
          </Button>
        </CardBody>
      </Card>

      <Card>
        <CardHeader
          заголовок="Что повторяется"
          подпись="Сравнение месяцев между собой, не разбор одного периода"
        />
        {паттерны && паттерны.собранныхПериодов < паттерны.нужноПериодов ? (
          <CardBody>
            <p className="text-caption text-ink-3">
              Собрано {паттерны.собранныхПериодов} из {паттерны.нужноПериодов}{' '}
              месяцев с данными. Меньше — и вывод был бы по паре точек, а не
              по-настоящему повторяющимся.
            </p>
          </CardBody>
        ) : паттерны && паттерны.паттерны.length === 0 ? (
          <CardBody>
            <p className="text-caption text-ink-3">
              Данных достаточно, но ничего повторяющегося не найдено.
            </p>
          </CardBody>
        ) : (
          <div className="divide-y divide-line border-t border-line">
            {паттерны?.паттерны.map((паттерн) => (
              <div key={паттерн.id} className="px-5 py-3.5">
                <p className="text-meta font-medium text-ink">{паттерн.текст}</p>
                <p className="mt-1 text-caption leading-relaxed text-ink-3">
                  {паттерн.объяснение}
                </p>
              </div>
            ))}
          </div>
        )}
      </Card>

      <Card>
        <CardHeader заголовок="Прошлые обзоры" подпись={`вид: ${вид}`} />
        {прошлые.length === 0 ? (
          <EmptyState
            заголовок="Прошлых обзоров нет"
            подпись="Первый обзор станет точкой отсчёта: со второго появится с чем сравнивать."
          />
        ) : (
          <div className="divide-y divide-line border-t border-line">
            {прошлые.map((обзор) => (
              <div key={обзор.id} className="px-5 py-3.5">
                <div className="flex flex-wrap items-baseline justify-between gap-2">
                  <span className="text-meta font-medium text-ink">
                    {обзор.период}
                  </span>
                  <span className="tnum text-caption text-ink-3">
                    задачи {обзор.показатели.задачСделано ?? 0}/
                    {обзор.показатели.задачВсего ?? 0} · поток{' '}
                    {деньги(обзор.показатели.поток ?? 0, { знак: true })}
                  </span>
                </div>
                {обзор.следующийШаг ? (
                  <p className="mt-1 text-caption text-ink-2">
                    Следующий шаг: {обзор.следующийШаг}
                  </p>
                ) : null}
              </div>
            ))}
          </div>
        )}
      </Card>
    </div>
  )
}
