import type { КатегорияДенег, Операция } from '@/core/db/types'
import { границыМесяца } from '@/core/calendar/CalendarRu'
import { деньги } from '@/core/money/Money'
import { расходыПоКатегориям } from '@/features/finance/model/calc'
import type { Паттерн } from './types'

const МИНИМУМ_ПОДРЯД = 3

/** Одна и та же категория расходов — крупнейшая несколько месяцев подряд. */
export function паттернКатегория(
  данные: { операции: Операция[]; категории: КатегорияДенег[] },
  месяцы: string[],
): Паттерн[] {
  const имена = new Map(данные.категории.map((к) => [к.id, к.название]))

  const топПоМесяцам = месяцы.map((месяц) => {
    const границы = границыМесяца(месяц)
    const поКатегориям = расходыПоКатегориям(данные.операции, границы.от, границы.до)
    let лучшая: { id: string; сумма: number } | null = null
    for (const [id, сумма] of поКатегориям) {
      if (!лучшая || сумма > лучшая.сумма) лучшая = { id, сумма }
    }
    return { месяц, лучшая }
  })

  // Последняя подряд идущая серия одинаковой категории, считая с конца окна.
  const последние = [...топПоМесяцам].reverse()
  const перваяId = последние[0]?.лучшая?.id
  if (!перваяId) return []

  const серия: typeof топПоМесяцам = []
  for (const запись of последние) {
    if (запись.лучшая?.id !== перваяId) break
    серия.push(запись)
  }
  серия.reverse()

  if (серия.length < МИНИМУМ_ПОДРЯД) return []

  const название = имена.get(перваяId) ?? 'без категории'
  const помесячно = серия
    .map((запись) => `${запись.месяц.slice(5)}: ${деньги(запись.лучшая?.сумма ?? 0)}`)
    .join(', ')

  return [
    {
      id: `паттерн-категория-${перваяId}`,
      текст: `${серия.length}-й месяц подряд больше всего потрачено на «${название}»`,
      объяснение: `По месяцам: ${помесячно}.`,
      раздел: 'Финансы',
      ссылка: '/finance/operations',
    },
  ]
}
