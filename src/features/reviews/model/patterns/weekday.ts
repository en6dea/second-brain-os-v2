import type { Задача, ДатаДень } from '@/core/db/types'
import { границыМесяца, деньНедели } from '@/core/calendar/CalendarRu'
import type { Паттерн } from './types'

const МИНИМУМ_ЗАДАЧ = 8
const РАЗРЫВ_ПРОЦЕНТНЫХ_ПУНКТОВ = 20

/** День недели, в который задачи закрываются заметно реже остальных. */
export function паттернДеньНедели(
  данные: { задачи: Задача[] },
  месяцы: string[],
): Паттерн[] {
  const границы = границыМесяца(месяцы[0] ?? '')
  const границыПоследнего = границыМесяца(месяцы.at(-1) ?? '')
  const от = границы.от
  const до = границыПоследнего.до

  const вОкне = данные.задачи.filter(
    (з) =>
      з.дата !== null && з.дата >= от && з.дата <= до && з.состояние !== 'отменена',
  )

  const поДням = new Map<string, { всего: number; сделано: number }>()
  for (const задача of вОкне) {
    const день = деньНедели(задача.дата as ДатаДень)
    const запись = поДням.get(день) ?? { всего: 0, сделано: 0 }
    запись.всего += 1
    if (задача.состояние === 'сделана') запись.сделано += 1
    поДням.set(день, запись)
  }

  const дни = [...поДням.entries()].filter(([, з]) => з.всего >= МИНИМУМ_ЗАДАЧ)
  if (дни.length < 2) return []

  const результат: Паттерн[] = []
  for (const [день, запись] of дни) {
    const остальные = дни.filter(([д]) => д !== день)
    const всегоОстальных = остальные.reduce((сумма, [, з]) => сумма + з.всего, 0)
    const сделаноОстальных = остальные.reduce((сумма, [, з]) => сумма + з.сделано, 0)
    if (всегоОстальных === 0) continue

    const процентДня = Math.round((запись.сделано / запись.всего) * 100)
    const процентОстальных = Math.round((сделаноОстальных / всегоОстальных) * 100)

    if (процентОстальных - процентДня >= РАЗРЫВ_ПРОЦЕНТНЫХ_ПУНКТОВ) {
      результат.push({
        id: `паттерн-день-недели-${день}`,
        текст: `По ${день.toLowerCase()}ам задачи закрываются реже`,
        объяснение: `${день}: ${запись.сделано} из ${запись.всего} (${процентДня}%). Остальные дни: ${сделаноОстальных} из ${всегоОстальных} (${процентОстальных}%).`,
        раздел: 'Задачи',
        ссылка: '/tasks',
      })
    }
  }

  return результат
}
