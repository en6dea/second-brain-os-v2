import type { Задача, Цель } from '@/core/db/types'
import { границыМесяца } from '@/core/calendar/CalendarRu'
import { склонение } from '@/core/language/Plural'
import type { Паттерн } from './types'

const МИНИМУМ_ПОДРЯД = 3

/** Активная цель, у которой несколько месяцев подряд не закрыто ни одной связанной задачи. */
export function паттернЦельБезДвижения(
  данные: { задачи: Задача[]; цели: Цель[] },
  месяцы: string[],
): Паттерн[] {
  const результат: Паттерн[] = []

  for (const цель of данные.цели) {
    if (цель.состояние !== 'активна') continue
    const связанные = данные.задачи.filter((з) => з.цельId === цель.id)
    if (связанные.length === 0) continue

    const последние = [...месяцы].reverse()
    let подряд = 0
    for (const месяц of последние) {
      const границы = границыМесяца(месяц)
      const естьЗакрытая = связанные.some(
        (з) =>
          з.состояние === 'сделана' &&
          з.выполненаВ !== null &&
          з.выполненаВ.slice(0, 10) >= границы.от &&
          з.выполненаВ.slice(0, 10) <= границы.до,
      )
      if (естьЗакрытая) break
      подряд += 1
    }

    if (подряд >= МИНИМУМ_ПОДРЯД) {
      результат.push({
        id: `паттерн-цель-${цель.id}`,
        текст: `«${цель.название}»: ${подряд} ${склонение(подряд, 'месяц', 'месяца', 'месяцев')} подряд без закрытой задачи`,
        объяснение: `Считается по задачам, связанным с целью (поле «цельId»): ни одна не закрыта за последние ${подряд} ${склонение(подряд, 'месяц', 'месяца', 'месяцев')}.`,
        раздел: 'Цели',
        ссылка: '/goals',
      })
    }
  }

  return результат
}
