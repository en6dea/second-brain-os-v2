import { describe, expect, it } from 'vitest'
import { датыПериода, собратьПоказатели } from './ReviewMetrics'
import type { Задача, Операция, Привычка, Цель } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'

function задача(изменения: Partial<Задача> = {}): Задача {
  return {
    id: 'з',
    createdAt: момент,
    updatedAt: момент,
    название: 'Задача',
    заметка: '',
    дата: '2026-08-11',
    время: null,
    длительностьМинут: null,
    состояние: 'новая',
    важность: 'обычная',
    проектId: null,
    цельId: null,
    сфераId: null,
    выполненаВ: null,
    переносов: 0,
    повтор: null,
    ...изменения,
  }
}

function привычка(отметки: Record<string, number>): Привычка {
  return {
    id: 'п',
    createdAt: момент,
    updatedAt: момент,
    название: 'Привычка',
    иконка: '',
    цвет: 'accent',
    частота: 'ежедневно',
    дниНедели: [],
    разВНеделю: null,
    норма: 1,
    единица: 'раз',
    цельId: null,
    сфераId: null,
    активна: true,
    постер: '',
    отметки,
  }
}

function цель(изменения: Partial<Цель> = {}): Цель {
  return {
    id: 'ц',
    createdAt: момент,
    updatedAt: момент,
    название: 'Цель',
    зачем: '',
    сфераId: null,
    состояние: 'активна',
    срок: null,
    цель: null,
    текущее: null,
    единица: '',
    порядок: 0,
    вехи: [],
    последняяАктивность: null,
    постер: '',
    ...изменения,
  }
}

function операция(изменения: Partial<Операция> = {}): Операция {
  return {
    id: 'о',
    createdAt: момент,
    updatedAt: момент,
    дата: '2026-08-11',
    тип: 'расход',
    сумма: 10000,
    счётId: null,
    счётПолучательId: null,
    категорияId: null,
    классРасхода: null,
    заметка: '',
    планId: null,
    отпечатокИмпорта: null,
    разобрана: true,
    ...изменения,
  }
}

const пусто = { задачи: [], привычки: [], цели: [], операции: [] }

describe('датыПериода', () => {
  it('возвращает все дни включительно', () => {
    expect(датыПериода('2026-08-10', '2026-08-12')).toEqual([
      '2026-08-10',
      '2026-08-11',
      '2026-08-12',
    ])
  })

  it('для одного дня возвращает один день', () => {
    expect(датыПериода('2026-08-11', '2026-08-11')).toHaveLength(1)
  })
})

describe('собратьПоказатели', () => {
  it('на пустых данных не выдумывает чисел', () => {
    const итог = собратьПоказатели(пусто, '2026-08-01', '2026-08-31')
    expect(итог.задачВсего).toBe(0)
    expect(итог.отметокВозможно).toBe(0)
    expect(итог.доходы).toBe(0)
    expect(итог.лучшаяСерия).toBe(0)
  })

  it('считает задачи только внутри периода', () => {
    const итог = собратьПоказатели(
      {
        ...пусто,
        задачи: [
          задача({ id: '1', дата: '2026-08-11', состояние: 'сделана' }),
          задача({ id: '2', дата: '2026-08-11' }),
          задача({ id: '3', дата: '2026-07-20', состояние: 'сделана' }),
        ],
      },
      '2026-08-01',
      '2026-08-31',
    )
    expect(итог.задачВсего).toBe(2)
    expect(итог.задачСделано).toBe(1)
  })

  it('не считает отменённые задачи', () => {
    const итог = собратьПоказатели(
      { ...пусто, задачи: [задача({ состояние: 'отменена' })] },
      '2026-08-01',
      '2026-08-31',
    )
    expect(итог.задачВсего).toBe(0)
  })

  it('просроченное с прежних периодов считается отдельно', () => {
    const итог = собратьПоказатели(
      { ...пусто, задачи: [задача({ дата: '2026-07-01' })] },
      '2026-08-01',
      '2026-08-31',
    )
    expect(итог.задачВсего).toBe(0)
    expect(итог.задачПросрочено).toBe(1)
  })

  it('возможные отметки равны числу привычек на число дней', () => {
    const итог = собратьПоказатели(
      {
        ...пусто,
        привычки: [
          привычка({ '2026-08-10': 1, '2026-08-11': 1 }),
          привычка({ '2026-08-11': 1 }),
        ],
      },
      '2026-08-10',
      '2026-08-12',
    )
    expect(итог.отметокВозможно).toBe(6)
    expect(итог.отметокСделано).toBe(3)
  })

  it('перевод не попадает в доходы и расходы', () => {
    const итог = собратьПоказатели(
      {
        ...пусто,
        операции: [
          операция({ id: '1', тип: 'доход', сумма: 50000 }),
          операция({ id: '2', тип: 'перевод', сумма: 30000 }),
        ],
      },
      '2026-08-01',
      '2026-08-31',
    )
    expect(итог.доходы).toBe(50000)
    expect(итог.расходы).toBe(0)
    expect(итог.поток).toBe(50000)
  })

  it('цель без движения определяется по дате последней активности', () => {
    const итог = собратьПоказатели(
      {
        ...пусто,
        цели: [
          цель({ id: '1', последняяАктивность: '2026-07-01T00:00:00.000Z' }),
          цель({ id: '2', последняяАктивность: '2026-08-15T00:00:00.000Z' }),
        ],
      },
      '2026-08-01',
      '2026-08-31',
    )
    expect(итог.целейАктивных).toBe(2)
    expect(итог.целейБезДвижения).toBe(1)
  })
})
