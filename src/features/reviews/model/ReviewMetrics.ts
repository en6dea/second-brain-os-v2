import type { Задача, Обзор, Операция, Привычка, Цель } from '@/core/db/types'
import { итогПериода } from '@/features/finance/model/calc'
import { длинаСерии } from '@/core/signals/engine'

/**
 * Показатели обзора собираются из записей, а не вводятся заново.
 *
 * Каждое число здесь можно проверить: рядом с ним в интерфейсе стоит
 * пояснение, из чего оно посчитано. Ничего не додумывается: если данных
 * за период нет, показатель равен нулю по факту, а не по умолчанию.
 */

export interface ПоказателиОбзора {
  задачВсего: number
  задачСделано: number
  задачПросрочено: number
  привычекАктивных: number
  отметокСделано: number
  отметокВозможно: number
  лучшаяСерия: number
  доходы: number
  расходы: number
  поток: number
  операций: number
  целейАктивных: number
  целейБезДвижения: number
}

export interface ДанныеОбзора {
  задачи: Задача[]
  привычки: Привычка[]
  цели: Цель[]
  операции: Операция[]
}

const ДЕНЬ = 86_400_000

/** Список дат периода включительно. */
export function датыПериода(от: string, до: string): string[] {
  const итог: string[] = []
  const начало = new Date(`${от}T12:00:00`).getTime()
  const конец = new Date(`${до}T12:00:00`).getTime()
  for (let момент = начало; момент <= конец; момент += ДЕНЬ) {
    итог.push(new Date(момент).toISOString().slice(0, 10))
  }
  return итог
}

export function собратьПоказатели(
  данные: ДанныеОбзора,
  от: string,
  до: string,
): ПоказателиОбзора {
  const вПериоде = (дата: string | null) =>
    дата !== null && дата >= от && дата <= до

  const задачиПериода = данные.задачи.filter(
    (задача) => вПериоде(задача.дата) && задача.состояние !== 'отменена',
  )
  const сделано = задачиПериода.filter((з) => з.состояние === 'сделана').length
  const просрочено = данные.задачи.filter(
    (задача) =>
      задача.дата !== null &&
      задача.дата < от &&
      задача.состояние !== 'сделана' &&
      задача.состояние !== 'отменена',
  ).length

  const активныеПривычки = данные.привычки.filter((п) => п.активна)
  const дни = датыПериода(от, до)
  let отметок = 0
  for (const привычка of активныеПривычки) {
    for (const дата of дни) {
      if ((привычка.отметки[дата] ?? 0) > 0) отметок += 1
    }
  }

  const лучшаяСерия = активныеПривычки.reduce(
    (итог, привычка) => Math.max(итог, длинаСерии(привычка, до)),
    0,
  )

  const деньги = итогПериода(данные.операции, от, до)

  const активныеЦели = данные.цели.filter((ц) => ц.состояние === 'активна')
  const безДвижения = активныеЦели.filter((цель) => {
    const последняя = цель.последняяАктивность ?? цель.updatedAt
    return последняя.slice(0, 10) < от
  }).length

  return {
    задачВсего: задачиПериода.length,
    задачСделано: сделано,
    задачПросрочено: просрочено,
    привычекАктивных: активныеПривычки.length,
    отметокСделано: отметок,
    отметокВозможно: активныеПривычки.length * дни.length,
    лучшаяСерия,
    доходы: деньги.доходы,
    расходы: деньги.расходы,
    поток: деньги.поток,
    операций: деньги.операций,
    целейАктивных: активныеЦели.length,
    целейБезДвижения: безДвижения,
  }
}

/** Показатели в виде, пригодном для хранения в обзоре. */
export function вСлепок(показатели: ПоказателиОбзора): Обзор['показатели'] {
  return { ...показатели }
}
