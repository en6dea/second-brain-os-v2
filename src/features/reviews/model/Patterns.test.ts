import { describe, expect, it } from 'vitest'
import { выявитьПаттерны } from './Patterns'
import type { Задача, Операция, Цель, КатегорияДенег } from '@/core/db/types'
import { деньги } from '@/core/money/Money'

const момент = '2026-01-01T10:00:00.000Z'
const сегодня = '2026-06-15'

function операция(id: string, изменения: Partial<Операция> = {}): Операция {
  return {
    id,
    createdAt: момент,
    updatedAt: момент,
    дата: '2026-01-15',
    тип: 'расход',
    сумма: 1000,
    счётId: null,
    счётПолучательId: null,
    категорияId: null,
    классРасхода: null,
    заметка: '',
    планId: null,
    отпечатокИмпорта: null,
    разобрана: true,
    ...изменения,
  }
}

function задача(id: string, изменения: Partial<Задача> = {}): Задача {
  return {
    id,
    createdAt: момент,
    updatedAt: момент,
    название: 'Задача',
    заметка: '',
    дата: '2026-01-15',
    время: null,
    длительностьМинут: null,
    состояние: 'новая',
    важность: 'обычная',
    проектId: null,
    цельId: null,
    сфераId: null,
    выполненаВ: null,
    переносов: 0,
    повтор: null,
    ...изменения,
  }
}

function цель(id: string, изменения: Partial<Цель> = {}): Цель {
  return {
    id,
    createdAt: момент,
    updatedAt: момент,
    название: 'Цель',
    зачем: '',
    сфераId: null,
    состояние: 'активна',
    срок: null,
    цель: null,
    текущее: null,
    единица: '',
    порядок: 0,
    вехи: [],
    последняяАктивность: null,
    постер: '',
    ...изменения,
  }
}

function категория(id: string, название: string): КатегорияДенег {
  return {
    id,
    createdAt: момент,
    updatedAt: момент,
    название,
    вид: 'расход',
    иконка: '',
    цвет: '',
    месячныйЛимит: null,
    классПоУмолчанию: null,
    архив: false,
    порядок: 0,
    правила: [],
  }
}

const КАТЕГОРИИ = [категория('еда', 'Еда'), категория('транспорт', 'Транспорт')]

// Месяцы окна при сегодня = 2026-06-15 и месяцев = 6: 01..06.
function минимальныеДанныеЗаКаждыйМесяц(): Операция[] {
  // По одной мелкой операции в каждом из шести месяцев — просто чтобы месяц
  // засчитался как «с данными» для общего порога, без влияния на паттерны.
  return ['01', '02', '03', '04', '05', '06'].map((месяц, шаг) =>
    операция(`фон-${шаг}`, {
      дата: `2026-${месяц}-05`,
      категорияId: 'транспорт',
      сумма: 10,
    }),
  )
}

describe('выявитьПаттерны — общий порог истории', () => {
  it('меньше четырёх месяцев с данными — паттернов нет, порог честно назван', () => {
    const итог = выявитьПаттерны(
      { задачи: [], операции: [операция('1', { дата: '2026-06-05' })], цели: [], категории: КАТЕГОРИИ },
      сегодня,
    )
    expect(итог.собранныхПериодов).toBe(1)
    expect(итог.нужноПериодов).toBe(4)
    expect(итог.паттерны).toHaveLength(0)
  })

  it('четыре и больше месяцев с данными — порог пройден', () => {
    const итог = выявитьПаттерны(
      {
        задачи: [],
        операции: минимальныеДанныеЗаКаждыйМесяц(),
        цели: [],
        категории: КАТЕГОРИИ,
      },
      сегодня,
    )
    expect(итог.собранныхПериодов).toBe(6)
  })
})

describe('паттерн категории', () => {
  it('одна категория крупнейшая три месяца подряд — паттерн есть, с точными суммами', () => {
    const операции = [
      ...минимальныеДанныеЗаКаждыйМесяц(),
      операция('апр', { дата: '2026-04-10', категорияId: 'еда', сумма: 800000 }),
      операция('май', { дата: '2026-05-10', категорияId: 'еда', сумма: 900000 }),
      операция('июн', { дата: '2026-06-10', категорияId: 'еда', сумма: 700000 }),
    ]

    const итог = выявитьПаттерны(
      { задачи: [], операции, цели: [], категории: КАТЕГОРИИ },
      сегодня,
    )
    const паттерн = итог.паттерны.find((п) => п.id.startsWith('паттерн-категория'))
    expect(паттерн?.текст).toContain('3-й месяц подряд')
    expect(паттерн?.текст).toContain('Еда')
    expect(паттерн?.объяснение).toContain(деньги(800000))
  })

  it('категория менялась каждый месяц — паттерна нет', () => {
    const операции = [
      операция('1', { дата: '2026-01-05', категорияId: 'еда', сумма: 5000 }),
      операция('2', { дата: '2026-02-05', категорияId: 'транспорт', сумма: 5000 }),
      операция('3', { дата: '2026-03-05', категорияId: 'еда', сумма: 5000 }),
      операция('4', { дата: '2026-04-05', категорияId: 'транспорт', сумма: 5000 }),
      операция('5', { дата: '2026-05-05', категорияId: 'еда', сумма: 5000 }),
      операция('6', { дата: '2026-06-05', категорияId: 'транспорт', сумма: 5000 }),
    ]
    const итог = выявитьПаттерны(
      { задачи: [], операции, цели: [], категории: КАТЕГОРИИ },
      сегодня,
    )
    expect(итог.паттерны.some((п) => п.id.startsWith('паттерн-категория'))).toBe(
      false,
    )
  })
})

describe('паттерн дня недели', () => {
  it('день недели с заметно меньшим закрытием — паттерн есть', () => {
    // 15 июня 2026 — понедельник. Строим по восемь задач на понедельник и
    // на четверг за окно, понедельник закрывается заметно реже.
    const задачи: Задача[] = []
    for (let неделя = 0; неделя < 8; неделя += 1) {
      задачи.push(
        задача(`пн-${неделя}`, {
          дата: `2026-0${2 + Math.floor(неделя / 4)}-${String(2 + (неделя % 4) * 7).padStart(2, '0')}`,
          состояние: неделя < 2 ? 'сделана' : 'новая',
        }),
      )
      задачи.push(
        задача(`чт-${неделя}`, {
          дата: `2026-0${2 + Math.floor(неделя / 4)}-${String(5 + (неделя % 4) * 7).padStart(2, '0')}`,
          состояние: 'сделана',
        }),
      )
    }

    const итог = выявитьПаттерны(
      {
        задачи,
        операции: минимальныеДанныеЗаКаждыйМесяц(),
        цели: [],
        категории: КАТЕГОРИИ,
      },
      сегодня,
    )
    expect(итог.паттерны.some((п) => п.id.startsWith('паттерн-день-недели'))).toBe(
      true,
    )
  })

  it('меньше минимума задач в дне недели — паттерна нет', () => {
    const задачи = [
      задача('1', { дата: '2026-06-01', состояние: 'новая' }),
      задача('2', { дата: '2026-06-08', состояние: 'сделана' }),
    ]
    const итог = выявитьПаттерны(
      {
        задачи,
        операции: минимальныеДанныеЗаКаждыйМесяц(),
        цели: [],
        категории: КАТЕГОРИИ,
      },
      сегодня,
    )
    expect(итог.паттерны.some((п) => п.id.startsWith('паттерн-день-недели'))).toBe(
      false,
    )
  })
})

describe('паттерн цели без движения', () => {
  it('три месяца подряд без закрытой задачи — паттерн есть', () => {
    const цели = [цель('ц1', { название: 'Выучить язык' })]
    const задачи = [
      задача('старая', {
        цельId: 'ц1',
        состояние: 'сделана',
        выполненаВ: '2026-03-10T10:00:00.000Z',
      }),
      задача('открытая', { цельId: 'ц1', состояние: 'новая', дата: '2026-06-01' }),
    ]
    const итог = выявитьПаттерны(
      {
        задачи,
        операции: минимальныеДанныеЗаКаждыйМесяц(),
        цели,
        категории: КАТЕГОРИИ,
      },
      сегодня,
    )
    const паттерн = итог.паттерны.find((п) => п.id === 'паттерн-цель-ц1')
    expect(паттерн?.текст).toContain('месяца подряд')
  })

  it('задача по цели закрыта недавно — паттерна нет', () => {
    const цели = [цель('ц1', { название: 'Выучить язык' })]
    const задачи = [
      задача('свежая', {
        цельId: 'ц1',
        состояние: 'сделана',
        выполненаВ: '2026-06-05T10:00:00.000Z',
      }),
    ]
    const итог = выявитьПаттерны(
      {
        задачи,
        операции: минимальныеДанныеЗаКаждыйМесяц(),
        цели,
        категории: КАТЕГОРИИ,
      },
      сегодня,
    )
    expect(итог.паттерны.some((п) => п.id === 'паттерн-цель-ц1')).toBe(false)
  })

  it('неактивная цель не участвует', () => {
    const цели = [цель('ц1', { название: 'Старая цель', состояние: 'достигнута' })]
    const задачи = [задача('т', { цельId: 'ц1', состояние: 'новая' })]
    const итог = выявитьПаттерны(
      {
        задачи,
        операции: минимальныеДанныеЗаКаждыйМесяц(),
        цели,
        категории: КАТЕГОРИИ,
      },
      сегодня,
    )
    expect(итог.паттерны.some((п) => п.id === 'паттерн-цель-ц1')).toBe(false)
  })
})
