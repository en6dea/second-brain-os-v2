import type {
  Задача,
  КатегорияДенег,
  Операция,
  Цель,
  ДатаДень,
} from '@/core/db/types'
import { границыМесяца, сдвинутьМесяц } from '@/core/calendar/CalendarRu'
import { паттернКатегория } from './patterns/category'
import { паттернДеньНедели } from './patterns/weekday'
import { паттернЦельБезДвижения } from './patterns/goal'
import type { Паттерн } from './patterns/types'

export type { Паттерн } from './patterns/types'

/**
 * Что повторяется — сравнение периодов между собой, а не одного периода.
 *
 * Три правила (`patterns/`) по своим областям. Каждый паттерн — только
 * описание того, что повторилось, с точными числами по каждому месяцу:
 * совпадение не объявляется причиной. Ниже минимума истории — честное
 * «пока рано», а не додуманный вывод по паре точек.
 */

const МИНИМУМ_ПЕРИОДОВ = 4

export interface ИтогПаттернов {
  собранныхПериодов: number
  нужноПериодов: number
  паттерны: Паттерн[]
}

interface ДанныеДляПаттернов {
  задачи: Задача[]
  операции: Операция[]
  цели: Цель[]
  категории: КатегорияДенег[]
}

function месяцыОкна(сегодня: ДатаДень, месяцев: number): string[] {
  const текущий = сегодня.slice(0, 7)
  return Array.from({ length: месяцев }, (_, шаг) =>
    сдвинутьМесяц(`${текущий}-01`, -(месяцев - 1 - шаг)).slice(0, 7),
  )
}

export function выявитьПаттерны(
  данные: ДанныеДляПаттернов,
  сегодня: ДатаДень,
  месяцев = 6,
): ИтогПаттернов {
  const месяцы = месяцыОкна(сегодня, месяцев)

  const собранныхПериодов = месяцы.filter((месяц) => {
    const границы = границыМесяца(месяц)
    return (
      данные.операции.some((о) => о.дата >= границы.от && о.дата <= границы.до) ||
      данные.задачи.some(
        (з) => з.дата !== null && з.дата >= границы.от && з.дата <= границы.до,
      )
    )
  }).length

  if (собранныхПериодов < МИНИМУМ_ПЕРИОДОВ) {
    return { собранныхПериодов, нужноПериодов: МИНИМУМ_ПЕРИОДОВ, паттерны: [] }
  }

  const паттерны = [
    ...паттернКатегория(данные, месяцы),
    ...паттернДеньНедели(данные, месяцы),
    ...паттернЦельБезДвижения(данные, месяцы),
  ]

  return { собранныхПериодов, нужноПериодов: МИНИМУМ_ПЕРИОДОВ, паттерны }
}
