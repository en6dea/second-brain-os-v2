import { useMemo, useState } from 'react'
import { Droplet, HeartHandshake, Pencil, Plus, Trash2 } from 'lucide-react'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import { сейчас } from '@/core/db/RecordId'
import type { ДеньПартнёра, Человек } from '@/core/db/types'
import { деньКратко, деньСловами, сегодня } from '@/core/calendar/CalendarRu'
import { склонение } from '@/core/language/Plural'
import { наблюдения, сводкаЦикла } from '../model/Cycle'
import { useИнтерфейс } from '@/app/providers/ui'
import { cn } from '@/design-system/classNames'
import {
  Badge,
  Button,
  Card,
  CardBody,
  CardHeader,
  Dialog,
  EmptyState,
  Field,
  IconButton,
  Input,
  Metric,
  Segmented,
  Select,
  Textarea,
} from '@/design-system/components'

const СОСТОЯНИЯ = ['хорошо', 'обычно', 'трудно'] as const
const ОТМЕТКИ_ЦИКЛА = ['начало', 'идут', 'конец'] as const

const ТОН_СОСТОЯНИЯ = {
  хорошо: 'успех',
  обычно: 'нейтральный',
  трудно: 'опасность',
} as const

function пустойДень(дата: string, человекId: string | null): Partial<ДеньПартнёра> {
  return {
    дата,
    человекId,
    состояние: null,
    энергия: null,
    дискомфорт: null,
    стресс: null,
    настроение: '',
    сон: '',
    цикл: null,
    симптомы: [],
    чтоПомогло: '',
    чтоНеПомогло: '',
    какаяПоддержкаНужна: '',
    просьба: '',
    планы: '',
    заметка: '',
  }
}

/** Оценка от нуля до десяти, где «не отмечено» — отдельное состояние, а не ноль. */
function ScoreRow({
  подпись,
  значение,
  наИзменение,
}: {
  подпись: string
  значение: number | null
  наИзменение: (значение: number | null) => void
}) {
  return (
    <Field
      подпись={подпись}
      подсказка={значение === null ? 'не отмечено' : 'нажмите ещё раз, чтобы снять'}
    >
      <div className="flex flex-wrap gap-1">
        {Array.from({ length: 11 }, (_, число) => (
          <button
            key={число}
            type="button"
            aria-label={`${подпись}: ${число}`}
            aria-pressed={значение === число}
            onClick={() => наИзменение(значение === число ? null : число)}
            className={cn(
              'tnum h-8 w-8 rounded-2 border text-[12.5px] transition-colors duration-150 active:scale-90',
              значение === число
                ? 'border-transparent bg-accent text-on-accent'
                : 'border-line text-ink-3 hover:border-accent-line hover:bg-accent-soft',
            )}
          >
            {число}
          </button>
        ))}
      </div>
    </Field>
  )
}

export function DayPanel({ дни, люди }: { дни: ДеньПартнёра[]; люди: Человек[] }) {
  const сообщить = useИнтерфейс((с) => с.сообщить)
  const [черновик, установитьЧерновик] = useState<Partial<ДеньПартнёра> | null>(null)

  const день = сегодня()
  const человекПоУмолчанию = дни.find((запись) => запись.человекId)?.человекId ?? null

  const сводка = useMemo(() => сводкаЦикла(дни, день), [дни, день])
  const заметки = useMemo(() => наблюдения(дни, сводка), [дни, сводка])

  const поДате = useMemo(
    () => [...дни].sort((а, б) => б.дата.localeCompare(а.дата)),
    [дни],
  )
  const сегодняшний = дни.find((запись) => запись.дата === день) ?? null

  async function сохранить() {
    if (!черновик?.дата) return
    const поля = {
      человекId: черновик.человекId ?? null,
      дата: черновик.дата,
      состояние: черновик.состояние ?? null,
      энергия: черновик.энергия ?? null,
      дискомфорт: черновик.дискомфорт ?? null,
      стресс: черновик.стресс ?? null,
      настроение: черновик.настроение ?? '',
      сон: черновик.сон ?? '',
      цикл: черновик.цикл ?? null,
      симптомы: черновик.симптомы ?? [],
      чтоПомогло: черновик.чтоПомогло ?? '',
      чтоНеПомогло: черновик.чтоНеПомогло ?? '',
      какаяПоддержкаНужна: черновик.какаяПоддержкаНужна ?? '',
      просьба: черновик.просьба ?? '',
      планы: черновик.планы ?? '',
      заметка: черновик.заметка ?? '',
    }

    // День уникален по дате: запись за уже отмеченный день правится,
    // а не задваивается.
    const занятый = дни.find(
      (запись) => запись.дата === поля.дата && запись.id !== черновик.id,
    )
    const id = черновик.id ?? занятый?.id

    if (id) {
      const текущий = await база.partnerDays.get(id)
      if (текущий) {
        await база.partnerDays.put({ ...текущий, ...поля, updatedAt: сейчас() })
        сообщить(занятый && !черновик.id ? 'День дополнен' : 'День изменён')
      }
    } else {
      await база.partnerDays.add(новаяЗапись(поля) as never)
      сообщить('День записан')
    }
    установитьЧерновик(null)
  }

  const подписьЦикла =
    сводка.надёжность === 'нет данных'
      ? 'Отметьте начало цикла хотя бы дважды — тогда появится длина'
      : сводка.надёжность === 'предварительно'
        ? `Пока ${сводка.циклы.length} ${склонение(сводка.циклы.length, 'цикл', 'цикла', 'циклов')} — вывод предварительный`
        : `Посчитано по ${сводка.циклы.length} циклам ваших отметок`

  return (
    <div className="space-y-5">
      <Card>
        <CardHeader заголовок="Цикл" подпись={подписьЦикла} />
        <div className="grid grid-cols-2 gap-5 px-5 pb-5 sm:grid-cols-4">
          <Metric
            единица="дней · среднее"
            подпись="Длина цикла"
            значение={сводка.средняяДлина === null ? '—' : String(сводка.средняяДлина)}
            источник={
              сводка.разброс
                ? `разброс от ${сводка.разброс.минимум} до ${сводка.разброс.максимум}`
                : 'считать не из чего'
            }
          />
          <Metric
            единица="день"
            подпись="Сегодня день цикла"
            значение={сводка.деньЦикла === null ? '—' : String(сводка.деньЦикла)}
            источник={
              сводка.начала.at(-1)
                ? `от ${деньКратко(сводка.начала.at(-1) ?? null)}`
                : 'начало не отмечено'
            }
          />
          <Metric
            единица="дата · ожидание"
            подпись="Следующее начало"
            значение={сводка.ожидаемоеНачало ? деньКратко(сводка.ожидаемоеНачало) : '—'}
            источник={
              сводка.ожидаемоеНачало
                ? 'арифметика по вашим отметкам'
                : 'нет средней длины'
            }
            тон={сводка.надёжность === 'предварительно' ? 'внимание' : undefined}
          />
          <Metric
            единица="шт · записей"
            подпись="Отмечено дней"
            значение={String(дни.length)}
            источник={`с отметкой цикла: ${сводка.начала.length}`}
          />
        </div>

        {заметки.length > 0 ? (
          <CardBody className="border-t border-line">
            <ul className="space-y-2">
              {заметки.map((текст) => (
                <li key={текст} className="text-[13px] leading-relaxed text-ink-2">
                  {текст}
                </li>
              ))}
            </ul>
          </CardBody>
        ) : null}
      </Card>

      <Card>
        <CardHeader
          заголовок="Дни"
          подпись={
            сегодняшний
              ? 'Сегодняшний день уже записан — его можно дополнить'
              : 'Сегодняшний день ещё не записан'
          }
          действие={
            <Button
              вид={сегодняшний ? 'обычная' : 'основная'}
              onClick={() =>
                установитьЧерновик(
                  сегодняшний
                    ? { ...сегодняшний }
                    : пустойДень(день, человекПоУмолчанию),
                )
              }
            >
              <Plus size={15} />
              {сегодняшний ? 'Дополнить сегодня' : 'Записать сегодня'}
            </Button>
          }
        />

        {поДате.length === 0 ? (
          <EmptyState
            иконка={<HeartHandshake size={22} />}
            заголовок="Записей пока нет"
            подпись="Отметьте, как прошёл день: состояние, силы, что помогло. Через несколько недель станут видны закономерности."
          />
        ) : (
          <ul className="divide-y divide-line border-t border-line">
            {поДате.map((запись) => (
              <li
                key={запись.id}
                className="flex items-start gap-3 px-5 py-3.5 transition-colors duration-150 hover:bg-hover"
              >
                <div className="min-w-0 flex-1">
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="text-[13.5px] font-medium text-ink">
                      {деньСловами(запись.дата)}
                    </span>
                    {запись.состояние ? (
                      <Badge тон={ТОН_СОСТОЯНИЯ[запись.состояние]}>
                        {запись.состояние}
                      </Badge>
                    ) : null}
                    {запись.цикл ? (
                      <Badge тон="опасность">
                        <Droplet size={11} />
                        цикл: {запись.цикл}
                      </Badge>
                    ) : null}
                  </div>

                  <div className="mt-1 flex flex-wrap gap-x-4 gap-y-0.5 text-[12px] text-ink-3">
                    {запись.энергия !== null ? (
                      <span>
                        силы <span className="tnum text-ink-2">{запись.энергия}</span>
                      </span>
                    ) : null}
                    {запись.дискомфорт !== null ? (
                      <span>
                        дискомфорт{' '}
                        <span className="tnum text-ink-2">{запись.дискомфорт}</span>
                      </span>
                    ) : null}
                    {запись.стресс !== null ? (
                      <span>
                        стресс <span className="tnum text-ink-2">{запись.стресс}</span>
                      </span>
                    ) : null}
                    {запись.настроение ? <span>{запись.настроение}</span> : null}
                  </div>

                  {запись.какаяПоддержкаНужна || запись.просьба ? (
                    <p className="mt-1.5 text-[12.5px] leading-relaxed text-ink-2">
                      {[запись.какаяПоддержкаНужна, запись.просьба]
                        .filter(Boolean)
                        .join(' · ')}
                    </p>
                  ) : null}
                </div>

                <div className="flex shrink-0 gap-1">
                  <IconButton
                    подпись="Изменить запись"
                    onClick={() => установитьЧерновик({ ...запись })}
                  >
                    <Pencil size={15} />
                  </IconButton>
                  <IconButton
                    подпись="Удалить запись"
                    onClick={async () => {
                      await база.partnerDays.delete(запись.id)
                      сообщить('Запись дня удалена')
                    }}
                  >
                    <Trash2 size={15} />
                  </IconButton>
                </div>
              </li>
            ))}
          </ul>
        )}
      </Card>

      <Dialog
        открыто={черновик !== null}
        наЗакрытие={() => установитьЧерновик(null)}
        заголовок={черновик?.id ? 'Изменить день' : 'Записать день'}
        подпись="Незаполненное останется неизвестным — это не ноль"
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьЧерновик(null)}>
              Отменить
            </Button>
            <Button вид="основная" onClick={сохранить}>
              Сохранить
            </Button>
          </>
        }
      >
        {черновик ? (
          <div className="space-y-4">
            <div className="grid gap-4 sm:grid-cols-2">
              <Field подпись="Дата">
                <Input
                  type="date"
                  value={черновик.дата ?? день}
                  onChange={(событие) =>
                    установитьЧерновик({ ...черновик, дата: событие.target.value })
                  }
                />
              </Field>
              <Field подпись="Кто" подсказка="карточка из раздела «Люди»">
                <Select
                  value={черновик.человекId ?? ''}
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      человекId: событие.target.value || null,
                    })
                  }
                >
                  <option value="">не указан</option>
                  {люди.map((человек) => (
                    <option key={человек.id} value={человек.id}>
                      {человек.имя}
                    </option>
                  ))}
                </Select>
              </Field>
            </div>

            <Field подпись="Как прошёл день">
              <Segmented
                выбрано={черновик.состояние ?? ''}
                наВыбор={(ключ) =>
                  установитьЧерновик({
                    ...черновик,
                    состояние: (ключ || null) as ДеньПартнёра['состояние'],
                  })
                }
                значения={[
                  { ключ: '', подпись: 'не отмечено' },
                  ...СОСТОЯНИЯ.map((имя) => ({ ключ: имя, подпись: имя })),
                ]}
              />
            </Field>

            <Field подпись="Цикл">
              <Segmented
                выбрано={черновик.цикл ?? ''}
                наВыбор={(ключ) =>
                  установитьЧерновик({
                    ...черновик,
                    цикл: (ключ || null) as ДеньПартнёра['цикл'],
                  })
                }
                значения={[
                  { ключ: '', подпись: 'нет отметки' },
                  ...ОТМЕТКИ_ЦИКЛА.map((имя) => ({ ключ: имя, подпись: имя })),
                ]}
              />
            </Field>

            <ScoreRow
              подпись="Силы"
              значение={черновик.энергия ?? null}
              наИзменение={(значение) =>
                установитьЧерновик({ ...черновик, энергия: значение })
              }
            />
            <ScoreRow
              подпись="Дискомфорт"
              значение={черновик.дискомфорт ?? null}
              наИзменение={(значение) =>
                установитьЧерновик({ ...черновик, дискомфорт: значение })
              }
            />
            <ScoreRow
              подпись="Стресс"
              значение={черновик.стресс ?? null}
              наИзменение={(значение) =>
                установитьЧерновик({ ...черновик, стресс: значение })
              }
            />

            <div className="grid gap-4 sm:grid-cols-2">
              <Field подпись="Настроение словами">
                <Input
                  value={черновик.настроение ?? ''}
                  placeholder="как сама сказала"
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      настроение: событие.target.value,
                    })
                  }
                />
              </Field>
              <Field подпись="Сон">
                <Input
                  value={черновик.сон ?? ''}
                  placeholder="выспалась, просыпалась ночью…"
                  onChange={(событие) =>
                    установитьЧерновик({ ...черновик, сон: событие.target.value })
                  }
                />
              </Field>
            </div>

            <Field подпись="Симптомы" подсказка="через запятую">
              <Input
                value={(черновик.симптомы ?? []).join(', ')}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    симптомы: событие.target.value
                      .split(',')
                      .map((слово) => слово.trim())
                      .filter(Boolean),
                  })
                }
              />
            </Field>

            <div className="grid gap-4 sm:grid-cols-2">
              <Field подпись="Что помогло">
                <Textarea
                  rows={2}
                  value={черновик.чтоПомогло ?? ''}
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      чтоПомогло: событие.target.value,
                    })
                  }
                />
              </Field>
              <Field подпись="Что не помогло">
                <Textarea
                  rows={2}
                  value={черновик.чтоНеПомогло ?? ''}
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      чтоНеПомогло: событие.target.value,
                    })
                  }
                />
              </Field>
            </div>

            <Field подпись="Какая поддержка нужна">
              <Textarea
                rows={2}
                value={черновик.какаяПоддержкаНужна ?? ''}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    какаяПоддержкаНужна: событие.target.value,
                  })
                }
              />
            </Field>

            <div className="grid gap-4 sm:grid-cols-2">
              <Field подпись="Просьба">
                <Input
                  value={черновик.просьба ?? ''}
                  onChange={(событие) =>
                    установитьЧерновик({ ...черновик, просьба: событие.target.value })
                  }
                />
              </Field>
              <Field подпись="Планы на день">
                <Input
                  value={черновик.планы ?? ''}
                  onChange={(событие) =>
                    установитьЧерновик({ ...черновик, планы: событие.target.value })
                  }
                />
              </Field>
            </div>

            <Field подпись="Заметка">
              <Textarea
                rows={3}
                value={черновик.заметка ?? ''}
                onChange={(событие) =>
                  установитьЧерновик({ ...черновик, заметка: событие.target.value })
                }
              />
            </Field>
          </div>
        ) : null}
      </Dialog>
    </div>
  )
}
