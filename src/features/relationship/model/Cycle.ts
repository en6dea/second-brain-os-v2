import type { ДатаДень, ДеньПартнёра } from '@/core/db/types'
import { сдвинутьДень } from '@/core/calendar/CalendarRu'

/**
 * Расчёты по циклу.
 *
 * Всё считается только из отмеченных дней. Ничего не достраивается «средним по
 * популяции»: 28 дней — это книжная цифра, а не ваша. Пока начал цикла меньше
 * двух, длину считать не из чего, и прогноза не будет.
 *
 * Прогноз здесь — арифметика, а не медицина. Он говорит «по вашим отметкам
 * получается так», и не более того.
 */

/** Один зафиксированный цикл: от начала до следующего начала. */
export interface Цикл {
  начало: ДатаДень
  следующееНачало: ДатаДень
  длина: number
}

export interface СводкаЦикла {
  /** Начала циклов по возрастанию даты. */
  начала: ДатаДень[]
  циклы: Цикл[]
  /** Средняя длина цикла в днях. `null` — считать не из чего. */
  средняяДлина: number | null
  /** Самый короткий и самый длинный цикл — показывают разброс. */
  разброс: { минимум: number; максимум: number } | null
  /** Ожидаемое следующее начало. `null`, если нет средней длины. */
  ожидаемоеНачало: ДатаДень | null
  /** Какой сегодня день цикла, считая от последнего начала. */
  деньЦикла: number | null
  /** Насколько выводам можно верить. */
  надёжность: 'нет данных' | 'предварительно' | 'рабочая'
}

function разностьДней(от: ДатаДень, до: ДатаДень): number {
  const начало = new Date(`${от}T00:00:00`)
  const конец = new Date(`${до}T00:00:00`)
  return Math.round((конец.getTime() - начало.getTime()) / 86_400_000)
}

/**
 * Начала циклов.
 *
 * Отметка «начало» ставится руками, но человек может отметить так два дня
 * подряд. Подряд идущие отметки считаются одним началом — берётся первая.
 */
export function началаЦиклов(дни: ДеньПартнёра[]): ДатаДень[] {
  const отмеченные = дни
    .filter((день) => день.цикл === 'начало')
    .map((день) => день.дата)
    .sort()

  const итог: ДатаДень[] = []
  for (const дата of отмеченные) {
    const прошлое = итог.at(-1)
    if (прошлое && разностьДней(прошлое, дата) <= 3) continue
    итог.push(дата)
  }
  return итог
}

export function сводкаЦикла(дни: ДеньПартнёра[], сегодняшний: ДатаДень): СводкаЦикла {
  const начала = началаЦиклов(дни)

  const циклы: Цикл[] = []
  for (let индекс = 1; индекс < начала.length; индекс += 1) {
    const предыдущее = начала[индекс - 1]
    const текущее = начала[индекс]
    if (!предыдущее || !текущее) continue
    циклы.push({
      начало: предыдущее,
      следующееНачало: текущее,
      длина: разностьДней(предыдущее, текущее),
    })
  }

  // Слишком длинный промежуток означает пропущенную отметку, а не цикл в
  // сто дней. Такой промежуток в среднее не берём, но и не прячем — он
  // остаётся в списке циклов.
  const правдоподобные = циклы.filter((цикл) => цикл.длина >= 15 && цикл.длина <= 60)

  const средняяДлина =
    правдоподобные.length === 0
      ? null
      : Math.round(
          правдоподобные.reduce((сумма, цикл) => сумма + цикл.длина, 0) /
            правдоподобные.length,
        )

  const разброс =
    правдоподобные.length === 0
      ? null
      : {
          минимум: Math.min(...правдоподобные.map((цикл) => цикл.длина)),
          максимум: Math.max(...правдоподобные.map((цикл) => цикл.длина)),
        }

  const последнее = начала.at(-1) ?? null

  const ожидаемоеНачало =
    последнее && средняяДлина ? сдвинутьДень(последнее, средняяДлина) : null

  const деньЦикла = последнее ? разностьДней(последнее, сегодняшний) + 1 : null

  const надёжность: СводкаЦикла['надёжность'] =
    правдоподобные.length === 0
      ? 'нет данных'
      : правдоподобные.length < 3
        ? 'предварительно'
        : 'рабочая'

  return {
    начала,
    циклы,
    средняяДлина,
    разброс,
    ожидаемоеНачало,
    деньЦикла: деньЦикла !== null && деньЦикла > 0 ? деньЦикла : null,
    надёжность,
  }
}

/** Числовые отметки, по которым можно искать совпадения. */
type ЧисловаяОтметка = 'энергия' | 'дискомфорт' | 'стресс'

const НАЗВАНИЯ_ОТМЕТОК: Record<ЧисловаяОтметка, string> = {
  энергия: 'энергии',
  дискомфорт: 'дискомфорта',
  стресс: 'стресса',
}

/**
 * Что заметно в отметках рядом с началом цикла.
 *
 * Сравниваются два средних: дни рядом с началом и все остальные. Порог по
 * количеству дней намеренно высокий — на пяти записях считать нечего.
 *
 * Ни при каких условиях совпадение не называется причиной, и в тексте это
 * сказано прямо.
 */
export function наблюдения(дни: ДеньПартнёра[], сводка: СводкаЦикла): string[] {
  if (сводка.средняяДлина === null || сводка.начала.length === 0) return []

  const итог: string[] = []

  for (const отметка of ['энергия', 'дискомфорт', 'стресс'] as ЧисловаяОтметка[]) {
    const сОценкой = дни.filter((день) => день[отметка] !== null)
    if (сОценкой.length < 10) continue

    let рядом = 0
    let суммаРядом = 0
    let прочих = 0
    let суммаПрочих = 0

    for (const день of сОценкой) {
      const близко = сводка.начала.some((начало) => {
        const сдвиг = разностьДней(начало, день.дата)
        return сдвиг >= -4 && сдвиг <= 2
      })
      const значение = день[отметка] ?? 0
      if (близко) {
        рядом += 1
        суммаРядом += значение
      } else {
        прочих += 1
        суммаПрочих += значение
      }
    }

    if (рядом < 4 || прочих < 4) continue

    const разница = суммаРядом / рядом - суммаПрочих / прочих
    if (Math.abs(разница) < 0.8) continue

    const направление = разница > 0 ? 'выше' : 'ниже'
    итог.push(
      `Рядом с началом цикла отметки ${НАЗВАНИЯ_ОТМЕТОК[отметка]} в среднем ` +
        `${направление} на ${Math.abs(разница).toFixed(1)} балла, чем в остальные ` +
        `дни (${рядом} и ${прочих} дней с отметкой). ` +
        `Это совпадение по датам, а не причина.`,
    )
  }

  return итог
}
