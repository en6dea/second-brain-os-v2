import { describe, expect, it } from 'vitest'
import { наблюдения, началаЦиклов, сводкаЦикла } from './Cycle'
import type { ДеньПартнёра } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'

function день(дата: string, изменения: Partial<ДеньПартнёра> = {}): ДеньПартнёра {
  return {
    id: дата,
    createdAt: момент,
    updatedAt: момент,
    человекId: null,
    дата,
    состояние: null,
    энергия: null,
    дискомфорт: null,
    стресс: null,
    настроение: '',
    сон: '',
    цикл: null,
    симптомы: [],
    чтоПомогло: '',
    чтоНеПомогло: '',
    какаяПоддержкаНужна: '',
    просьба: '',
    планы: '',
    заметка: '',
    ...изменения,
  }
}

describe('началаЦиклов', () => {
  it('без отметок возвращает пустой список', () => {
    expect(началаЦиклов([день('2026-08-01')])).toEqual([])
  })

  it('склеивает отметки, поставленные подряд, в одно начало', () => {
    const дни = [
      день('2026-06-01', { цикл: 'начало' }),
      день('2026-06-02', { цикл: 'начало' }),
      день('2026-06-29', { цикл: 'начало' }),
    ]
    expect(началаЦиклов(дни)).toEqual(['2026-06-01', '2026-06-29'])
  })
})

describe('сводкаЦикла', () => {
  it('по одному началу длину не считает и прогноза не даёт', () => {
    const сводка = сводкаЦикла([день('2026-08-01', { цикл: 'начало' })], '2026-08-05')
    expect(сводка.средняяДлина).toBeNull()
    expect(сводка.ожидаемоеНачало).toBeNull()
    expect(сводка.надёжность).toBe('нет данных')
  })

  it('считает день цикла от последнего начала', () => {
    const сводка = сводкаЦикла([день('2026-08-01', { цикл: 'начало' })], '2026-08-05')
    expect(сводка.деньЦикла).toBe(5)
  })

  it('по двум началам считает длину, но помечает вывод предварительным', () => {
    const дни = [
      день('2026-06-01', { цикл: 'начало' }),
      день('2026-06-29', { цикл: 'начало' }),
    ]
    const сводка = сводкаЦикла(дни, '2026-07-01')
    expect(сводка.средняяДлина).toBe(28)
    expect(сводка.ожидаемоеНачало).toBe('2026-07-27')
    expect(сводка.надёжность).toBe('предварительно')
  })

  it('на трёх и более циклах считает вывод рабочим', () => {
    const дни = [
      день('2026-04-05', { цикл: 'начало' }),
      день('2026-05-03', { цикл: 'начало' }),
      день('2026-05-31', { цикл: 'начало' }),
      день('2026-06-28', { цикл: 'начало' }),
    ]
    const сводка = сводкаЦикла(дни, '2026-07-01')
    expect(сводка.надёжность).toBe('рабочая')
    expect(сводка.разброс).toEqual({ минимум: 28, максимум: 28 })
  })

  it('пропущенная отметка не портит среднее', () => {
    const дни = [
      день('2026-01-01', { цикл: 'начало' }),
      день('2026-01-29', { цикл: 'начало' }),
      // Полгода без отметок — человек просто не записывал.
      день('2026-07-01', { цикл: 'начало' }),
      день('2026-07-29', { цикл: 'начало' }),
    ]
    const сводка = сводкаЦикла(дни, '2026-08-01')
    expect(сводка.средняяДлина).toBe(28)
    expect(сводка.циклы).toHaveLength(3)
  })
})

describe('наблюдения', () => {
  it('молчат, пока отметок мало', () => {
    const дни = [
      день('2026-06-01', { цикл: 'начало', энергия: 4 }),
      день('2026-06-29', { цикл: 'начало', энергия: 4 }),
    ]
    expect(наблюдения(дни, сводкаЦикла(дни, '2026-07-01'))).toEqual([])
  })

  it('замечают разницу и прямо говорят, что это не причина', () => {
    const дни: ДеньПартнёра[] = [
      день('2026-06-01', { цикл: 'начало', энергия: 3 }),
      день('2026-06-02', { энергия: 3 }),
      день('2026-06-10', { энергия: 8 }),
      день('2026-06-11', { энергия: 8 }),
      день('2026-06-12', { энергия: 7 }),
      день('2026-06-13', { энергия: 8 }),
      день('2026-06-27', { энергия: 4 }),
      день('2026-06-28', { энергия: 3 }),
      день('2026-06-29', { цикл: 'начало', энергия: 3 }),
      день('2026-06-30', { энергия: 4 }),
      день('2026-07-08', { энергия: 8 }),
      день('2026-07-09', { энергия: 7 }),
    ]
    const тексты = наблюдения(дни, сводкаЦикла(дни, '2026-07-10'))
    expect(тексты).toHaveLength(1)
    expect(тексты[0]).toContain('ниже')
    expect(тексты[0]).toContain('не причина')
  })

  it('незаполненные отметки не считаются нулями', () => {
    // Двадцать дней без единой оценки не должны дать ни одного вывода.
    const дни = [
      день('2026-06-01', { цикл: 'начало' }),
      день('2026-06-29', { цикл: 'начало' }),
      ...Array.from({ length: 20 }, (_, номер) =>
        день(`2026-06-${String(номер + 3).padStart(2, '0')}`),
      ),
    ]
    expect(наблюдения(дни, сводкаЦикла(дни, '2026-07-01'))).toEqual([])
  })
})
