import { useMemo, useState } from 'react'
import { useLiveQuery } from 'dexie-react-hooks'
import { ChevronRight, Plus, Trash2 } from 'lucide-react'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import type { Задача } from '@/core/db/types'
import { деньКратко, сегодня, сдвинутьДень } from '@/core/calendar/CalendarRu'
import { склонение } from '@/core/language/Plural'
import { сейчас } from '@/core/db/RecordId'
import {
  записатьПовтор,
  разобратьПовтор,
  следующаяДата,
  type Повтор,
} from './model/Recurrence'
import { useИнтерфейс } from '@/app/providers/ui'
import { cn } from '@/design-system/classNames'
import {
  Input,
  Select,
  Skeleton,
  Badge,
  Card,
  Button,
  IconButton,
  Dialog,
  Field,
  EmptyState,
  Segmented,
  Textarea,
  CheckMark,
} from '@/design-system/components'

type Отбор = 'сегодня' | 'просрочено' | 'все' | 'сделано'

export function TasksPage() {
  const сообщить = useИнтерфейс((с) => с.сообщить)
  const день = сегодня()
  const [отбор, установитьОтбор] = useState<Отбор>('сегодня')
  const [черновик, установитьЧерновик] = useState<Partial<Задача> | null>(null)

  const задачи = useLiveQuery(() => база.tasks.toArray(), [])
  const цели = useLiveQuery(() => база.goals.toArray(), [])
  const проекты = useLiveQuery(() => база.projects.toArray(), [])

  const отобранные = useMemo(() => {
    if (!задачи) return []
    const открытые = (задача: Задача) =>
      задача.состояние !== 'сделана' && задача.состояние !== 'отменена'
    switch (отбор) {
      case 'сегодня':
        return задачи.filter(
          (з) => открытые(з) && (з.дата === день || з.дата === null),
        )
      case 'просрочено':
        return задачи.filter((з) => открытые(з) && з.дата !== null && з.дата < день)
      case 'сделано':
        return задачи.filter((з) => з.состояние === 'сделана')
      default:
        return задачи.filter(открытые)
    }
  }, [задачи, отбор, день])

  if (!задачи) {
    return (
      <Card>
        <Skeleton строк={5} />
      </Card>
    )
  }

  const просрочено = задачи.filter(
    (з) =>
      з.дата !== null &&
      з.дата < день &&
      з.состояние !== 'сделана' &&
      з.состояние !== 'отменена',
  ).length

  async function переключить(задача: Задача) {
    const сделана = задача.состояние === 'сделана'
    await база.tasks.put({
      ...задача,
      состояние: сделана ? 'новая' : 'сделана',
      выполненаВ: сделана ? null : сейчас(),
      updatedAt: сейчас(),
    })

    // Повтор создаёт следующую задачу только при переходе в «сделана», не
    // при снятии отметки — иначе случайный повторный клик плодит копии.
    // Без даты сдвигать нечего: следующая дата не придумывается.
    if (!сделана && задача.повтор !== null && задача.дата !== null) {
      const дата = следующаяДата(задача.дата, задача.повтор)
      if (дата) {
        await база.tasks.add(
          новаяЗапись({
            название: задача.название,
            заметка: задача.заметка,
            дата,
            время: задача.время,
            длительностьМинут: задача.длительностьМинут,
            состояние: 'новая',
            важность: задача.важность,
            проектId: задача.проектId,
            цельId: задача.цельId,
            сфераId: задача.сфераId,
            выполненаВ: null,
            переносов: 0,
            повтор: задача.повтор,
          }) as never,
        )
      }
    }
  }

  async function перенести(задача: Задача) {
    await база.tasks.put({
      ...задача,
      дата: сдвинутьДень(задача.дата ?? день, 1),
      переносов: задача.переносов + 1,
      updatedAt: сейчас(),
    })
    сообщить(
      задача.переносов + 1 >= 3
        ? `Перенесено. Это уже ${задача.переносов + 1}-й перенос — возможно, задача слишком крупная.`
        : 'Перенесено на завтра',
    )
  }

  async function сохранить() {
    if (!черновик?.название?.trim()) return
    if (черновик.id) {
      const текущая = await база.tasks.get(черновик.id)
      if (текущая) {
        await база.tasks.put({
          ...текущая,
          ...черновик,
          updatedAt: сейчас(),
        } as Задача)
        сообщить('Задача изменена')
      }
    } else {
      await база.tasks.add(
        новаяЗапись({
          название: черновик.название.trim(),
          заметка: черновик.заметка ?? '',
          дата: черновик.дата ?? день,
          время: null,
          длительностьМинут: null,
          состояние: 'новая',
          важность: черновик.важность ?? 'обычная',
          проектId: черновик.проектId ?? null,
          цельId: черновик.цельId ?? null,
          сфераId: null,
          выполненаВ: null,
          переносов: 0,
          повтор: черновик.повтор ?? null,
        }) as never,
      )
      сообщить('Задача добавлена')
    }
    установитьЧерновик(null)
  }

  return (
    <div className="anim-rise space-y-5">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="text-h2 font-semibold text-ink">Задачи</h1>
          <p className="mt-0.5 text-meta text-ink-3">
            {отобранные.length}{' '}
            {склонение(отобранные.length, 'задача', 'задачи', 'задач')} в отборе
            {просрочено > 0 ? ` · просрочено: ${просрочено}` : ''}
          </p>
        </div>
        <Button
          вид="основная"
          иконка={<Plus size={16} />}
          onClick={() => установитьЧерновик({ дата: день })}
        >
          Задача
        </Button>
      </div>

      <Segmented
        значения={[
          { ключ: 'сегодня' as const, подпись: 'Сегодня' },
          {
            ключ: 'просрочено' as const,
            подпись: `Просрочено${просрочено ? ` · ${просрочено}` : ''}`,
          },
          { ключ: 'все' as const, подпись: 'Все открытые' },
          { ключ: 'сделано' as const, подпись: 'Сделано' },
        ]}
        выбрано={отбор}
        наВыбор={установитьОтбор}
      />

      <Card>
        {отобранные.length === 0 ? (
          <EmptyState
            заголовок={
              отбор === 'сегодня'
                ? 'На сегодня задач нет'
                : отбор === 'просрочено'
                  ? 'Просроченных задач нет'
                  : 'Пусто'
            }
            подпись="Добавьте задачу или проверьте другой отбор."
          />
        ) : (
          <div className="divide-y divide-line">
            {отобранные.map((задача) => {
              const сделана = задача.состояние === 'сделана'
              const просроченa =
                задача.дата !== null && задача.дата < день && !сделана
              return (
                <div key={задача.id} className="flex items-center gap-3 px-5 py-3">
                  <CheckMark
                    отмечено={сделана}
                    подпись={сделана ? 'Вернуть в работу' : 'Отметить выполненной'}
                    наПереключение={() => переключить(задача)}
                  />

                  <div className="min-w-0 flex-1">
                    <p
                      className={cn(
                        'truncate text-meta',
                        сделана ? 'text-ink-3 line-through' : 'text-ink',
                      )}
                    >
                      {задача.название}
                    </p>
                    <p className="mt-0.5 flex flex-wrap items-center gap-1.5 text-caption text-ink-3">
                      <span className={просроченa ? 'text-bad' : undefined}>
                        {задача.дата ? деньКратко(задача.дата) : 'без даты'}
                      </span>
                      {задача.важность === 'высокая' ||
                      задача.важность === 'срочная' ? (
                        <Badge тон="внимание">{задача.важность}</Badge>
                      ) : null}
                      {задача.переносов >= 3 ? (
                        <Badge тон="опасность">переносов: {задача.переносов}</Badge>
                      ) : null}
                    </p>
                  </div>

                  {!сделана ? (
                    <IconButton
                      подпись="Перенести на завтра"
                      onClick={() => перенести(задача)}
                    >
                      <ChevronRight size={16} />
                    </IconButton>
                  ) : null}
                  <IconButton
                    подпись="Изменить задачу"
                    onClick={() => установитьЧерновик(задача)}
                  >
                    <span className="text-meta">✎</span>
                  </IconButton>
                  <IconButton
                    подпись="Удалить задачу"
                    onClick={async () => {
                      await база.tasks.delete(задача.id)
                      сообщить('Задача удалена')
                    }}
                  >
                    <Trash2 size={15} />
                  </IconButton>
                </div>
              )
            })}
          </div>
        )}
      </Card>

      <Dialog
        открыто={черновик !== null}
        наЗакрытие={() => установитьЧерновик(null)}
        заголовок={черновик?.id ? 'Изменить задачу' : 'Новая задача'}
        подвал={
          <>
            <Button вид="тихая" onClick={() => установитьЧерновик(null)}>
              Отмена
            </Button>
            <Button
              вид="основная"
              onClick={сохранить}
              disabled={!черновик?.название?.trim()}
            >
              Сохранить
            </Button>
          </>
        }
      >
        {черновик ? (
          <div className="space-y-4">
            <Field подпись="Что нужно сделать" обязательное>
              <Input
                value={черновик.название ?? ''}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    название: событие.target.value,
                  })
                }
                autoFocus
              />
            </Field>
            <div className="grid gap-4 sm:grid-cols-2">
              <Field подпись="Дата">
                <Input
                  type="date"
                  value={черновик.дата ?? ''}
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      дата: событие.target.value || null,
                    })
                  }
                />
              </Field>
              <Field подпись="Важность">
                <Select
                  value={черновик.важность ?? 'обычная'}
                  onChange={(событие) =>
                    установитьЧерновик({
                      ...черновик,
                      важность: событие.target.value as Задача['важность'],
                    })
                  }
                >
                  <option value="низкая">Низкая</option>
                  <option value="обычная">Обычная</option>
                  <option value="высокая">Высокая</option>
                  <option value="срочная">Срочная</option>
                </Select>
              </Field>
            </div>
            <Field
              подпись="Повтор"
              подсказка={
                черновик.дата
                  ? 'После отметки «сделана» появится следующая задача на эту дату'
                  : 'Без даты повтор не сработает — сначала укажите дату'
              }
            >
              <div className="flex gap-3">
                <Select
                  value={разобратьПовтор(черновик.повтор ?? null)?.тип ?? 'нет'}
                  onChange={(событие) => {
                    const тип = событие.target.value
                    if (тип === 'нет') {
                      установитьЧерновик({ ...черновик, повтор: null })
                      return
                    }
                    установитьЧерновик({
                      ...черновик,
                      повтор: записатьПовтор({
                        тип: тип as Повтор['тип'],
                        шаг:
                          тип === 'каждые'
                            ? (разобратьПовтор(черновик.повтор ?? null)?.шаг ?? 2)
                            : 1,
                      }),
                    })
                  }}
                >
                  <option value="нет">Без повтора</option>
                  <option value="ежедневно">Ежедневно</option>
                  <option value="еженедельно">Еженедельно</option>
                  <option value="ежемесячно">Ежемесячно</option>
                  <option value="каждые">Каждые N дней</option>
                </Select>
                {разобратьПовтор(черновик.повтор ?? null)?.тип === 'каждые' ? (
                  <Input
                    type="number"
                    min={2}
                    className="w-24"
                    value={String(
                      разобратьПовтор(черновик.повтор ?? null)?.шаг ?? 2,
                    )}
                    onChange={(событие) => {
                      const шаг = Math.max(2, Number(событие.target.value) || 2)
                      установитьЧерновик({
                        ...черновик,
                        повтор: записатьПовтор({ тип: 'каждые', шаг }),
                      })
                    }}
                  />
                ) : null}
              </div>
            </Field>
            <Field
              подпись="Проект"
              подсказка="Задачи проекта складываются в его прогресс"
            >
              <Select
                value={черновик.проектId ?? ''}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    проектId: событие.target.value || null,
                  })
                }
              >
                <option value="">Без проекта</option>
                {(проекты ?? [])
                  .filter((проект) => проект.состояние === 'активен')
                  .map((проект) => (
                    <option key={проект.id} value={проект.id}>
                      {проект.название}
                    </option>
                  ))}
              </Select>
            </Field>
            <Field
              подпись="Связать с целью"
              подсказка="Задача, не связанная с целью, — это просто дело"
            >
              <Select
                value={черновик.цельId ?? ''}
                onChange={(событие) =>
                  установитьЧерновик({
                    ...черновик,
                    цельId: событие.target.value || null,
                  })
                }
              >
                <option value="">Без цели</option>
                {(цели ?? [])
                  .filter((цель) => цель.состояние === 'активна')
                  .map((цель) => (
                    <option key={цель.id} value={цель.id}>
                      {цель.название}
                    </option>
                  ))}
              </Select>
            </Field>
            <Field подпись="Заметка">
              <Textarea
                rows={3}
                value={черновик.заметка ?? ''}
                onChange={(событие) =>
                  установитьЧерновик({ ...черновик, заметка: событие.target.value })
                }
              />
            </Field>
          </div>
        ) : null}
      </Dialog>
    </div>
  )
}
