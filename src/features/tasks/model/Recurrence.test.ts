import { describe, expect, it } from 'vitest'
import { записатьПовтор, разобратьПовтор, следующаяДата } from './Recurrence'

describe('разобратьПовтор', () => {
  it('распознаёт ежедневно', () => {
    expect(разобратьПовтор('ежедневно')).toEqual({ тип: 'ежедневно', шаг: 1 })
  })

  it('распознаёт еженедельно', () => {
    expect(разобратьПовтор('еженедельно')).toEqual({ тип: 'еженедельно', шаг: 7 })
  })

  it('распознаёт ежемесячно', () => {
    expect(разобратьПовтор('ежемесячно')).toEqual({ тип: 'ежемесячно', шаг: 1 })
  })

  it('распознаёт «каждые:N»', () => {
    expect(разобратьПовтор('каждые:3')).toEqual({ тип: 'каждые', шаг: 3 })
  })

  it('null — не повтор', () => {
    expect(разобратьПовтор(null)).toBeNull()
  })

  it('нераспознанная строка — не повтор, не гадаем', () => {
    expect(разобратьПовтор('раз в год по обещанию')).toBeNull()
  })

  it('«каждые» без числа или с шагом меньше двух — не повтор', () => {
    expect(разобратьПовтор('каждые:')).toBeNull()
    expect(разобратьПовтор('каждые:1')).toBeNull()
    expect(разобратьПовтор('каждые:abc')).toBeNull()
  })

  it('старое значение из миграции (произвольный текст) не распознаётся', () => {
    expect(разобратьПовтор('daily-legacy-key')).toBeNull()
  })
})

describe('записатьПовтор', () => {
  it('простые типы записываются как есть', () => {
    expect(записатьПовтор({ тип: 'ежедневно', шаг: 1 })).toBe('ежедневно')
  })

  it('«каждые» включает число дней', () => {
    expect(записатьПовтор({ тип: 'каждые', шаг: 5 })).toBe('каждые:5')
  })
})

describe('следующаяДата', () => {
  it('ежедневно — на день вперёд', () => {
    expect(следующаяДата('2026-08-17', 'ежедневно')).toBe('2026-08-18')
  })

  it('еженедельно — на семь дней вперёд', () => {
    expect(следующаяДата('2026-08-17', 'еженедельно')).toBe('2026-08-24')
  })

  it('ежемесячно — на месяц вперёд с клэмпингом', () => {
    expect(следующаяДата('2026-01-31', 'ежемесячно')).toBe('2026-02-28')
  })

  it('каждые:3 — на три дня вперёд', () => {
    expect(следующаяДата('2026-08-17', 'каждые:3')).toBe('2026-08-20')
  })

  it('нераспознанный повтор — null, следующей даты нет', () => {
    expect(следующаяДата('2026-08-17', 'что-то своё')).toBeNull()
  })
})
