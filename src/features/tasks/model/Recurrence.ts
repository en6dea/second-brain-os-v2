import type { ДатаДень } from '@/core/db/types'
import { сдвинутьДень, сдвинутьМесяц } from '@/core/calendar/CalendarRu'

/**
 * Повтор задачи.
 *
 * Формат — управляемый словарь, а не свободный текст: `'ежедневно'`,
 * `'еженедельно'`, `'ежемесячно'` или `'каждые:N'` (N — целое число дней,
 * не меньше двух). Всё остальное, включая унаследованные значения из
 * прежней версии, не распознаётся и не даёт следующей даты — гадать по
 * произвольной строке значит рано или поздно создать задачу не в тот день.
 */

export type ТипПовтора = 'ежедневно' | 'еженедельно' | 'ежемесячно' | 'каждые'

export interface Повтор {
  тип: ТипПовтора
  /** Для «каждые» — число дней. Для остальных типов не используется. */
  шаг: number
}

export function разобратьПовтор(значение: string | null): Повтор | null {
  if (значение === 'ежедневно') return { тип: 'ежедневно', шаг: 1 }
  if (значение === 'еженедельно') return { тип: 'еженедельно', шаг: 7 }
  if (значение === 'ежемесячно') return { тип: 'ежемесячно', шаг: 1 }

  if (значение?.startsWith('каждые:')) {
    const шаг = Number(значение.slice('каждые:'.length))
    if (Number.isInteger(шаг) && шаг >= 2) return { тип: 'каждые', шаг }
  }

  return null
}

/** Строковое представление для хранения в `Задача.повтор`. */
export function записатьПовтор(повтор: Повтор): string {
  return повтор.тип === 'каждые' ? `каждые:${повтор.шаг}` : повтор.тип
}

export function следующаяДата(текущая: ДатаДень, значение: string): ДатаДень | null {
  const повтор = разобратьПовтор(значение)
  if (!повтор) return null

  if (повтор.тип === 'ежемесячно') return сдвинутьМесяц(текущая, 1)
  return сдвинутьДень(текущая, повтор.шаг)
}
