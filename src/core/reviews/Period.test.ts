import { describe, expect, it } from 'vitest'
import { ключПериодаОбзора } from './Period'

describe('ключПериодаОбзора', () => {
  it('день — сам день', () => {
    expect(ключПериодаОбзора('день', '2026-08-17')).toBe('2026-08-17')
  })

  it('неделя — границы недели через тире', () => {
    // 2026-08-17 — понедельник, неделя начинается с него.
    expect(ключПериодаОбзора('неделя', '2026-08-17')).toBe('2026-08-17—2026-08-23')
  })

  it('неделя — тот же ключ для любого дня внутри недели', () => {
    expect(ключПериодаОбзора('неделя', '2026-08-20')).toBe('2026-08-17—2026-08-23')
  })

  it('месяц — «ГГГГ-ММ»', () => {
    expect(ключПериодаОбзора('месяц', '2026-08-17')).toBe('2026-08')
  })
})
