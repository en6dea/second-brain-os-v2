/* Шаг 1. Разбор файла и предпросмотр                                  */
/* ------------------------------------------------------------------ */

export function разобратьСтарыйФайл(текстФайла: string): РазборСтарогоФайла {
  let разобрано: unknown
  try {
    разобрано = JSON.parse(текстФайла)
  } catch {
    throw new Error('Файл не является корректным JSON.')
  }

  const корень = разобрано as Запись
  const состояние: Запись =
    корень && typeof корень === 'object' && корень.state
      ? (корень.state as Запись)
      : корень

  if (!состояние || typeof состояние !== 'object') {
    throw new Error('В файле нет данных прежнего приложения.')
  }

  const предупреждения: string[] = []
  const версияСхемы = числоИлиNull(состояние.schemaVersion)

  if (версияСхемы === null) {
    предупреждения.push(
      'В файле нет номера схемы. Разбор выполнен по известной структуре — проверьте предпросмотр внимательнее.',
    )
  } else if (версияСхемы < 3) {
    предупреждения.push(
      `Схема прежних данных: ${версияСхемы}. Это более ранняя версия, часть полей может отличаться — они сохранятся без изменений.`,
    )
  }

  const найдено: НайденнаяКоллекция[] = []
  let всегоЗаписей = 0
  let коллекций = 0

  for (const ключ of Object.keys(состояние)) {
    const значение = состояние[ключ]
    if (!Array.isArray(значение) || значение.length === 0) continue
    коллекций += 1
    всегоЗаписей += значение.length
    const описание = ОПИСАНИЕ[ключ]
    найдено.push({
      ключ,
      название: описание?.название ?? ключ,
      записей: значение.length,
      переносится: Boolean(описание),
      куда: описание?.куда ?? 'Сохранится в поле «прежние данные»',
    })
  }

  найдено.sort((а, б) => б.записей - а.записей)

  const нераспознанные = найдено.filter((строка) => !строка.переносится)
  if (нераспознанные.length > 0) {
    предупреждения.push(
      `Коллекций без отдельного раздела: ${нераспознанные.length} (${нераспознанные
        .map((строка) => строка.ключ)
        .join(', ')}). Данные не потеряются — они сохранятся целиком.`,
    )
  }

  return {
    версияСхемы,
    коллекций,
    всегоЗаписей,
    найдено,
    предупреждения,
    ошибки: [],
    состояние,
  }
}

