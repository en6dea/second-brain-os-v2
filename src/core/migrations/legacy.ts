/* Шаг 2. Перенос                                                      */
/* ------------------------------------------------------------------ */

export async function выполнитьПеренос(
  разбор: РазборСтарогоФайла,
): Promise<ОтчётПереноса> {
  const состояние = разбор.состояние
  const строки: СтрокаОтчёта[] = []
  const предупреждения = [...разбор.предупреждения]

  // Порядок важен: категории и счета нужны операциям, цели — задачам.
  const категории = await перенестиКатегории(состояние)
  строки.push(категории.строка)

  const счета = await перенестиСчета(состояние)
  строки.push(счета.строка)

  const операции = await перенестиОперации(состояние, {
    категорияПоИмени: категории.поИмени,
    счётПоСтаромуId: счета.поСтаромуId,
    счётПоИмени: счета.поИмени,
  })
  строки.push(операции.строка)
  предупреждения.push(...операции.предупреждения)

  строки.push(...(await перенестиОбязательства(состояние)).строки)
  строки.push(
    ...(await перенестиПланыИБюджеты(состояние, категории.поИмени)).строки,
  )
  строки.push((await перенестиСферы(состояние)).строка)

  const цели = await перенестиЦели(состояние)
  строки.push(цели.строка)
  строки.push((await перенестиЗадачи(состояние, цели.поСтаромуId)).строка)
  строки.push(...(await перенестиПривычки(состояние, цели.поСтаромуId)).строки)
  строки.push((await перенестиСобытия(состояние)).строка)
  строки.push((await перенестиЛюдей(состояние)).строка)

  строки.push((await перенестиДниПартнёра(состояние, await близкийЧеловек())).строка)
  строки.push((await перенестиДелаВдвоём(состояние)).строка)

  строки.push((await перенестиЗнания(состояние)).строка)
  строки.push((await перенестиОбучение(состояние)).строка)
  строки.push((await перенестиДневник(состояние)).строка)
  строки.push((await перенестиСделки(состояние)).строка)

  строки.push((await перенестиВходящие(состояние)).строка)
  строки.push((await перенестиАрхив(состояние)).строка)

  await сохранитьНераспознанное(состояние)

  return {
    строки: строки.filter((строка) => строка.из > 0),
    предупреждения,
    ошибки: [],
  }
}

/**
 * Кого считать близким человеком в записях о самочувствии.
 *
 * В прежней версии коллекция называлась по имени, и связи с карточкой человека
 * там не было. Ищем совпадение по имени среди уже перенесённых людей. Не нашли —
 * записи остаются без привязки, и связать их можно вручную. Придумывать
 * человека под записи нельзя.
 */
async function близкийЧеловек(): Promise<string | null> {
  const люди = await база.people.toArray()
  const найден = люди.find((человек) =>
    человек.имя.toLowerCase().startsWith('полин'),
  )
  return найден?.id ?? null
}

/** Настройки и коллекции без раздела сохраняются целиком, без разбора. */
async function сохранитьНераспознанное(состояние: Запись) {
  const текущие = await база.settings.get('настройки')
  if (!текущие) return

  const нераспознанные: Запись = {}
  for (const ключ of Object.keys(состояние)) {
    if (ОПИСАНИЕ[ключ]) continue
    const значение = состояние[ключ]
    if (Array.isArray(значение) && значение.length > 0)
      нераспознанные[ключ] = значение
  }

  await база.settings.put({
    ...текущие,
    legacy: {
      ...(текущие.legacy ?? {}),
      настройкиПрежнейВерсии: состояние.settings ?? null,
      нераспознанныеКоллекции:
        Object.keys(нераспознанные).length > 0 ? нераспознанные : null,
    },
    updatedAt: сейчас(),
  })
}

/** Отпечаток строки выписки — защита от повторного импорта операций. */
export function отпечатокОперации(данные: {
  дата: string
  сумма: number
  описание: string
}): string {
  const описание = данные.описание.toLowerCase().replace(/\s+/g, ' ').trim()
  return `${данные.дата}|${данные.сумма}|${описание}`
}

/** Число записей в коллекции — для предпросмотра и проверок. */
export function записейВКоллекции(состояние: Запись, ключ: string): number {
  return массив(состояние, ключ).length
}
