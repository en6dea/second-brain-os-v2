export function разобратьСтарыйФайл(текстФайла: string): РазборСтарогоФайла {
  const ошибки: string[] = []
  const предупреждения: string[] = []

  let разобрано: unknown
  try {
    разобрано = JSON.parse(текстФайла)
  } catch {
    throw new Error('Файл не является корректным JSON.')
  }

  const корень = разобрано as Запись
  const состояние: Запись =
    корень && typeof корень === 'object' && корень.state
      ? (корень.state as Запись)
      : (корень as Запись)

  if (!состояние || typeof состояние !== 'object') {
    throw new Error('В файле нет данных прежнего приложения.')
  }

  const версияСхемы = числоИлиNull(состояние.schemaVersion)
  if (версияСхемы === null) {
    предупреждения.push(
      'В файле нет номера схемы. Разбор выполнен по известной структуре версии 3 — проверьте предпросмотр внимательнее.',
    )
  } else if (версияСхемы !== 3) {
    предупреждения.push(
      `Схема прежних данных: ${версияСхемы}, ожидалась 3. Часть полей может не распознаться — они сохранятся без изменений.`,
    )
  }

  const найдено: НайденнаяКоллекция[] = []
  let всегоЗаписей = 0
  let коллекций = 0

  for (const ключ of Object.keys(состояние)) {
    const значение = состояние[ключ]
    if (!Array.isArray(значение)) continue
    коллекций += 1
    всегоЗаписей += значение.length
    const описание = ОПИСАНИЕ_КОЛЛЕКЦИЙ[ключ]
    найдено.push({
      ключ,
      название: описание?.название ?? ключ,
      записей: значение.length,
      переносится: Boolean(описание),
      куда: описание?.куда ?? 'Сохранится как есть, без отдельного раздела',
    })
  }

  найдено.sort((а, б) => б.записей - а.записей)

  const нераспознанные = найдено.filter(
    (строка) => !строка.переносится && строка.записей > 0,
  )
  if (нераспознанные.length > 0) {
    предупреждения.push(
      `Коллекций без отдельного раздела в новой версии: ${нераспознанные.length}. Данные не потеряются — они сохранятся в поле «прежние данные».`,
    )
  }

  return {
    версияСхемы,
    коллекций,
    всегоЗаписей,
    найдено,
    предупреждения,
    ошибки,
    состояние,
  }
}

