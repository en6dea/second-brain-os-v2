export async function выполнитьПеренос(
  разбор: РазборСтарогоФайла,
): Promise<ОтчётПереноса> {
  const состояние = разбор.состояние
  const строки: ОтчётПереноса['строки'] = []
  const предупреждения = [...разбор.предупреждения]
  const ошибки: string[] = []

  /* --- Категории денег: нужны раньше операций --- */
  const категорияПоИмени = new Map<string, string>()
  for (const существующая of await база.moneyCategories.toArray()) {
    категорияПоИмени.set(существующая.название.toLowerCase(), существующая.id)
  }

  const старыеКатегории = массив(состояние, 'financeCategories')
  const новыеКатегории: КатегорияДенег[] = []
  for (const строка of старыеКатегории) {
    const название = текст(строка.name) || текст(строка.title)
    if (!название) continue
    if (категорияПоИмени.has(название.toLowerCase())) continue
    const запись = новаяЗапись({
      название,
      вид: текст(строка.type) === 'income' ? 'доход' : 'расход',
      иконка: текст(строка.icon),
      цвет: текст(строка.color) || 'ink-2',
      месячныйЛимит: деньгиИзСтарого(строка.monthlyLimit),
      классПоУмолчанию: КЛАССЫ_РАСХОДА[текст(строка.defaultExpenseClass)] ?? null,
      архив: Boolean(строка.archived),
      порядок: числоИлиNull(строка.order) ?? 0,
      правила: [],
      legacy: остаток(строка, [
        'id',
        'name',
        'title',
        'type',
        'icon',
        'color',
        'monthlyLimit',
        'defaultExpenseClass',
        'archived',
        'order',
        'active',
        'createdAt',
        'updatedAt',
      ]),
    }) as КатегорияДенег
    новыеКатегории.push(запись)
    категорияПоИмени.set(название.toLowerCase(), запись.id)
  }
  if (новыеКатегории.length > 0) await база.moneyCategories.bulkPut(новыеКатегории)
  строки.push({
    название: 'Категории денег',
    перенесено: новыеКатегории.length,
    из: старыеКатегории.length,
  })

  /* --- Счета --- */
  const старыеСчета = массив(состояние, 'financeAccounts')
  const счётПоСтаромуId = new Map<string, string>()
  const счётПоИмени = new Map<string, string>()
  const новыеСчета: Счёт[] = []

  старыеСчета.forEach((строка, индекс) => {
    const название = текст(строка.name) || `Счёт ${индекс + 1}`
    const тип = ТИПЫ_СЧЕТОВ[текст(строка.type)] ?? 'иное'
    const запись = новаяЗапись({
      название,
      тип,
      валюта: 'RUB',
      // Незаполненный остаток остаётся незаполненным — это не ноль.
      фактическийОстаток: деньгиИзСтарого(строка.actualBalance),
      подтверждён: строка.actualBalance === null ? null : сейчас(),
      кредитныйЛимит: деньгиИзСтарого(строка.creditLimit),
      учитыватьВДоступных: строка.includeAvailable !== false,
      архив: Boolean(строка.archived),
      порядок: индекс,
      legacy: остаток(строка, [
        'id',
        'name',
        'type',
        'currency',
        'actualBalance',
        'creditLimit',
        'includeAvailable',
        'archived',
        'createdAt',
        'updatedAt',
      ]),
    }) as Счёт
    новыеСчета.push(запись)
    const староеId = текст(строка.id)
    if (староеId) счётПоСтаромуId.set(староеId, запись.id)
    счётПоИмени.set(название.toLowerCase(), запись.id)
  })
  if (новыеСчета.length > 0) await база.accounts.bulkPut(новыеСчета)
  строки.push({
    название: 'Счета',
    перенесено: новыеСчета.length,
    из: старыеСчета.length,
  })

  /* --- Операции --- */
  const старыеОперации = массив(состояние, 'operations')
  const новыеОперации: Операция[] = []
  let операцийБезДаты = 0

  for (const строка of старыеОперации) {
    const дата = датаИлиNull(строка.date)
    if (!дата) {
      операцийБезДаты += 1
      continue
    }
    const названиеКатегории = текст(строка.category)
    const счётId =
      счётПоСтаромуId.get(текст(строка.accountId)) ??
      счётПоИмени.get(текст(строка.account).toLowerCase()) ??
      null

    новыеОперации.push(
      новаяЗапись({
        дата,
        тип: ТИПЫ_ОПЕРАЦИЙ[текст(строка.type)] ?? 'расход',
        сумма: Math.abs(деньгиИзСтарого(строка.amount) ?? 0),
        счётId,
        счётПолучательId: null,
        категорияId: категорияПоИмени.get(названиеКатегории.toLowerCase()) ?? null,
        классРасхода: КЛАССЫ_РАСХОДА[текст(строка.expenseClass)] ?? null,
        заметка: текст(строка.note),
        планId: null,
        отпечатокИмпорта: null,
        разобрана: Boolean(названиеКатегории),
        legacy: остаток(строка, [
          'id',
          'date',
          'type',
          'amount',
          'category',
          'expenseClass',
          'account',
          'accountId',
          'note',
          'planId',
          'createdAt',
          'updatedAt',
        ]),
      }) as Операция,
    )
  }
  if (новыеОперации.length > 0) await база.operations.bulkPut(новыеОперации)
  строки.push({
    название: 'Операции',
    перенесено: новыеОперации.length,
    из: старыеОперации.length,
  })
  if (операцийБезДаты > 0) {
    предупреждения.push(
      `Операций без даты пропущено: ${операцийБезДаты}. Без даты операция не может участвовать в расчётах периода.`,
    )
  }

  /* --- Обязательства и платежи --- */
  const старыеДолги = массив(состояние, 'debts')
  const долгПоСтаромуId = new Map<string, string>()
  const новыеДолги: Обязательство[] = []

  for (const строка of старыеДолги) {
    const направление =
      текст(строка.direction) === 'in' || текст(строка.direction) === 'incoming'
        ? 'мне должны'
        : 'я должен'
    const статус = текст(строка.status).toLowerCase()
    const запись = новаяЗапись({
      название: текст(строка.creditor) || текст(строка.person) || 'Обязательство',
      направление,
      вид: 'иное',
      телоОстаток:
        деньгиИзСтарого(строка.principalBalance) ??
        деньгиИзСтарого(строка.currentBalance) ??
        деньгиИзСтарого(строка.amount),
      начисленныеПроценты: деньгиИзСтарого(строка.accruedInterest),
      штрафы: деньгиИзСтарого(строка.penalties),
      ставкаГодовых: числоИлиNull(строка.interestRate),
      минимальныйПлатёж: деньгиИзСтарого(строка.minimumPayment),
      датаСледующегоПлатежа: датаИлиNull(строка.nextPaymentDate ?? строка.due),
      датаОкончания: датаИлиNull(строка.endDate),
      контрагент: текст(строка.person) || текст(строка.creditor),
      закрыто: ['закрыт', 'закрыто', 'оплачен', 'оплачено', 'closed'].includes(
        статус,
      ),
      заметка: текст(строка.note),
      legacy: остаток(строка, [
        'id',
        'direction',
        'creditor',
        'person',
        'type',
        'status',
        'principalBalance',
        'currentBalance',
        'amount',
        'accruedInterest',
        'penalties',
        'interestRate',
        'minimumPayment',
        'nextPaymentDate',
        'due',
        'endDate',
        'note',
        'createdAt',
        'updatedAt',
      ]),
    }) as Обязательство
    новыеДолги.push(запись)
    const староеId = текст(строка.id)
    if (староеId) долгПоСтаромуId.set(староеId, запись.id)
  }
  if (новыеДолги.length > 0) await база.obligations.bulkPut(новыеДолги)
  строки.push({
    название: 'Обязательства',
    перенесено: новыеДолги.length,
    из: старыеДолги.length,
  })

  const старыеПлатежи = массив(состояние, 'debtPayments')
  const новыеПлатежи: ПлатёжПоОбязательству[] = []
  for (const строка of старыеПлатежи) {
    const обязательствоId = долгПоСтаромуId.get(текст(строка.debtId))
    if (!обязательствоId) continue
    const тело = деньгиИзСтарого(строка.principal) ?? 0
    const проценты = деньгиИзСтарого(строка.interest) ?? 0
    const штрафы = деньгиИзСтарого(строка.penalty) ?? 0
    новыеПлатежи.push(
      новаяЗапись({
        обязательствоId,
        дата: датаИлиNull(строка.date) ?? сейчас().slice(0, 10),
        всего: деньгиИзСтарого(строка.amount) ?? тело + проценты + штрафы,
        тело,
        проценты,
        штрафы,
        операцияId: null,
        legacy: остаток(строка, [
          'id',
          'debtId',
          'date',
          'amount',
          'principal',
          'interest',
          'penalty',
          'createdAt',
          'updatedAt',
        ]),
      }) as ПлатёжПоОбязательству,
    )
  }
  if (новыеПлатежи.length > 0) await база.obligationPayments.bulkPut(новыеПлатежи)
  строки.push({
    название: 'Платежи по обязательствам',
    перенесено: новыеПлатежи.length,
    из: старыеПлатежи.length,
  })

  /* --- Задачи --- */
  const старыеЗадачи = массив(состояние, 'tasks')
  const состоянияЗадач: Record<string, Задача['состояние']> = {
    done: 'сделана',
    completed: 'сделана',
    сделано: 'сделана',
    canceled: 'отменена',
    'in-progress': 'в работе',
  }
  const новыеЗадачи = старыеЗадачи.map(
    (строка) =>
      новаяЗапись({
        название: текст(строка.title) || 'Задача без названия',
        заметка: текст(строка.note),
        дата: датаИлиNull(строка.date),
        время: текст(строка.time) || null,
        длительностьМинут: числоИлиNull(строка.durationMinutes),
        состояние: состоянияЗадач[текст(строка.status)] ?? 'новая',
        важность: текст(строка.priority) === 'high' ? 'высокая' : 'обычная',
        проектId: null,
        цельId: null,
        сфераId: null,
        выполненаВ: текст(строка.completedAt) || null,
        переносов: числоИлиNull(строка.postponed) ?? 0,
        повтор: текст(строка.automationKey) || null,
        legacy: остаток(строка, [
          'id',
          'title',
          'note',
          'date',
          'time',
          'durationMinutes',
          'status',
          'priority',
          'completedAt',
          'postponed',
          'automationKey',
          'createdAt',
          'updatedAt',
        ]),
      }) as Задача,
  )
  if (новыеЗадачи.length > 0) await база.tasks.bulkPut(новыеЗадачи)
  строки.push({
    название: 'Задачи',
    перенесено: новыеЗадачи.length,
    из: старыеЗадачи.length,
  })

  /* --- Привычки: словарь отметок сохраняется как есть --- */
  const старыеПривычки = массив(состояние, 'habits')
  const новыеПривычки = старыеПривычки.map((строка) => {
    const исходныеОтметки = (строка.marks ?? {}) as Record<string, unknown>
    const отметки: Record<string, number> = {}
    for (const ключ of Object.keys(исходныеОтметки)) {
      const значение = исходныеОтметки[ключ]
      отметки[ключ] =
        typeof значение === 'number'
          ? значение
          : значение === true
            ? 1
            : (числоИлиNull(значение) ?? 0)
    }
    return новаяЗапись({
      название: текст(строка.name) || 'Привычка',
      иконка: текст(строка.icon),
      цвет: текст(строка.color) || 'accent',
      частота: 'ежедневно',
      дниНедели: [],
      разВНеделю: null,
      норма: числоИлиNull(строка.target) ?? 1,
      единица: текст(строка.unit) || 'раз',
      цельId: null,
      сфераId: null,
      активна: строка.active !== false,
      отметки,
      legacy: остаток(строка, [
        'id',
        'name',
        'icon',
        'color',
        'marks',
        'target',
        'unit',
        'frequency',
        'active',
        'note',
        'createdAt',
        'updatedAt',
      ]),
    }) as Привычка
  })
  if (новыеПривычки.length > 0) await база.habits.bulkPut(новыеПривычки)
  строки.push({
    название: 'Привычки',
    перенесено: новыеПривычки.length,
    из: старыеПривычки.length,
  })

  /* --- Цели --- */
  const старыеЦели = массив(состояние, 'goals')
  const новыеЦели = старыеЦели.map(
    (строка, индекс) =>
      новаяЗапись({
        название: текст(строка.title) || текст(строка.name) || 'Цель',
        зачем: текст(строка.why) || текст(строка.description),
        сфераId: null,
        состояние: строка.done ? 'достигнута' : 'активна',
        срок: датаИлиNull(строка.deadline ?? строка.due),
        цель: числоИлиNull(строка.target),
        текущее: числоИлиNull(строка.current),
        единица: текст(строка.unit),
        порядок: индекс,
        вехи: [],
        последняяАктивность: текст(строка.updatedAt) || null,
        legacy: остаток(строка, [
          'id',
          'title',
          'name',
          'why',
          'description',
          'done',
          'deadline',
          'due',
          'target',
          'current',
          'unit',
          'createdAt',
          'updatedAt',
        ]),
      }) as Цель,
  )
  if (новыеЦели.length > 0) await база.goals.bulkPut(новыеЦели)
  строки.push({
    название: 'Цели',
    перенесено: новыеЦели.length,
    из: старыеЦели.length,
  })

  /* --- Люди --- */
  const старыеЛюди = массив(состояние, 'people')
  const новыеЛюди = старыеЛюди.map(
    (строка) =>
      новаяЗапись({
        имя: текст(строка.name) || 'Без имени',
        отношения: текст(строка.relation) || текст(строка.role),
        телефон: текст(строка.phone),
        почта: текст(строка.email),
        деньРождения: датаИлиNull(строка.birthday),
        важныеДаты: [],
        заметка: текст(строка.note),
        обещания: '',
        подарки: текст(строка.gifts),
        последнийКонтакт: датаИлиNull(строка.lastContact),
        напоминатьЧерезДней: null,
        legacy: остаток(строка, [
          'id',
          'name',
          'relation',
          'role',
          'phone',
          'email',
          'birthday',
          'note',
          'gifts',
          'lastContact',
          'createdAt',
          'updatedAt',
        ]),
      }) as Человек,
  )
  if (новыеЛюди.length > 0) await база.people.bulkPut(новыеЛюди)
  строки.push({
    название: 'Люди',
    перенесено: новыеЛюди.length,
    из: старыеЛюди.length,
  })

  /* --- Знания: несколько прежних коллекций сходятся в одну --- */
  const источникиЗнаний: { ключ: string; вид: ЗаписьЗнания['вид'] }[] = [
    { ключ: 'notes', вид: 'заметка' },
    { ключ: 'ideas', вид: 'инсайт' },
    { ключ: 'documents', вид: 'инструкция' },
    { ключ: 'books', вид: 'книга' },
    { ключ: 'films', вид: 'статья' },
    { ключ: 'wishes', вид: 'заметка' },
    { ключ: 'trips', вид: 'заметка' },
    { ключ: 'knowledgeLinks', вид: 'ссылка' },
  ]
  const новыеЗнания: ЗаписьЗнания[] = []
  let изЗнаний = 0
  for (const источник of источникиЗнаний) {
    const записи = массив(состояние, источник.ключ)
    изЗнаний += записи.length
    for (const строка of записи) {
      новыеЗнания.push(
        новаяЗапись({
          заголовок:
            текст(строка.title) || текст(строка.name) || 'Запись без названия',
          вид: источник.вид,
          текст: текст(строка.text) || текст(строка.note) || текст(строка.content),
          ссылка: текст(строка.url) || текст(строка.link),
          меткиId: [],
          папкаId: null,
          проектId: null,
          цельId: null,
          избранное: Boolean(строка.favorite),
          legacy: {
            прежняяКоллекция: источник.ключ,
            ...остаток(строка, [
              'id',
              'title',
              'name',
              'text',
              'note',
              'content',
              'url',
              'link',
              'favorite',
              'createdAt',
              'updatedAt',
            ]),
          },
        }) as ЗаписьЗнания,
      )
    }
  }
  if (новыеЗнания.length > 0) await база.knowledge.bulkPut(новыеЗнания)
  строки.push({
    название: 'Знания',
    перенесено: новыеЗнания.length,
    из: изЗнаний,
  })

  /* --- Обучение --- */
  const старыеМатериалы = массив(состояние, 'learningMaterials')
  const новыеМатериалы = старыеМатериалы.map(
    (строка) =>
      новаяЗапись({
        название: текст(строка.title) || текст(строка.name) || 'Материал',
        вид: 'иное',
        источник: текст(строка.source) || текст(строка.url),
        состояние: строка.done ? 'завершено' : 'изучаю',
        прогресс: числоИлиNull(строка.progress) ?? 0,
        часов: числоИлиNull(строка.hours),
        цельId: null,
        заметка: текст(строка.note),
        legacy: остаток(строка, [
          'id',
          'title',
          'name',
          'source',
          'url',
          'done',
          'progress',
          'hours',
          'note',
          'createdAt',
          'updatedAt',
        ]),
      }) as МатериалОбучения,
  )
  if (новыеМатериалы.length > 0) await база.learning.bulkPut(новыеМатериалы)
  строки.push({
    название: 'Обучение',
    перенесено: новыеМатериалы.length,
    из: старыеМатериалы.length,
  })

  /* --- Дневник: обычный и подсознания --- */
  const личные = массив(состояние, 'personal')
  const подсознание = массив(состояние, 'subconsciousEntries')
  const новыйДневник: ЗаписьДневника[] = []

  for (const строка of личные) {
    новыйДневник.push(
      новаяЗапись({
        дата: датаИлиNull(строка.date) ?? сейчас().slice(0, 10),
        вид: 'день',
        заголовок: текст(строка.title),
        текст: текст(строка.text) || текст(строка.note),
        настроение: числоИлиNull(строка.mood),
        сон: числоИлиNull(строка.sleep),
        личное: true,
        legacy: остаток(строка, [
          'id',
          'date',
          'title',
          'text',
          'note',
          'mood',
          'sleep',
          'createdAt',
          'updatedAt',
        ]),
      }) as ЗаписьДневника,
    )
  }
  for (const строка of подсознание) {
    новыйДневник.push(
      новаяЗапись({
        дата: датаИлиNull(строка.date) ?? сейчас().slice(0, 10),
        вид: 'подсознание',
        заголовок: текст(строка.title),
        текст: текст(строка.text) || текст(строка.content),
        настроение: числоИлиNull(строка.mood),
        сон: null,
        личное: true,
        legacy: остаток(строка, [
          'id',
          'date',
          'title',
          'text',
          'content',
          'mood',
          'createdAt',
          'updatedAt',
        ]),
      }) as ЗаписьДневника,
    )
  }
  if (новыйДневник.length > 0) await база.journal.bulkPut(новыйДневник)
  строки.push({
    название: 'Дневник',
    перенесено: новыйДневник.length,
    из: личные.length + подсознание.length,
  })

  /* --- Входящие --- */
  const старыеВходящие = массив(состояние, 'inbox')
  if (старыеВходящие.length > 0) {
    await база.inbox.bulkPut(
      старыеВходящие.map((строка) =>
        новаяЗапись({
          текст: текст(строка.text) || текст(строка.title),
          разобрано: Boolean(строка.processed),
          источник: 'импорт' as const,
          legacy: остаток(строка, [
            'id',
            'text',
            'title',
            'processed',
            'createdAt',
            'updatedAt',
          ]),
        }),
      ) as never,
    )
  }
  строки.push({
    название: 'Входящие',
    перенесено: старыеВходящие.length,
    из: старыеВходящие.length,
  })

  /* --- Настройки прежней версии сохраняем целиком --- */
  const прежниеНастройки = состояние.settings
  if (прежниеНастройки && typeof прежниеНастройки === 'object') {
    const текущие = await база.settings.get('настройки')
    if (текущие) {
      await база.settings.put({
        ...текущие,
        legacy: {
          ...(текущие.legacy ?? {}),
          настройкиПрежнейВерсии: прежниеНастройки,
        },
        updatedAt: сейчас(),
      })
    }
  }

  return { строки, предупреждения, ошибки }
}

/** Идентификатор для сопоставления записей при повторном переносе. */
export function отпечатокОперации(данные: {
  дата: string
  сумма: number
  описание: string
}): string {
  const описание = данные.описание.toLowerCase().replace(/\s+/g, ' ').trim()
  return `${данные.дата}|${данные.сумма}|${описание}`
}
