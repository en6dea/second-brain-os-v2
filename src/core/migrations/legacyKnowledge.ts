export async function перенестиЗнания(
  состояние: Запись,
): Promise<{ строка: СтрокаОтчёта }> {
  const новые: ЗаписьЗнания[] = []
  let всего = 0

  for (const источник of ИСТОЧНИКИ) {
    const записи = массив(состояние, источник.ключ)
    всего += записи.length
    for (const строка of записи) {
      новые.push(
        новаяЗапись({
          заголовок:
            текст(строка.title) || текст(строка.name) || 'Запись без названия',
          вид: источник.вид,
          текст: собратьТекст(строка, источник.части),
          ссылка: текст(строка.url) || текст(строка.target),
          меткиId: [],
          папкаId: null,
          проектId: null,
          цельId: null,
          избранное: Boolean(строка.pinned),
          legacy: {
            прежняяКоллекция: источник.ключ,
            ...остаток(строка, [
              ...СЛУЖЕБНЫЕ,
              'title',
              'name',
              'url',
              'target',
              'pinned',
              ...источник.части.map(([ключ]) => ключ),
            ]),
          },
        }) as ЗаписьЗнания,
      )
    }
  }

  if (новые.length > 0) await база.knowledge.bulkPut(новые)
  return { строка: { название: 'Знания', перенесено: новые.length, из: всего } }
}

