/**
 * Дневник. Прежде записи лежали в пяти коллекциях с разными полями.
 * Записи подсознания состояли из десятка узких полей — они собираются
 * в читаемый текст, а исходные значения сохраняются в `legacy`.
 */
export async function перенестиДневник(
  состояние: Запись,
): Promise<{ строка: СтрокаОтчёта }> {
  const новые: ЗаписьДневника[] = []
  let всего = 0

  const простые = [
    { ключ: 'journal', вид: 'день' as const },
    { ключ: 'journalEntries', вид: 'день' as const },
    { ключ: 'personal', вид: 'день' as const },
    { ключ: 'weeklyReviews', вид: 'размышление' as const },
    { ключ: 'reviews', вид: 'размышление' as const },
    { ключ: 'reports', вид: 'размышление' as const },
  ]

  for (const источник of простые) {
    const записи = массив(состояние, источник.ключ)
    всего += записи.length
    for (const строка of записи) {
      const содержимое = текст(строка.text) || текст(строка.note)
      if (!содержимое && !текст(строка.title)) continue
      новые.push(
        новаяЗапись({
          дата: датаИлиNull(строка.date) ?? сейчас().slice(0, 10),
          вид: источник.вид,
          заголовок: текст(строка.title),
          текст: содержимое,
          настроение: числоИлиNull(строка.mood),
          сон: числоИлиNull(строка.sleep),
          личное: true,
          legacy: {
            прежняяКоллекция: источник.ключ,
            ...остаток(строка, [...СЛУЖЕБНЫЕ, 'date', 'title', 'text', 'note']),
          },
        }) as ЗаписьДневника,
      )
    }
  }

  const подсознание = массив(состояние, 'subconsciousEntries')
  всего += подсознание.length
  for (const строка of подсознание) {
    новые.push(
      новаяЗапись({
        дата: датаИлиNull(строка.date) ?? сейчас().slice(0, 10),
        вид: 'подсознание',
        заголовок: текст(строка.theme) || текст(строка.question),
        текст: собратьТекст(строка, [
          ['question', 'Вопрос'],
          ['answer', 'Ответ'],
          ['answers', 'Ответы'],
          ['questions', 'Вопросы'],
          ['emotion', 'Чувство'],
          ['trigger', 'Что запустило'],
          ['body', 'Тело'],
          ['thought', 'Мысль'],
          ['fear', 'Страх'],
          ['cause', 'Причина'],
          ['pattern', 'Повторяющееся'],
          ['need', 'Потребность'],
          ['summary', 'Итог'],
          ['nextStep', 'Следующий шаг'],
          ['promise', 'Обещание себе'],
          ['note', ''],
        ]),
        настроение: числоИлиNull(строка.mood),
        сон: null,
        личное: true,
        legacy: остаток(строка, [...СЛУЖЕБНЫЕ, 'date', 'theme']),
      }) as ЗаписьДневника,
    )
  }

  const дневникПодсознания = массив(состояние, 'subconsciousDiary')
  всего += дневникПодсознания.length
  for (const строка of дневникПодсознания) {
    новые.push(
      новаяЗапись({
        дата: датаИлиNull(строка.date) ?? сейчас().slice(0, 10),
        вид: 'подсознание',
        заголовок: '',
        текст: собратьТекст(строка, [
          ['feeling', 'Что чувствую'],
          ['avoid', 'Чего избегаю'],
          ['truth', 'Правда'],
          ['step', 'Шаг'],
          ['extra', ''],
        ]),
        настроение: null,
        сон: null,
        личное: true,
        legacy: остаток(строка, [...СЛУЖЕБНЫЕ, 'date']),
      }) as ЗаписьДневника,
    )
  }

  const сон = массив(состояние, 'sleepEntries')
  всего += сон.length
  for (const строка of сон) {
    новые.push(
      новаяЗапись({
        дата: датаИлиNull(строка.date) ?? сейчас().slice(0, 10),
        вид: 'день',
        заголовок: 'Сон',
        текст: текст(строка.note),
        настроение: null,
        сон: числоИлиNull(строка.hours),
        личное: true,
        legacy: остаток(строка, [...СЛУЖЕБНЫЕ, 'date', 'hours', 'note']),
      }) as ЗаписьДневника,
    )
  }

  if (новые.length > 0) await база.journal.bulkPut(новые)
  const пропущено = всего - новые.length
  return {
    строка: {
      название: 'Дневник',
      перенесено: новые.length,
      из: всего,
      пояснение:
        пропущено > 0
          ? `${пропущено} без заголовка и текста — переносить нечего`
          : undefined,
    },
  }
}

/**
 * Сделки. В прежнем приложении раздела для них не было, но данные
 * накапливались — поэтому они переносятся, а не заводятся заново.
 */
export async function перенестиСделки(
  состояние: Запись,
): Promise<{ строка: СтрокаОтчёта }> {
  const старые = массив(состояние, 'trades')
  const счета = массив(состояние, 'tradingAccounts')
  const учебные = new Set(
    счета
      .filter((счёт) => текст(счёт.kind) !== 'real')
      .map((счёт) => текст(счёт.id)),
  )

  const новые = старые.map((строка) => {
    const режим = текст(строка.mode)
    const учебная = режим ? режим !== 'real' : учебные.has(текст(строка.accountId))
    const дата = датаИлиNull(строка.date) ?? сейчас().slice(0, 10)
    return новаяЗапись({
      счётТипа: учебная ? 'учебный' : 'реальный',
      инструмент: текст(строка.pair) || 'не указан',
      направление: текст(строка.direction) === 'sell' ? 'продажа' : 'покупка',
      открыта: `${дата}T00:00:00.000Z`,
      закрыта: null,
      входЦена: числоИлиNull(строка.entry),
      стопЦена: числоИлиNull(строка.stopLoss),
      цельЦена: числоИлиNull(строка.takeProfit),
      выходЦена: null,
      объём: числоИлиNull(строка.riskAmount),
      результат: деньгиИзСтарого(строка.resultAmount),
      планСоблюдён:
        строка.followedPlan === undefined ? null : Boolean(строка.followedPlan),
      причинаВхода: собратьТекст(строка, [
        ['setup', 'Схема входа'],
        ['emotion', 'Состояние'],
      ]),
      вывод: текст(строка.note),
      снимокЭкрана: текст(строка.beforeImage) || текст(строка.afterImage) || null,
      legacy: остаток(строка, [
        ...СЛУЖЕБНЫЕ,
        'mode',
        'date',
        'pair',
        'direction',
        'entry',
        'stopLoss',
        'takeProfit',
        'riskAmount',
        'resultAmount',
        'followedPlan',
        'setup',
        'emotion',
        'note',
        'beforeImage',
        'afterImage',
      ]),
    }) as Сделка
  })

  if (новые.length > 0) await база.trades.bulkPut(новые)
  return {
    строка: { название: 'Сделки', перенесено: новые.length, из: старые.length },
  }
}
