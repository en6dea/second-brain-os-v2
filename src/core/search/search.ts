import { база } from '@/core/db/db'
import { деньги } from '@/core/money/Money'
import { деньКратко } from '@/core/calendar/CalendarRu'

export interface НайденноеСовпадение {
  id: string
  раздел: string
  заголовок: string
  подпись: string
  путь: string
}

function содержит(текст: string | null | undefined, запрос: string): boolean {
  return (текст ?? '').toLowerCase().includes(запрос)
}

/**
 * Общий поиск по записям.
 * Ищет по тем разделам, где данные уже есть, и не притворяется,
 * что нашёл что-то в разделах, которых ещё нет.
 */
export async function искать(
  запросИсходный: string,
  предел = 24,
): Promise<НайденноеСовпадение[]> {
  const запрос = запросИсходный.trim().toLowerCase()
  if (запрос.length < 2) return []

  const результат: НайденноеСовпадение[] = []

  const [задачи, цели, привычки, знания, люди, дневник, операции, обязательства] =
    await Promise.all([
      база.tasks.toArray(),
      база.goals.toArray(),
      база.habits.toArray(),
      база.knowledge.toArray(),
      база.people.toArray(),
      база.journal.toArray(),
      база.operations.toArray(),
      база.obligations.toArray(),
    ])

  for (const запись of задачи) {
    if (содержит(запись.название, запрос) || содержит(запись.заметка, запрос)) {
      результат.push({
        id: запись.id,
        раздел: 'Задачи',
        заголовок: запись.название,
        подпись: запись.дата ? деньКратко(запись.дата) : 'без даты',
        путь: '/tasks',
      })
    }
  }

  for (const запись of цели) {
    if (содержит(запись.название, запрос) || содержит(запись.зачем, запрос)) {
      результат.push({
        id: запись.id,
        раздел: 'Цели',
        заголовок: запись.название,
        подпись: запись.состояние,
        путь: '/goals',
      })
    }
  }

  for (const запись of привычки) {
    if (содержит(запись.название, запрос)) {
      результат.push({
        id: запись.id,
        раздел: 'Привычки',
        заголовок: запись.название,
        подпись: `${запись.норма} ${запись.единица}`,
        путь: '/habits',
      })
    }
  }

  for (const запись of знания) {
    if (содержит(запись.заголовок, запрос) || содержит(запись.текст, запрос)) {
      результат.push({
        id: запись.id,
        раздел: 'Знания',
        заголовок: запись.заголовок,
        подпись: запись.вид,
        путь: '/knowledge',
      })
    }
  }

  for (const запись of люди) {
    if (содержит(запись.имя, запрос) || содержит(запись.заметка, запрос)) {
      результат.push({
        id: запись.id,
        раздел: 'Люди',
        заголовок: запись.имя,
        подпись: запись.отношения || 'человек',
        путь: '/people',
      })
    }
  }

  for (const запись of дневник) {
    if (содержит(запись.заголовок, запрос) || содержит(запись.текст, запрос)) {
      результат.push({
        id: запись.id,
        раздел: 'Дневник',
        заголовок: запись.заголовок || деньКратко(запись.дата),
        подпись: запись.вид,
        путь: '/journal',
      })
    }
  }

  for (const запись of операции) {
    if (содержит(запись.заметка, запрос)) {
      результат.push({
        id: запись.id,
        раздел: 'Операции',
        заголовок: запись.заметка,
        подпись: `${деньКратко(запись.дата)} · ${деньги(запись.сумма)}`,
        путь: '/finance/operations',
      })
    }
  }

  for (const запись of обязательства) {
    if (содержит(запись.название, запрос) || содержит(запись.контрагент, запрос)) {
      результат.push({
        id: запись.id,
        раздел: 'Обязательства',
        заголовок: запись.название,
        подпись: запись.направление,
        путь: '/obligations',
      })
    }
  }

  return результат.slice(0, предел)
}
