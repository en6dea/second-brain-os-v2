describe('длинаСерии', () => {
  it('считает дни подряд, включая сегодня', () => {
    const отметки = {
      [день]: 1,
      [сдвинутьДень(день, -1)]: 1,
      [сдвинутьДень(день, -2)]: 1,
    }
    expect(длинаСерии(привычка(отметки), день)).toBe(3)
  })

  it('без отметки сегодня считает по вчерашний день', () => {
    const отметки = {
      [сдвинутьДень(день, -1)]: 1,
      [сдвинутьДень(день, -2)]: 1,
    }
    expect(длинаСерии(привычка(отметки), день)).toBe(2)
  })

  it('пропуск обрывает серию', () => {
    const отметки = {
      [день]: 1,
      [сдвинутьДень(день, -2)]: 1,
    }
    expect(длинаСерии(привычка(отметки), день)).toBe(1)
  })

  it('без отметок серия равна нулю', () => {
    expect(длинаСерии(привычка({}), день)).toBe(0)
  })
})

describe('собратьСигналы', () => {
  it('на пустых данных не выдумывает сигналов', () => {
    expect(собратьСигналы(пусто)).toHaveLength(0)
  })

  it('просроченная задача даёт критичный сигнал', () => {
    const сигналы = собратьСигналы({
      ...пусто,
      задачи: [задача({ дата: сдвинутьДень(день, -3) })],
    })
    const найден = сигналы.find((с) => с.id === 'задачи-просрочены')
    expect(найден?.уровень).toBe('критично')
  })

  it('выполненная задача просроченной не считается', () => {
    const сигналы = собратьСигналы({
      ...пусто,
      задачи: [задача({ дата: сдвинутьДень(день, -3), состояние: 'сделана' })],
    })
    expect(сигналы.find((с) => с.id === 'задачи-просрочены')).toBeUndefined()
  })

  it('задача с тремя переносами попадает в сигналы', () => {
    const сигналы = собратьСигналы({
      ...пусто,
      задачи: [задача({ переносов: 4, дата: день })],
    })
    expect(сигналы.some((с) => с.id.startsWith('задача-переносится'))).toBe(true)
  })

  it('просроченный платёж критичнее ближайшего', () => {
    const сигналы = собратьСигналы({
      ...пусто,
      обязательства: [
        обязательство({
          id: '1',
          датаСледующегоПлатежа: сдвинутьДень(день, -2),
        }),
      ],
    })
    expect(сигналы[0]?.уровень).toBe('критично')
  })

  it('закрытое обязательство сигналов не даёт', () => {
    const сигналы = собратьСигналы({
      ...пусто,
      обязательства: [
        обязательство({ закрыто: true, датаСледующегоПлатежа: день }),
      ],
    })
    expect(сигналы).toHaveLength(0)
  })

  it('цель без движения замечается через две недели', () => {
    const давно = new Date(Date.now() - 20 * 86_400_000).toISOString()
    const сигналы = собратьСигналы({
      ...пусто,
      цели: [цель({ последняяАктивность: давно })],
    })
    expect(сигналы.some((с) => с.id.startsWith('цель-без-движения'))).toBe(true)
  })

  it('проект без задач замечается, а проект с задачами — нет', () => {
    const проект = {
      id: 'пр',
      createdAt: момент,
      updatedAt: момент,
      название: 'Проект',
      описание: '',
      целиId: [],
      сфераId: null,
      состояние: 'активен' as const,
      срок: null,
    }
    const пустойПроект = собратьСигналы({ ...пусто, проекты: [проект] })
    expect(пустойПроект.some((с) => с.id.startsWith('проект-без-задач'))).toBe(true)

    const сЗадачей = собратьСигналы({
      ...пусто,
      проекты: [проект],
      задачи: [задача({ проектId: 'пр' })],
    })
    expect(сЗадачей.some((с) => с.id.startsWith('проект-без-задач'))).toBe(false)
  })

  it('сигналы упорядочены по важности', () => {
    const сигналы = собратьСигналы({
      ...пусто,
      входящих: 3,
      задачи: [задача({ дата: сдвинутьДень(день, -1) })],
    })
    expect(сигналы[0]?.уровень).toBe('критично')
    expect(сигналы.at(-1)?.уровень).toBe('наблюдение')
  })

  it('у каждого сигнала есть объяснение и раздел', () => {
    const сигналы = собратьСигналы({
      ...пусто,
      входящих: 2,
      задачи: [задача({ дата: сдвинутьДень(день, -1) })],
    })
    for (const сигнал of сигналы) {
      expect(сигнал.объяснение.length).toBeGreaterThan(10)
      expect(сигнал.раздел.length).toBeGreaterThan(0)
    }
  })
})
