import { describe, expect, it } from 'vitest'
import { длинаСерии, собратьСигналы, type ДанныеДляСигналов } from './engine'
import { сегодня, сдвинутьДень } from '@/core/calendar/CalendarRu'
import type { Задача, Обязательство, Привычка, Цель } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'
const день = сегодня()

const пусто: ДанныеДляСигналов = {
  задачи: [],
  привычки: [],
  цели: [],
  счета: [],
  операции: [],
  обязательства: [],
  входящих: 0,
}

