import type { Привычка } from '@/core/db/types'

/** Текущая серия привычки: сколько дней подряд есть отметка. */
export function длинаСерии(привычка: Привычка, отДня: string): number {
  let серия = 0
  const дата = new Date(`${отДня}T12:00:00`)
  // Если сегодня отметки нет — серия считается по вчерашний день.
  const отмечен = (ключ: string) => (привычка.отметки[ключ] ?? 0) > 0
  if (!отмечен(отДня)) дата.setDate(дата.getDate() - 1)

  for (let шаг = 0; шаг < 400; шаг += 1) {
    const ключ = дата.toISOString().slice(0, 10)
    if (отмечен(ключ)) {
      серия += 1
      дата.setDate(дата.getDate() - 1)
    } else break
  }
  return серия
}

/**
 * Самая длинная серия подряд отмеченных дней в окне из `дней` дней назад.
 *
 * В отличие от `длинаСерии` (только текущая, незакрытая серия), эта смотрит
 * в прошлое целиком — нужна, чтобы заметить: серия была хорошей и
 * оборвалась, а не только что серии нет вовсе.
 */
export function максимальнаяСерияЗа(
  привычка: Привычка,
  дней: number,
  отДня: string,
): number {
  const отмечен = (ключ: string) => (привычка.отметки[ключ] ?? 0) > 0
  const дата = new Date(`${отДня}T12:00:00`)
  let максимум = 0
  let текущая = 0

  for (let шаг = 0; шаг < дней; шаг += 1) {
    const ключ = дата.toISOString().slice(0, 10)
    if (отмечен(ключ)) {
      текущая += 1
      максимум = Math.max(максимум, текущая)
    } else {
      текущая = 0
    }
    дата.setDate(дата.getDate() - 1)
  }

  return максимум
}
