import type {
  Вызов,
  Задача,
  Обязательство,
  Операция,
  Опыт,
  План,
  Привычка,
  Проект,
  Сигнал,
  Счёт,
  Цель,
} from '@/core/db/types'
import { сегодня } from '@/core/calendar/CalendarRu'
import { сигналыЗадачИПроектов } from './rules/tasksAndProjects'
import { сигналыДенег } from './rules/money'
import { сигналыЖизни } from './rules/life'

export { длинаСерии } from './streak'

/**
 * Движок сигналов.
 *
 * Сигнал — это не уведомление «просто так». Каждый сигнал обязан:
 *  · опираться на конкретные записи;
 *  · объяснять, откуда взялось число;
 *  · вести туда, где с этим можно что-то сделать.
 *
 * Сама функция — тонкая: три модуля правил (`rules/`) по своим областям,
 * здесь только сбор и сортировка. Разбито из одного файла на 290 строк —
 * правило проекта в 200 строк на файл иначе было бы нарушено с первым же
 * новым правилом.
 */
export interface ДанныеДляСигналов {
  задачи: Задача[]
  привычки: Привычка[]
  цели: Цель[]
  счета: Счёт[]
  операции: Операция[]
  обязательства: Обязательство[]
  входящих: number
  проекты?: Проект[]
  опыт?: Опыт[]
  вызовы?: Вызов[]
  планы?: План[]
}

export function собратьСигналы(данные: ДанныеДляСигналов): Сигнал[] {
  const день = сегодня()

  const сигналы = [
    ...сигналыЗадачИПроектов(данные, день),
    ...сигналыДенег(данные),
    ...сигналыЖизни(данные, день),
  ]

  const вес: Record<Сигнал['уровень'], number> = {
    критично: 0,
    внимание: 1,
    наблюдение: 2,
    хорошо: 3,
  }
  return сигналы.sort((а, б) => вес[а.уровень] - вес[б.уровень])
}
