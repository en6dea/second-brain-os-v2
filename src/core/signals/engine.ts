import type {
  Вызов,
  Задача,
  Обязательство,
  Операция,
  Опыт,
  План,
  Привычка,
  Проект,
  Сигнал,
  Счёт,
  Цель,
} from '@/core/db/types'
import { днейДо, сегодня } from '@/core/calendar/CalendarRu'
import { склонение } from '@/core/language/Plural'
import { деньги } from '@/core/money/Money'

/**
 * Движок сигналов.
 *
 * Сигнал — это не уведомление «просто так». Каждый сигнал обязан:
 *  · опираться на конкретные записи;
 *  · объяснять, откуда взялось число;
 *  · вести туда, где с этим можно что-то сделать.
 *
 * Функция чистая: на вход — данные, на выход — список. Ничего не выдумывает.
 */
export interface ДанныеДляСигналов {
  задачи: Задача[]
  привычки: Привычка[]
  цели: Цель[]
  счета: Счёт[]
  операции: Операция[]
  обязательства: Обязательство[]
  входящих: number
  проекты?: Проект[]
  опыт?: Опыт[]
  вызовы?: Вызов[]
  планы?: План[]
}

const ДНЕЙ_БЕЗ_АКТИВНОСТИ_ЦЕЛИ = 14
const ПЕРЕНОСОВ_ДЛЯ_СИГНАЛА = 3
const ДНЕЙ_ДО_ПЛАТЕЖА = 5

export function собратьСигналы(данные: ДанныеДляСигналов): Сигнал[] {
  const сигналы: Сигнал[] = []
  const день = сегодня()

  /* --- Просроченные задачи --- */
  const просрочено = данные.задачи.filter(
    (задача) =>
      задача.дата !== null &&
      задача.дата < день &&
      задача.состояние !== 'сделана' &&
      задача.состояние !== 'отменена',
  )
  if (просрочено.length > 0) {
    сигналы.push({
      id: 'задачи-просрочены',
      уровень: 'критично',
      текст: `${просрочено.length} ${склонение(просрочено.length, 'задача просрочена', 'задачи просрочены', 'задач просрочено')}`,
      объяснение: `Срок этих задач раньше сегодняшнего дня, а состояние не «сделана».`,
      раздел: 'Задачи',
      ссылка: '/tasks',
    })
  }

  /* --- Задача, которую переносят --- */
  const залипшая = данные.задачи
    .filter(
      (задача) =>
        задача.переносов >= ПЕРЕНОСОВ_ДЛЯ_СИГНАЛА && задача.состояние !== 'сделана',
    )
    .sort((а, б) => б.переносов - а.переносов)[0]
  if (залипшая) {
    сигналы.push({
      id: `задача-переносится-${залипшая.id}`,
      уровень: 'внимание',
      текст: `«${залипшая.название}» переносили ${залипшая.переносов} ${склонение(залипшая.переносов, 'раз', 'раза', 'раз')}`,
      объяснение:
        'Задача, которую переносят снова и снова, обычно сформулирована слишком крупно либо на самом деле не нужна.',
      раздел: 'Задачи',
      ссылка: '/tasks',
    })
  }

  /* --- Ближайшие платежи --- */
  for (const обязательство of данные.обязательства) {
    if (обязательство.закрыто) continue
    const дней = днейДо(обязательство.датаСледующегоПлатежа)
    if (дней === null) continue
    if (дней < 0) {
      сигналы.push({
        id: `платёж-просрочен-${обязательство.id}`,
        уровень: 'критично',
        текст: `Платёж «${обязательство.название}» просрочен на ${Math.abs(дней)} ${склонение(Math.abs(дней), 'день', 'дня', 'дней')}`,
        объяснение: `Дата платежа: ${обязательство.датаСледующегоПлатежа}. Сумма: ${деньги(обязательство.минимальныйПлатёж)}.`,
        раздел: 'Обязательства',
        ссылка: '/obligations',
      })
    } else if (дней <= ДНЕЙ_ДО_ПЛАТЕЖА) {
      сигналы.push({
        id: `платёж-скоро-${обязательство.id}`,
        уровень: 'внимание',
        текст:
          дней === 0
            ? `Сегодня платёж «${обязательство.название}»`
            : `Через ${дней} ${склонение(дней, 'день', 'дня', 'дней')} платёж «${обязательство.название}»`,
        объяснение: `Минимальный платёж: ${деньги(обязательство.минимальныйПлатёж)}.`,
        раздел: 'Обязательства',
        ссылка: '/obligations',
      })
    }
  }

  /* --- Цель без движения --- */
  for (const цель of данные.цели) {
    if (цель.состояние !== 'активна') continue
    const последняя = цель.последняяАктивность ?? цель.updatedAt
    const дней = Math.floor(
      (Date.now() - new Date(последняя).getTime()) / 86_400_000,
    )
    if (дней >= ДНЕЙ_БЕЗ_АКТИВНОСТИ_ЦЕЛИ) {
      сигналы.push({
        id: `цель-без-движения-${цель.id}`,
        уровень: 'внимание',
        текст: `Цель «${цель.название}» не двигалась ${дней} ${склонение(дней, 'день', 'дня', 'дней')}`,
        объяснение:
          'Дата последнего изменения цели или связанной с ней записи старше двух недель.',
        раздел: 'Цели',
        ссылка: '/goals',
      })
    }
  }

  /* --- Неразобранные операции --- */
  const неразобрано = данные.операции.filter((операция) => !операция.разобрана)
  if (неразобрано.length > 0) {
    сигналы.push({
      id: 'операции-без-категории',
      уровень: 'внимание',
      текст: `${неразобрано.length} ${склонение(неразобрано.length, 'операция ждёт', 'операции ждут', 'операций ждут')} категории`,
      объяснение:
        'Пока у операции нет категории, отчёт по расходам и бюджет неполны.',
      раздел: 'Финансы',
      ссылка: '/finance/operations',
    })
  }

  /* --- Счета без подтверждённого остатка --- */
  const безОстатка = данные.счета.filter(
    (счёт) => !счёт.архив && счёт.фактическийОстаток === null,
  )
  if (безОстатка.length > 0) {
    сигналы.push({
      id: 'счета-без-остатка',
      уровень: 'наблюдение',
      текст: `${безОстатка.length} ${склонение(безОстатка.length, 'счёт', 'счёта', 'счетов')} без остатка`,
      объяснение:
        'Незаполненный остаток не считается нулём: эти счета не входят в сумму доступных денег.',
      раздел: 'Финансы',
      ссылка: '/finance/accounts',
    })
  }

  /* --- Входящие --- */
  if (данные.входящих > 0) {
    сигналы.push({
      id: 'входящие',
      уровень: 'наблюдение',
      текст: `${данные.входящих} ${склонение(данные.входящих, 'запись ждёт', 'записи ждут', 'записей ждут')} разбора`,
      объяснение:
        'Быстрые записи ещё не превращены в задачи, заметки или операции.',
      раздел: 'Разбор',
      ссылка: '/inbox',
    })
  }

  /* --- Проект без задач --- */
  const пустойПроект = (данные.проекты ?? []).find(
    (проект) =>
      проект.состояние === 'активен' &&
      !данные.задачи.some((задача) => задача.проектId === проект.id),
  )
  if (пустойПроект) {
    сигналы.push({
      id: `проект-без-задач-${пустойПроект.id}`,
      уровень: 'внимание',
      текст: `У проекта «${пустойПроект.название}» нет ни одной задачи`,
      объяснение:
        'Проект без задач не двигается: в нём нечего сделать. Либо разбейте его на шаги, либо закройте.',
      раздел: 'Проекты',
      ссылка: '/projects',
    })
  }

  /* --- Опыт месяца не выбран --- */
  const месяц = день.slice(0, 7)
  const числоМесяца = Number(день.slice(8))
  const опытВыбран = (данные.опыт ?? []).some((опыт) => опыт.месяц === месяц)
  if (данные.опыт !== undefined && !опытВыбран && числоМесяца >= 5) {
    сигналы.push({
      id: 'опыт-не-выбран',
      уровень: 'наблюдение',
      текст: 'Новый опыт на этот месяц не выбран',
      объяснение: `Прошло ${числоМесяца} ${склонение(числоМесяца, 'день', 'дня', 'дней')} месяца. Чем позже выбор, тем меньше времени на сам опыт.`,
      раздел: 'Опыт и вызовы',
      ссылка: '/experience',
    })
  }

  /* --- Вызов месяца отстаёт --- */
  for (const вызов of данные.вызовы ?? []) {
    if (вызов.месяц !== месяц || вызов.завершён) continue
    const отмечено = Object.keys(вызов.отметки).filter(
      (дата) => дата.startsWith(месяц) && (вызов.отметки[дата] ?? 0) > 0,
    ).length
    if (числоМесяца >= 7 && отмечено < числоМесяца / 2) {
      сигналы.push({
        id: `вызов-отстаёт-${вызов.id}`,
        уровень: 'внимание',
        текст: `Вызов «${вызов.название}» отстаёт: ${отмечено} из ${числоМесяца} дней`,
        объяснение:
          'Отмечено меньше половины прошедших дней. Либо вызов слишком тяжёлый, либо он не тот, который нужен.',
        раздел: 'Опыт и вызовы',
        ссылка: '/experience',
      })
    }
  }

  /* --- План месяца не составлен --- */
  const планМесяца = (данные.планы ?? []).some(
    (план) => план.тип === 'месяц' && план.период === месяц,
  )
  if (данные.планы !== undefined && !планМесяца && числоМесяца <= 10) {
    сигналы.push({
      id: 'план-месяца-нет',
      уровень: 'наблюдение',
      текст: 'План на месяц не составлен',
      объяснение:
        'Начало месяца — единственное время, когда план ещё может на что-то повлиять.',
      раздел: 'Планирование',
      ссылка: '/planning',
    })
  }

  /* --- Хорошее: длинная серия привычки --- */
  for (const привычка of данные.привычки) {
    if (!привычка.активна) continue
    const серия = длинаСерии(привычка, день)
    if (серия >= 7) {
      сигналы.push({
        id: `серия-${привычка.id}`,
        уровень: 'хорошо',
        текст: `«${привычка.название}» — ${серия} ${склонение(серия, 'день', 'дня', 'дней')} подряд`,
        объяснение:
          'Считается по отметкам без пропусков, включая сегодняшний день.',
        раздел: 'Привычки',
        ссылка: '/habits',
      })
    }
  }

  const вес: Record<Сигнал['уровень'], number> = {
    критично: 0,
    внимание: 1,
    наблюдение: 2,
    хорошо: 3,
  }
  return сигналы.sort((а, б) => вес[а.уровень] - вес[б.уровень])
}

/** Текущая серия привычки: сколько дней подряд есть отметка. */
export function длинаСерии(привычка: Привычка, отДня: string): number {
  let серия = 0
  const дата = new Date(`${отДня}T12:00:00`)
  // Если сегодня отметки нет — серия считается по вчерашний день.
  const отмечен = (ключ: string) => (привычка.отметки[ключ] ?? 0) > 0
  if (!отмечен(отДня)) дата.setDate(дата.getDate() - 1)

  for (let шаг = 0; шаг < 400; шаг += 1) {
    const ключ = дата.toISOString().slice(0, 10)
    if (отмечен(ключ)) {
      серия += 1
      дата.setDate(дата.getDate() - 1)
    } else break
  }
  return серия
}
