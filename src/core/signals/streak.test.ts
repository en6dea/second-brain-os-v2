import { describe, expect, it } from 'vitest'
import { максимальнаяСерияЗа } from './streak'
import { сдвинутьДень } from '@/core/calendar/CalendarRu'
import type { Привычка } from '@/core/db/types'

const момент = '2026-08-01T10:00:00.000Z'
const день = '2026-08-17'

function привычка(отметки: Record<string, number>): Привычка {
  return {
    id: 'п',
    createdAt: момент,
    updatedAt: момент,
    название: 'Чтение',
    иконка: '',
    цвет: 'accent',
    частота: 'ежедневно',
    дниНедели: [],
    разВНеделю: null,
    норма: 1,
    единица: 'раз',
    цельId: null,
    сфераId: null,
    активна: true,
    постер: '',
    отметки,
  }
}

describe('максимальнаяСерияЗа', () => {
  it('без отметок — ноль', () => {
    expect(максимальнаяСерияЗа(привычка({}), 60, день)).toBe(0)
  })

  it('одна серия из пяти дней где-то в окне', () => {
    const отметки: Record<string, number> = {}
    for (let сдвиг = -10; сдвиг <= -6; сдвиг += 1) {
      отметки[сдвинутьДень(день, сдвиг)] = 1
    }
    expect(максимальнаяСерияЗа(привычка(отметки), 60, день)).toBe(5)
  })

  it('берёт большую из двух серий', () => {
    const отметки: Record<string, number> = {}
    // Серия из трёх дней.
    for (let сдвиг = -50; сдвиг <= -48; сдвиг += 1) {
      отметки[сдвинутьДень(день, сдвиг)] = 1
    }
    // Серия из семи дней, разорвана пропуском.
    for (let сдвиг = -20; сдвиг <= -14; сдвиг += 1) {
      отметки[сдвинутьДень(день, сдвиг)] = 1
    }
    expect(максимальнаяСерияЗа(привычка(отметки), 60, день)).toBe(7)
  })

  it('не считает отметки за пределами окна', () => {
    const отметки: Record<string, number> = {}
    for (let сдвиг = -90; сдвиг <= -84; сдвиг += 1) {
      отметки[сдвинутьДень(день, сдвиг)] = 1
    }
    expect(максимальнаяСерияЗа(привычка(отметки), 60, день)).toBe(0)
  })

  it('учитывает текущую незакрытую серию', () => {
    const отметки: Record<string, number> = {}
    for (let сдвиг = -6; сдвиг <= 0; сдвиг += 1) {
      отметки[сдвинутьДень(день, сдвиг)] = 1
    }
    expect(максимальнаяСерияЗа(привычка(отметки), 60, день)).toBe(7)
  })
})
