import type {
  Вызов,
  Опыт,
  План,
  Привычка,
  Сигнал,
  Цель,
  Человек,
} from '@/core/db/types'
import { днейДо, разностьДней } from '@/core/calendar/CalendarRu'
import { склонение } from '@/core/language/Plural'
import { длинаСерии, максимальнаяСерияЗа } from '@/core/signals/streak'

const ДНЕЙ_БЕЗ_АКТИВНОСТИ_ЦЕЛИ = 14
const СЕРИЯ_ДЛЯ_ХОРОШЕГО_СИГНАЛА = 7
const ДНЕЙ_ДЛЯ_ИСТОРИИ_СЕРИИ = 60
const ПОРОГ_ОТСТАВАНИЯ_ЦЕЛИ = 25

export function сигналыЖизни(
  данные: {
    цели: Цель[]
    привычки: Привычка[]
    опыт?: Опыт[]
    вызовы?: Вызов[]
    планы?: План[]
    люди?: Человек[]
  },
  день: string,
): Сигнал[] {
  const сигналы: Сигнал[] = []

  /* --- Цель без движения --- */
  for (const цель of данные.цели) {
    if (цель.состояние !== 'активна') continue
    const последняя = цель.последняяАктивность ?? цель.updatedAt
    const дней = Math.floor(
      (Date.now() - new Date(последняя).getTime()) / 86_400_000,
    )
    if (дней >= ДНЕЙ_БЕЗ_АКТИВНОСТИ_ЦЕЛИ) {
      сигналы.push({
        id: `цель-без-движения-${цель.id}`,
        уровень: 'внимание',
        текст: `Цель «${цель.название}» не двигалась ${дней} ${склонение(дней, 'день', 'дня', 'дней')}`,
        объяснение:
          'Дата последнего изменения цели или связанной с ней записи старше двух недель.',
        раздел: 'Цели',
        ссылка: '/goals',
      })
    }
  }

  /* --- Цель отстаёт от графика --- */
  for (const цель of данные.цели) {
    if (цель.состояние !== 'активна') continue
    if (цель.срок === null || цель.вехи.length === 0) continue

    const днейДоСрока = днейДо(цель.срок)
    if (днейДоСрока === null || днейДоСрока < 0) continue // просрочено — другой сигнал

    const всегоДней = разностьДней(цель.createdAt.slice(0, 10), цель.срок)
    if (всегоДней <= 0) continue

    const прошлоДней = всегоДней - днейДоСрока
    const долягоВремени = Math.max(
      0,
      Math.min(100, Math.round((прошлоДней / всегоДней) * 100)),
    )

    const выполненоВех = цель.вехи.filter((веха) => веха.выполнена).length
    const долягоВех = Math.round((выполненоВех / цель.вехи.length) * 100)

    if (долягоВремени - долягоВех < ПОРОГ_ОТСТАВАНИЯ_ЦЕЛИ) continue

    сигналы.push({
      id: `цель-отстаёт-${цель.id}`,
      уровень: 'внимание',
      текст: `Цель «${цель.название}» отстаёт от графика`,
      объяснение: `Пройдено ${долягоВремени}% срока (от даты создания цели до срока), сделано ${долягоВех}% вех (${выполненоВех} из ${цель.вехи.length}).`,
      раздел: 'Цели',
      ссылка: '/goals',
    })
  }

  /* --- Опыт месяца не выбран --- */
  const месяц = день.slice(0, 7)
  const числоМесяца = Number(день.slice(8))
  const опытВыбран = (данные.опыт ?? []).some((опыт) => опыт.месяц === месяц)
  if (данные.опыт !== undefined && !опытВыбран && числоМесяца >= 5) {
    сигналы.push({
      id: 'опыт-не-выбран',
      уровень: 'наблюдение',
      текст: 'Новый опыт на этот месяц не выбран',
      объяснение: `Прошло ${числоМесяца} ${склонение(числоМесяца, 'день', 'дня', 'дней')} месяца. Чем позже выбор, тем меньше времени на сам опыт.`,
      раздел: 'Опыт и вызовы',
      ссылка: '/experience',
    })
  }

  /* --- Вызов месяца отстаёт --- */
  for (const вызов of данные.вызовы ?? []) {
    if (вызов.месяц !== месяц || вызов.завершён) continue
    const отмечено = Object.keys(вызов.отметки).filter(
      (дата) => дата.startsWith(месяц) && (вызов.отметки[дата] ?? 0) > 0,
    ).length
    if (числоМесяца >= 7 && отмечено < числоМесяца / 2) {
      сигналы.push({
        id: `вызов-отстаёт-${вызов.id}`,
        уровень: 'внимание',
        текст: `Вызов «${вызов.название}» отстаёт: ${отмечено} из ${числоМесяца} дней`,
        объяснение:
          'Отмечено меньше половины прошедших дней. Либо вызов слишком тяжёлый, либо он не тот, который нужен.',
        раздел: 'Опыт и вызовы',
        ссылка: '/experience',
      })
    }
  }

  /* --- План месяца не составлен --- */
  const планМесяца = (данные.планы ?? []).some(
    (план) => план.тип === 'месяц' && план.период === месяц,
  )
  if (данные.планы !== undefined && !планМесяца && числоМесяца <= 10) {
    сигналы.push({
      id: 'план-месяца-нет',
      уровень: 'наблюдение',
      текст: 'План на месяц не составлен',
      объяснение:
        'Начало месяца — единственное время, когда план ещё может на что-то повлиять.',
      раздел: 'Планирование',
      ссылка: '/planning',
    })
  }

  /* --- Давно не было контакта --- */
  for (const человек of данные.люди ?? []) {
    if (человек.напоминатьЧерезДней === null || человек.последнийКонтакт === null) {
      continue
    }
    const прошло = -(днейДо(человек.последнийКонтакт) ?? 0)
    if (прошло >= человек.напоминатьЧерезДней) {
      сигналы.push({
        id: `человек-давно-${человек.id}`,
        уровень: 'внимание',
        текст: `Давно не общались: ${человек.имя}`,
        объяснение: `Порог для напоминания: ${человек.напоминатьЧерезДней} ${склонение(человек.напоминатьЧерезДней, 'день', 'дня', 'дней')}. Последний контакт: ${человек.последнийКонтакт}.`,
        раздел: 'Люди',
        ссылка: '/people',
      })
    }
  }

  /* --- Хорошее: длинная серия привычки --- */
  for (const привычка of данные.привычки) {
    if (!привычка.активна) continue
    const серия = длинаСерии(привычка, день)
    if (серия >= СЕРИЯ_ДЛЯ_ХОРОШЕГО_СИГНАЛА) {
      сигналы.push({
        id: `серия-${привычка.id}`,
        уровень: 'хорошо',
        текст: `«${привычка.название}» — ${серия} ${склонение(серия, 'день', 'дня', 'дней')} подряд`,
        объяснение:
          'Считается по отметкам без пропусков, включая сегодняшний день.',
        раздел: 'Привычки',
        ссылка: '/habits',
      })
    }
  }

  /* --- Серия оборвалась --- */
  for (const привычка of данные.привычки) {
    if (!привычка.активна) continue
    if (длинаСерии(привычка, день) > 0) continue

    const макс = максимальнаяСерияЗа(привычка, ДНЕЙ_ДЛЯ_ИСТОРИИ_СЕРИИ, день)
    if (макс < СЕРИЯ_ДЛЯ_ХОРОШЕГО_СИГНАЛА) continue

    const последняяДата = Object.keys(привычка.отметки)
      .filter((дата) => (привычка.отметки[дата] ?? 0) > 0)
      .sort()
      .at(-1)
    if (!последняяДата) continue

    const днейБезОтметки = -(днейДо(последняяДата) ?? 0)
    сигналы.push({
      id: `серия-оборвалась-${привычка.id}`,
      уровень: 'внимание',
      текст: `«${привычка.название}»: серия оборвалась`,
      объяснение: `Была серия из ${макс} ${склонение(макс, 'день', 'дня', 'дней')} подряд за последние ${ДНЕЙ_ДЛЯ_ИСТОРИИ_СЕРИИ} дней. Последняя отметка — ${днейБезОтметки} ${склонение(днейБезОтметки, 'день', 'дня', 'дней')} назад.`,
      раздел: 'Привычки',
      ссылка: '/habits',
    })
  }

  return сигналы
}
