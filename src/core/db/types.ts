/** Шифротекст AES-GCM: данные и вектор инициализации, оба base64. */
export interface Шифротекст {
  данные: string
  vector: string
}

export interface ЗаписьПароля extends БазоваяЗапись {
  /** Название сервиса — открытым текстом: нужно для списка без разблокировки. */
  название: string
  логин: Шифротекст | null
  пароль: Шифротекст | null
  заметка: Шифротекст | null
}

/**
 * Единственная запись хранилища паролей: соль и проверочный шифротекст.
 *
 * Соль — не секрет сама по себе, но должна быть одной и той же на всех
 * устройствах: иначе один и тот же мастер-пароль выведет на каждом
 * устройстве свой ключ, и расшифровать запись с другого устройства станет
 * невозможно. Поэтому запись — обычная синхронизируемая таблица, а не
 * `settings`, который остаётся на устройстве.
 */
export interface КонфигурацияПаролей extends БазоваяЗапись {
  соль: string
  /** Известный текст, зашифрованный выведенным ключом — проверка мастер-пароля. */
  проверка: Шифротекст
}
