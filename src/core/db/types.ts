export interface Настройки extends БазоваяЗапись {
  тема: 'light' | 'dark' | 'system'
  режимДемо: boolean
  минимальныйРезерв: Копейки
  /** Резерв уже лежит на счетах, исключённых из доступных денег. */
  резервУжеИсключён?: boolean
  /**
   * Горизонт, до которого человек хочет защитить деньги.
   *
   * Поле необязательное: настройки прежних версий продолжают читаться без
   * миграции. Ожидаемый доход показывается только как ориентир и никогда не
   * прибавляется к уже имеющимся деньгам.
   */
  денежныйГоризонт?: {
    датаСледующегоДохода: ДатаДень | null
    ожидаемыйДоход: Копейки | null
    /** Повторяющиеся дни месяца, например 10 и 25. */
    дниДохода?: number[]
    /** Что делать, когда день выплаты приходится на выходной. */
    переносВыходного?: 'раньше' | 'позже' | 'без переноса'
    /**
     * Отдельные выплаты цикла, например зарплата 10-го и аванс 25-го.
     * Старые дни и общая ожидаемая сумма остаются для обратной совместимости.
     */
    регулярныеДоходы?: РегулярныйДоход[]
  }
  скрыватьСуммы: boolean
  пинВключён: boolean
  /** Загружать ли обложки с чужих серверов. */
  показыватьПостеры: boolean
  /** Свои формулировки для разговора с собой. */
  своиУтверждения: string[]
  /** Показывать ли уведомления браузера. Выключено, пока человек не включит сам. */
  уведомленияВключены: boolean
  /**
   * Что уже показано сегодня. Хранится, чтобы обновление страницы не
   * повторило то же напоминание. Сбрасывается со сменой дня.
   */
  показанныеНапоминания: { день: string; ключи: string[] }
  /**
   * Подключение к синхронизации. Конфигурация Firebase — не секрет в
   * привычном смысле (её видно в исходном коде любого веб-приложения на
   * Firebase, защита — в правилах доступа на стороне Firebase), но хранится
   * только на устройстве человека, не в репозитории. Пароль не хранится
   * нигде в приложении — вход подтверждает сама Firebase.
   */
  синхронизация: {
    конфигурация: {
      apiKey: string
      authDomain: string
      projectId: string
      storageBucket?: string
      messagingSenderId?: string
      appId: string
    } | null
    /** Отметка последнего успешного прохода. `null` — синхронизации ещё не было. */
    отметка: string | null
  }
}

