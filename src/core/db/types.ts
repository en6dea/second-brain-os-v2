/**
 * Модель данных «Второй мозг 2.0».
 *
 * Правила, унаследованные от прежней версии и обязательные к соблюдению:
 *  1. Незаполненное ≠ ноль. `null` означает «неизвестно» и не участвует в суммах.
 *  2. Деньги хранятся в копейках целым числом — без ошибок дробной арифметики.
 *  3. Связи только по идентификаторам, объекты не копируются.
 *  4. Поле `legacy` хранит нераспознанные поля старого приложения дословно.
 */

/** Дата без времени в виде «ГГГГ-ММ-ДД». */
export type ДатаДень = string
/** Момент времени в формате ISO 8601. */
export type Момент = string
/** Денежная величина в копейках. `null` — «неизвестно». */
export type Копейки = number

export interface БазоваяЗапись {
  id: string
  createdAt: Момент
  updatedAt: Момент
  /** Нераспознанные поля из старого приложения. Никогда не удаляются. */
  legacy?: Record<string, unknown>
}

