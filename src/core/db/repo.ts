/** Чтение без записи — безопасно внутри живого запроса. */
export async function читатьПрофиль(): Promise<Профиль> {
  return (await база.profile.get(ID_ПРОФИЛЯ)) ?? ПРОФИЛЬ_ПО_УМОЛЧАНИЮ
}

/** Чтение без записи — безопасно внутри живого запроса. */
export async function читатьНастройки(): Promise<Настройки> {
  return (await база.settings.get(ID_НАСТРОЕК)) ?? НАСТРОЙКИ_ПО_УМОЛЧАНИЮ
}

export async function получитьПрофиль(): Promise<Профиль> {
  const найден = await база.profile.get(ID_ПРОФИЛЯ)
  if (найден) return найден
  const момент = сейчас()
  const профиль: Профиль = {
    id: ID_ПРОФИЛЯ,
    createdAt: момент,
    updatedAt: момент,
    имя: '',
    подпись: 'Панель управления жизнью',
    валюта: 'RUB',
    началоНедели: 1,
  }
  await база.profile.put(профиль)
  return профиль
}

export async function изменитьПрофиль(изменения: Partial<Профиль>) {
  const текущий = await получитьПрофиль()
  await база.profile.put({ ...текущий, ...изменения, updatedAt: сейчас() })
}

