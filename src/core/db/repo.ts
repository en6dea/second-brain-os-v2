type ПоляЗаписи = Record<string, unknown>

/**
 * Служебные поля заполняются в одном месте, а не в каждой форме.
 *
 * Время создания и изменения намеренно можно переопределить: при переносе из
 * прежней версии сохраняются исходные даты. А вот идентификатор — нет.
 * Форма легко передаёт пустой или отсутствующий `id`, собрав черновик из
 * заготовки; пустая строка и `undefined` ключом не являются, и запись тихо
 * не сохранялась вовсе. Поэтому пустой идентификатор всегда заменяется новым.
 */
export function новаяЗапись<T extends ПоляЗаписи>(данные: T): T & БазоваяЗапись {
  const момент = сейчас()
  const запись = { id: новыйId(), createdAt: момент, updatedAt: момент, ...данные }
  if (typeof запись.id !== 'string' || запись.id.trim() === '') {
    запись.id = новыйId()
  }
  return запись
}

