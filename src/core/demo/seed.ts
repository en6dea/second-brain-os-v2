import { база } from '@/core/db/db'
import { изменитьНастройки, новаяЗапись } from '@/core/db/repo'
import { сдвинутьДень, сегодня } from '@/core/calendar/CalendarRu'

/**
 * Показательные данные.
 *
 * Нужны только для разработки и знакомства с интерфейсом.
 * Включаются явно и помечают базу признаком `режимДемо`, чтобы их нельзя было
 * спутать с настоящими записями. Ни одна цифра здесь не попадает в отчёты
 * рабочего режима сама по себе.
 */
export async function засеятьПоказательныеДанные() {
  const день = сегодня()

  const карта = новаяЗапись({
    название: 'Показательная карта',
    тип: 'карта' as const,
    валюта: 'RUB' as const,
    фактическийОстаток: 8420000,
    подтверждён: new Date().toISOString(),
    кредитныйЛимит: null,
    учитыватьВДоступных: true,
    архив: false,
    порядок: 0,
  })

  const наличные = новаяЗапись({
    название: 'Показательные наличные',
    тип: 'наличные' as const,
    валюта: 'RUB' as const,
    фактическийОстаток: 1500000,
    подтверждён: new Date().toISOString(),
    кредитныйЛимит: null,
    учитыватьВДоступных: true,
    архив: false,
    порядок: 1,
  })

  await база.accounts.bulkPut([карта, наличные] as never)

  const категории = await база.moneyCategories.toArray()
  const продукты = категории.find((к) => к.название === 'Продукты')
  const зарплата = категории.find((к) => к.название === 'Зарплата')

  await база.operations.bulkPut([
    новаяЗапись({
      дата: сдвинутьДень(день, -3),
      тип: 'доход' as const,
      сумма: 14800000,
      счётId: карта.id,
      счётПолучательId: null,
      категорияId: зарплата?.id ?? null,
      классРасхода: null,
      заметка: 'Зарплата за месяц',
      планId: null,
      отпечатокИмпорта: null,
      разобрана: true,
    }),
    новаяЗапись({
      дата: сдвинутьДень(день, -1),
      тип: 'расход' as const,
      сумма: 425000,
      счётId: карта.id,
      счётПолучательId: null,
      категорияId: продукты?.id ?? null,
      классРасхода: 'обязательный' as const,
      заметка: 'Продукты на неделю',
      планId: null,
      отпечатокИмпорта: null,
      разобрана: true,
    }),
    новаяЗапись({
      дата: день,
      тип: 'перевод' as const,
      сумма: 1000000,
      счётId: карта.id,
      счётПолучательId: наличные.id,
      категорияId: null,
      классРасхода: null,
      заметка: 'Снятие наличных',
      планId: null,
      отпечатокИмпорта: null,
      разобрана: true,
    }),
  ] as never)

  const цель = новаяЗапись({
    название: 'Показательная цель: подушка безопасности',
    зачем: 'Чтобы решения принимались не из страха остаться без денег',
    сфераId: null,
    состояние: 'активна' as const,
    срок: сдвинутьДень(день, 180),
    цель: 300000,
    текущее: 84200,
    единица: '₽',
    порядок: 0,
    вехи: [],
    постер: '',
    последняяАктивность: new Date().toISOString(),
  })
  await база.goals.put(цель as never)

  await база.tasks.bulkPut([
    новаяЗапись({
      название: 'Показательная задача: свериться с банком',
      заметка: '',
      дата: день,
      время: null,
      длительностьМинут: null,
      состояние: 'новая' as const,
      важность: 'обычная' as const,
      проектId: null,
      цельId: цель.id,
      сфераId: null,
      выполненаВ: null,
      переносов: 0,
      повтор: null,
    }),
    новаяЗапись({
      название: 'Показательная задача: она уже просрочена',
      заметка: '',
      дата: сдвинутьДень(день, -4),
      время: null,
      длительностьМинут: null,
      состояние: 'новая' as const,
      важность: 'высокая' as const,
      проектId: null,
      цельId: null,
      сфераId: null,
      выполненаВ: null,
      переносов: 3,
      повтор: null,
    }),
  ] as never)

  const отметки: Record<string, number> = {}
  for (let шаг = 0; шаг < 9; шаг += 1) отметки[сдвинутьДень(день, -шаг)] = 1

  await база.habits.put(
    новаяЗапись({
      название: 'Показательная привычка: чтение',
      иконка: '',
      цвет: 'accent',
      частота: 'ежедневно' as const,
      дниНедели: [],
      разВНеделю: null,
      норма: 20,
      единица: 'страниц',
      цельId: null,
      сфераId: null,
      активна: true,
      постер: '',
      отметки,
    }) as never,
  )

  await база.obligations.put(
    новаяЗапись({
      название: 'Показательное обязательство',
      направление: 'я должен' as const,
      вид: 'кредит' as const,
      телоОстаток: 12000000,
      начисленныеПроценты: 340000,
      штрафы: 0,
      ставкаГодовых: 18,
      минимальныйПлатёж: 950000,
      датаСледующегоПлатежа: сдвинутьДень(день, 3),
      датаОкончания: null,
      контрагент: 'Показательный банк',
      закрыто: false,
      заметка: '',
    }) as never,
  )

  await изменитьНастройки({ режимДемо: true })
}
