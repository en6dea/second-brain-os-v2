import { describe, expect, it } from 'vitest'
import { можноСинхронизировать } from './privacy'

describe('можноСинхронизировать', () => {
  it('дни партнёра не синхронизируются целиком, что бы в записи ни было', () => {
    expect(можноСинхронизировать('partnerDays', {})).toBe(false)
    expect(можноСинхронизировать('partnerDays', { настроение: 'плохо' })).toBe(false)
  })

  it('настройки устройства не синхронизируются', () => {
    expect(можноСинхронизировать('settings', {})).toBe(false)
  })

  it('личная запись дневника не синхронизируется', () => {
    expect(можноСинхронизировать('journal', { личное: true })).toBe(false)
  })

  it('обычная запись дневника синхронизируется', () => {
    expect(можноСинхронизировать('journal', { личное: false })).toBe(true)
    expect(можноСинхронизировать('journal', {})).toBe(true)
  })

  it('обычные таблицы синхронизируются', () => {
    expect(можноСинхронизировать('tasks', { название: 'Позвонить' })).toBe(true)
    expect(можноСинхронизировать('goals', {})).toBe(true)
    expect(можноСинхронизировать('operations', { сумма: 1000 })).toBe(true)
  })
})
