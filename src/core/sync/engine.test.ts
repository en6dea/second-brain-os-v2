import { describe, expect, it, beforeEach } from 'vitest'
import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import { синхронизировать } from './engine'
import { установитьПоставщика, БезОблака } from './provider'
import type { ИзменениеЗаписи, ПоставщикСинхронизации } from './provider'

/** Поставщик в памяти: без сети и без Firebase, ведёт себя как настоящее облако. */
function поддельноеОблако(): ПоставщикСинхронизации & { запись: ИзменениеЗаписи[] } {
  const хранилище: ИзменениеЗаписи[] = []
  return {
    название: 'Тестовое облако',
    запись: хранилище,
    async состояние() {
      return { подключено: true, последняя: null, ожидаетОтправки: 0, ошибка: null }
    },
    async отправитьИзменения(изменения) {
      for (const запись of изменения) {
        const индекс = хранилище.findIndex(
          (з) => з.таблица === запись.таблица && з.id === запись.id,
        )
        if (индекс >= 0) хранилище[индекс] = запись
        else хранилище.push(запись)
      }
    },
    async получитьИзменения(послеМомента) {
      const отметка = послеМомента ?? '0000-01-01T00:00:00.000Z'
      return хранилище.filter((з) => з.изменена > отметка)
    },
    async разрешитьКонфликт() {
      /* не используется движком */
    },
  }
}

async function очиститьВсеТаблицы() {
  await база.tasks.clear()
  await база.goals.clear()
  await база.journal.clear()
  await база.partnerDays.clear()
  await база.syncTombstones.clear()
}

beforeEach(async () => {
  await очиститьВсеТаблицы()
  установитьПоставщика(БезОблака)
})

describe('синхронизировать', () => {
  it('без поставщика и без записей ничего не делает и не падает', async () => {
    const итог = await синхронизировать(null)
    expect(итог.ошибка).toBeNull()
    expect(итог.отправлено).toBe(0)
    expect(итог.получено).toBe(0)
  })

  it('локальная задача уходит в облако', async () => {
    const облако = поддельноеОблако()
    установитьПоставщика(облако)

    await база.tasks.add(
      новаяЗапись({
        название: 'Позвонить',
        заметка: '',
        дата: null,
        время: null,
        длительностьМинут: null,
        состояние: 'новая',
        важность: 'обычная',
        проектId: null,
        цельId: null,
        сфераId: null,
        выполненаВ: null,
        переносов: 0,
        повтор: null,
      }) as never,
    )

    const итог = await синхронизировать(null)
    expect(итог.отправлено).toBe(1)
    expect(облако.запись).toHaveLength(1)
    expect(облако.запись[0]?.таблица).toBe('tasks')
  })

  it('запись из облака применяется локально', async () => {
    const облако = поддельноеОблако()
    установитьПоставщика(облако)

    облако.запись.push({
      таблица: 'goals',
      id: 'из-облака',
      изменена: новоеВремя(),
      удалена: false,
      данные: {
        id: 'из-облака',
        createdAt: новоеВремя(),
        updatedAt: новоеВремя(),
        название: 'Цель из облака',
        зачем: '',
        сфераId: null,
        состояние: 'активна',
        срок: null,
        цель: null,
        текущее: null,
        единица: '',
        порядок: 0,
        вехи: [],
        последняяАктивность: null,
        постер: '',
      },
    })

    const итог = await синхронизировать(null)
    expect(итог.получено).toBe(1)
    const цель = await база.goals.get('из-облака')
    expect(цель?.название).toBe('Цель из облака')
  })

  it('дни партнёра синхронизируются как любая другая таблица', async () => {
    const облако = поддельноеОблако()
    установитьПоставщика(облако)

    await база.partnerDays.add(
      новаяЗапись({
        человекId: null,
        дата: '2026-08-17',
        состояние: 'хорошо',
        энергия: null,
        дискомфорт: null,
        стресс: null,
        настроение: '',
        сон: '',
        цикл: null,
        симптомы: [],
        чтоПомогло: '',
        чтоНеПомогло: '',
        какаяПоддержкаНужна: '',
        просьба: '',
        планы: '',
        заметка: '',
      }) as never,
    )

    await синхронизировать(null)
    expect(облако.запись).toHaveLength(1)
    expect(облако.запись[0]?.таблица).toBe('partnerDays')
  })

  it('личная и обычная записи дневника синхронизируются одинаково', async () => {
    const облако = поддельноеОблако()
    установитьПоставщика(облако)

    await база.journal.add(
      новаяЗапись({
        дата: '2026-08-17',
        вид: 'день',
        заголовок: '',
        текст: 'личное',
        настроение: null,
        сон: null,
        личное: true,
        утверждение: '',
        чтоЧувствую: '',
        чтоДумаю: '',
        согласие: null,
      }) as never,
    )
    await база.journal.add(
      новаяЗапись({
        дата: '2026-08-17',
        вид: 'день',
        заголовок: '',
        текст: 'обычное',
        настроение: null,
        сон: null,
        личное: false,
        утверждение: '',
        чтоЧувствую: '',
        чтоДумаю: '',
        согласие: null,
      }) as never,
    )

    await синхронизировать(null)
    expect(облако.запись).toHaveLength(2)
    const тексты = облако.запись
      .map((з) => (з.данные as { текст: string } | null)?.текст)
      .sort()
    expect(тексты).toEqual(['личное', 'обычное'])
  })

  it('удаление обычной таблицы доходит до облака как «удалена»', async () => {
    const облако = поддельноеОблако()
    установитьПоставщика(облако)

    const задача = новаяЗапись({
      название: 'Временная',
      заметка: '',
      дата: null,
      время: null,
      длительностьМинут: null,
      состояние: 'новая',
      важность: 'обычная',
      проектId: null,
      цельId: null,
      сфераId: null,
      выполненаВ: null,
      переносов: 0,
      повтор: null,
    })
    await база.tasks.add(задача as never)
    // Первый проход переносит создание в отметку — второй должен увидеть удаление.
    const первый = await синхронизировать(null)
    await база.tasks.delete(задача.id)
    await ждатьНадгробие(`tasks:${задача.id}`)

    const второй = await синхронизировать(первый.новаяОтметка)
    const надгробие = облако.запись.find((з) => з.id === задача.id)
    expect(надгробие?.удалена).toBe(true)
    expect(второй.отправлено).toBe(1)
  })

  it('удаление дневника доходит до облака как «удалена»', async () => {
    const облако = поддельноеОблако()
    установитьПоставщика(облако)

    const запись = новаяЗапись({
      дата: '2026-08-17',
      вид: 'день',
      заголовок: '',
      текст: 'было',
      настроение: null,
      сон: null,
      личное: false,
      утверждение: '',
      чтоЧувствую: '',
      чтоДумаю: '',
      согласие: null,
    })
    await база.journal.add(запись as never)
    const первый = await синхронизировать(null)
    await база.journal.delete(запись.id)
    await ждатьНадгробие(`journal:${запись.id}`)

    const второй = await синхронизировать(первый.новаяОтметка)
    const надгробие = облако.запись.find((з) => з.id === запись.id)
    expect(надгробие?.удалена).toBe(true)
    expect(второй.отправлено).toBe(1)
  })

  it('ошибка поставщика не прерывает работу и возвращается как текст', async () => {
    установитьПоставщика({
      название: 'Ломающееся облако',
      async состояние() {
        return { подключено: true, последняя: null, ожидаетОтправки: 0, ошибка: null }
      },
      async отправитьИзменения() {
        throw new Error('Сеть недоступна')
      },
      async получитьИзменения() {
        return []
      },
      async разрешитьКонфликт() {},
    })

    await база.tasks.add(
      новаяЗапись({
        название: 'Что-то',
        заметка: '',
        дата: null,
        время: null,
        длительностьМинут: null,
        состояние: 'новая',
        важность: 'обычная',
        проектId: null,
        цельId: null,
        сфераId: null,
        выполненаВ: null,
        переносов: 0,
        повтор: null,
      }) as never,
    )

    const итог = await синхронизировать(null)
    expect(итог.ошибка).toBe('Сеть недоступна')
  })
})

function новоеВремя(): string {
  return new Date().toISOString()
}

async function ждатьНадгробие(id: string, попыток = 30): Promise<void> {
  for (let номер = 0; номер < попыток; номер += 1) {
    if (await база.syncTombstones.get(id)) return
    await new Promise((resolve) => setTimeout(resolve, 10))
  }
}
