import type { ИзменениеЗаписи } from './provider'

/**
 * Слияние изменений при синхронизации.
 *
 * Правило простое и одно на все случаи: побеждает более поздняя правка —
 * "last write wins" по `изменена`. Для личного приложения на двух
 * устройствах одного человека это достаточно: настоящие одновременные правки
 * одной и той же записи с двух сторон случаются редко, а ручное разрешение
 * конфликта для такого случая — сложность, которая не окупается.
 *
 * Чистая функция без сети и без базы: обе стороны уже собраны заранее,
 * решение о том, что делать с каждой записью, проверяется тестом.
 */

export interface ИтогСлияния {
  /** Облачные записи новее — применить их поверх локальных. */
  применитьЛокально: ИзменениеЗаписи[]
  /** Локальные записи новее или существуют только здесь — отправить. */
  отправитьВОблако: ИзменениеЗаписи[]
}

function ключ(запись: ИзменениеЗаписи): string {
  return `${запись.таблица}:${запись.id}`
}

export function объединитьИзменения(
  локальные: ИзменениеЗаписи[],
  облачные: ИзменениеЗаписи[],
): ИтогСлияния {
  const облачныеПоКлючу = new Map(облачные.map((запись) => [ключ(запись), запись]))
  const локальныеПоКлючу = new Map(локальные.map((запись) => [ключ(запись), запись]))

  const применитьЛокально: ИзменениеЗаписи[] = []
  const отправитьВОблако: ИзменениеЗаписи[] = []

  const всеКлючи = new Set([...облачныеПоКлючу.keys(), ...локальныеПоКлючу.keys()])

  for (const текущийКлюч of всеКлючи) {
    const локальная = локальныеПоКлючу.get(текущийКлюч)
    const облачная = облачныеПоКлючу.get(текущийКлюч)

    if (локальная && !облачная) {
      отправитьВОблако.push(локальная)
      continue
    }
    if (облачная && !локальная) {
      применитьЛокально.push(облачная)
      continue
    }
    if (локальная && облачная) {
      // Равенство меток времени решается в пользу локальной: незачем
      // передавать по сети то, что там уже, вероятно, и так есть.
      if (облачная.изменена > локальная.изменена) применитьЛокально.push(облачная)
      else отправитьВОблако.push(локальная)
    }
  }

  return { применитьЛокально, отправитьВОблако }
}
