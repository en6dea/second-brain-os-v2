import { describe, expect, it } from 'vitest'
import { объединитьИзменения } from './merge'
import type { ИзменениеЗаписи } from './provider'

function изменение(поля: Partial<ИзменениеЗаписи> = {}): ИзменениеЗаписи {
  return {
    таблица: 'tasks',
    id: 'a',
    изменена: '2026-08-17T10:00:00.000Z',
    удалена: false,
    данные: { название: 'Задача' },
    ...поля,
  }
}

describe('объединитьИзменения', () => {
  it('без изменений с обеих сторон ничего не делает', () => {
    const итог = объединитьИзменения([], [])
    expect(итог.применитьЛокально).toHaveLength(0)
    expect(итог.отправитьВОблако).toHaveLength(0)
  })

  it('запись только локально — отправляется в облако', () => {
    const итог = объединитьИзменения([изменение()], [])
    expect(итог.отправитьВОблако).toEqual([изменение()])
    expect(итог.применитьЛокально).toHaveLength(0)
  })

  it('запись только в облаке — применяется локально', () => {
    const итог = объединитьИзменения([], [изменение()])
    expect(итог.применитьЛокально).toEqual([изменение()])
    expect(итог.отправитьВОблако).toHaveLength(0)
  })

  it('при конфликте побеждает более поздняя правка', () => {
    const старая = изменение({ изменена: '2026-08-17T10:00:00.000Z' })
    const новая = изменение({ изменена: '2026-08-17T12:00:00.000Z' })

    const облакоНовее = объединитьИзменения([старая], [новая])
    expect(облакоНовее.применитьЛокально).toEqual([новая])
    expect(облакоНовее.отправитьВОблако).toHaveLength(0)

    const локальноеНовее = объединитьИзменения([новая], [старая])
    expect(локальноеНовее.отправитьВОблако).toEqual([новая])
    expect(локальноеНовее.применитьЛокально).toHaveLength(0)
  })

  it('одинаковое время решается в пользу локальной, без лишней передачи', () => {
    const одна = изменение({ изменена: '2026-08-17T10:00:00.000Z' })
    const итог = объединитьИзменения([одна], [одна])
    expect(итог.отправитьВОблако).toEqual([одна])
    expect(итог.применитьЛокально).toHaveLength(0)
  })

  it('удаление — такая же запись, побеждает по тому же правилу', () => {
    const удалено = изменение({ удалена: true, изменена: '2026-08-17T12:00:00.000Z' })
    const созданоПозже = изменение({
      удалена: false,
      изменена: '2026-08-17T11:00:00.000Z',
    })
    const итог = объединитьИзменения([созданоПозже], [удалено])
    expect(итог.применитьЛокально).toEqual([удалено])
  })

  it('записи из разных таблиц с одинаковым id не путаются', () => {
    const задача = изменение({ таблица: 'tasks', id: 'x' })
    const цель = изменение({ таблица: 'goals', id: 'x' })
    const итог = объединитьИзменения([задача], [цель])
    expect(итог.отправитьВОблако).toEqual([задача])
    expect(итог.применитьЛокально).toEqual([цель])
  })

  it('несколько независимых записей распределяются каждая по себе', () => {
    const итог = объединитьИзменения(
      [изменение({ id: 'a' }), изменение({ id: 'b' })],
      [изменение({ id: 'c' })],
    )
    expect(итог.отправитьВОблако.map((з) => з.id).sort()).toEqual(['a', 'b'])
    expect(итог.применитьЛокально.map((з) => з.id)).toEqual(['c'])
  })
})
