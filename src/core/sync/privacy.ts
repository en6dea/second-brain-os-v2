import type { ИмяТаблицы } from '@/core/db/db'

/**
 * Что никогда не покидает устройство.
 *
 * Единственное исключение — настройки устройства: тема, показанные
 * уведомления, данные подключения к синхронизации. У каждого устройства свои,
 * отправлять их на другое означало бы затирать чужие настройки чужими же.
 * Это исключение про устройство, а не про приватность содержимого — всё
 * остальное синхронизируется целиком, без деления на «личное» и обычное.
 */

/** Таблицы, которые не участвуют в синхронизации вообще. */
const ИСКЛЮЧЕНЫ_ЦЕЛИКОМ = new Set<ИмяТаблицы>(['settings'])

/** Можно ли отправить записи этой таблицы в облако. */
export function можноСинхронизировать(таблица: ИмяТаблицы): boolean {
  return !ИСКЛЮЧЕНЫ_ЦЕЛИКОМ.has(таблица)
}
