import type { ИмяТаблицы } from '@/core/db/db'

/**
 * Что никогда не покидает устройство.
 *
 * Раздел «Отношения» обещает прямо в интерфейсе: записи о самочувствии
 * близкого человека не входят в облачную копию. Дневник даёт то же обещание
 * записям, отмеченным личными. Синхронизация — новый код, который может
 * случайно отправить лишнее; правило вынесено в одно место и закрыто
 * тестами, чтобы обещание нельзя было нарушить, просто забыв про него в
 * новом месте движка.
 *
 * Таблицы вне списка синхронизируются целиком за вычетом того, что отфильтровано
 * здесь.
 */

/** Таблицы, которые не участвуют в синхронизации вообще. */
const ИСКЛЮЧЕНЫ_ЦЕЛИКОМ = new Set<ИмяТаблицы>([
  // Самочувствие другого человека — самое чувствительное, что есть в
  // приложении. Договорено с человеком при создании раздела.
  'partnerDays',
  // Настройки устройства: тема, показанные уведомления, данные подключения
  // к синхронизации. У каждого устройства свои, отправлять их на другое
  // означало бы затирать чужие настройки чужими же.
  'settings',
])

/**
 * Можно ли отправить конкретную запись в облако.
 *
 * Таблица целиком решает вопрос почти всегда. Единственное исключение —
 * дневник: там личное отмечается на уровне записи полем «личное», а не всей
 * таблицей, потому что рядом лежат и обычные, не приватные записи.
 */
export function можноСинхронизировать(
  таблица: ИмяТаблицы,
  запись: Record<string, unknown>,
): boolean {
  if (ИСКЛЮЧЕНЫ_ЦЕЛИКОМ.has(таблица)) return false
  if (таблица === 'journal' && запись.личное === true) return false
  return true
}
