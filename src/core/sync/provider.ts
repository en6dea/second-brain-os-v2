import type { ИмяТаблицы } from '@/core/db/db'

/**
 * Договор синхронизации.
 *
 * Прикладная логика не знает, что стоит за облаком: Firebase, свой сервер
 * или ничего. Заменить хранилище позже — значит написать другую реализацию
 * этого интерфейса, не трогая разделы приложения.
 */

export interface ИзменениеЗаписи {
  таблица: ИмяТаблицы
  id: string
  изменена: string
  удалена: boolean
  данные: unknown
}

export interface Конфликт {
  таблица: ИмяТаблицы
  id: string
  локальная: ИзменениеЗаписи
  облачная: ИзменениеЗаписи
}

export type РешениеКонфликта = 'локальная' | 'облачная' | 'обе'

export interface СостояниеСинхронизации {
  подключено: boolean
  последняя: string | null
  ожидаетОтправки: number
  ошибка: string | null
}

export interface ПоставщикСинхронизации {
  название: string
  состояние(): Promise<СостояниеСинхронизации>
  отправитьИзменения(изменения: ИзменениеЗаписи[]): Promise<void>
  получитьИзменения(послеМомента: string | null): Promise<ИзменениеЗаписи[]>
  разрешитьКонфликт(конфликт: Конфликт, решение: РешениеКонфликта): Promise<void>
}

/**
 * Поставщик по умолчанию: облака нет.
 * Приложение полностью работает без сети и без сервера — это не заглушка,
 * а осознанный основной режим.
 */
export const БезОблака: ПоставщикСинхронизации = {
  название: 'Только это устройство',
  async состояние() {
    return {
      подключено: false,
      последняя: null,
      ожидаетОтправки: 0,
      ошибка: null,
    }
  },
  async отправитьИзменения() {
    /* нечего отправлять: данные живут только здесь */
  },
  async получитьИзменения() {
    return []
  },
  async разрешитьКонфликт() {
    /* конфликтов не бывает, пока источник один */
  },
}

let текущий: ПоставщикСинхронизации = БезОблака

export function установитьПоставщика(поставщик: ПоставщикСинхронизации) {
  текущий = поставщик
}

export function поставщикСинхронизации(): ПоставщикСинхронизации {
  return текущий
}
