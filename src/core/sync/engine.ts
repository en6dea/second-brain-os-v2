import { база, ТАБЛИЦЫ, type ИмяТаблицы } from '@/core/db/db'
import { сейчас } from '@/core/db/RecordId'
import { можноСинхронизировать } from './privacy'
import { объединитьИзменения } from './merge'
import { поставщикСинхронизации, type ИзменениеЗаписи } from './provider'

/**
 * Движок синхронизации.
 *
 * Собирает то, что изменилось на этом устройстве с прошлого раза, спрашивает
 * поставщика, что изменилось в облаке, решает через `merge.ts`, кто кого
 * перекрывает, и применяет результат. Сам движок ничего не знает про
 * Firebase — только про договор `ПоставщикСинхронизации`.
 */

/** Таблицы, чьё удаление не передаётся дальше вообще. */
const УДАЛЕНИЯ_НЕ_СИНХРОНИЗИРУЮТСЯ = new Set<ИмяТаблицы>([
  'partnerDays',
  'settings',
  // Запись дневника после удаления неоткуда узнать, была ли она личной —
  // это поле хранилось в самой записи, а её больше нет. Безопаснее не
  // передавать удаление вовсе, чем случайно раскрыть личную запись.
  'journal',
])

export interface ИтогСинхронизации {
  отправлено: number
  получено: number
  ошибка: string | null
}

async function локальныеИзменения(послеМомента: string | null): Promise<ИзменениеЗаписи[]> {
  const отметка = послеМомента ?? '0000-01-01T00:00:00.000Z'
  const итог: ИзменениеЗаписи[] = []

  for (const таблица of ТАБЛИЦЫ) {
    if (таблица === 'settings') continue
    const записи = await база.table(таблица).toArray()
    for (const запись of записи as { id: string; updatedAt?: string }[]) {
      if (!запись.updatedAt || запись.updatedAt <= отметка) continue
      if (!можноСинхронизировать(таблица, запись as Record<string, unknown>)) continue
      итог.push({
        таблица,
        id: запись.id,
        изменена: запись.updatedAt,
        удалена: false,
        данные: запись,
      })
    }
  }

  const надгробия = await база.syncTombstones
    .where('удаленоВ')
    .above(отметка)
    .toArray()
  for (const надгробие of надгробия) {
    const таблица = надгробие.таблица as ИмяТаблицы
    if (УДАЛЕНИЯ_НЕ_СИНХРОНИЗИРУЮТСЯ.has(таблица)) continue
    итог.push({
      таблица,
      id: надгробие.recordId,
      изменена: надгробие.удаленоВ,
      удалена: true,
      данные: null,
    })
  }

  return итог
}

async function применитьОблачныеИзменения(изменения: ИзменениеЗаписи[]): Promise<void> {
  for (const запись of изменения) {
    const таблица = запись.таблица
    if (запись.удалена) {
      await база.table(таблица).delete(запись.id)
      continue
    }
    if (запись.данные && typeof запись.данные === 'object') {
      await база.table(таблица).put(запись.данные as never)
    }
  }
}

/**
 * Отметка для следующего прохода.
 *
 * Самая поздняя метка среди того, что реально ушло или пришло в этот раз.
 * Если в этот раз обмениваться было нечем — оба устройства уже совпадают на
 * момент запуска, и отметку можно смело сдвинуть на «сейчас»: пересматривать
 * с нуля при следующем проходе незачем.
 */
function следующаяОтметка(
  прежняя: string | null,
  обработано: ИзменениеЗаписи[],
): string {
  if (обработано.length === 0) return сейчас()
  let лучшая = прежняя ?? '0000-01-01T00:00:00.000Z'
  for (const запись of обработано) {
    if (запись.изменена > лучшая) лучшая = запись.изменена
  }
  return лучшая
}

/**
 * Один проход синхронизации: собрать, спросить облако, слить, применить.
 *
 * Не читает и не пишет настройки сама — отметку последней синхронизации
 * передаёт и получает обратно вызывающий код, чтобы движок оставался чистой
 * оркестрацией без знания о том, где эта отметка хранится.
 */
export async function синхронизировать(
  отметкаДо: string | null,
): Promise<ИтогСинхронизации & { новаяОтметка: string }> {
  const поставщик = поставщикСинхронизации()

  try {
    const [локальные, облачные] = await Promise.all([
      локальныеИзменения(отметкаДо),
      поставщик.получитьИзменения(отметкаДо),
    ])

    const { применитьЛокально, отправитьВОблако } = объединитьИзменения(
      локальные,
      облачные,
    )

    await поставщик.отправитьИзменения(отправитьВОблако)
    await применитьОблачныеИзменения(применитьЛокально)

    return {
      отправлено: отправитьВОблако.length,
      получено: применитьЛокально.length,
      ошибка: null,
      новаяОтметка: следующаяОтметка(отметкаДо, [
        ...отправитьВОблако,
        ...применитьЛокально,
      ]),
    }
  } catch (ошибка) {
    return {
      отправлено: 0,
      получено: 0,
      ошибка: ошибка instanceof Error ? ошибка.message : 'Не удалось синхронизировать',
      новаяОтметка: отметкаДо ?? '0000-01-01T00:00:00.000Z',
    }
  }
}
