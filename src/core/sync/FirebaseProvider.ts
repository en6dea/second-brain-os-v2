import { initializeApp, type FirebaseApp } from 'firebase/app'
import {
  createUserWithEmailAndPassword,
  getAuth,
  onAuthStateChanged,
  signInWithEmailAndPassword,
  signOut,
  type Auth,
  type User,
} from 'firebase/auth'
import {
  getFirestore,
  collection,
  doc,
  getDocs,
  query,
  where,
  writeBatch,
  type Firestore,
} from 'firebase/firestore'
import type {
  ИзменениеЗаписи,
  ПоставщикСинхронизации,
  СостояниеСинхронизации,
} from './provider'

/**
 * Firebase как облако для синхронизации.
 *
 * Данные лежат в Firestore под `users/{uid}/records/{ключ}` — по документу
 * на запись, где `uid` берётся из Firebase Auth. Разделение по `uid` не
 * защита само по себе: настоящая защита — правила безопасности Firestore,
 * которые нужно выставить в консоли Firebase (текст правил — в настройках
 * приложения рядом с полем подключения). Без них любой авторизованный
 * пользователь Firebase технически мог бы прочитать чужие записи.
 *
 * Инициализация ленивая: приложение Firebase создаётся только когда человек
 * сам вписывает конфигурацию — до этого момента ни один байт никуда не
 * уходит, а этот файл вообще не выполняется в холостом (без облака) режиме.
 */

export interface КонфигFirebase {
  apiKey: string
  authDomain: string
  projectId: string
  storageBucket?: string
  messagingSenderId?: string
  appId: string
}

let приложение: FirebaseApp | null = null
let аутентификация: Auth | null = null
let хранилище: Firestore | null = null
let активнаяКонфигурация: string | null = null

/** Инициализация по конфигурации. Повторный вызов с той же — не пересоздаёт. */
function убедитьсяИнициализирован(конфигурация: КонфигFirebase): void {
  const ключ = JSON.stringify(конфигурация)
  if (приложение && активнаяКонфигурация === ключ) return
  приложение = initializeApp(конфигурация, 'второй-мозг')
  аутентификация = getAuth(приложение)
  хранилище = getFirestore(приложение)
  активнаяКонфигурация = ключ
}

export async function войти(
  конфигурация: КонфигFirebase,
  почта: string,
  пароль: string,
): Promise<void> {
  убедитьсяИнициализирован(конфигурация)
  await signInWithEmailAndPassword(аутентификация as Auth, почта, пароль)
}

/**
 * Учётная запись заводится один раз, на первом устройстве.
 *
 * Отдельная функция, а не автоматический переход от неудачного входа: у
 * современного Firebase включена защита от перебора почт, и ошибка «нет
 * такого пользователя» и «неверный пароль» на новых проектах приходят
 * одним и тем же кодом — по нему нельзя надёжно отличить «аккаунта ещё нет»
 * от «пароль неверный». Явные два действия снимают эту неоднозначность:
 * человек сам знает, заводит он аккаунт впервые или входит в уже созданный.
 */
export async function создатьАккаунт(
  конфигурация: КонфигFirebase,
  почта: string,
  пароль: string,
): Promise<void> {
  убедитьсяИнициализирован(конфигурация)
  await createUserWithEmailAndPassword(аутентификация as Auth, почта, пароль)
}

export async function выйти(): Promise<void> {
  if (!аутентификация) return
  await signOut(аутентификация)
}

export function текущийПользователь(): User | null {
  return аутентификация?.currentUser ?? null
}

/** Оповещение при смене входа: например, чтобы обновить статус в настройках. */
export function наСменуПользователя(колбэк: (пользователь: User | null) => void) {
  if (!аутентификация) return () => {}
  return onAuthStateChanged(аутентификация, колбэк)
}

/** Firestore допускает `_` и `-` в id документа, но не одиночную точку и слэш. */
function идДокумента(запись: ИзменениеЗаписи): string {
  return `${запись.таблица}_${запись.id}`
}

const РАЗМЕР_ПАКЕТА = 400

/**
 * Поставщик синхронизации на Firebase.
 *
 * Конфигурация передаётся при создании, а не хранится внутри: откуда она
 * взялась (настройки, введённые человеком) — забота вызывающего кода.
 */
export function создатьFirebaseПоставщика(
  конфигурация: КонфигFirebase,
): ПоставщикСинхронизации {
  убедитьсяИнициализирован(конфигурация)

  function коллекцияЗаписей() {
    const пользователь = текущийПользователь()
    if (!пользователь) throw new Error('Нет входа в Firebase — сначала войдите')
    return collection(хранилище as Firestore, 'users', пользователь.uid, 'records')
  }

  return {
    название: 'Firebase',

    async состояние(): Promise<СостояниеСинхронизации> {
      return {
        подключено: текущийПользователь() !== null,
        последняя: null,
        ожидаетОтправки: 0,
        ошибка: null,
      }
    },

    async отправитьИзменения(изменения: ИзменениеЗаписи[]): Promise<void> {
      if (изменения.length === 0) return
      const коллекция = коллекцияЗаписей()

      for (let начало = 0; начало < изменения.length; начало += РАЗМЕР_ПАКЕТА) {
        const пакет = writeBatch(хранилище as Firestore)
        for (const запись of изменения.slice(начало, начало + РАЗМЕР_ПАКЕТА)) {
          пакет.set(doc(коллекция, идДокумента(запись)), {
            таблица: запись.таблица,
            id: запись.id,
            изменена: запись.изменена,
            удалена: запись.удалена,
            данные: запись.данные ?? null,
          })
        }
        await пакет.commit()
      }
    },

    async получитьИзменения(послеМомента: string | null): Promise<ИзменениеЗаписи[]> {
      const коллекция = коллекцияЗаписей()
      const отметка = послеМомента ?? '0000-01-01T00:00:00.000Z'
      const запрос = query(коллекция, where('изменена', '>', отметка))
      const снимок = await getDocs(запрос)
      return снимок.docs.map((документ) => documentToChange(документ.data()))
    },

    async разрешитьКонфликт(конфликт, решение): Promise<void> {
      // Автоматическое слияние («кто позже правил») закрывает почти все
      // случаи — см. core/sync/merge.ts. Ручной выбор здесь на случай,
      // если поверх когда-нибудь появится интерфейс для него; сейчас
      // движок синхронизации им не пользуется.
      if (решение === 'локальная' || решение === 'обе') {
        await this.отправитьИзменения([конфликт.локальная])
      }
    },
  }
}

function documentToChange(данные: Record<string, unknown>): ИзменениеЗаписи {
  return {
    таблица: данные.таблица as ИзменениеЗаписи['таблица'],
    id: данные.id as string,
    изменена: данные.изменена as string,
    удалена: Boolean(данные.удалена),
    данные: данные.данные ?? null,
  }
}
