import { база, НАЗВАНИЯ_ТАБЛИЦ, ТАБЛИЦЫ, type ИмяТаблицы } from '@/core/db/db'
import { сейчас } from '@/core/db/RecordId'

export const ВЕРСИЯ_КОПИИ = 1

export interface Копия {
  приложение: 'второй-мозг'
  версияКопии: number
  версияПриложения: string
  создана: string
  таблицы: Partial<Record<ИмяТаблицы, unknown[]>>
}

/**
 * Полная выгрузка. Вложения (двоичные файлы) в копию не входят —
 * это честно указано в отчёте, а не умалчивается.
 */
export async function собратьКопию(
  выбранные: readonly ИмяТаблицы[] = ТАБЛИЦЫ,
): Promise<Копия> {
  const таблицы: Partial<Record<ИмяТаблицы, unknown[]>> = {}

  await база.transaction('r', база.tables, async () => {
    for (const имя of выбранные) {
      таблицы[имя] = await база.table(имя).toArray()
    }
  })

  return {
    приложение: 'второй-мозг',
    версияКопии: ВЕРСИЯ_КОПИИ,
    версияПриложения: __ВЕРСИЯ_ПРИЛОЖЕНИЯ__,
    создана: сейчас(),
    таблицы,
  }
}

export function именаТаблицКопии(копия: Копия): {
  имя: ИмяТаблицы
  название: string
  записей: number
}[] {
  return ТАБЛИЦЫ.filter((имя) => копия.таблицы[имя] !== undefined).map((имя) => ({
    имя,
    название: НАЗВАНИЯ_ТАБЛИЦ[имя],
    записей: копия.таблицы[имя]?.length ?? 0,
  }))
}

export function скачатьКопию(копия: Копия, имяФайла?: string) {
  const текст = JSON.stringify(копия, null, 2)
  const файл = new Blob([текст], { type: 'application/json' })
  const адрес = URL.createObjectURL(файл)
  const ссылка = document.createElement('a')
  ссылка.href = адрес
  ссылка.download =
    имяФайла ?? `второй-мозг-копия-${копия.создана.slice(0, 10)}.json`
  ссылка.click()
  setTimeout(() => URL.revokeObjectURL(адрес), 1000)
}

export interface ОтчётВосстановления {
  таблица: string
  добавлено: number
  обновлено: number
  пропущено: number
}

export function разобратьКопию(текст: string): Копия {
  const разобрано: unknown = JSON.parse(текст)
  if (
    typeof разобрано !== 'object' ||
    разобрано === null ||
    (разобрано as Копия).приложение !== 'второй-мозг'
  ) {
    throw new Error(
      'Это не копия «Второго мозга». Для переноса из прежней версии используйте раздел «Перенос данных».',
    )
  }
  return разобрано as Копия
}

/**
 * Восстановление. Режим «дополнить» идемпотентен: повторная загрузка того же
 * файла ничего не дублирует. Режим «заменить» очищает только те таблицы,
 * которые есть в файле.
 */
export async function восстановитьИзКопии(
  копия: Копия,
  режим: 'дополнить' | 'заменить',
): Promise<ОтчётВосстановления[]> {
  const отчёт: ОтчётВосстановления[] = []

  await база.transaction('rw', база.tables, async () => {
    for (const имя of ТАБЛИЦЫ) {
      const записи = копия.таблицы[имя]
      if (!Array.isArray(записи)) continue

      const таблица = база.table(имя)
      if (режим === 'заменить') await таблица.clear()

      let добавлено = 0
      let обновлено = 0
      let пропущено = 0

      for (const запись of записи as { id?: string }[]) {
        if (!запись || typeof запись.id !== 'string') {
          пропущено += 1
          continue
        }
        const существующая = await таблица.get(запись.id)
        await таблица.put(запись)
        if (существующая) обновлено += 1
        else добавлено += 1
      }

      отчёт.push({
        таблица: НАЗВАНИЯ_ТАБЛИЦ[имя],
        добавлено,
        обновлено,
        пропущено,
      })
    }
  })

  return отчёт
}

/**
 * Страховочная копия перед любой опасной операцией.
 * Сохраняется в файл, а не только в память: файл переживёт закрытие вкладки.
 */
export async function копияПередОпасным(повод: string) {
  const копия = await собратьКопию()
  скачатьКопию(
    копия,
    `второй-мозг-перед-${повод}-${копия.создана.slice(0, 10)}.json`,
  )
  return копия
}
