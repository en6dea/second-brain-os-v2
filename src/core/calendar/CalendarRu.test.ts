import { describe, expect, it } from 'vitest'
import { месяцКоротко, месяцСловами, разностьДней, сдвинутьМесяц } from './CalendarRu'

describe('подписи месяцев', () => {
  it('полное имя месяца идёт с годом', () => {
    expect(месяцСловами('2026-08')).toBe('август 2026')
  })

  it('короткое имя без года — для оси графика', () => {
    // Номер месяца на оси читается как число месяца: «03» выглядит третьим
    // августа. Поэтому подпись всегда словом.
    expect(месяцКоротко('2026-03')).not.toMatch(/^\d+$/)
    expect(месяцКоротко('2026-03').toLowerCase()).toContain('мар')
  })

  it('при смене года короткое имя получает год', () => {
    expect(месяцКоротко('2025-12', true)).toContain('25')
  })
})

describe('сдвинутьМесяц', () => {
  it('сдвигает на месяц вперёд', () => {
    expect(сдвинутьМесяц('2026-01-15', 1)).toBe('2026-02-15')
  })

  it('сдвигает на несколько месяцев назад', () => {
    expect(сдвинутьМесяц('2026-03-10', -2)).toBe('2026-01-10')
  })

  it('клэмпит конец месяца: 31 января + 1 месяц = 28 февраля', () => {
    expect(сдвинутьМесяц('2026-01-31', 1)).toBe('2026-02-28')
  })

  it('клэмпит на високосный год: 31 января 2028 + 1 месяц = 29 февраля', () => {
    expect(сдвинутьМесяц('2028-01-31', 1)).toBe('2028-02-29')
  })

  it('сдвиг на год через 12 месяцев', () => {
    expect(сдвинутьМесяц('2026-06-01', 12)).toBe('2027-06-01')
  })
})

describe('разностьДней', () => {
  it('положительная разница вперёд', () => {
    expect(разностьДней('2026-08-01', '2026-08-10')).toBe(9)
  })

  it('отрицательная разница назад', () => {
    expect(разностьДней('2026-08-10', '2026-08-01')).toBe(-9)
  })

  it('одна и та же дата — ноль', () => {
    expect(разностьДней('2026-08-01', '2026-08-01')).toBe(0)
  })
})
