/**
 * Согласование числительных с существительными в русском языке.
 * Отдельный модуль: это правило языка, а не работы с датами.
 */

/** Склонение существительного при числе: 1 задача, 2 задачи, 5 задач. */
export function склонение(
  число: number,
  одна: string,
  две: string,
  пять: string,
): string {
  const н = Math.abs(число) % 100
  if (н >= 11 && н <= 14) return пять
  const е = н % 10
  if (е === 1) return одна
  if (е >= 2 && е <= 4) return две
  return пять
}
