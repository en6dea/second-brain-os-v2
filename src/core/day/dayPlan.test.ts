import { describe, expect, it } from 'vitest'
import {
  оценитьЗагрузку,
  предложитьРазгрузку,
  собратьПланДня,
  type ЧерновикПункта,
} from './dayPlan'
import type { ДанныеДня } from './NextAction'
import type { Задача, Обязательство, Привычка } from '@/core/db/types'

const момент = '2026-08-13T10:00:00.000Z'
const день = '2026-08-13'

const пусто: ДанныеДня = {
  задачи: [],
  цели: [],
  привычки: [],
  обязательства: [],
  замыслы: [],
  входящие: [],
}

function задача(изменения: Partial<Задача> = {}): Задача {
  return {
    id: 'з',
    createdAt: момент,
    updatedAt: момент,
    название: 'Задача',
    заметка: '',
    дата: день,
    время: null,
    длительностьМинут: null,
    состояние: 'новая',
    важность: 'обычная',
    проектId: null,
    цельId: null,
    сфераId: null,
    выполненаВ: null,
    переносов: 0,
    повтор: null,
    ...изменения,
  }
}

function обязательство(изменения: Partial<Обязательство> = {}): Обязательство {
  return {
    id: 'о',
    createdAt: момент,
    updatedAt: момент,
    название: 'Интернет',
    направление: 'я должен',
    вид: 'подписка',
    телоОстаток: 0,
    начисленныеПроценты: null,
    штрафы: null,
    ставкаГодовых: null,
    минимальныйПлатёж: 70000,
    датаСледующегоПлатежа: день,
    повторПлатежа: null,
    датаОкончания: null,
    контрагент: '',
    закрыто: false,
    заметка: '',
    ...изменения,
  }
}

function привычка(изменения: Partial<Привычка> = {}): Привычка {
  return {
    id: 'п',
    createdAt: момент,
    updatedAt: момент,
    название: 'Чтение',
    иконка: '',
    цвет: 'accent',
    частота: 'ежедневно',
    дниНедели: [],
    разВНеделю: null,
    норма: 20,
    единица: 'минут',
    цельId: null,
    сфераId: null,
    активна: true,
    постер: '',
    отметки: {},
    ...изменения,
  }
}

describe('собратьПланДня', () => {
  it('без данных возвращает пустой план, а не выдуманные пункты', () => {
    expect(собратьПланДня(пусто, день, 10)).toEqual([])
  })

  it('берёт до пяти пунктов из правил следующего действия', () => {
    const данные: ДанныеДня = {
      ...пусто,
      обязательства: [обязательство({ id: 'об1', датаСледующегоПлатежа: день })],
      задачи: [задача({ id: 'з1', переносов: 4 })],
    }
    const план = собратьПланДня(данные, день, 10)
    expect(план.map((пункт) => пункт.вид)).toEqual(['обязательство', 'задача'])
    expect(план[0]?.записьId).toBe('об1')
    expect(план[1]?.записьId).toBe('з1')
  })

  it('не повторяет одну и ту же запись дважды', () => {
    // Застрявшая задача без даты на сегодня не попадёт вторым пунктом из
    // добора задач на сегодня, потому что adddate !== день — проверяем
    // обратный случай: задача и застрявшая, и на сегодня.
    const данные: ДанныеДня = {
      ...пусто,
      задачи: [задача({ id: 'з1', переносов: 5, дата: день })],
    }
    const план = собратьПланДня(данные, день, 10)
    const количество = план.filter((пункт) => пункт.записьId === 'з1').length
    expect(количество).toBe(1)
  })

  it('добирает открытые задачи на сегодня, если правил не хватило на три пункта', () => {
    const данные: ДанныеДня = {
      ...пусто,
      задачи: [
        задача({ id: 'з1', важность: 'срочная' }),
        задача({ id: 'з2', важность: 'низкая' }),
      ],
    }
    const план = собратьПланДня(данные, день, 10)
    expect(план.map((пункт) => пункт.записьId)).toEqual(['з1', 'з2'])
    expect(план.every((пункт) => пункт.вид === 'задача')).toBe(true)
  })

  it('не добирает задачи не на сегодня и не сделанные/отменённые', () => {
    const данные: ДанныеДня = {
      ...пусто,
      задачи: [
        задача({ id: 'завтра', дата: '2026-08-14' }),
        задача({ id: 'сделана', состояние: 'сделана' }),
      ],
    }
    expect(собратьПланДня(данные, день, 10)).toEqual([])
  })

  it('добирает привычки, только если задач всё ещё не хватило', () => {
    const данные: ДанныеДня = {
      ...пусто,
      задачи: [задача({ id: 'з1' }), задача({ id: 'з2' })],
      привычки: [привычка({ id: 'п1' })],
    }
    const план = собратьПланДня(данные, день, 10)
    expect(план.map((пункт) => пункт.записьId)).toEqual(['з1', 'з2', 'п1'])
  })

  it('не добирает уже отмеченную сегодня или неактивную привычку', () => {
    const данные: ДанныеДня = {
      ...пусто,
      привычки: [
        привычка({ id: 'отмечена', отметки: { [день]: 1 } }),
        привычка({ id: 'неактивна', активна: false }),
      ],
    }
    expect(собратьПланДня(данные, день, 10)).toEqual([])
  })

  it('не добирает привычки вне расписания или с выполненной недельной нормой', () => {
    const данные: ДанныеДня = {
      ...пусто,
      привычки: [
        привычка({
          id: 'не-сегодня',
          частота: 'по дням недели',
          дниНедели: [5],
        }),
        привычка({
          id: 'норма-выполнена',
          частота: 'сколько-то раз в неделю',
          разВНеделю: 2,
          отметки: { '2026-08-10': 1, '2026-08-11': 1 },
        }),
      ],
    }
    expect(собратьПланДня(данные, день, 10)).toEqual([])
  })

  it('не превышает пять пунктов', () => {
    const данные: ДанныеДня = {
      ...пусто,
      задачи: Array.from({ length: 10 }, (_, индекс) =>
        задача({ id: `з${индекс}` }),
      ),
    }
    expect(собратьПланДня(данные, день, 10)).toHaveLength(5)
  })

  it('сохраняет указанную длительность задачи, не придумывая её', () => {
    const сОценкой = собратьПланДня(
      { ...пусто, задачи: [задача({ id: 'з1', длительностьМинут: 45 })] },
      день,
      10,
    )
    const безОценки = собратьПланДня(
      { ...пусто, задачи: [задача({ id: 'з2', длительностьМинут: null })] },
      день,
      10,
    )

    expect(сОценкой[0]?.ожидаемоМинут).toBe(45)
    expect(безОценки[0]?.ожидаемоМинут).toBeNull()
  })

  it('использует минутную норму привычки как известную нагрузку', () => {
    const план = собратьПланДня(
      {
        ...пусто,
        привычки: [привычка({ id: 'п1', норма: 20, единица: 'минут' })],
      },
      день,
      10,
    )

    expect(план[0]?.ожидаемоМинут).toBe(20)
  })
})

describe('оценитьЗагрузку', () => {
  it('показывает известное время и отдельно пункты без оценки', () => {
    expect(
      оценитьЗагрузку(
        [{ ожидаемоМинут: 30 }, { ожидаемоМинут: null }, { ожидаемоМинут: 45 }],
        60,
      ),
    ).toEqual({ известноМинут: 75, безОценки: 1, превышениеМинут: 15 })
  })

  it('не принимает неизвестную длительность за ноль подтверждённых минут', () => {
    expect(оценитьЗагрузку([{ ожидаемоМинут: null }], 60)).toEqual({
      известноМинут: 0,
      безОценки: 1,
      превышениеМинут: 0,
    })
  })
})

describe('предложитьРазгрузку', () => {
  function пунктИзЗадачи(запись: Задача): ЧерновикПункта {
    return {
      вид: 'задача',
      записьId: запись.id,
      заголовок: запись.название,
      зачем: 'Задача на сегодня',
      ожидаемоМинут: запись.длительностьМинут,
    }
  }

  it('сначала предлагает менее приоритетную задачу, достаточную для лимита', () => {
    const важная = задача({
      id: 'важная',
      название: 'Важная',
      важность: 'высокая',
      длительностьМинут: 90,
    })
    const низкая = задача({
      id: 'низкая',
      название: 'Можно позже',
      важность: 'низкая',
      длительностьМинут: 60,
    })

    const итог = предложитьРазгрузку(
      [пунктИзЗадачи(важная), пунктИзЗадачи(низкая)],
      [важная, низкая],
      90,
      3,
    )

    expect(итог.задачи.map((запись) => запись.id)).toEqual(['низкая'])
    expect(итог.превышениеМинут).toBe(60)
    expect(итог.останетсяПревышениеМинут).toBe(0)
  })

  it('при низкой энергии сокращает план до трёх пунктов', () => {
    const задачи = Array.from({ length: 5 }, (_, индекс) =>
      задача({
        id: `з${индекс}`,
        название: `Задача ${индекс}`,
        важность: индекс < 2 ? 'низкая' : 'обычная',
        длительностьМинут: null,
      }),
    )

    const итог = предложитьРазгрузку(задачи.map(пунктИзЗадачи), задачи, 180, 2)

    expect(итог.лишнихПунктовПриНизкойЭнергии).toBe(2)
    expect(итог.задачи.map((запись) => запись.id)).toEqual(['з0', 'з1'])
    expect(итог.останетсяЛишнихПунктов).toBe(0)
  })

  it('не предлагает срочную или многократно переносимую задачу', () => {
    const срочная = задача({
      id: 'срочная',
      важность: 'срочная',
      длительностьМинут: 60,
    })
    const застряла = задача({
      id: 'застряла',
      важность: 'низкая',
      длительностьМинут: 60,
      переносов: 3,
    })

    const итог = предложитьРазгрузку(
      [пунктИзЗадачи(срочная), пунктИзЗадачи(застряла)],
      [срочная, застряла],
      30,
      3,
    )

    expect(итог.задачи).toEqual([])
    expect(итог.останетсяПревышениеМинут).toBe(90)
    expect(итог.защищённыхЗастрявшихЗадач).toBe(1)
  })

  it('не считает неизвестное время освобождёнными минутами', () => {
    const неизвестная = задача({
      id: 'неизвестная',
      важность: 'низкая',
      длительностьМинут: null,
    })
    const обязательный: ЧерновикПункта = {
      вид: 'обязательство',
      записьId: 'обязательство',
      заголовок: 'Обязательный платёж',
      зачем: 'Сегодня',
      ожидаемоМинут: 90,
    }

    const итог = предложитьРазгрузку(
      [обязательный, пунктИзЗадачи(неизвестная)],
      [неизвестная],
      30,
      3,
    )

    expect(итог.задачи).toEqual([])
    expect(итог.останетсяПревышениеМинут).toBe(60)
  })
})
