import { describe, expect, it } from 'vitest'
import { собратьПланДня } from './dayPlan'
import type { ДанныеДня } from './NextAction'
import type { Задача, Обязательство, Привычка } from '@/core/db/types'

const момент = '2026-08-13T10:00:00.000Z'
const день = '2026-08-13'

const пусто: ДанныеДня = {
  задачи: [],
  цели: [],
  привычки: [],
  обязательства: [],
  замыслы: [],
  входящие: [],
}

function задача(изменения: Partial<Задача> = {}): Задача {
  return {
    id: 'з',
    createdAt: момент,
    updatedAt: момент,
    название: 'Задача',
    заметка: '',
    дата: день,
    время: null,
    длительностьМинут: null,
    состояние: 'новая',
    важность: 'обычная',
    проектId: null,
    цельId: null,
    сфераId: null,
    выполненаВ: null,
    переносов: 0,
    повтор: null,
    ...изменения,
  }
}

function обязательство(изменения: Partial<Обязательство> = {}): Обязательство {
  return {
    id: 'о',
    createdAt: момент,
    updatedAt: момент,
    название: 'Интернет',
    направление: 'я должен',
    вид: 'подписка',
    телоОстаток: 0,
    начисленныеПроценты: null,
    штрафы: null,
    ставкаГодовых: null,
    минимальныйПлатёж: 70000,
    датаСледующегоПлатежа: день,
    повторПлатежа: null,
    датаОкончания: null,
    контрагент: '',
    закрыто: false,
    заметка: '',
    ...изменения,
  }
}

function привычка(изменения: Partial<Привычка> = {}): Привычка {
  return {
    id: 'п',
    createdAt: момент,
    updatedAt: момент,
    название: 'Чтение',
    иконка: '',
    цвет: 'accent',
    частота: 'ежедневно',
    дниНедели: [],
    разВНеделю: null,
    норма: 20,
    единица: 'минут',
    цельId: null,
    сфераId: null,
    активна: true,
    постер: '',
    отметки: {},
    ...изменения,
  }
}

describe('собратьПланДня', () => {
  it('без данных возвращает пустой план, а не выдуманные пункты', () => {
    expect(собратьПланДня(пусто, день, 10)).toEqual([])
  })

  it('берёт до пяти пунктов из правил следующего действия', () => {
    const данные: ДанныеДня = {
      ...пусто,
      обязательства: [обязательство({ id: 'об1', датаСледующегоПлатежа: день })],
      задачи: [задача({ id: 'з1', переносов: 4 })],
    }
    const план = собратьПланДня(данные, день, 10)
    expect(план.map((пункт) => пункт.вид)).toEqual(['обязательство', 'задача'])
    expect(план[0]?.записьId).toBe('об1')
    expect(план[1]?.записьId).toBe('з1')
  })

  it('не повторяет одну и ту же запись дважды', () => {
    // Застрявшая задача без даты на сегодня не попадёт вторым пунктом из
    // добора задач на сегодня, потому что adddate !== день — проверяем
    // обратный случай: задача и застрявшая, и на сегодня.
    const данные: ДанныеДня = {
      ...пусто,
      задачи: [задача({ id: 'з1', переносов: 5, дата: день })],
    }
    const план = собратьПланДня(данные, день, 10)
    const количество = план.filter((пункт) => пункт.записьId === 'з1').length
    expect(количество).toBe(1)
  })

  it('добирает открытые задачи на сегодня, если правил не хватило на три пункта', () => {
    const данные: ДанныеДня = {
      ...пусто,
      задачи: [
        задача({ id: 'з1', важность: 'срочная' }),
        задача({ id: 'з2', важность: 'низкая' }),
      ],
    }
    const план = собратьПланДня(данные, день, 10)
    expect(план.map((пункт) => пункт.записьId)).toEqual(['з1', 'з2'])
    expect(план.every((пункт) => пункт.вид === 'задача')).toBe(true)
  })

  it('не добирает задачи не на сегодня и не сделанные/отменённые', () => {
    const данные: ДанныеДня = {
      ...пусто,
      задачи: [
        задача({ id: 'завтра', дата: '2026-08-14' }),
        задача({ id: 'сделана', состояние: 'сделана' }),
      ],
    }
    expect(собратьПланДня(данные, день, 10)).toEqual([])
  })

  it('добирает привычки, только если задач всё ещё не хватило', () => {
    const данные: ДанныеДня = {
      ...пусто,
      задачи: [задача({ id: 'з1' }), задача({ id: 'з2' })],
      привычки: [привычка({ id: 'п1' })],
    }
    const план = собратьПланДня(данные, день, 10)
    expect(план.map((пункт) => пункт.записьId)).toEqual(['з1', 'з2', 'п1'])
  })

  it('не добирает уже отмеченную сегодня или неактивную привычку', () => {
    const данные: ДанныеДня = {
      ...пусто,
      привычки: [
        привычка({ id: 'отмечена', отметки: { [день]: 1 } }),
        привычка({ id: 'неактивна', активна: false }),
      ],
    }
    expect(собратьПланДня(данные, день, 10)).toEqual([])
  })

  it('не добирает привычки вне расписания или с выполненной недельной нормой', () => {
    const данные: ДанныеДня = {
      ...пусто,
      привычки: [
        привычка({
          id: 'не-сегодня',
          частота: 'по дням недели',
          дниНедели: [5],
        }),
        привычка({
          id: 'норма-выполнена',
          частота: 'сколько-то раз в неделю',
          разВНеделю: 2,
          отметки: { '2026-08-10': 1, '2026-08-11': 1 },
        }),
      ],
    }
    expect(собратьПланДня(данные, день, 10)).toEqual([])
  })

  it('не превышает пять пунктов', () => {
    const данные: ДанныеДня = {
      ...пусто,
      задачи: Array.from({ length: 10 }, (_, индекс) => задача({ id: `з${индекс}` })),
    }
    expect(собратьПланДня(данные, день, 10)).toHaveLength(5)
  })
})
