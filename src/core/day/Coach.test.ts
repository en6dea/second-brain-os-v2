import { describe, expect, it } from 'vitest'
import { советПомощника } from './Coach'
import type { ПричинаПрокрастинации } from '@/core/db/types'

describe('советПомощника', () => {
  it.each<
    [
      ПричинаПрокрастинации,
      'психолог' | 'бизнес-коуч' | 'тайм-менеджер',
      5 | 10 | 15,
    ]
  >([
    ['неясно', 'бизнес-коуч', 10],
    ['слишком большое', 'тайм-менеджер', 10],
    ['страшно ошибиться', 'психолог', 10],
    ['нет сил', 'психолог', 5],
    ['отвлекаюсь', 'тайм-менеджер', 15],
  ])(
    'для причины «%s» выбирает прозрачный режим помощи',
    (причина, роль, минут) => {
      const совет = советПомощника(причина, 'Подготовить предложение')

      expect(совет.роль).toBe(роль)
      expect(совет.минут).toBe(минут)
      expect(совет.поддержка.length).toBeGreaterThan(30)
      expect(совет.вопрос).toMatch(/\?$/)
      expect(совет.микрошаг).toContain('Подготовить предложение')
    },
  )

  it('не приписывает человеку диагноз или скрытую причину', () => {
    const текст = Object.values({
      неясно: советПомощника('неясно', 'Задача'),
      размер: советПомощника('слишком большое', 'Задача'),
      страх: советПомощника('страшно ошибиться', 'Задача'),
      силы: советПомощника('нет сил', 'Задача'),
      внимание: советПомощника('отвлекаюсь', 'Задача'),
    })
      .flatMap((совет) => [совет.поддержка, совет.вопрос, совет.микрошаг])
      .join(' ')
      .toLocaleLowerCase('ru')

    expect(текст).not.toMatch(/диагноз|депресси|тревожное расстройство|ленив/)
  })
})
