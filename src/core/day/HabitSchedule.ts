import type { ДатаДень, Привычка } from '@/core/db/types'
import { границыНедели, кДате } from '@/core/calendar/CalendarRu'

/**
 * Нужна ли привычка именно в этот день.
 *
 * Ежедневная привычка нужна каждый день; привычка по дням недели — только в
 * выбранные дни; недельная цель остаётся актуальной, пока недельная норма не
 * набрана. Уже сделанное сегодня повторно не предлагается.
 */
export function привычкаНужнаВДень(
  привычка: Привычка,
  день: ДатаДень,
): boolean {
  if (!привычка.активна || (привычка.отметки[день] ?? 0) > 0) return false

  if (привычка.частота === 'ежедневно') return true

  if (привычка.частота === 'по дням недели') {
    const деньJs = кДате(день).getDay()
    const номерПонедельникПервый = деньJs === 0 ? 7 : деньJs
    return привычка.дниНедели.includes(номерПонедельникПервый)
  }

  const недельнаяНорма = привычка.разВНеделю ?? 0
  if (недельнаяНорма <= 0) return false

  const неделя = границыНедели(день)
  const сделано = Object.entries(привычка.отметки).filter(
    ([дата, значение]) =>
      дата >= неделя.от && дата <= неделя.до && значение > 0,
  ).length
  return сделано < недельнаяНорма
}
