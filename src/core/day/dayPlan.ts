import type { ВидПунктаПлана } from '@/core/db/types'
import {
  открытые,
  поВехе,
  поВходящим,
  поЗастрявшейЗадаче,
  поПлатежу,
  поПривычке,
  type ДанныеДня,
  type СледующееДействие,
} from './NextAction'
import { привычкаНужнаВДень } from './HabitSchedule'

/**
 * План на день.
 *
 * Не одно действие, а короткий список: до пяти пунктов, каждый — из тех же
 * правил, что и «следующее действие», плюс открытые задачи и привычки на
 * сегодня, если правил не хватило на три пункта. Меньше трёх — план так и
 * показывает меньше трёх: придумывать пункты, чтобы набрать число, нечестно.
 *
 * Заголовок и числа каждого пункта экран берёт из самой записи по
 * `записьId` — здесь их нет и не будет.
 */

const МИНИМУМ_ПУНКТОВ = 3
const МАКСИМУМ_ПУНКТОВ = 5

export interface ЧерновикПункта {
  вид: ВидПунктаПлана
  записьId: string
  заголовок: string
  зачем: string
}

const ВИД_ПО_РАЗДЕЛУ: Record<string, ВидПунктаПлана> = {
  '/obligations': 'обязательство',
  '/tasks': 'задача',
  '/goals': 'цель',
  '/habits': 'привычка',
  '/inbox': 'входящие',
}

/** Раздел, куда ведёт пункт плана — обратная сторона {@link ВИД_ПО_РАЗДЕЛУ}. */
export const РАЗДЕЛ_ПО_ВИДУ: Record<ВидПунктаПлана, string> = {
  обязательство: '/obligations',
  задача: '/tasks',
  цель: '/goals',
  привычка: '/habits',
  входящие: '/inbox',
}

function изДействия(действие: СледующееДействие): ЧерновикПункта {
  return {
    вид: ВИД_ПО_РАЗДЕЛУ[действие.раздел] ?? 'задача',
    записьId: действие.источникId,
    заголовок: действие.заголовок,
    зачем: действие.зачем,
  }
}

export function собратьПланДня(
  данные: ДанныеДня,
  день: string,
  час: number,
): ЧерновикПункта[] {
  const пункты: ЧерновикПункта[] = []
  const включён = (id: string) => пункты.some((пункт) => пункт.записьId === id)

  for (const действие of [
    поПлатежу(данные, день),
    поЗастрявшейЗадаче(данные, день),
    поВехе(данные, день),
    поПривычке(данные, день, час),
    поВходящим(данные),
  ]) {
    if (действие && !включён(действие.источникId)) пункты.push(изДействия(действие))
  }

  if (пункты.length < МИНИМУМ_ПУНКТОВ) {
    const задачиНаСегодня = открытые(данные.задачи)
      .filter((задача) => задача.дата === день && !включён(задача.id))
      .sort((первая, вторая) => вес(вторая.важность) - вес(первая.важность))

    for (const задача of задачиНаСегодня) {
      if (пункты.length >= МАКСИМУМ_ПУНКТОВ) break
      пункты.push({
        вид: 'задача',
        записьId: задача.id,
        заголовок: задача.название,
        зачем: 'Задача на сегодня',
      })
    }
  }

  if (пункты.length < МИНИМУМ_ПУНКТОВ) {
    const непривычки = данные.привычки.filter(
      (привычка) =>
        привычкаНужнаВДень(привычка, день) &&
        !включён(привычка.id),
    )

    for (const привычка of непривычки) {
      if (пункты.length >= МАКСИМУМ_ПУНКТОВ) break
      пункты.push({
        вид: 'привычка',
        записьId: привычка.id,
        заголовок: привычка.название,
        зачем: 'Ещё не отмечена сегодня',
      })
    }
  }

  return пункты.slice(0, МАКСИМУМ_ПУНКТОВ)
}

function вес(важность: 'низкая' | 'обычная' | 'высокая' | 'срочная'): number {
  return { низкая: 0, обычная: 1, высокая: 2, срочная: 3 }[важность]
}
