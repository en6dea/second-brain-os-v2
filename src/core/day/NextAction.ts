/**
 * Следующее действие.
 *
 * Одно. Не список из двенадцати карточек, из которого человек всё равно
 * выберет самое лёгкое.
 *
 * Каждое основание выведено из записей и называет источник. Здесь намеренно
 * нет доводов вида «утром внимание на пике»: приложение не знает, когда у вас
 * пик, и выдавать общее место за знание о человеке нечестно.
 *
 * Чистая функция: день и час приходят снаружи.
 */

export interface Основание {
  заголовок: string
  текст: string
}

export interface СледующееДействие {
  заголовок: string
  зачем: string
  основания: Основание[]
  /** Сколько займёт. `null` — не указано, и придумывать нечего. */
  минут: number | null
  раздел: string
  /** Что произойдёт, если отложить. Пусто — ничего страшного. */
  еслиОтложить: string
  /**
   * Запись, из которой выведено действие.
   *
   * Нужна экрану, чтобы не показать то же самое второй раз списком сигналов:
   * один и тот же текст дважды читается как сбой, а не как акцент.
   */
  источникId: string
}

export interface ДанныеДня {
  задачи: Задача[]
  цели: Цель[]
  привычки: Привычка[]
  обязательства: Обязательство[]
  замыслы: Замысел[]
  входящие: Входящее[]
}

function разностьДней(от: string, до: string): number {
  const начало = new Date(`${от}T00:00:00`).getTime()
  const конец = new Date(`${до}T00:00:00`).getTime()
  return Math.round((конец - начало) / 86_400_000)
}

export function открытые(задачи: Задача[]): Задача[] {
  return задачи.filter(
    (задача) => задача.состояние !== 'сделана' && задача.состояние !== 'отменена',
  )
}

/** Платёж, который нельзя пропустить: последствия дороже всего остального. */
export function поПлатежу(данные: ДанныеДня, день: string): СледующееДействие | null {
  const близкие = данные.обязательства
    .filter(
      (о) => !о.закрыто && о.датаСледующегоПлатежа !== null,
    )
    .map((о) => ({ о, дней: разностьДней(день, о.датаСледующегоПлатежа as string) }))
    .filter(({ дней }) => дней <= 1)
    .sort((первый, второй) => первый.дней - второй.дней)

  const ближайший = близкие[0]
  if (!ближайший) return null

  const { о, дней } = ближайший
  const сумма =
    о.минимальныйПлатёж === null ? null : деньгиКратко(о.минимальныйПлатёж)

  return {
    заголовок: `Оплатить: ${о.название}`,
    зачем:
      дней < 0
        ? `Платёж просрочен на ${Math.abs(дней)} ${склонение(Math.abs(дней), 'день', 'дня', 'дней')}.`
        : дней === 0
          ? 'Платёж сегодня.'
          : 'Платёж завтра.',
    основания: [
      {
        заголовок: 'Откуда взято',
        текст: `Из обязательства «${о.название}», поле «дата следующего платежа»`,
      },
      {
        заголовок: 'Сумма',
        текст: сумма ? `${сумма} — минимальный платёж` : 'Не указана в обязательстве',
      },
    ],
    минут: null,
    раздел: '/obligations',
    источникId: о.id,
    еслиОтложить:
      'Дата платежа останется просроченной; финансовые последствия зависят от условий обязательства.',
  }
}

/** Задача, которая переносится снова и снова. Её надо либо сделать, либо снять. */
export function поЗастрявшейЗадаче(
  данные: ДанныеДня,
  день: string,
): СледующееДействие | null {
  const застряла = открытые(данные.задачи)
    .filter((задача) => задача.переносов >= 3)
    .sort((первая, вторая) => вторая.переносов - первая.переносов)[0]

  if (!застряла) return null

  const цель = данные.цели.find((ц) => ц.id === застряла.цельId)
  const просрочена =
    застряла.дата !== null && разностьДней(день, застряла.дата) < 0

  return {
    заголовок: застряла.название,
    зачем: `Задачу переносили ${застряла.переносов} ${склонение(застряла.переносов, 'раз', 'раза', 'раз')}. Решите: сделать, уменьшить или отменить.`,
    основания: [
      {
        заголовок: 'Число переносов',
        текст: `${застряла.переносов} — считается по самой задаче`,
      },
      цель
        ? { заголовок: 'Ведёт к цели', текст: цель.название }
        : { заголовок: 'Цель не указана', текст: 'Задача ни к чему не привязана' },
      ...(просрочена
        ? [{ заголовок: 'Срок', текст: `Прошёл ${деньСловами(застряла.дата)}` }]
        : []),
    ],
    минут: застряла.длительностьМинут,
    раздел: '/tasks',
    источникId: застряла.id,
    еслиОтложить: `Задача останется открытой после ${застряла.переносов} ${склонение(застряла.переносов, 'переноса', 'переносов', 'переносов')}.`,
  }
}

/** Ближайшая веха активной цели: то, что двигает вперёд, а не тушит пожар. */
export function поВехе(данные: ДанныеДня, день: string): СледующееДействие | null {
  const активные = данные.цели.filter((цель) => цель.состояние === 'активна')

  let лучшая: { цель: Цель; веха: Цель['вехи'][number]; дней: number } | null = null
  for (const цель of активные) {
    for (const веха of цель.вехи) {
      if (веха.выполнена || веха.срок === null) continue
      const дней = разностьДней(день, веха.срок)
      if (дней > 14) continue
      if (!лучшая || дней < лучшая.дней) лучшая = { цель, веха, дней }
    }
  }

  if (!лучшая) return null

  return {
    заголовок: лучшая.веха.название,
    зачем: `Ближайшая веха цели «${лучшая.цель.название}».`,
    основания: [
      { заголовок: 'Цель', текст: лучшая.цель.название },
      {
        заголовок: 'Срок вехи',
        текст:
          лучшая.дней < 0
            ? `Прошёл ${Math.abs(лучшая.дней)} ${склонение(Math.abs(лучшая.дней), 'день', 'дня', 'дней')} назад`
            : лучшая.дней === 0
              ? 'Сегодня'
              : `Через ${лучшая.дней} ${склонение(лучшая.дней, 'день', 'дня', 'дней')}`,
      },
      лучшая.цель.зачем
        ? { заголовок: 'Зачем эта цель', текст: лучшая.цель.зачем }
        : {
            заголовок: 'Зачем не записано',
            текст: 'У цели пустое поле «зачем» — в трудный день это подводит',
          },
    ],
    минут: null,
    раздел: '/goals',
    источникId: лучшая.цель.id,
    еслиОтложить: 'Срок вехи ближе, а сделано столько же.',
  }
}

/** Разбор входящих: факт о текущем количестве без выдуманной динамики. */
export function поВходящим(данные: ДанныеДня): СледующееДействие | null {
  const ждут = данные.входящие.filter((запись) => !запись.разобрано).length
  if (ждут < 5) return null

  return {
    заголовок: `Разобрать входящие: ${ждут}`,
    зачем:
      `Сейчас не разобрано ${ждут} быстрых записей. Пока они не разобраны, они не задачи и не заметки, а просто текст.`,
    основания: [
      { заголовок: 'Сколько ждёт', текст: `${ждут} — посчитано по неразобранным` },
      { заголовок: 'Порог', текст: 'Предлагается начиная с пяти записей' },
    ],
    минут: null,
    раздел: '/inbox',
    источникId: 'входящие',
    еслиОтложить: 'Без разбора эти записи останутся во входящих.',
  }
}

/** Привычка, не отмеченная к вечеру. Предлагается только вечером. */
export function поПривычке(
  данные: ДанныеДня,
  день: string,
  час: number,
): СледующееДействие | null {
  if (час < 18) return null

  const неотмеченная = данные.привычки.find(
    (привычка) => привычкаНужнаВДень(привычка, день),
  )
  if (!неотмеченная) return null

  const недельнаяЦель = неотмеченная.частота === 'сколько-то раз в неделю'

  return {
    заголовок: неотмеченная.название,
    зачем: недельнаяЦель
      ? 'Недельная норма привычки ещё не набрана, а день заканчивается.'
      : 'Привычка запланирована на сегодня и ещё не отмечена.',
    основания: [
      { заголовок: 'Норма', текст: `${неотмеченная.норма} ${неотмеченная.единица}` },
      { заголовок: 'Почему сейчас', текст: `Вечер: уже ${час}:00` },
    ],
    минут: null,
    раздел: '/habits',
    источникId: неотмеченная.id,
    еслиОтложить: недельнаяЦель
      ? 'До конца недели останется меньше времени на недельную норму.'
      : 'Запланированный день закроется без отметки.',
  }
}

/**
 * Что делать сейчас.
 *
 * Порядок доверия: сначала то, что дорого стоит при пропуске, потом то, что
 * застряло, потом то, что двигает цель. Возврат `null` — честный ответ:
 * оснований предлагать что-либо нет, и выдумывать занятие приложение не станет.
 */
export function следующееДействие(
  данные: ДанныеДня,
  день: string,
  час: number,
): СледующееДействие | null {
  return (
    поПлатежу(данные, день) ??
    поЗастрявшейЗадаче(данные, день) ??
    поВехе(данные, день) ??
    поПривычке(данные, день, час) ??
    поВходящим(данные) ??
    null
  )
}
