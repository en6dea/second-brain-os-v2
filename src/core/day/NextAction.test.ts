import { describe, expect, it } from 'vitest'
import { следующееДействие, type ДанныеДня } from './NextAction'
import type { Задача, Обязательство, Привычка, Цель } from '@/core/db/types'

const момент = '2026-08-13T10:00:00.000Z'
const день = '2026-08-13'

const пусто: ДанныеДня = {
  задачи: [],
  цели: [],
  привычки: [],
  обязательства: [],
  замыслы: [],
  входящие: [],
}

function задача(изменения: Partial<Задача> = {}): Задача {
  return {
    id: 'з',
    createdAt: момент,
    updatedAt: момент,
    название: 'Задача',
    заметка: '',
    дата: день,
    время: null,
    длительностьМинут: null,
    состояние: 'новая',
    важность: 'обычная',
    проектId: null,
    цельId: null,
    сфераId: null,
    выполненаВ: null,
    переносов: 0,
    повтор: null,
    ...изменения,
  }
}

function цель(изменения: Partial<Цель> = {}): Цель {
  return {
    id: 'ц',
    createdAt: момент,
    updatedAt: момент,
    название: 'Свободный английский',
    зачем: 'Говорить без переводчика',
    сфераId: null,
    состояние: 'активна',
    срок: null,
    цель: null,
    текущее: null,
    единица: '',
    порядок: 0,
    вехи: [],
    последняяАктивность: null,
    постер: '',
    ...изменения,
  }
}

function обязательство(изменения: Partial<Обязательство> = {}): Обязательство {
  return {
    id: 'о',
    createdAt: момент,
    updatedAt: момент,
    название: 'Интернет',
    направление: 'я должен',
    вид: 'подписка',
    телоОстаток: 0,
    начисленныеПроценты: null,
    штрафы: null,
    ставкаГодовых: null,
    минимальныйПлатёж: 70000,
    датаСледующегоПлатежа: день,
    повторПлатежа: null,
    датаОкончания: null,
    контрагент: '',
    закрыто: false,
    заметка: '',
    ...изменения,
  }
}

function привычка(отметки: Record<string, number> = {}): Привычка {
  return {
    id: 'п',
    createdAt: момент,
    updatedAt: момент,
    название: 'Чтение',
    иконка: '',
    цвет: 'accent',
    частота: 'ежедневно',
    дниНедели: [],
    разВНеделю: null,
    норма: 20,
    единица: 'минут',
    цельId: null,
    сфераId: null,
    активна: true,
    постер: '',
    отметки,
  }
}

describe('следующееДействие', () => {
  it('без данных ничего не предлагает', () => {
    expect(следующееДействие(пусто, день, 10)).toBeNull()
  })

  it('платёж важнее всего остального', () => {
    const итог = следующееДействие(
      {
        ...пусто,
        обязательства: [обязательство()],
        задачи: [задача({ переносов: 9 })],
      },
      день,
      10,
    )
    expect(итог?.заголовок).toContain('Оплатить')
    expect(итог?.раздел).toBe('/obligations')
  })

  it('платёж без суммы честно говорит, что сумма не указана', () => {
    const итог = следующееДействие(
      { ...пусто, обязательства: [обязательство({ минимальныйПлатёж: null })] },
      день,
      10,
    )
    expect(итог?.основания.some((о) => о.текст.includes('Не указана'))).toBe(true)
  })

  it('далёкий платёж действием не становится', () => {
    const итог = следующееДействие(
      { ...пусто, обязательства: [обязательство({ датаСледующегоПлатежа: '2026-09-01' })] },
      день,
      10,
    )
    expect(итог).toBeNull()
  })

  it('застрявшая задача предлагается с числом переносов', () => {
    const итог = следующееДействие(
      { ...пусто, задачи: [задача({ название: 'Позвонить', переносов: 4 })] },
      день,
      10,
    )
    expect(итог?.заголовок).toBe('Позвонить')
    expect(итог?.зачем).toContain('4')
    expect(итог?.еслиОтложить).toContain('4')
  })

  it('задача с двумя переносами застрявшей не считается', () => {
    const итог = следующееДействие(
      { ...пусто, задачи: [задача({ переносов: 2 })] },
      день,
      10,
    )
    expect(итог).toBeNull()
  })

  it('веха цели предлагается и называет цель', () => {
    const итог = следующееДействие(
      {
        ...пусто,
        цели: [
          цель({
            вехи: [
              { id: 'в', название: 'Сдать пробный тест', срок: день, выполнена: false },
            ],
          }),
        ],
      },
      день,
      10,
    )
    expect(итог?.заголовок).toBe('Сдать пробный тест')
    expect(итог?.основания[0]?.текст).toBe('Свободный английский')
  })

  it('цель без ответа «зачем» получает об этом отдельное основание', () => {
    const итог = следующееДействие(
      {
        ...пусто,
        цели: [
          цель({
            зачем: '',
            вехи: [{ id: 'в', название: 'Веха', срок: день, выполнена: false }],
          }),
        ],
      },
      день,
      10,
    )
    expect(итог?.основания.some((о) => о.заголовок.includes('не записано'))).toBe(true)
  })

  it('выполненная веха и веха отложенной цели не предлагаются', () => {
    const выполнена = следующееДействие(
      {
        ...пусто,
        цели: [
          цель({ вехи: [{ id: 'в', название: 'Веха', срок: день, выполнена: true }] }),
        ],
      },
      день,
      10,
    )
    expect(выполнена).toBeNull()

    const отложена = следующееДействие(
      {
        ...пусто,
        цели: [
          цель({
            состояние: 'отложена',
            вехи: [{ id: 'в', название: 'Веха', срок: день, выполнена: false }],
          }),
        ],
      },
      день,
      10,
    )
    expect(отложена).toBeNull()
  })

  it('привычка предлагается только вечером', () => {
    const данные = { ...пусто, привычки: [привычка()] }
    expect(следующееДействие(данные, день, 12)).toBeNull()
    expect(следующееДействие(данные, день, 20)?.заголовок).toBe('Чтение')
  })

  it('отмеченная привычка вечером не предлагается', () => {
    const итог = следующееДействие(
      { ...пусто, привычки: [привычка({ [день]: 20 })] },
      день,
      20,
    )
    expect(итог).toBeNull()
  })

  it('не предлагает привычку вне её расписания', () => {
    const поПятницам: Привычка = {
      ...привычка(),
      частота: 'по дням недели',
      дниНедели: [5],
    }
    expect(
      следующееДействие({ ...пусто, привычки: [поПятницам] }, день, 20),
    ).toBeNull()
  })

  it('не предлагает недельную привычку после выполнения нормы', () => {
    const дваждыВНеделю: Привычка = {
      ...привычка({ '2026-08-10': 20, '2026-08-11': 20 }),
      частота: 'сколько-то раз в неделю',
      разВНеделю: 2,
    }
    expect(
      следующееДействие({ ...пусто, привычки: [дваждыВНеделю] }, день, 20),
    ).toBeNull()
  })

  it('входящие предлагаются от пяти записей', () => {
    const запись = (id: string) => ({
      id,
      createdAt: момент,
      updatedAt: момент,
      текст: 'мысль',
      разобрано: false,
      источник: 'быстрая запись' as const,
    })

    const мало = следующееДействие(
      { ...пусто, входящие: [запись('1'), запись('2')] },
      день,
      10,
    )
    expect(мало).toBeNull()

    const много = следующееДействие(
      {
        ...пусто,
        входящие: ['1', '2', '3', '4', '5', '6'].map(запись),
      },
      день,
      10,
    )
    expect(много?.заголовок).toContain('6')
    expect(много?.зачем).toContain('Сейчас не разобрано 6')
    expect(`${много?.зачем} ${много?.еслиОтложить}`).not.toMatch(/вырос|растёт/)
  })

  it('у каждого действия есть основания и они не пустые', () => {
    const итог = следующееДействие(
      { ...пусто, задачи: [задача({ переносов: 5 })] },
      день,
      10,
    )
    expect(итог!.основания.length).toBeGreaterThan(0)
    for (const основание of итог!.основания) {
      expect(основание.заголовок.length).toBeGreaterThan(0)
      expect(основание.текст.length).toBeGreaterThan(0)
    }
  })

  it('время выполнения не выдумывается', () => {
    const без = следующееДействие(
      { ...пусто, задачи: [задача({ переносов: 4 })] },
      день,
      10,
    )
    expect(без?.минут).toBeNull()

    const с = следующееДействие(
      { ...пусто, задачи: [задача({ переносов: 4, длительностьМинут: 15 })] },
      день,
      10,
    )
    expect(с?.минут).toBe(15)
  })
})
