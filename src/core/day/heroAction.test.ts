import { describe, expect, it } from 'vitest'
import { выбратьГлавноеДействие } from './heroAction'
import type { Сигнал } from '@/core/db/types'

function сигнал(изменения: Partial<Сигнал> = {}): Сигнал {
  return {
    id: 'с1',
    уровень: 'внимание',
    текст: 'Текст сигнала',
    объяснение: 'Объяснение',
    раздел: 'Раздел',
    ссылка: '/tasks',
    ...изменения,
  }
}

describe('выбратьГлавноеДействие', () => {
  it('без данных честно говорит, что всё закрыто', () => {
    const итог = выбратьГлавноеДействие([], [])
    expect(итог.заголовок).toBe('На сегодня всё закрыто')
    expect(итог.ссылка).toBeNull()
    expect(итог.сигналId).toBeNull()
  })

  it('критичный сигнал важнее задачи и других сигналов', () => {
    const итог = выбратьГлавноеДействие(
      [{ название: 'Задача', состояние: 'новая', важность: 'обычная' }],
      [сигнал({ id: 'внимание', уровень: 'внимание' }), сигнал({ id: 'критичный', уровень: 'критично' })],
    )
    expect(итог.сигналId).toBe('критичный')
    expect(итог.подписьКнопки).toBe('Разобраться')
  })

  it('без критичного сигнала — первая невыполненная задача', () => {
    const итог = выбратьГлавноеДействие(
      [
        { название: 'Сделана', состояние: 'сделана', важность: 'обычная' },
        { название: 'Новая', состояние: 'новая', важность: 'обычная' },
      ],
      [],
    )
    expect(итог.заголовок).toBe('Новая')
    expect(итог.ссылка).toBe('/tasks')
    expect(итог.сигналId).toBeNull()
  })

  it('без задач — первый сигнал по порядку', () => {
    const итог = выбратьГлавноеДействие([], [сигнал({ id: 'первый' })])
    expect(итог.сигналId).toBe('первый')
    expect(итог.подписьКнопки).toBe('Посмотреть')
  })

  it('задачи, все сделанные, не перекрывают сигнал', () => {
    const итог = выбратьГлавноеДействие(
      [{ название: 'Сделана', состояние: 'сделана', важность: 'обычная' }],
      [сигнал({ id: 'единственный' })],
    )
    expect(итог.сигналId).toBe('единственный')
  })
})
