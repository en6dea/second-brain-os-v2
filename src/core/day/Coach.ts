import type { ПричинаПрокрастинации, РольПомощника } from '@/core/db/types'

export interface СоветПомощника {
  роль: РольПомощника
  поддержка: string
  вопрос: string
  микрошаг: string
  минут: 5 | 10 | 15
}

export interface ЧерновикКоучингСессии {
  причина: ПричинаПрокрастинации
  роль: РольПомощника
  микрошаг: string
  минут: 5 | 10 | 15
}

function названиеБезТочки(название: string): string {
  return название.trim().replace(/[.!?]+$/u, '')
}

/**
 * Локальный помощник не ставит диагнозов и не выдумывает причины поведения.
 * Он отвечает только на причину, которую человек выбрал сам, и сводит её к
 * одному проверяемому действию. Правила намеренно прозрачны и тестируемы.
 */
export function советПомощника(
  причина: ПричинаПрокрастинации,
  название: string,
): СоветПомощника {
  const действие = названиеБезТочки(название) || 'эту задачу'

  if (причина === 'неясно') {
    return {
      роль: 'бизнес-коуч',
      поддержка:
        'Туман перед стартом часто означает, что не определён видимый результат. Сначала уточним финиш, а не будем требовать от себя мотивации.',
      вопрос:
        'Что должно появиться после первого блока, чтобы вы увидели продвижение?',
      микрошаг: `Записать один видимый результат для «${действие}»`,
      минут: 10,
    }
  }

  if (причина === 'слишком большое') {
    return {
      роль: 'тайм-менеджер',
      поддержка:
        'Это похоже не на одно действие, а на проект. Уменьшим горизонт до части, которую можно закончить за один короткий блок.',
      вопрос: 'Какая самая маленькая законченная часть не зависит от остальных?',
      микрошаг: `Разделить «${действие}» на три части и выбрать самую короткую`,
      минут: 10,
    }
  }

  if (причина === 'страшно ошибиться') {
    return {
      роль: 'психолог',
      поддержка:
        'Желание сделать хорошо может превращать первый шаг в экзамен. Сейчас нужен не идеальный результат, а безопасный черновик.',
      вопрос: 'Как выглядела бы версия, которую пока не нужно никому показывать?',
      микрошаг: `Сделать грубый личный черновик для «${действие}»`,
      минут: 10,
    }
  }

  if (причина === 'нет сил') {
    return {
      роль: 'психолог',
      поддержка:
        'Низкий ресурс — это ограничение плана, а не оценка вас. Сохраним контакт с делом без попытки выжать полный результат.',
      вопрос: 'Что можно сделать бережно, не обещая себе продолжение?',
      микрошаг: `Открыть материалы по «${действие}» и сделать один простой шаг`,
      минут: 5,
    }
  }

  return {
    роль: 'тайм-менеджер',
    поддержка:
      'Внимание легче защитить средой, чем силой воли. На один блок уберём главный источник переключений.',
    вопрос: 'Что сейчас чаще всего уводит вас от этой задачи?',
    микрошаг: `Убрать одно отвлечение и начать «${действие}»`,
    минут: 15,
  }
}
