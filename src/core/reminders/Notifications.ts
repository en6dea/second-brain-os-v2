import type { Оповещение } from './Schedule'

/**
 * Показ уведомлений браузера.
 *
 * Честно про ограничение: это не push. Push с сервера требует своего
 * сервера и подписки устройства — здесь его нет и не будет, пока в
 * приложении нет ничего, что могло бы прислать сигнал, пока оно закрыто.
 * Уведомление показывается, только пока приложение открыто хотя бы в фоновой
 * вкладке — таймер в этом файле и решает, когда наступил момент.
 *
 * На iPhone уведомления работают только у приложения, добавленного на
 * домашний экран: Safari не даёт их обычной вкладке. Это ограничение самой
 * системы, а не этого кода.
 */

export function поддерживаются(): boolean {
  return typeof window !== 'undefined' && 'Notification' in window
}

export function разрешение(): NotificationPermission | 'нет-поддержки' {
  if (!поддерживаются()) return 'нет-поддержки'
  return Notification.permission
}

/**
 * Запрос разрешения.
 *
 * Браузер требует, чтобы запрос шёл прямо из обработчика клика человека —
 * поэтому эта функция вызывается кнопкой в настройках, а не сама по себе
 * при загрузке страницы.
 */
export async function запроситьРазрешение(): Promise<NotificationPermission> {
  if (!поддерживаются()) return 'denied'
  return Notification.requestPermission()
}

export function показать(оповещение: Оповещение): void {
  if (!поддерживаются() || Notification.permission !== 'granted') return
  const уведомление = new Notification(оповещение.заголовок, {
    body: оповещение.текст,
    tag: оповещение.ключ,
    icon: '/icon-192.png',
  })
  уведомление.onclick = () => {
    window.focus()
    // Вкладка уже открыта — иначе уведомление показать было бы неоткуда,
    // push с сервера здесь нет. Переход внутри неё делается тем же способом,
    // каким решает сам роутер: на GitHub Pages путь живёт в решётке.
    const хешевойРоутер =
      import.meta.env.MODE === 'production' && import.meta.env.BASE_URL !== '/'
    window.location.hash = хешевойРоутер ? оповещение.раздел : ''
    if (!хешевойРоутер) window.location.pathname = оповещение.раздел
    уведомление.close()
  }
}
