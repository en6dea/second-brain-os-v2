import type {
  Задача,
  Замысел,
  Обязательство,
  Привычка,
  Человек,
} from '@/core/db/types'
import { сегодня } from '@/core/calendar/CalendarRu'
import { деньгиКратко } from '@/core/money/Money'
import { склонение } from '@/core/language/Plural'

/**
 * Расписание напоминаний.
 *
 * Напоминания не заводятся руками — они выводятся из того, что уже записано.
 * Платёж известен из обязательства, срок задачи из самой задачи, ожидаемое
 * начало цикла посчитано по отметкам. Просить человека завести напоминание о
 * том, что система и так знает, значит заставлять его работать за неё.
 *
 * Чистая функция без базы, без интерфейса и без обращения к часам: время
 * приходит снаружи, поэтому расписание проверяется тестом.
 */

export type ВажностьОповещения = 'срочно' | 'обычно' | 'мягко'

export interface Оповещение {
  /** Устойчивый ключ: одно и то же напоминание в один день даёт один ключ. */
  ключ: string
  /** Когда показать. */
  когда: string
  заголовок: string
  текст: string
  раздел: string
  важность: ВажностьОповещения
}

export interface ДанныеРасписания {
  задачи: Задача[]
  обязательства: Обязательство[]
  привычки: Привычка[]
  замыслы: Замысел[]
  люди: Человек[]
  /** Ожидаемое начало цикла. `null` — считать не из чего. */
  ожидаемоеНачалоЦикла: string | null
  /** Заполнен ли дневник за сегодня. */
  дневникЗаполнен: boolean
}

export interface ЧасыДня {
  утро: number
  вечер: number
}

export const ЧАСЫ_ПО_УМОЛЧАНИЮ: ЧасыДня = { утро: 8, вечер: 21 }

/**
 * Сколько дней между двумя днями.
 *
 * Считается от переданного дня, а не от системных часов. Расписание обязано
 * быть чистым: иначе один и тот же набор записей даёт разный ответ в
 * зависимости от того, когда его вычислили, и проверить его тестом нельзя.
 */
function разностьДней(от: string, до: string): number {
  const начало = new Date(`${от}T00:00:00`).getTime()
  const конец = new Date(`${до}T00:00:00`).getTime()
  return Math.round((конец - начало) / 86_400_000)
}

/** Момент внутри дня по местному времени. */
function вМомент(день: string, час: number, минута = 0): string {
  const дата = new Date(`${день}T00:00:00`)
  дата.setHours(час, минута, 0, 0)
  return дата.toISOString()
}

/** Задача со временем напоминает за десять минут — успеть переключиться. */
function передЗадачей(день: string, время: string): string {
  const [час, минута] = время.split(':').map(Number)
  const дата = new Date(`${день}T00:00:00`)
  дата.setHours(час ?? 0, (минута ?? 0) - 10, 0, 0)
  return дата.toISOString()
}

function задачи(данные: ДанныеРасписания, день: string, часы: ЧасыДня): Оповещение[] {
  const итог: Оповещение[] = []
  const открытые = данные.задачи.filter(
    (задача) => задача.состояние !== 'сделана' && задача.состояние !== 'отменена',
  )

  for (const задача of открытые) {
    if (задача.дата === день && задача.время) {
      итог.push({
        ключ: `задача-${задача.id}-${день}`,
        когда: передЗадачей(день, задача.время),
        заголовок: задача.название,
        текст: `Через десять минут, в ${задача.время}`,
        раздел: '/tasks',
        важность: 'обычно',
      })
    }
  }

  const наСегодня = открытые.filter(
    (задача) => задача.дата === день && !задача.время,
  ).length
  const просрочено = открытые.filter(
    (задача) => задача.дата !== null && задача.дата < день,
  ).length

  if (наСегодня > 0 || просрочено > 0) {
    const части = [
      наСегодня > 0
        ? `${наСегодня} ${склонение(наСегодня, 'задача', 'задачи', 'задач')} на сегодня`
        : '',
      просрочено > 0 ? `${просрочено} просрочено` : '',
    ].filter(Boolean)

    итог.push({
      ключ: `утро-задачи-${день}`,
      когда: вМомент(день, часы.утро),
      заголовок: 'С чего начать',
      текст: части.join(', '),
      раздел: '/tasks',
      важность: просрочено > 0 ? 'срочно' : 'обычно',
    })
  }

  return итог
}

function платежи(данные: ДанныеРасписания, день: string, часы: ЧасыДня): Оповещение[] {
  const итог: Оповещение[] = []

  for (const обязательство of данные.обязательства) {
    if (обязательство.закрыто || !обязательство.датаСледующегоПлатежа) continue
    const дней = разностьДней(день, обязательство.датаСледующегоПлатежа)
    if (дней > 3) continue

    const сумма =
      обязательство.минимальныйПлатёж === null
        ? 'сумма не указана'
        : деньгиКратко(обязательство.минимальныйПлатёж)

    итог.push({
      ключ: `платёж-${обязательство.id}-${обязательство.датаСледующегоПлатежа}`,
      когда: вМомент(день, часы.утро),
      заголовок: `Платёж: ${обязательство.название}`,
      текст:
        дней < 0
          ? `Просрочен на ${Math.abs(дней)} ${склонение(Math.abs(дней), 'день', 'дня', 'дней')}. ${сумма}`
          : дней === 0
            ? `Сегодня. ${сумма}`
            : `Через ${дней} ${склонение(дней, 'день', 'дня', 'дней')}. ${сумма}`,
      раздел: '/obligations',
      важность: дней <= 0 ? 'срочно' : 'обычно',
    })
  }

  return итог
}

function вечерние(данные: ДанныеРасписания, день: string, часы: ЧасыДня): Оповещение[] {
  const итог: Оповещение[] = []

  const неотмечено = данные.привычки.filter(
    (привычка) => привычка.активна && !(привычка.отметки[день] > 0),
  ).length

  if (неотмечено > 0) {
    итог.push({
      ключ: `вечер-привычки-${день}`,
      когда: вМомент(день, часы.вечер),
      заголовок: 'Привычки за сегодня',
      текст: `Не отмечено: ${неотмечено}`,
      раздел: '/habits',
      важность: 'мягко',
    })
  }

  if (!данные.дневникЗаполнен) {
    итог.push({
      ключ: `вечер-дневник-${день}`,
      когда: вМомент(день, часы.вечер),
      заголовок: 'Разговор с собой',
      текст: 'Утверждение дня ждёт ответа',
      раздел: '/journal',
      важность: 'мягко',
    })
  }

  return итог
}

function прочее(данные: ДанныеРасписания, день: string, часы: ЧасыДня): Оповещение[] {
  const итог: Оповещение[] = []

  if (данные.ожидаемоеНачалоЦикла) {
    const дней = разностьДней(день, данные.ожидаемоеНачалоЦикла)
    if (дней >= 0 && дней <= 2) {
      итог.push({
        ключ: `цикл-${данные.ожидаемоеНачалоЦикла}`,
        когда: вМомент(день, часы.утро),
        заголовок: 'Скоро начало цикла',
        текст:
          дней === 0
            ? 'По вашим отметкам — сегодня. Это арифметика, а не предсказание'
            : `По вашим отметкам — через ${дней} ${склонение(дней, 'день', 'дня', 'дней')}`,
        раздел: '/relationship',
        важность: 'мягко',
      })
    }
  }

  for (const замысел of данные.замыслы) {
    if (замысел.состояние === 'сделано' || замысел.состояние === 'отменено') continue
    for (const пункт of замысел.пункты) {
      if (пункт.выполнен || пункт.срок !== день) continue
      итог.push({
        ключ: `пункт-${пункт.id}-${день}`,
        когда: вМомент(день, часы.утро),
        заголовок: `${замысел.название}: сегодня`,
        текст: пункт.название,
        раздел: '/planner',
        важность: 'обычно',
      })
    }
  }

  for (const человек of данные.люди) {
    if (человек.напоминатьЧерезДней === null || !человек.последнийКонтакт) continue
    const прошло = разностьДней(человек.последнийКонтакт, день)
    if (прошло < человек.напоминатьЧерезДней) continue
    итог.push({
      ключ: `человек-${человек.id}-${день}`,
      когда: вМомент(день, часы.утро),
      заголовок: `Давно не общались: ${человек.имя}`,
      текст: `${прошло} ${склонение(прошло, 'день', 'дня', 'дней')} с последнего разговора`,
      раздел: '/people',
      важность: 'мягко',
    })
  }

  return итог
}

/** Все напоминания на день, по возрастанию времени. */
export function расписаниеДня(
  данные: ДанныеРасписания,
  день = сегодня(),
  часы: ЧасыДня = ЧАСЫ_ПО_УМОЛЧАНИЮ,
): Оповещение[] {
  return [
    ...задачи(данные, день, часы),
    ...платежи(данные, день, часы),
    ...вечерние(данные, день, часы),
    ...прочее(данные, день, часы),
  ].sort((первое, второе) => первое.когда.localeCompare(второе.когда))
}

/** Что пора показать: время наступило, а показано ещё не было. */
export function пораПоказать(
  расписание: Оповещение[],
  сейчас: string,
  ужеПоказано: string[],
): Оповещение[] {
  const показанные = new Set(ужеПоказано)
  return расписание.filter(
    (оповещение) => оповещение.когда <= сейчас && !показанные.has(оповещение.ключ),
  )
}
