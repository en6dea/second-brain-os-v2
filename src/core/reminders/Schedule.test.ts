import { describe, expect, it } from 'vitest'
import { пораПоказать, расписаниеДня, ЧАСЫ_ПО_УМОЛЧАНИЮ } from './Schedule'
import type { ДанныеРасписания } from './Schedule'
import type { Задача, Обязательство, Привычка } from '@/core/db/types'
import { сдвинутьДень } from '@/core/calendar/CalendarRu'

const момент = '2026-08-13T10:00:00.000Z'
const день = '2026-08-13'

const пусто: ДанныеРасписания = {
  задачи: [],
  обязательства: [],
  привычки: [],
  замыслы: [],
  люди: [],
  ожидаемоеНачалоЦикла: null,
  дневникЗаполнен: true,
}

function задача(изменения: Partial<Задача> = {}): Задача {
  return {
    id: 'з',
    createdAt: момент,
    updatedAt: момент,
    название: 'Задача',
    заметка: '',
    дата: день,
    время: null,
    длительностьМинут: null,
    состояние: 'новая',
    важность: 'обычная',
    проектId: null,
    цельId: null,
    сфераId: null,
    выполненаВ: null,
    переносов: 0,
    повтор: null,
    ...изменения,
  }
}

function обязательство(изменения: Partial<Обязательство> = {}): Обязательство {
  return {
    id: 'о',
    createdAt: момент,
    updatedAt: момент,
    название: 'Интернет',
    направление: 'я должен',
    вид: 'подписка',
    телоОстаток: 0,
    начисленныеПроценты: null,
    штрафы: null,
    ставкаГодовых: null,
    минимальныйПлатёж: 70000,
    датаСледующегоПлатежа: день,
    датаОкончания: null,
    контрагент: '',
    закрыто: false,
    заметка: '',
    ...изменения,
  }
}

function привычка(отметки: Record<string, number> = {}): Привычка {
  return {
    id: 'п',
    createdAt: момент,
    updatedAt: момент,
    название: 'Чтение',
    иконка: '',
    цвет: 'accent',
    частота: 'ежедневно',
    дниНедели: [],
    разВНеделю: null,
    норма: 1,
    единица: 'раз',
    цельId: null,
    сфераId: null,
    активна: true,
    постер: '',
    отметки,
  }
}

describe('расписаниеДня', () => {
  it('на пустых данных не выдумывает напоминаний', () => {
    expect(расписаниеДня(пусто, день)).toHaveLength(0)
  })

  it('задача со временем напоминает за десять минут', () => {
    const итог = расписаниеДня(
      { ...пусто, задачи: [задача({ время: '14:00' })] },
      день,
    )
    const найдено = итог.find((о) => о.ключ.startsWith('задача-'))
    expect(найдено?.когда).toContain('T')
    expect(new Date(найдено!.когда).getHours()).toBe(13)
    expect(new Date(найдено!.когда).getMinutes()).toBe(50)
  })

  it('выполненная задача напоминаний не даёт', () => {
    const итог = расписаниеДня(
      { ...пусто, задачи: [задача({ время: '14:00', состояние: 'сделана' })] },
      день,
    )
    expect(итог).toHaveLength(0)
  })

  it('утром собирает задачи на сегодня и просроченные вместе', () => {
    const итог = расписаниеДня(
      {
        ...пусто,
        задачи: [задача({ id: '1' }), задача({ id: '2', дата: '2026-08-01' })],
      },
      день,
    )
    const утро = итог.find((о) => о.ключ === `утро-задачи-${день}`)
    expect(утро?.текст).toContain('1 задача на сегодня')
    expect(утро?.текст).toContain('1 просрочено')
    expect(утро?.важность).toBe('срочно')
  })

  it('платёж напоминает за три дня и раньше не беспокоит', () => {
    const близко = расписаниеДня(
      {
        ...пусто,
        обязательства: [
          обязательство({ датаСледующегоПлатежа: сдвинутьДень(день, 2) }),
        ],
      },
      день,
    )
    expect(близко.some((о) => о.ключ.startsWith('платёж-'))).toBe(true)

    const далеко = расписаниеДня(
      {
        ...пусто,
        обязательства: [
          обязательство({ датаСледующегоПлатежа: сдвинутьДень(день, 10) }),
        ],
      },
      день,
    )
    expect(далеко.some((о) => о.ключ.startsWith('платёж-'))).toBe(false)
  })

  it('закрытое обязательство молчит', () => {
    const итог = расписаниеДня(
      { ...пусто, обязательства: [обязательство({ закрыто: true })] },
      день,
    )
    expect(итог).toHaveLength(0)
  })

  it('платёж без суммы честно говорит, что сумма не указана', () => {
    const итог = расписаниеДня(
      { ...пусто, обязательства: [обязательство({ минимальныйПлатёж: null })] },
      день,
    )
    expect(итог[0]?.текст).toContain('сумма не указана')
  })

  it('вечером напоминает о неотмеченных привычках', () => {
    const итог = расписаниеДня({ ...пусто, привычки: [привычка()] }, день)
    const вечер = итог.find((о) => о.ключ === `вечер-привычки-${день}`)
    expect(вечер?.текст).toContain('1')
    expect(new Date(вечер!.когда).getHours()).toBe(ЧАСЫ_ПО_УМОЛЧАНИЮ.вечер)
  })

  it('отмеченная привычка вечером не тревожит', () => {
    const итог = расписаниеДня(
      { ...пусто, привычки: [привычка({ [день]: 1 })] },
      день,
    )
    expect(итог.some((о) => о.ключ.startsWith('вечер-привычки'))).toBe(false)
  })

  it('цикл напоминает мягко и называет расчёт арифметикой', () => {
    const итог = расписаниеДня(
      { ...пусто, ожидаемоеНачалоЦикла: день },
      день,
    )
    const найдено = итог.find((о) => о.ключ.startsWith('цикл-'))
    expect(найдено?.важность).toBe('мягко')
    expect(найдено?.текст).toContain('арифметика')
  })

  it('напоминания идут по возрастанию времени', () => {
    const итог = расписаниеДня(
      {
        ...пусто,
        задачи: [задача()],
        привычки: [привычка()],
      },
      день,
    )
    const времена = итог.map((о) => о.когда)
    expect([...времена].sort()).toEqual(времена)
  })
})

describe('пораПоказать', () => {
  const расписание = расписаниеДня({ ...пусто, задачи: [задача()] }, день)

  it('до времени не показывает', () => {
    const рано = new Date(`${день}T00:00:00`).toISOString()
    expect(пораПоказать(расписание, рано, [])).toHaveLength(0)
  })

  it('после времени показывает', () => {
    const поздно = new Date(`${день}T23:00:00`).toISOString()
    expect(пораПоказать(расписание, поздно, []).length).toBeGreaterThan(0)
  })

  it('показанное второй раз не показывает', () => {
    const поздно = new Date(`${день}T23:00:00`).toISOString()
    const ключи = расписание.map((о) => о.ключ)
    expect(пораПоказать(расписание, поздно, ключи)).toHaveLength(0)
  })
})
