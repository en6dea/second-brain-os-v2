import { describe, expect, it } from 'vitest'
import { известныеКоманды, разобратьКоманду, разобратьКогда } from './Command'

const день = '2026-08-12'

describe('разобратьКоманду: деньги', () => {
  it('разбирает расход с заметкой', () => {
    const итог = разобратьКоманду('расход;350;кофе', день)
    expect(итог.намерение).toEqual({
      вид: 'операция',
      тип: 'расход',
      сумма: 35000,
      заметка: 'кофе',
    })
  })

  it('понимает разговорные слова', () => {
    expect(разобратьКоманду('потратил;350;кофе', день).намерение).toEqual(
      разобратьКоманду('расход;350;кофе', день).намерение,
    )
    expect(разобратьКоманду('получил;1000', день).намерение).toMatchObject({
      тип: 'доход',
    })
  })

  it('принимает запятую в сумме и пробелы в разрядах', () => {
    expect(разобратьКоманду('расход;1 250,50;продукты', день).намерение).toMatchObject(
      { сумма: 125050 },
    )
  })

  it('заметка из нескольких частей собирается целиком', () => {
    expect(разобратьКоманду('расход;350;кофе;с молоком', день).намерение).toMatchObject(
      { заметка: 'кофе с молоком' },
    )
  })

  it('без суммы отказывается и показывает пример', () => {
    const итог = разобратьКоманду('расход;;кофе', день)
    expect(итог.намерение).toBeNull()
    expect(итог.пример).toContain('расход;350')
  })

  it('ноль и минус суммой не считаются', () => {
    expect(разобратьКоманду('расход;0;кофе', день).намерение).toBeNull()
    expect(разобратьКоманду('расход;-5;кофе', день).намерение).toBeNull()
  })
})

describe('разобратьКоманду: задачи и записи', () => {
  it('задача на завтра получает завтрашний день', () => {
    expect(разобратьКоманду('задача;позвонить маме;завтра', день).намерение).toEqual({
      вид: 'задача',
      название: 'позвонить маме',
      дата: '2026-08-13',
    })
  })

  it('задача без срока остаётся без даты, а не получает сегодня', () => {
    expect(разобратьКоманду('задача;прибраться', день).намерение).toMatchObject({
      дата: null,
    })
  })

  it('непонятное слово срока не превращается в дату', () => {
    expect(разобратьКоманду('задача;прибраться;когда-нибудь', день).намерение)
      .toMatchObject({ дата: null })
  })

  it('заметка и идея ведут в одну запись', () => {
    expect(разобратьКоманду('идея;сделать сайт', день).намерение).toEqual({
      вид: 'запись',
      текст: 'сделать сайт',
    })
  })

  it('привычка отмечается по названию', () => {
    expect(разобратьКоманду('привычка;чтение', день).намерение).toEqual({
      вид: 'привычка',
      название: 'чтение',
    })
  })
})

describe('разобратьКоманду: устойчивость', () => {
  it('решётка в начале и лишние пробелы не мешают', () => {
    expect(разобратьКоманду('#  расход ; 350 ; кофе ', день).намерение).toMatchObject({
      сумма: 35000,
      заметка: 'кофе',
    })
  })

  it('вертикальная черта работает как разделитель', () => {
    expect(разобратьКоманду('расход|350|кофе', день).намерение).toMatchObject({
      сумма: 35000,
    })
  })

  it('разбирает строку, закодированную браузером', () => {
    const закодировано = encodeURIComponent('расход;350;кофе')
    expect(разобратьКоманду(закодировано, день).намерение).toMatchObject({
      сумма: 35000,
    })
  })

  it('ё и регистр не мешают', () => {
    expect(разобратьКоманду('ЗАДАЧА;дело;Завтра', день).намерение).toMatchObject({
      дата: '2026-08-13',
    })
  })

  it('пустая команда даёт понятную ошибку', () => {
    expect(разобратьКоманду('', день).ошибка).toContain('пустая')
  })

  it('неизвестное слово перечисляет известные', () => {
    const итог = разобратьКоманду('погода;завтра', день)
    expect(итог.намерение).toBeNull()
    expect(итог.ошибка).toContain('расход')
  })
})

describe('разобратьКогда', () => {
  it('понимает сегодня, завтра и послезавтра', () => {
    expect(разобратьКогда('сегодня', день)).toBe(день)
    expect(разобратьКогда('завтра', день)).toBe('2026-08-13')
    expect(разобратьКогда('послезавтра', день)).toBe('2026-08-14')
  })

  it('принимает дату целиком', () => {
    expect(разобратьКогда('2026-12-31', день)).toBe('2026-12-31')
  })
})

describe('известныеКоманды', () => {
  it('у каждой команды есть рабочий пример', () => {
    for (const { пример } of известныеКоманды()) {
      expect(разобратьКоманду(пример).намерение).not.toBeNull()
    }
  })
})
