import type { ДатаДень, Копейки } from '@/core/db/types'
import { рублиВКопейки } from '@/core/money/Money'
import { сегодня, сдвинутьДень } from '@/core/calendar/CalendarRu'

/**
 * Команды быстрого ввода.
 *
 * Нужны для телефона. На iPhone нет ни ярлыков в манифесте, ни приёма
 * «Поделиться» — единственный рабочий путь ведёт через приложение «Команды»,
 * которое умеет открывать адрес. Поэтому ввод описывается строкой:
 *
 *     расход;350;кофе
 *     задача;позвонить маме;завтра
 *
 * Строка передаётся после решётки, а не в параметрах запроса. Всё, что стоит
 * после «?», уходит на сервер в HTTP-запросе и попадает в его журналы; всё,
 * что после «#», браузер на сервер не отправляет никогда. Суммы и заметки
 * должны остаться на устройстве.
 *
 * Разбор — чистая функция без базы и без интерфейса. Записью занимается
 * `Intent.ts`.
 */

export type Намерение =
  | { вид: 'операция'; тип: 'доход' | 'расход'; сумма: Копейки; заметка: string }
  | { вид: 'задача'; название: string; дата: ДатаДень | null }
  | { вид: 'запись'; текст: string }
  | { вид: 'привычка'; название: string }

export interface РазборКоманды {
  намерение: Намерение | null
  /** Что непонятно. Пусто, когда разбор удался. */
  ошибка: string
  /** Пример правильной команды — показывается вместе с ошибкой. */
  пример: string
}

/** Слово команды приводится к одному виду: «Потратил» и «трата» — расход. */
const СЛОВА: Record<string, 'расход' | 'доход' | 'задача' | 'запись' | 'привычка'> = {
  расход: 'расход',
  трата: 'расход',
  потратил: 'расход',
  купил: 'расход',
  оплатил: 'расход',
  доход: 'доход',
  приход: 'доход',
  получил: 'доход',
  заработал: 'доход',
  задача: 'задача',
  дело: 'задача',
  надо: 'задача',
  заметка: 'запись',
  идея: 'запись',
  мысль: 'запись',
  запись: 'запись',
  привычка: 'привычка',
  отметить: 'привычка',
}

const ПРИМЕРЫ: Record<string, string> = {
  расход: 'расход;350;кофе',
  доход: 'доход;90000;зарплата',
  задача: 'задача;позвонить маме;завтра',
  запись: 'заметка;проверить страховку',
  привычка: 'привычка;чтение',
}

const ПРИМЕР_ОБЩИЙ = 'расход;350;кофе'

/** Разделителем может быть точка с запятой или вертикальная черта. */
function разделить(строка: string): string[] {
  return строка
    .split(/[;|]/)
    .map((часть) => часть.trim())
    .filter((часть, индекс) => индекс === 0 || часть.length > 0)
}

/**
 * Когда назначена задача.
 *
 * Понимает «сегодня», «завтра», «послезавтра» и дату вида ГГГГ-ММ-ДД.
 * Незнакомое слово не превращается в дату: лучше задача без срока, чем
 * задача на выдуманный день.
 */
export function разобратьКогда(значение: string, отДня = сегодня()): ДатаДень | null {
  const текст = значение.toLowerCase().replace(/ё/g, 'е').trim()
  if (!текст) return null
  if (текст === 'сегодня') return отДня
  if (текст === 'завтра') return сдвинутьДень(отДня, 1)
  if (текст === 'послезавтра') return сдвинутьДень(отДня, 2)
  if (/^\d{4}-\d{2}-\d{2}$/.test(текст)) return текст
  return null
}

function ошибка(текст: string, пример = ПРИМЕР_ОБЩИЙ): РазборКоманды {
  return { намерение: null, ошибка: текст, пример }
}

/**
 * Разбор строки команды.
 *
 * Строка приходит из адреса, то есть от человека и с телефона. Любая
 * непонятная часть — это ошибка с подсказкой, а не молчаливое угадывание:
 * записать не то хуже, чем не записать ничего.
 */
export function разобратьКоманду(строка: string, отДня = сегодня()): РазборКоманды {
  const очищено = decodeURIComponent(строка.trim().replace(/^#/, ''))
  if (!очищено) return ошибка('Команда пустая.')

  const части = разделить(очищено)
  const слово = (части[0] ?? '').toLowerCase().replace(/ё/g, 'е')
  const вид = СЛОВА[слово]

  if (!вид) {
    return ошибка(
      `Слово «${части[0]}» не похоже ни на одну команду. Известны: расход, доход, задача, заметка, привычка.`,
    )
  }

  const пример = ПРИМЕРЫ[вид] ?? ПРИМЕР_ОБЩИЙ

  if (вид === 'расход' || вид === 'доход') {
    const сумма = рублиВКопейки((части[1] ?? '').replace(/\s/g, ''))
    if (сумма === null || сумма <= 0) {
      return ошибка(`Не разобрал сумму «${части[1] ?? ''}».`, пример)
    }
    return {
      намерение: {
        вид: 'операция',
        тип: вид,
        сумма,
        заметка: части.slice(2).join(' ').trim(),
      },
      ошибка: '',
      пример,
    }
  }

  if (вид === 'задача') {
    const название = (части[1] ?? '').trim()
    if (!название) return ошибка('У задачи нет названия.', пример)
    return {
      намерение: {
        вид: 'задача',
        название,
        дата: разобратьКогда(части[2] ?? '', отДня),
      },
      ошибка: '',
      пример,
    }
  }

  if (вид === 'привычка') {
    const название = (части[1] ?? '').trim()
    if (!название) return ошибка('Не указано, какую привычку отметить.', пример)
    return { намерение: { вид: 'привычка', название }, ошибка: '', пример }
  }

  const текст = части.slice(1).join(' ').trim()
  if (!текст) return ошибка('Запись пустая.', пример)
  return { намерение: { вид: 'запись', текст }, ошибка: '', пример }
}

/** Все понятные слова — для подсказки на странице быстрого ввода. */
export function известныеКоманды(): { слово: string; пример: string }[] {
  return Object.entries(ПРИМЕРЫ).map(([вид, пример]) => ({ слово: вид, пример }))
}
