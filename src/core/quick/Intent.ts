import { база } from '@/core/db/db'
import { новаяЗапись } from '@/core/db/repo'
import { сейчас } from '@/core/db/RecordId'
import { сегодня } from '@/core/calendar/CalendarRu'
import { подсказать, запомнить } from '@/features/finance/model/CategoryHints'
import type { Намерение } from './Command'

/**
 * Запись намерения в базу.
 *
 * Отделено от разбора: разбор — чистая функция, здесь единственное место,
 * которое трогает хранилище. Каждый ответ объясняет, что именно записано и
 * куда идти дальше — быстрый ввод не должен оставлять сомнений.
 */

export interface ИтогКоманды {
  записано: boolean
  сообщение: string
  /** Чем дополнено само собой: категория, счёт. Пусто — дополнять было нечем. */
  дополнено: string
  /** Куда перейти, чтобы увидеть запись. */
  раздел: string
}

/** Сравнение названий: регистр и «ё» не должны мешать найти привычку. */
function похоже(первое: string, второе: string): boolean {
  const свести = (строка: string) => строка.toLowerCase().replace(/ё/g, 'е').trim()
  return свести(первое) === свести(второе)
}

/**
 * Счёт для быстрой операции.
 *
 * Если действующий счёт ровно один, выбор очевиден и спрашивать нечего.
 * Когда счетов несколько, приложение не угадывает: операция записывается без
 * счёта и попадает в разбор.
 */
async function единственныйСчёт(): Promise<string | null> {
  const счета = await база.accounts.filter((счёт) => !счёт.архив).toArray()
  return счета.length === 1 ? (счета[0]?.id ?? null) : null
}

async function записатьОперацию(
  намерение: Extract<Намерение, { вид: 'операция' }>,
): Promise<ИтогКоманды> {
  const [категории, операции, счётId] = await Promise.all([
    база.moneyCategories.toArray(),
    база.operations.toArray(),
    единственныйСчёт(),
  ])

  const подсказка = намерение.заметка
    ? подсказать(намерение.заметка, запомнить(операции), категории, намерение.тип)
    : null

  await база.operations.add(
    новаяЗапись({
      дата: сегодня(),
      тип: намерение.тип,
      сумма: намерение.сумма,
      счётId,
      счётПолучательId: null,
      категорияId: подсказка?.категорияId ?? null,
      классРасхода: null,
      заметка: намерение.заметка,
      планId: null,
      отпечатокИмпорта: null,
      разобрана: подсказка !== null,
    }) as never,
  )

  const имяКатегории = подсказка
    ? (категории.find((к) => к.id === подсказка.категорияId)?.название ?? '')
    : ''

  const дополнения = [
    имяКатегории ? `категория «${имяКатегории}» — ${подсказка?.основание}` : '',
    счётId ? 'счёт подставлен: он у вас один' : '',
  ].filter(Boolean)

  return {
    записано: true,
    сообщение: намерение.тип === 'расход' ? 'Расход записан' : 'Доход записан',
    дополнено: дополнения.join('; '),
    раздел: '/finance/operations',
  }
}

async function записатьЗадачу(
  намерение: Extract<Намерение, { вид: 'задача' }>,
): Promise<ИтогКоманды> {
  await база.tasks.add(
    новаяЗапись({
      название: намерение.название,
      заметка: '',
      дата: намерение.дата,
      время: null,
      длительностьМинут: null,
      состояние: 'новая',
      важность: 'обычная',
      проектId: null,
      цельId: null,
      сфераId: null,
      выполненаВ: null,
      переносов: 0,
      повтор: null,
    }) as never,
  )

  return {
    записано: true,
    сообщение: 'Задача добавлена',
    дополнено: намерение.дата ? '' : 'срок не указан — задача без даты',
    раздел: '/tasks',
  }
}

async function записатьЗапись(
  намерение: Extract<Намерение, { вид: 'запись' }>,
): Promise<ИтогКоманды> {
  await база.inbox.add(
    новаяЗапись({
      текст: намерение.текст,
      разобрано: false,
      источник: 'быстрая запись' as const,
    }) as never,
  )

  return {
    записано: true,
    сообщение: 'Записано во входящие',
    дополнено: 'разберёте позже — в разделе «Разбор»',
    раздел: '/inbox',
  }
}

async function отметитьПривычку(
  намерение: Extract<Намерение, { вид: 'привычка' }>,
): Promise<ИтогКоманды> {
  const привычки = await база.habits.toArray()
  const найдена = привычки.find((привычка) =>
    похоже(привычка.название, намерение.название),
  )

  if (!найдена) {
    const имена = привычки
      .filter((привычка) => привычка.активна)
      .map((привычка) => привычка.название)
      .join(', ')
    return {
      записано: false,
      сообщение: `Привычка «${намерение.название}» не найдена.`,
      дополнено: имена ? `Есть такие: ${имена}` : 'Ни одной привычки пока не заведено',
      раздел: '/habits',
    }
  }

  const день = сегодня()
  const отметки = { ...найдена.отметки }
  const было = отметки[день] ?? 0
  отметки[день] = было > 0 ? было : найдена.норма || 1

  await база.habits.put({ ...найдена, отметки, updatedAt: сейчас() })

  return {
    записано: true,
    сообщение: было > 0 ? 'Уже было отмечено сегодня' : `Отмечено: ${найдена.название}`,
    дополнено: '',
    раздел: '/habits',
  }
}

export async function применить(намерение: Намерение): Promise<ИтогКоманды> {
  if (намерение.вид === 'операция') return записатьОперацию(намерение)
  if (намерение.вид === 'задача') return записатьЗадачу(намерение)
  if (намерение.вид === 'привычка') return отметитьПривычку(намерение)
  return записатьЗапись(намерение)
}
