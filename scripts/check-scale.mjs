// Проверка: произвольных размеров в разметке не становится больше.
//
// Размер текста, радиус и размер значка когда-то подбирались на глаз в каждом
// экране: девятнадцать размеров текста, одиннадцать размеров значка. Теперь
// шкала объявлена в `src/index.css` и `src/design-system/iconSize.ts`, но
// перевести три сотни мест разом — значит рискнуть внешним видом всего
// приложения ради оформления.
//
// Поэтому проверка работает как храповик: она не требует нуля, она требует,
// чтобы число произвольных значений не росло. Новый экран берёт токен; старый
// переводится, когда его и так правят. Когда счётчик падает — опустите базу
// в этом файле, чтобы он не пополз обратно.

import { readdirSync, readFileSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'

/** Сколько произвольных значений осталось. Только вниз. */
const БАЗА = {
  'размер текста': 268,
  радиус: 2,
  'размер значка': 63,
}

const ЗНАЧОК_ПО_ШКАЛЕ = new Set([12, 14, 16, 18, 20])

const проверки = [
  {
    имя: 'размер текста',
    образец: /text-\[[0-9.]+px\]/g,
    совет: 'возьмите text-micro…text-display из src/index.css',
  },
  {
    имя: 'радиус',
    образец: /rounded-\[[0-9.]+px\]/g,
    совет: 'возьмите rounded-1…rounded-5 из src/index.css',
  },
  {
    имя: 'размер значка',
    образец: /size=\{([0-9]+)\}/g,
    годится: (совпадение) => ЗНАЧОК_ПО_ШКАЛЕ.has(Number(совпадение[1])),
    совет: 'возьмите ЗНАЧОК из src/design-system/iconSize.ts',
  },
]

const корень = fileURLToPath(new URL('..', import.meta.url))

function файлы(каталог) {
  const итог = []
  for (const имя of readdirSync(каталог)) {
    const путь = join(каталог, имя)
    if (statSync(путь).isDirectory()) итог.push(...файлы(путь))
    else if (/\.tsx?$/.test(имя)) итог.push(путь)
  }
  return итог
}

const найдено = new Map(проверки.map(({ имя }) => [имя, []]))

for (const путь of файлы(join(корень, 'src'))) {
  const строки = readFileSync(путь, 'utf8').split('\n')
  for (const проверка of проверки) {
    for (const [номер, строка] of строки.entries()) {
      for (const совпадение of строка.matchAll(проверка.образец)) {
        if (проверка.годится?.(совпадение)) continue
        найдено.get(проверка.имя).push({
          место: `${relative(корень, путь).split('\\').join('/')}:${номер + 1}`,
          текст: совпадение[0],
        })
      }
    }
  }
}

const превышенные = []

for (const { имя } of проверки) {
  const стало = найдено.get(имя).length
  const база = БАЗА[имя]
  const примечание =
    стало > база
      ? '✗ стало больше'
      : стало < база
        ? `— опустите базу до ${стало}`
        : ''
  console.log(
    `${имя.padEnd(14)} ${String(стало).padStart(4)} при базе ${база} ${примечание}`,
  )
  if (стало > база) превышенные.push(имя)
}

if (превышенные.length > 0) {
  for (const имя of превышенные) {
    const { совет } = проверки.find((п) => п.имя === имя)
    console.error(`\n${имя}: ${совет}. Все произвольные значения этого вида:`)
    for (const { место, текст } of найдено.get(имя)) {
      console.error(`  ${место} ${текст}`)
    }
  }
  process.exit(1)
}

console.log('\nПроизвольных размеров не прибавилось.')
