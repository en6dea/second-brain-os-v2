// Проверка контраста текстовых токенов по формуле WCAG.
//
// Подпись под числом — это указание источника, ради которого действует правило
// «ни одной выдуманной цифры». Если её нельзя прочитать при ярком свете, правило
// не работает. Контраст нельзя проверить глазами: он считается, а не кажется.
//
// Проверка читает реальные значения из src/index.css, поэтому её нельзя обойти,
// поменяв токен и забыв про порог.

import { readFileSync } from 'node:fs'

const ПОРОГ = 4.5 // WCAG AA, мелкий текст
const ПОРОГ_ЭЛЕМЕНТА = 3 // WCAG non-text contrast для границы управления
const ТЕКСТ = ['--ink', '--ink-2', '--ink-3']
const ПОВЕРХНОСТИ = [
  '--surface-bg',
  '--surface-sidebar',
  '--surface-card',
  '--surface-card-deep',
  '--surface-raised',
  '--surface-over',
  '--surface-sunken',
  '--surface-hover',
]

const css = readFileSync(new URL('../src/index.css', import.meta.url), 'utf8')

/** Значения токенов внутри одного селектора. */
function токены(селектор) {
  const начало = css.indexOf(селектор)
  if (начало < 0) throw new Error(`Не найден блок ${селектор} в src/index.css`)
  const открытие = css.indexOf('{', начало)
  const закрытие = css.indexOf('\n}', открытие)
  const тело = css.slice(открытие, закрытие)
  const итог = {}
  for (const [, имя, значение] of тело.matchAll(
    /(--[a-z0-9-]+):\s*(#[0-9a-fA-F]{6})\s*;/g,
  )) {
    итог[имя] = значение
  }
  return итог
}

/** Относительная яркость по WCAG 2.1. */
function яркость(hex) {
  const каналы = [1, 3, 5].map((сдвиг) => {
    const доля = parseInt(hex.slice(сдвиг, сдвиг + 2), 16) / 255
    return доля <= 0.03928 ? доля / 12.92 : ((доля + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * каналы[0] + 0.7152 * каналы[1] + 0.0722 * каналы[2]
}

function контраст(первый, второй) {
  const a = яркость(первый)
  const b = яркость(второй)
  const светлее = Math.max(a, b)
  const темнее = Math.min(a, b)
  return (светлее + 0.05) / (темнее + 0.05)
}

const светлая = токены(':root')
const тёмная = { ...светлая, ...токены(":root[data-theme='dark']") }

const провалы = []

for (const [названиеТемы, набор] of [
  ['светлая Daylight Observatory', светлая],
  ['тёмная Daylight Observatory', тёмная],
]) {
  console.log(`\n${названиеТемы}`)
  for (const текст of ТЕКСТ) {
    const строка = ПОВЕРХНОСТИ
      .map((поверхность) => {
        const значение = контраст(набор[текст], набор[поверхность])
        if (значение < ПОРОГ)
          провалы.push({ названиеТемы, текст, поверхность, значение })
        const имя = поверхность.replace('--surface-', '')
        return `${имя} ${значение.toFixed(2)}${значение < ПОРОГ ? ' ✗' : ''}`
      })
      .join('   ')
    console.log(`  ${текст.padEnd(8)} ${строка}`)
  }

  const контрастГалочки = контраст(набор['--ink-on-good'], набор['--good'])
  console.log(`  отметка  good ${контрастГалочки.toFixed(2)}`)
  if (контрастГалочки < 3) {
    провалы.push({
      названиеТемы,
      текст: '--ink-on-good',
      поверхность: '--good',
      значение: контрастГалочки,
    })
  }

  for (const поверхность of ['--accent', '--accent-hover']) {
    const значение = контраст(набор['--ink-on-accent'], набор[поверхность])
    console.log(
      `  акцент   ${поверхность.replace('--', '')} ${значение.toFixed(2)}`,
    )
    if (значение < ПОРОГ) {
      провалы.push({
        названиеТемы,
        текст: '--ink-on-accent',
        поверхность,
        значение,
      })
    }
  }

  const контрастГлавнойКнопки = контраст(
    набор['--ink-on-primary'],
    набор['--accent-bright'],
  )
  console.log(`  CTA      accent-bright ${контрастГлавнойКнопки.toFixed(2)}`)
  if (контрастГлавнойКнопки < ПОРОГ) {
    провалы.push({
      названиеТемы,
      текст: '--ink-on-primary',
      поверхность: '--accent-bright',
      значение: контрастГлавнойКнопки,
    })
  }

  for (const поверхность of ['--surface-card', '--surface-raised']) {
    const значение = контраст(набор['--control-line'], набор[поверхность])
    console.log(
      `  control  ${поверхность.replace('--surface-', '')} ${значение.toFixed(2)}`,
    )
    if (значение < ПОРОГ_ЭЛЕМЕНТА) {
      провалы.push({
        названиеТемы,
        текст: '--control-line',
        поверхность,
        значение,
      })
    }
  }
}

if (провалы.length > 0) {
  console.error(`\nНиже порога WCAG AA (${ПОРОГ}:1):`)
  for (const { названиеТемы, текст, поверхность, значение } of провалы) {
    console.error(
      `  ${текст} на ${поверхность} (${названиеТемы}) — ${значение.toFixed(2)}:1`,
    )
  }
  process.exit(1)
}

console.log(`\nВсе пары текст/поверхность проходят ${ПОРОГ}:1.`)
